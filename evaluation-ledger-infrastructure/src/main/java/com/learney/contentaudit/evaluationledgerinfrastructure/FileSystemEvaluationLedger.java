/**
 * Filesystem adapter that persists {@link EvaluationRecord}s as one file per
 * evaluator under {@code <baseDir>/.content-audit/evaluations/}, one entry per
 * physical line, written strictly in append mode.
 *
 * <p>That shape is what makes every guarantee in F-EVCOST-R004 hold:
 * <ul>
 *   <li><b>Immediate availability</b>: {@link #append(EvaluationRecord)} writes
 *       the moment a result is obtained, not at the end of a run. A new
 *       instance opened later over the same directory reads everything a
 *       previous, possibly interrupted, instance wrote.</li>
 *   <li><b>Complete or non-existent</b>: each record is serialized to a single
 *       JSON line (the plain, non-pretty-printing Jackson writer escapes any
 *       control character inside string values, so a record's JSON can never
 *       itself contain a raw line break) and appended with one {@code
 *       FileChannel} write per call. Reading tolerates a half-written trailing
 *       line — one that a crash left mid-write — by simply failing to parse
 *       it and treating its content as never registered, rather than
 *       throwing.</li>
 *   <li><b>Safe concurrency</b>: every append opens a fresh channel with
 *       {@link StandardOpenOption#APPEND}. On a local filesystem that makes
 *       the OS perform the seek-to-end-and-write as a single atomic
 *       operation, so two ledgers — even from two runs happening at the same
 *       time — never interleave their bytes or clobber each other's line. The
 *       worst case two concurrent runs can produce is evaluating (and paying
 *       for) the same content twice, never a corrupted or lost record.</li>
 * </ul>
 */
