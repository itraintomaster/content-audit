/**
 * The saved sentences of the production copy the importer leaves in {@code db/quiz-templates.json}
 * (F-DATOS-R001, DOUBT-DATOS-PRODUCCION): of each document only its {@code _id} and its
 * {@code form.sentences} are read, streaming, once. A quiz the copy has without saved sentences
 * gives nothing, and a missing file is a copy without any.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
public class FileSystemProductionSentenceSource implements ProductionSentenceSource {
    private final Path exportPath;

    private Map<String, List<String>> sentences;

    public FileSystemProductionSentenceSource(Path exportPath) {
        this.exportPath = exportPath;
    }

    @Override
    public Optional<List<String>> savedSentences(String quizId) {
        if (quizId == null) {
            return Optional.empty();
        }
        return Optional.ofNullable(load().get(quizId));
    }

    private synchronized Map<String, List<String>> load() {
        if (sentences != null) {
            return sentences;
        }
        Map<String, List<String>> read = new HashMap<>();
        if (exportPath != null && Files.exists(exportPath)) {
            ObjectMapper mapper = new ObjectMapper();
            try (JsonParser parser = mapper.getFactory().createParser(exportPath.toFile())) {
                if (parser.nextToken() == JsonToken.START_ARRAY) {
                    while (parser.nextToken() == JsonToken.START_OBJECT) {
                        JsonNode document = mapper.readTree(parser);
                        String id = idOf(document.path("_id"));
                        JsonNode saved = document.path("form").path("sentences");
                        if (id == null || !saved.isArray()) {
                            continue;
                        }
                        List<String> list = new ArrayList<>();
                        saved.forEach(s -> {
                            if (s.isTextual()) {
                                list.add(s.asText());
                            }
                        });
                        read.put(id, Collections.unmodifiableList(list));
                    }
                }
            } catch (IOException e) {
                throw new UncheckedIOException("no se pudo leer la copia de producción " + exportPath, e);
            }
        }
        sentences = Collections.unmodifiableMap(read);
        return sentences;
    }

    private static String idOf(JsonNode id) {
        if (id.isTextual()) {
            return id.asText();
        }
        JsonNode oid = id.path("$oid");
        return oid.isTextual() ? oid.asText() : null;
    }
}
