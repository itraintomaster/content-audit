@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
public class FileSystemGoalDeclarationSource implements GoalDeclarationSource {
    private static final ObjectMapper MAPPER = JsonFiles.mapper()
            .configure(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES, true);

    private final Path declarationFile;

    public FileSystemGoalDeclarationSource(Path declarationFile) {
        this.declarationFile = declarationFile;
    }

    @Override
    public GoalDeclaration read() {
        if (declarationFile == null || !Files.isRegularFile(declarationFile)) {
            return new GoalDeclaration(new ArrayList<>(), new ArrayList<>(), null);
        }
        GoalDeclaration declaration;
        try {
            declaration = MAPPER.readValue(declarationFile.toFile(), GoalDeclaration.class);
        } catch (IOException e) {
            throw new AuditPersistenceException("The declaration of goals " + declarationFile
                    + " cannot be read: " + e.getMessage(), e);
        }
        List<Goal> goals = declaration.getGoals() != null ? new ArrayList<>(declaration.getGoals()) : new ArrayList<>();
        for (Goal goal : goals) {
            if (goal.getOrigin() == null) {
                goal.setOrigin(GoalOrigin.DECLARED);
            }
        }
        return new GoalDeclaration(
                declaration.getFamilyFloors() != null ? new ArrayList<>(declaration.getFamilyFloors()) : new ArrayList<>(),
                goals, declaration.getBlindSample());
    }
}
