    @Override
    public SavedProjection save(CourseProjection projection) {
        if (projection == null || projection.getAvailability() != ConsolidatedViewAvailability.AVAILABLE
                || projection.getProjected() == null) {
            throw new IllegalArgumentException("Only an available projection can be saved: it has no photo with "
                    + "the pending proposals");
        }
        if (isBlank(projection.getActiveAuditId()) || isBlank(projection.getActivePlanId())) {
            throw new IllegalArgumentException("A projection is saved for an active pair: it needs the active "
                    + "analysis and the active plan");
        }
        String projectionId = ID_PREFIX + projection.getActiveAuditId() + "-" + projection.getActivePlanId();
        JsonFiles.writeAtomically(reportMapper, reportFile(baseDir, projectionId), projection.getProjected());

        SavedProjection saved = new SavedProjection(projectionId, projection.getActiveAuditId(),
                projection.getActivePlanId(), projection.getScopeId(), Instant.now(),
                appliedPendingIds(projection), nonApplicable(projection));
        JsonFiles.writeAtomically(RECORD_MAPPER, projectionsDir(baseDir).resolve(projectionId + SAVED_SUFFIX), saved);
        return saved;
    }

    @Override
    public Optional<AuditReport> load(String projectionId) {
        return existingReportFile(baseDir, projectionId).map(file -> readReport(reportMapper, file));
    }

    /**
     * The photo of the saved projection with that id, if there is one; {@link FileSystemAuditReportStore}
     * reads it too (hook F-05). The record of what was saved ({@code .saved.json}) is never a photo.
     */
    static Optional<Path> existingReportFile(Path baseDir, String projectionId) {
        if (isBlank(projectionId) || projectionId.endsWith(SAVED_MARK)) {
            return Optional.empty();
        }
        Path file = reportFile(baseDir, projectionId);
        return Files.isRegularFile(file) ? Optional.of(file) : Optional.empty();
    }

    private static Path reportFile(Path baseDir, String projectionId) {
        return projectionsDir(baseDir).resolve(projectionId + REPORT_SUFFIX);
    }

    /** Reads a report written with {@link AuditReportObjectMapper} and gives each node its parent back. */
    static AuditReport readReport(ObjectMapper mapper, Path file) {
        try {
            AuditReport report = mapper.readValue(file.toFile(), AuditReport.class);
            if (report.getRoot() != null) {
                rebuildParents(report.getRoot(), null);
            }
            return report;
        } catch (IOException e) {
            throw new AuditPersistenceException("Failed to read report from " + file + ": " + e.getMessage(), e);
        }
    }

    private static void rebuildParents(AuditNode node, AuditNode parent) {
        node.setParent(parent);
        if (node.getChildren() != null) {
            for (AuditNode child : node.getChildren()) {
                rebuildParents(child, node);
            }
        }
    }

    private static Path projectionsDir(Path baseDir) {
        return baseDir.resolve(PROJECTIONS_SUBDIR);
    }

    /** F-PROYU-R002: the pending proposals that entered the photo, in the order they were applied. */
    private static List<String> appliedPendingIds(CourseProjection projection) {
        List<String> ids = new ArrayList<>();
        if (projection.getChanges() != null) {
            for (ProjectedChange change : projection.getChanges()) {
                if (change.isPending()) {
                    ids.add(change.getProposalId());
                }
            }
        }
        return ids;
    }

    private static List<NonApplicablePending> nonApplicable(CourseProjection projection) {
        return projection.getNonApplicablePendings() != null
                ? new ArrayList<>(projection.getNonApplicablePendings()) : new ArrayList<>();
    }

    private static boolean isBlank(String value) {
        return value == null || value.isBlank();
    }
