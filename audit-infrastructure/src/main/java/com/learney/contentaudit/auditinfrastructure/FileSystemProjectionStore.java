    private static final String ID_PREFIX = "proyeccion-";

    private static final String REPORT_SUFFIX = ".json";

    private static final String SAVED_MARK = ".saved";

    private static final String SAVED_SUFFIX = SAVED_MARK + REPORT_SUFFIX;

    private static final ObjectMapper RECORD_MAPPER = JsonFiles.mapper();

