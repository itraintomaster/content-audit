/**
 * F-CIEGA-R003: the blind samples and their answers are the only thing the blind sample writes,
 * under {@code <baseDir>/.content-audit/blind-samples/}: a sample of pairs in
 * {@code <sampleId>.json}, a sample of the blind error rate in {@code error-rate/<sampleId>.json}.
 * Each file holds the whole sample -- what was drawn, every answer with who and when, and when it
 * was closed --, so saving it again replaces it.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
public class FileSystemBlindSampleStore implements BlindSampleStore {
    static final String SAMPLES_SUBDIR = ".content-audit/blind-samples";

    private static final String ERROR_RATE_SUBDIR = "error-rate";

    private static final String SUFFIX = ".json";

    private static final ObjectMapper MAPPER = JsonFiles.mapper();

    private final Path baseDir;

    public FileSystemBlindSampleStore(Path baseDir) {
        this.baseDir = baseDir;
    }

    @Override
    public void savePairs(BlindSample sample) {
        JsonFiles.writeAtomically(MAPPER, pairsDir().resolve(fileName(sample != null ? sample.getSampleId() : null)),
                sample);
    }

    @Override
    public Optional<BlindSample> loadPairs(String sampleId) {
        if (!isValidId(sampleId)) {
            return Optional.empty();
        }
        return JsonFiles.read(MAPPER, pairsDir().resolve(sampleId + SUFFIX), BlindSample.class);
    }

    @Override
    public List<BlindSample> listPairs() {
        Path dir = pairsDir();
        if (!Files.isDirectory(dir)) {
            return new ArrayList<>();
        }
        List<BlindSample> samples = new ArrayList<>();
        try (Stream<Path> files = Files.list(dir)) {
            for (Path file : files.filter(Files::isRegularFile)
                    .filter(p -> p.getFileName().toString().endsWith(SUFFIX))
                    .sorted()
                    .toList()) {
                JsonFiles.read(MAPPER, file, BlindSample.class).ifPresent(samples::add);
            }
        } catch (IOException e) {
            throw new AuditPersistenceException("Failed to list the blind samples in " + dir + ": " + e.getMessage(), e);
        }
        samples.sort(Comparator.comparing((BlindSample s) -> s.getDrawnAt() != null ? s.getDrawnAt() : Instant.EPOCH)
                .thenComparing(s -> s.getSampleId() != null ? s.getSampleId() : ""));
        return samples;
    }

    @Override
    public void saveErrorRate(ErrorRateSample sample) {
        JsonFiles.writeAtomically(MAPPER,
                errorRateDir().resolve(fileName(sample != null ? sample.getSampleId() : null)), sample);
    }

    @Override
    public Optional<ErrorRateSample> loadErrorRate(String sampleId) {
        if (!isValidId(sampleId)) {
            return Optional.empty();
        }
        return JsonFiles.read(MAPPER, errorRateDir().resolve(sampleId + SUFFIX), ErrorRateSample.class);
    }

    private Path pairsDir() {
        return baseDir.resolve(SAMPLES_SUBDIR);
    }

    private Path errorRateDir() {
        return pairsDir().resolve(ERROR_RATE_SUBDIR);
    }

    private static String fileName(String sampleId) {
        if (!isValidId(sampleId)) {
            throw new IllegalArgumentException("A blind sample is saved by its id, and '" + sampleId
                    + "' is not one");
        }
        return sampleId + SUFFIX;
    }

    /** An id names a file of the directory, never a path out of it. */
    private static boolean isValidId(String sampleId) {
        return sampleId != null && !sampleId.isBlank() && !sampleId.contains("/") && !sampleId.contains("\\")
                && !sampleId.contains("..");
    }
}
