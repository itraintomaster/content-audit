        assertTrue(Files.isRegularFile(file), "one file per batch");

        batch.setOutcomes(new ArrayList<>(List.of(new BatchTaskOutcome("t-pista", BatchTaskOutcomeKind.RESOLVED_BY_RULE,
                "regla-hint-coherence-1ecd", 0, null))));
