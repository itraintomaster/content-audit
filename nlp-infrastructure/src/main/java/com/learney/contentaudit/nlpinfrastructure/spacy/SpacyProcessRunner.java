/**
 * Runs the spaCy processor over the sentences that are not in the token cache, and returns the
 * tokens of every sentence asked for, in the order they were asked.
 *
 * <p>F-RONDA2-R005: the disk cache keeps each sentence apart, and a batch launches spaCy once,
 * only with the sentences it does not find. F-RONDA2-R006: the key of a sentence is the sentence
 * plus the fingerprint of the content of the lemma list and of the processor, so a different list
 * or processor never reuses tokens of another; the entries of the old key -- the whole batch,
 * without fingerprints -- live outside {@code sentences/} and are never read again.
 * F-RONDA2-R007: the list and the processor are read before the cache is looked at, so a full
 * cache never hides that one of them is missing; without them, or when spaCy does not run for the
 * sentences it has to tokenize, the run stops with {@link NlpResourcesUnavailableException}
 * instead of carrying on with tokens nobody can trust.
 */
