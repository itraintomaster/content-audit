package com.learney.contentaudit.evaluationledgerdomain.contentfingerprint;

import com.learney.contentaudit.evaluationledgerdomain.ContentFingerprinter;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;
import java.util.Map;
import java.util.TreeMap;
import javax.annotation.processing.Generated;

/**
 * Derives F-EVCOST-R002's fingerprint from exactly the content map handed to
 * the evaluator, and from nothing else: no timestamps, no identifiers, no
 * iteration order.
 *
 * <p>Reproducibility (same content -&gt; same fingerprint, across runs and
 * across processes) rests on two choices: the map is canonicalized by
 * re-sorting its entries on the natural ordering of the keys (a plain
 * {@code HashMap}'s iteration order is unspecified and can vary between runs),
 * and every string is turned into bytes with a fixed, explicit encoding
 * (UTF-8) instead of relying on the platform default.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
public class Sha256ContentFingerprinter implements ContentFingerprinter {
    @Override
    public String fingerprint(Map<String, String> content) {
        // Canonical order: sorted by key, independent of the caller's map
        // implementation or insertion order.
        Map<String, String> canonical = new TreeMap<>(content);

        MessageDigest digest = newDigest();
        for (Map.Entry<String, String> entry : canonical.entrySet()) {
            digestString(digest, entry.getKey());
            digestString(digest, entry.getValue());
        }
        return HexFormat.of().formatHex(digest.digest());
    }

    /**
     * Feeds one string into the digest with an explicit presence flag and a
     * length prefix, so that no combination of keys/values can collide by
     * concatenation (e.g. {"a", "bc"} vs {"ab", "c"}), and so that a
     * {@code null} value is distinguishable from an empty string.
     */
    private static void digestString(MessageDigest digest, String value) {
        if (value == null) {
            digest.update((byte) 0);
            return;
        }
        digest.update((byte) 1);
        byte[] bytes = value.getBytes(StandardCharsets.UTF_8);
        digest.update(lengthPrefix(bytes.length));
        digest.update(bytes);
    }

    private static byte[] lengthPrefix(int length) {
        return new byte[] {
            (byte) (length >>> 24),
            (byte) (length >>> 16),
            (byte) (length >>> 8),
            (byte) length
        };
    }

    private static MessageDigest newDigest() {
        try {
            return MessageDigest.getInstance("SHA-256");
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException("SHA-256 algorithm not available", e);
        }
    }
}
