    @Test
    @DisplayName("should open exam sessions that consult, within the budget, a content the taking version never judged even when another version judged it")
    @Tag("FEAT-JEXAM")
    @Tag("F-JEXAM-R002")
    public void shouldOpenExamSessionsThatConsultWithinTheBudgetAContentTheTakingVersionNeverJudgedEvenWhenAnotherVersionJudgedIt(
            ) {
        // R002 inv. 2: a verdict of another version is never reused in the exam, so a new version is
        // really examined. v6 judged C on the course and in its exam, and D in its exam; v7 never
        // judged either. With a budget of 1, v7 is consulted on C and D waits.
        InMemoryLedger ledger = new InMemoryLedger();
        EvaluationRecord courseVerdictOfV6 =
                record(JUDGE_ID, "C", "course verdict of v6 on C", "2026-08-05T10:00:00Z", "v6");
        ledger.append(courseVerdictOfV6);
        ledger.append(record(EXAM_JUDGE_ID, "C", "exam verdict of v6 on C", "2026-09-29T10:00:00Z", "v6"));
        ledger.append(record(EXAM_JUDGE_ID, "D", "exam verdict of v6 on D", "2026-09-29T10:00:00Z", "v6"));

        CountingEvaluator v7 = new CountingEvaluator("v7");
        EvaluationSession exam =
                new ExamEvaluationSessionFactory(ledger, TEXT_FINGERPRINT).open(new EvaluationBudget(1), v7);

        List<EvaluationResolution> resolutions = exam.resolveAll(examRequests("C", "D"), 4);

        assertEquals(new EvaluationResolution(EvaluationResolutionKind.EVALUATED, "v7 verdict on C", "v7"),
                resolutions.get(0), "v7 never judged C: it is consulted although v6 judged it");
        assertEquals(EvaluationResolutionKind.PENDING, resolutions.get(1).getKind(),
                "the budget of 1 is spent: D waits instead of reusing the verdict of v6");
        assertEquals(List.of("C"), v7.consulted(), "one consultation, within the budget");

        List<EvaluationRecord> examHistoryOfC = ledger.history(new EvaluationKey(EXAM_JUDGE_ID, "fp:C"));
        assertEquals(2, examHistoryOfC.size(), "the new verdict is written in the exam space");
        assertEquals("v7 verdict on C", examHistoryOfC.get(1).getPayload());
        assertEquals("v7", examHistoryOfC.get(1).getEvaluatorVersion());
        assertEquals(List.of(courseVerdictOfV6), ledger.history(new EvaluationKey(JUDGE_ID, "fp:C")),
                "the course ledger keeps only what the course recorded");
    }
