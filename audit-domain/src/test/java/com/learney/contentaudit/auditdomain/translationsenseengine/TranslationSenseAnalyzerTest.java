    private static final class ConcurrencyProbe {
        final AtomicInteger inFlight = new AtomicInteger();
        final AtomicInteger maxInFlight = new AtomicInteger();

        void hold() {
            int now = inFlight.incrementAndGet();
            maxInFlight.accumulateAndGet(now, Math::max);
            try {
                // Stay in flight until four are, or a little while: enough for the others to pile up.
                long deadline = System.nanoTime() + TimeUnit.MILLISECONDS.toNanos(150);
                while (inFlight.get() < 4 && System.nanoTime() < deadline) {
                    Thread.sleep(2);
                }
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
            } finally {
                inFlight.decrementAndGet();
            }
        }
    }

