        QuizInstructionAnalyzer analyzer = new QuizInstructionAnalyzer(session, subjectBuilder, scorer, scopeMatcher, verdictReader, policy);
        analyzer.onQuiz(inDeclaredSet);
        analyzer.onQuiz(outsideWithVerdict);
