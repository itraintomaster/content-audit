    private static AuditNode topic(String level, String knowledgeId, String name, List<AuditableQuiz> quizzes) {
        AuditNode root = node(AuditTarget.COURSE, null, null);
        AuditNode milestone = node(AuditTarget.MILESTONE,
                new AuditableMilestone(List.of(), "m-" + level, level, level), root);
        AuditNode topic = node(AuditTarget.TOPIC, new AuditableTopic(List.of(), "t-" + knowledgeId, "Tema", "T"), milestone);
        AuditNode knowledge = node(AuditTarget.KNOWLEDGE,
                new AuditableKnowledge(quizzes, name, "Completa.", true, knowledgeId, name, "K", SentenceMode.FILL, "Tema"),
                topic);
        for (AuditableQuiz quiz : quizzes) node(AuditTarget.QUIZ, quiz, knowledge);
        return knowledge;
    }

    private static AuditNode node(AuditTarget target, AuditableEntity entity, AuditNode parent) {
        AuditNode node = new AuditNode();
        node.setTarget(target);
        node.setEntity(entity);
        node.setParent(parent);
        node.setChildren(new ArrayList<>());
        node.setScores(new LinkedHashMap<>());
        node.setMetadata(new LinkedHashMap<>());
        if (parent != null) parent.getChildren().add(node);
        return node;
    }
