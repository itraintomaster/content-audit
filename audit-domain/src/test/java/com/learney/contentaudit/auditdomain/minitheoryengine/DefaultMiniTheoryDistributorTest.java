    /** The scale of DefaultMiniTheoryConfig (audit-application), with the scope of each test. */
    private static final class Config implements MiniTheoryConfig {
        private final MiniTheoryErrorScope scope;

        Config(MiniTheoryErrorScope scope) {
            this.scope = scope;
        }

        @Override
        public MiniTheoryErrorScope getErrorScope() {
            return scope;
        }

        @Override
        public double getScoreFor(FindingSeverity severity) {
            if (severity == null) {
                return 1.0;
            }
            return switch (severity) {
                case BLOCKING, HIGH -> 0.3;
                case MEDIUM -> 0.6;
                case LOW -> 0.8;
            };
        }

        @Override
        public Map<String, Object> describe() {
            return Map.of("errorScope", scope.name());
        }
    }

    static MiniTheoryAssessment assessment(int miniTheory, boolean holds, MiniTheoryProblem problem,
            FindingSeverity severity, String counterexample, List<Integer> exercises, String explanation) {
        return new MiniTheoryAssessment(miniTheory, holds, problem, severity, counterexample, exercises, explanation);
    }

    private static AuditableQuiz cloze(String id, String before, String answer, String after, String sentence,
            String miniTheory) {
        return quiz(id, id, List.of(text(before), gap(answer), text(after)), sentence, miniTheory);
    }

    private static AuditableQuiz quiz(String id, String label, List<SentencePartEntity> parts, String sentence,
            String miniTheory) {
        return new AuditableQuiz(List.of(), id, label, "", "Traducción.", List.of(sentence), null, "Completa.", parts,
                null, miniTheory, null);
    }

    private static SentencePartEntity text(String text) {
        return new SentencePartEntity(SentencePartKind.TEXT, text, null);
    }

    private static SentencePartEntity gap(String answers) {
        return new SentencePartEntity(SentencePartKind.CLOZE, "", List.of(answers));
    }

    /** A level > topic > knowledge > exercises tree, as the engine builds it; returns the knowledge. */
    static AuditNode topic(String level, String knowledgeId, String name, String instructions,
            List<AuditableQuiz> quizzes) {
        AuditNode root = node(AuditTarget.COURSE, null, null);
        AuditNode milestone = node(AuditTarget.MILESTONE, new AuditableMilestone(List.of(), "m-" + level, level, level),
                root);
        AuditNode topic = node(AuditTarget.TOPIC, new AuditableTopic(List.of(), "t-" + knowledgeId, "Tema", "T"),
                milestone);
        AuditNode knowledge = node(AuditTarget.KNOWLEDGE, new AuditableKnowledge(quizzes, name, instructions, true,
                knowledgeId, name, "K", SentenceMode.FILL, "Tema"), topic);
        for (AuditableQuiz quiz : quizzes) {
            node(AuditTarget.QUIZ, quiz, knowledge);
        }
        return knowledge;
    }

    private static AuditNode node(AuditTarget target, AuditableEntity entity, AuditNode parent) {
        AuditNode node = new AuditNode();
        node.setTarget(target);
        node.setEntity(entity);
        node.setParent(parent);
        node.setChildren(new ArrayList<>());
        node.setScores(new LinkedHashMap<>());
        node.setMetadata(new LinkedHashMap<>());
        if (parent != null) {
            parent.getChildren().add(node);
        }
        return node;
    }

    private static List<FindingSeverity> severities(MiniTheoryQuizOutcome outcome) {
        List<FindingSeverity> severities = new ArrayList<>();
        for (FindingDraft finding : outcome.getFindings()) {
            severities.add(finding.getSeverity());
        }
        return severities;
    }

    private static List<String> rules(MiniTheoryQuizOutcome outcome) {
        List<String> rules = new ArrayList<>();
        for (FindingDraft finding : outcome.getFindings()) {
            rules.add(finding.getRule());
        }
        return rules;
    }

    private static List<String> labels(List<EvidencePart> parts) {
        List<String> labels = new ArrayList<>();
        for (EvidencePart part : parts) {
            labels.add(part.getLabel());
        }
        return labels;
    }

