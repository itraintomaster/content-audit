    /** One gap, nothing after it, and an «a / b» list holding the answer inside the closed sentence. */
    private static boolean listInsideClosedSentence(AuditableQuiz quiz) {
        List<SentencePartEntity> parts = quiz.getSentenceParts();
        int gaps = 0;
        int gap = -1;
        for (int i = 0; i < parts.size(); i++) {
            if (parts.get(i).getKind() == SentencePartKind.CLOZE) {
                gaps++;
                gap = i;
            }
        }
        if (gaps != 1 || quiz.getMultipleChoice() != null) {
            return false;
        }
        StringBuilder before = new StringBuilder();
        for (int i = 0; i < gap; i++) {
            before.append(parts.get(i).getText() != null ? parts.get(i).getText() : "").append(' ');
        }
        for (int i = gap + 1; i < parts.size(); i++) {
            if (parts.get(i).getText() != null && !parts.get(i).getText().isBlank()) {
                return false;
            }
        }
        String text = before.toString().strip();
        Matcher list = CHOICE.matcher(text);
        if (!CLOSED.matcher(text).find() || !list.find()) {
            return false;
        }
        List<String> options = parts.get(gap).getOptions();
        String first = options != null && !options.isEmpty() ? options.get(0).split("\\|")[0].strip() : "";
        for (String choice : list.group(1).split("\\s*/\\s*")) {
            if (choice.strip().equalsIgnoreCase(first)) {
                return true;
            }
        }
        return false;
    }

