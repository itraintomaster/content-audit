    /**
     * A double of the corrector's comparison (package A): case and spaces never count, and the long
     * forms «is not» and «are not» are the same answer as «isn't» and «aren't». It remembers what it
     * was asked in the context of a gap.
     */
    private static final class TableCorrectorMatcher implements CorrectorMatcher {

        private final List<List<String>> askedInContext = new ArrayList<>();

        @Override
        public Set<String> canonicalForms(String text) {
            return Set.of(canonical(text));
        }

        @Override
        public boolean accepts(GapContext context, List<String> acceptedOptions, String written) {
            for (String accepted : acceptedOptions) {
                if (sameAnswer(context, accepted, written)) {
                    return true;
                }
            }
            return false;
        }

        @Override
        public boolean sameAnswer(String first, String second) {
            return canonical(first).equals(canonical(second));
        }

        @Override
        public boolean sameAnswer(GapContext context, String first, String second) {
            askedInContext.add(List.of(context.getBefore(), context.getAfter(), first, second));
            return sameAnswer(first, second);
        }

        @Override
        public String tableVersion() {
            return "doble-de-prueba";
        }

        private static String canonical(String text) {
            String lower = text == null ? "" : text.strip().replaceAll("\\s+", " ").toLowerCase(Locale.ROOT);
            return lower.replace("isn't", "is not").replace("aren't", "are not");
        }
    }

