    @Test
    @DisplayName("should omit words justified for the level from the flags list")
    @Tag("FEAT-CLEX")
    @Tag("F-CLEX-R005")
    public void shouldOmitWordsJustifiedForTheLevelFromTheFlagsList() {
        // The scorer's lists already contain only genuine flags (F-CLEX-R005): a sentence
        // with a justified word alongside a misplaced one and an out-of-catalog one yields
        // exactly those two flagged entries, nothing more.
        MisplacedLemma misplaced = new MisplacedLemma(
                new LemmaAndPos("hail", "NOUN"), CefrLevel.C2, CefrLevel.A1,
                AbsenceType.APPEARS_TOO_EARLY, 12000, null, "VERB", 0.5);
        OutOfCatalogWord outOfCatalog = new OutOfCatalogWord("gadget", "NOUN", 6081, 0.3);
        SentenceLexicalScore score =
                new SentenceLexicalScore(0.5, List.of(misplaced), List.of(outOfCatalog));

        NlpToken catToken = new NlpToken("cat", "cat", "NOUN", 500, false, false);
        NlpToken hailToken = new NlpToken("hails", "hail", "VERB", 12000, false, false);
        NlpToken gadgetToken = new NlpToken("gadget", "gadget", "NOUN", 6081, false, false);
        List<NlpToken> tokens = List.of(catToken, hailToken, gadgetToken);
        when(sentenceLexicalScorer.score(tokens, CefrLevel.A1)).thenReturn(score);

        SentenceLexicalFlags flags = sut.evaluate(tokens, CefrLevel.A1);

        assertEquals(1, flags.getMisplacedWords().size(),
                "solo 'hail' es mal-ubicado; 'cat' esta justificada y no debe aparecer");
        assertEquals("hail", flags.getMisplacedWords().get(0).getLemma());
        assertEquals(1, flags.getOutOfCatalogWords().size(),
                "solo 'gadget' es fuera de catalogo penalizante");
        assertEquals("gadget", flags.getOutOfCatalogWords().get(0).getLemma());
    }

