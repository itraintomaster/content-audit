    @Test
    @DisplayName("should build the same content for a quiz whose translation, mini-theory or audio changed")
    @Tag("FEAT-UNICA")
    @Tag("F-UNICA-R001")
    public void shouldBuildTheSameContentForAQuizWhoseTranslationMinitheoryOrAudioChanged() {
        Sha256ContentFingerprinter fingerprinter = new Sha256ContentFingerprinter();
        List<SentencePartEntity> parts = List.of(text("Does he need water? He"), cloze("does"), text("."));
        String instructions = "Usa $short forms$ si es posible. Escribe la respuesta corta.";
        // …1f57 as it is today.
        AuditableQuiz today = quiz("67fab6d59930102295341f57", "Respuestas cortas", instructions, parts,
                "¿Necesita agua? Sí.", "Se contesta con el auxiliar, no con el verbo.", "A1.01.13.09");
        Map<String, String> base = builder().build(quizNode(today, knowledge("Respuestas cortas"))).getContent();

        List<AuditableQuiz> changedAfterAnswering = List.of(
                quiz("67fab6d59930102295341f57", "Respuestas cortas", instructions, parts,
                        "¿Él necesita agua? Sí, la necesita.", "Se contesta con el auxiliar, no con el verbo.",
                        "A1.01.13.09"),
                quiz("67fab6d59930102295341f57", "Respuestas cortas", instructions, parts,
                        "¿Necesita agua? Sí.", "Con does se contesta: Yes, he does / No, he doesn't.", "A1.01.13.09"),
                quiz("67fab6d59930102295341f57", "Respuestas cortas", instructions, parts,
                        "¿Necesita agua? Sí.", "Se contesta con el auxiliar, no con el verbo.", "A1.01.13.99"));
        for (AuditableQuiz changed : changedAfterAnswering) {
            Map<String, String> content = builder().build(quizNode(changed, knowledge("Respuestas cortas")))
                    .getContent();
            assertEquals(base, content, "what is shown after answering never enters what the judge reads");
            assertEquals(fingerprinter.fingerprint(base), fingerprinter.fingerprint(content),
                    "so the recorded verdict is reused and nothing is paid again");
        }

        // What the student sees before answering does count: other instructions are another content.
        AuditableQuiz otherInstructions = quiz("67fab6d59930102295341f57", "Respuestas cortas",
                "Escribe la respuesta corta.", parts, "¿Necesita agua? Sí.",
                "Se contesta con el auxiliar, no con el verbo.", "A1.01.13.09");
        Map<String, String> other = builder().build(quizNode(otherInstructions, knowledge("Respuestas cortas")))
                .getContent();
        assertNotEquals(fingerprinter.fingerprint(base), fingerprinter.fingerprint(other));
    }

