    // --- R007: Classify absence type ---
    private AbsenceType classifyAbsence(CefrLevel expectedLevel, List<CefrLevel> presentInLevels) {
        if (presentInLevels.isEmpty()) {
            return AbsenceType.COMPLETELY_ABSENT;
        }
        int expectedOrder = LEVEL_ORDER.get(expectedLevel);
        boolean hasEarlier = false;
        for (CefrLevel presentLevel : presentInLevels) {
            int presentOrder = LEVEL_ORDER.get(presentLevel);
            if (presentOrder < expectedOrder) {
                hasEarlier = true;
            }
        }
        // R007: If lemma appears in ANY earlier level -> TOO_EARLY (even if also in later levels)
        if (hasEarlier) {
            return AbsenceType.APPEARS_TOO_EARLY;
        } else {
            return AbsenceType.APPEARS_TOO_LATE;
        }
    }

    // --- R011-R013: Assign priority based on COCA rank ---
    private PriorityLevel assignPriority(String lemma, Optional<Integer> cocaRankOpt, CefrLevel level) {
        // Critical functional lemmas always get HIGH priority in A1/A2
        if (isCriticalFunctionalLemma(lemma.toLowerCase(), level)) {
            return PriorityLevel.HIGH;
        }
        if (!cocaRankOpt.isPresent()) {
            // R013: no COCA rank -> LOW by default
            return PriorityLevel.LOW;
        }
        int rank = cocaRankOpt.get();
        int highBound = lemmaAbsenceConfig.getHighPriorityBound();
        int mediumBound = lemmaAbsenceConfig.getMediumPriorityBound();
        int lowBound = lemmaAbsenceConfig.getLowPriorityBound();
        if (rank <= highBound) {
            return PriorityLevel.HIGH;
        } else if (rank <= mediumBound) {
            return PriorityLevel.MEDIUM;
        } else if (rank <= lowBound) {
            return PriorityLevel.LOW;
        } else {
            // rank > lowBound: not included in prioritized analysis, assign LOW
            return PriorityLevel.LOW;
        }
    }

    // --- R026: Apply report limits per priority ---
    private List<AbsentLemma> applyReportLimits(List<AbsentLemma> absentList) {
        int highLimit = lemmaAbsenceConfig.getHighReportLimit();
        int mediumLimit = lemmaAbsenceConfig.getMediumReportLimit();
        int lowLimit = lemmaAbsenceConfig.getLowReportLimit();

        List<AbsentLemma> high = new ArrayList<>();
        List<AbsentLemma> medium = new ArrayList<>();
        List<AbsentLemma> low = new ArrayList<>();

        for (AbsentLemma al : absentList) {
            switch (al.getPriorityLevel()) {
                case HIGH:
                    high.add(al);
                    break;
                case MEDIUM:
                    medium.add(al);
                    break;
                case LOW:
                    low.add(al);
                    break;
            }
        }

        List<AbsentLemma> result = new ArrayList<>();
        result.addAll(high.subList(0, Math.min(high.size(), highLimit)));
        result.addAll(medium.subList(0, Math.min(medium.size(), mediumLimit)));
        result.addAll(low.subList(0, Math.min(low.size(), lowLimit)));
        return result;
    }

