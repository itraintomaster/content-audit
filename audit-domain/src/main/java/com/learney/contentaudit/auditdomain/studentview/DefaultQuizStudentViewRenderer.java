    private static List<String> hintsOf(SentencePartEntity part) {
        List<String> hints = new ArrayList<>();
        if (part == null || part.getKind() != SentencePartKind.TEXT || part.getText() == null) {
            return hints;
        }
        Matcher matcher = HINT_PATTERN.matcher(part.getText());
        while (matcher.find()) {
            hints.add(matcher.group());
        }
        return hints;
    }

    /** Every variant of every entry, split on «|» only (a «/» is part of the answer). */
    private static List<String> acceptedAnswers(List<String> options) {
        List<String> accepted = new ArrayList<>();
        if (options == null) {
            return accepted;
        }
        for (String entry : options) {
            if (entry == null) {
                continue;
            }
            for (String variant : entry.split("\\|", -1)) {
                String trimmed = variant.strip();
                if (!trimmed.isEmpty()) {
                    accepted.add(trimmed);
                }
            }
        }
        return accepted;
    }

    /** F-QSENT-R018: the first sub-variant of the first entry. */
    private static String firstAnswer(List<String> options) {
        if (options == null || options.isEmpty() || options.get(0) == null) {
            return null;
        }
        return options.get(0).split("\\|", -1)[0].strip();
    }

