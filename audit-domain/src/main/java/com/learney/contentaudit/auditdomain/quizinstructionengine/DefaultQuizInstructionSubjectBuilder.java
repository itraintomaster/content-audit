    /** The single place the content is assembled, for both paths. */
    private Map<String, String> content(String cefrLevel, String topic, AuditableQuiz quiz) {
        QuizStudentView view = studentViewRenderer.render(quiz);

        Map<String, String> content = new LinkedHashMap<>();
        content.put(CEFR_LEVEL, orEmpty(cefrLevel));
        content.put(TOPIC, orEmpty(topic));
        content.put(TITLE, orEmpty(quiz.getLabel()));
        content.put(INSTRUCTIONS, orEmpty(quiz.getInstructions()));
        content.put(EXERCISE, orEmpty(view != null ? view.getStatement() : null));
        content.put(ACCEPTED_ANSWERS, acceptedAnswers(view != null ? view.getGaps() : null));
        content.put(OPTIONS, options(view != null ? view.getOptions() : null));
        return content;
    }

    /** One line per gap, in the order of the statement, numbered from 1. */
    private static String acceptedAnswers(List<StudentGapView> gaps) {
        if (gaps == null) {
            return "";
        }
        List<String> lines = new ArrayList<>();
        for (int i = 0; i < gaps.size(); i++) {
            StudentGapView gap = gaps.get(i);
            List<String> accepted = gap != null && gap.getAcceptedAnswers() != null
                    ? gap.getAcceptedAnswers()
                    : List.of();
            lines.add("Hueco " + (i + 1) + ": " + String.join(" | ", accepted));
        }
        return String.join("\n", lines);
    }

    /** One line per option, in the student's order, the correct one marked; empty without options. */
    private static String options(List<StudentOptionView> options) {
        if (options == null || options.isEmpty()) {
            return "";
        }
        List<String> lines = new ArrayList<>();
        for (StudentOptionView option : options) {
            if (option == null) {
                continue;
            }
            lines.add("- " + orEmpty(option.getLabel()) + (option.isCorrect() ? CORRECT_SUFFIX : ""));
        }
        return String.join("\n", lines);
    }

    private static String orEmpty(String value) {
        return value != null ? value : "";
    }
