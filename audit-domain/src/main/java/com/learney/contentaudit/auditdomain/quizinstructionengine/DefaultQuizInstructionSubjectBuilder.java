class DefaultQuizInstructionSubjectBuilder implements QuizInstructionSubjectBuilder {
    @Override
    public EvaluationSubject build(AuditNode quizNode) {
        AuditableQuiz quiz = (AuditableQuiz) quizNode.getEntity();

        // R009: the knowledge is the canonical source for the label and the
        // instructions -- never the quiz's own desynchronized copies -- and the
        // milestone is the canonical source for the CEFR level. The quiz
        // identifier deliberately never enters this map: identity is content,
        // not element (R009), and the fingerprint is computed over exactly this
        // content map (see Sha256ContentFingerprinter).
        AuditableKnowledge knowledge = (AuditableKnowledge) quizNode.ancestor(AuditTarget.KNOWLEDGE)
                .map(AuditNode::getEntity)
                .orElse(null);
        AuditableMilestone milestone = (AuditableMilestone) quizNode.ancestor(AuditTarget.MILESTONE)
                .map(AuditNode::getEntity)
                .orElse(null);

        Map<String, String> content = new LinkedHashMap<>();
        content.put("cefrLevel", milestone != null ? milestone.getLabel() : null);
        content.put("topic", knowledge != null ? knowledge.getTopicName() : null);
        content.put("title", knowledge != null ? knowledge.getLabel() : null);
        content.put("instructions", knowledge != null ? knowledge.getInstructions() : null);
        content.put("quiz", serializeQuiz(quiz));

        return new EvaluationSubject(quiz.getId(), content);
    }

    /**
     * Serializes the whole quiz -- every part, in order, with every accepted
     * option of every cloze -- into a single deterministic string: the same
     * parts, in the same order, always produce the same string, which is what
     * lets a reprocessed course reuse a verdict (R009) instead of always
     * missing the cache.
     */
    private static String serializeQuiz(AuditableQuiz quiz) {
        StringBuilder builder = new StringBuilder();
        List<SentencePartEntity> parts = quiz.getSentenceParts();
        if (parts != null) {
            for (SentencePartEntity part : parts) {
                builder.append(part.getKind())
                        .append(':')
                        .append(part.getText())
                        .append(':');
                if (part.getOptions() != null) {
                    builder.append(String.join(",", part.getOptions()));
                }
                builder.append('|');
            }
        }
        return builder.toString();
    }
}
