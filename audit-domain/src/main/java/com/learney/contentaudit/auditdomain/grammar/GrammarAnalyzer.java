    /**
     * Every finished sentence through both variants, the filter, the classifier and the final sign.
     * A problem two sentences show is one, the more severe if they differ.
     */
    private List<GrammarIssue> issuesOf(AuditableQuiz quiz, List<FinishedSentence> sentences) {
        Map<String, GrammarIssue> found = new LinkedHashMap<>();
        for (FinishedSentence sentence : sentences) {
            List<GrammarMatch> american = grammarChecker.check(sentence.getText(), EnglishVariant.AMERICAN);
            List<GrammarMatch> british = grammarChecker.check(sentence.getText(), EnglishVariant.BRITISH);
            List<GrammarMatch> kept = matchFilter.keep(american, british);
            Optional<GrammarIssue> sign = finalPunctuation.check(sentence, quiz.getTokens());
            for (GrammarMatch match : kept) {
                if (sign.isPresent() && match.getRuleId() != null && FINAL_SIGN_RULES.contains(match.getRuleId())) {
                    continue;
                }
                keep(found, issueClassifier.classify(match, sentence));
            }
            sign.ifPresent(issue -> keep(found, issue));
        }
        return new ArrayList<>(found.values());
    }

    private static void keep(Map<String, GrammarIssue> found, GrammarIssue issue) {
        String key = issue.getRule() + "|" + markerOf(issue);
        GrammarIssue earlier = found.get(key);
        if (earlier == null || moreSevere(issue, earlier)) {
            found.put(key, issue);
        }
    }

    private static boolean moreSevere(GrammarIssue issue, GrammarIssue than) {
        return issue.getSeverity() != null && than.getSeverity() != null
                && issue.getSeverity().ordinal() < than.getSeverity().ordinal();
    }

    /** The identity of a problem: the rule of LanguageTool and what it marked; empty for the sign. */
    static String markerOf(GrammarIssue issue) {
        if (issue.getToolRule() == null || issue.getToolRule().isBlank()) {
            return "";
        }
        return issue.getToolRule() + "|" + (issue.getMarked() != null ? issue.getMarked() : "");
    }

    /** A rewrite topic reads only the answer as the sentence (F-GRAMA-R001 inv. 2). */
