    static List<AuditNode> exercisesOf(AuditNode knowledgeNode) {
        List<AuditNode> exercises = new ArrayList<>();
        if (knowledgeNode == null || knowledgeNode.getChildren() == null) {
            return exercises;
        }
        for (AuditNode child : knowledgeNode.getChildren()) {
            if (child != null && child.getTarget() == AuditTarget.QUIZ
                    && child.getEntity() instanceof AuditableQuiz) {
                exercises.add(child);
            }
        }
        return exercises;
    }

