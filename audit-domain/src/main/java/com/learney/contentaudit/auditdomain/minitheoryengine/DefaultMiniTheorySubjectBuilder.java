    private String quizLines(List<AuditNode> exercises) {
        List<String> entries = new ArrayList<>();
        for (AuditNode exercise : exercises) {
            AuditableQuiz quiz = (AuditableQuiz) exercise.getEntity();
            QuizStudentView view = studentViewRenderer.render(quiz);
            entries.add("quizId: " + orEmpty(quiz.getId())
                    + "\nminiTheory: " + orEmpty(quiz.getMiniTheory())
                    + "\nprompt: " + orEmpty(view != null ? view.getStatement() : null)
                    + "\nanswers: " + answers(quiz, view));
        }
        return String.join("\n\n", entries);
    }

    /** «see | sees · go» for a cloze; «opciones: in, on (correcta)» for a multiple choice. */
    private static String answers(AuditableQuiz quiz, QuizStudentView view) {
        if (view == null) {
            return "";
        }
        if (quiz.getMultipleChoice() != null) {
            List<String> options = new ArrayList<>();
            if (view.getOptions() != null) {
                for (StudentOptionView option : view.getOptions()) {
                    if (option == null) {
                        continue;
                    }
                    options.add(orEmpty(option.getLabel()) + (option.isCorrect() ? " (correcta)" : ""));
                }
            }
            return "opciones: " + String.join(", ", options);
        }
        List<String> gaps = new ArrayList<>();
        if (view.getGaps() != null) {
            for (StudentGapView gap : view.getGaps()) {
                if (gap == null) {
                    continue;
                }
                List<String> accepted = gap.getAcceptedAnswers() != null ? gap.getAcceptedAnswers() : List.of();
                gaps.add(String.join(" | ", accepted));
            }
        }
        return String.join(" · ", gaps);
    }

    private static String orEmpty(String value) {
        return value != null ? value : "";
    }
