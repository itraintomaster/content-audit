    private void traverseAndNotify(AuditNode root, RunningAnalyzer ra) {
        ContentAnalyzer analyzer = ra.analyzer();
        for (AuditNode milestone : root.getChildren()) {
            invokeCallback(ra, milestone, () -> analyzer.onMilestone(milestone));
            for (AuditNode topic : milestone.getChildren()) {
                invokeCallback(ra, topic, () -> analyzer.onTopic(topic));
                for (AuditNode knowledge : topic.getChildren()) {
                    invokeCallback(ra, knowledge, () -> analyzer.onKnowledge(knowledge));
                    for (AuditNode quiz : knowledge.getChildren()) {
                        invokeCallback(ra, quiz, () -> analyzer.onQuiz(quiz));
                    }
                }
            }
        }
    }

    /**
     * F-QINST-R007, generalized: a failure of an analyzer that consults a model is isolated
     * to the node where it happened, which stays without that analyzer's score and is
     * declared not evaluated by it (F-HALL-R008). A failure of an instant analyzer is a bug
     * and propagates, as before the contract.
     */
    private void invokeCallback(RunningAnalyzer ra, AuditNode node, Runnable callback) {
        if (!ra.isolatesFailures()) {
            callback.run();
            return;
        }
        try {
            callback.run();
        } catch (RuntimeException e) {
            String name = ra.card().getName();
            if (node.getScores() != null) {
                node.getScores().remove(name);
            }
            if (node.getUnevaluatedBy() == null) {
                node.setUnevaluatedBy(new ArrayList<>());
            }
            if (!node.getUnevaluatedBy().contains(name)) {
                node.getUnevaluatedBy().add(name);
            }
        }
    }

    private void completeCourse(AuditNode root, RunningAnalyzer ra) {
        if (!ra.isolatesFailures()) {
            ra.analyzer().onCourseComplete(root);
            return;
        }
        try {
            ra.analyzer().onCourseComplete(root);
        } catch (RuntimeException e) {
            // F-QINST-R007: closing the course of a model-backed analyzer must not abort the
            // audit -- what the other analyzers left on the tree stays intact.
        }
    }

