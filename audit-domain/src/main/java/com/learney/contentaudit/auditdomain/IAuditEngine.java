    /**
     * F-HALL-R012: runs exactly the analyzers of the selection. Every analyzer is built by its
     * provider before the tree is touched, so an unknown name or a policy its provider rejects
     * stops the run before it starts. Then each one, in catalog order, walks the tree, closes
     * the course and hands its findings to the collector while the only scores on the tree are
     * its own; the tree is aggregated once, with the judges included (F-HALL-R011), and the
     * numbers of every node are published last (F-HALL-R010).
     */
    @Override
    public AuditReport runAudit(AuditableCourse auditableCourse, AnalyzerRunSelection selection) {
        List<String> requested = selection != null && selection.getAnalyzers() != null
                ? selection.getAnalyzers()
                : baseSelection();
        Map<String, EvaluationRunPolicy> policies = selection != null && selection.getPolicies() != null
                ? selection.getPolicies()
                : Map.of();

        // Step 1: every name has to be in the catalog -- the run is rejected before anything
        // is built or touched (F-HALL-R005/R012).
        for (String name : requested) {
            if (analyzerCatalog.find(name).isEmpty()) {
                throw new UnknownAnalyzerException(name);
            }
        }
        for (String name : policies.keySet()) {
            if (analyzerCatalog.find(name).isEmpty()) {
                throw new UnknownAnalyzerException(name);
            }
        }

        // Step 2: fresh analyzers for this run, in catalog order (F-HALL-R014: no state is
        // carried over from an earlier run in the same process).
        Set<String> requestedNames = new HashSet<>(requested);
        List<RunningAnalyzer> running = new ArrayList<>();
        for (AnalyzerDescriptor card : analyzerCatalog.list()) {
            if (!requestedNames.contains(card.getName())) {
                continue;
            }
            AnalyzerProvider provider = analyzerCatalog.provider(card.getName())
                    .orElseThrow(() -> new UnknownAnalyzerException(card.getName()));
            ContentAnalyzer analyzer = provider.create(policies.get(card.getName()));
            running.add(new RunningAnalyzer(card, analyzer));
        }

        // Step 3: build the AuditNode tree from the course hierarchy
        AuditNode root = buildTree(auditableCourse);

        // Step 4: each analyzer walks the tree, closes the course and leaves its findings,
        // before any aggregation (F-HALL-R001 inv. 2).
        List<AnalyzerDescriptor> ranCards = new ArrayList<>();
        for (RunningAnalyzer ra : running) {
            traverseAndNotify(root, ra);
            completeCourse(root, ra);
            findingCollector.collect(root, ra.analyzer(), ra.card());
            ranCards.add(ra.card());
        }

        // Step 5: one aggregation for everything that ran, judges included (F-HALL-R011)
        scoreAggregator.aggregate(root);

        // Step 6: the numbers of every node, published once (F-HALL-R008 to R010)
        contextNumbersCalculator.compute(root, ranCards);

        return new AuditReport(root);
    }

