    @Override
    public List<FindingDraft> findingsAt(AuditNode node) {
        if (node == null || node.getTarget() != AuditTarget.QUIZ
                || !(node.getEntity() instanceof AuditableQuiz quiz)
                || !(node.getDiagnoses() instanceof DefaultQuizDiagnoses diagnoses)) {
            return List.of();
        }
        Optional<MultipleChoiceValidityDiagnosis> found = diagnoses.getMultipleChoiceValidityDiagnosis();
        if (found.isEmpty()) {
            return List.of();
        }
        MultipleChoiceValidityDiagnosis diagnosis = found.get();
        List<OptionIssue> issues = diagnosis.getIssues() != null ? diagnosis.getIssues() : List.of();
        String statement = studentViewRenderer.render(quiz).getStatement();
        String options = options(quiz);
        List<FindingDraft> drafts = new ArrayList<>();
        Set<String> markers = new LinkedHashSet<>();

        for (OptionIssue issue : issues) {
            switch (issue.getKind()) {
                case NO_VALID_OPTION -> drafts.add(draft(issue.getRule(), "ninguna", FindingSeverity.BLOCKING,
                        FindingResolution.PANEL, statement, options, null,
                        issue.getOption() == null
                                ? "Ninguna opción vale: eligiendo una sola, el alumno nunca llega al puntaje entero."
                                : "«" + issue.getOption() + "» vale menos que el puntaje entero: eligiéndola, el alumno"
                                        + " nunca acierta.",
                        markers));
                case SEVERAL_VALID_OPTIONS -> drafts.add(draft(issue.getRule(), issue.getOption(),
                        FindingSeverity.BLOCKING, FindingResolution.PANEL, statement, options,
                        new EvidencePart("Valen", issue.getRelatedOption() + " · " + issue.getOption()),
                        "Valen «" + issue.getRelatedOption() + "» y «" + issue.getOption() + "»: con una sola"
                                + " selección el alumno nunca llega al puntaje entero. La mesa deja una sola correcta.",
                        markers));
                case IDENTICAL_OPTIONS, SAME_ANSWER_OTHER_FORM -> drafts.add(twins(issue, statement, options, markers));
                case ARTICLE_GIVES_AWAY -> drafts.add(draft(issue.getRule(), issue.getOption(),
                        FindingSeverity.MEDIUM, FindingResolution.PANEL, statement, options,
                        new EvidencePart("Artículo", issue.getRelatedOption()),
                        "Después de «" + issue.getRelatedOption() + "» no encaja «" + issue.getOption()
                                + "»: el artículo delata cuál es la correcta. Se rearma en la mesa.",
                        markers));
                default -> {
                    // R003 goes below, one finding per kind for all the options at once.
                }
            }
        }
        capitalFindings(issues, statement, options, drafts, markers);

        ChoiceAlternativeJudgment judgment = diagnosis.getJudgment();
        if (judgment != null && judgment.getStatus() == ChoiceAlternativeJudgmentStatus.JUDGED
                && judgment.getFindings() != null) {
            for (FindingDraft judged : judgment.getFindings()) {
                if (judged != null) {
                    drafts.add(judged); // F-MCVALE-R004: the judge's findings, as it emits them
                }
            }
        }
        return drafts;
    }

    /** R002: blocking if they look identical and one is correct; high if only the form differs; low if both are incorrect. */
    private static FindingDraft twins(OptionIssue issue, String statement, String options, Set<String> markers) {
        boolean identical = issue.getKind() == OptionIssueKind.IDENTICAL_OPTIONS;
        FindingSeverity severity = !issue.isInvolvesCorrect() ? FindingSeverity.LOW
                : identical ? FindingSeverity.BLOCKING : FindingSeverity.HIGH;
        String why;
        if (!issue.isInvolvesCorrect()) {
            why = "las dos son incorrectas: sobra una.";
        } else if (identical) {
            why = "una es la correcta y se ven idénticas: el alumno no puede distinguirlas.";
        } else {
            why = "una es la correcta y la otra sólo cambia en la forma: marca mal a quien eligió la otra.";
        }
        return draft(issue.getRule(), issue.getOption(), severity, FindingResolution.PANEL, statement, options,
                new EvidencePart("La misma respuesta", issue.getRelatedOption() + " · " + issue.getOption()),
                "«" + issue.getRelatedOption() + "» y «" + issue.getOption() + "» son la misma respuesta para el"
                        + " corrector; " + why + " La mesa rearma el ejercicio con una sola correcta.",
                markers);
    }

    /**
     * R003: the capital of the options that open the sentence (low if they all share their case,
     * medium if only some do), the lowercase «i» -- both fixed by one rule over all the options at
     * once -- and the dash at the start, which goes to the panel.
     */
    private static void capitalFindings(List<OptionIssue> issues, String statement, String options,
            List<FindingDraft> drafts, Set<String> markers) {
        List<String> lowercase = optionsOf(issues, OptionIssueKind.LOWERCASE_SENTENCE_START);
        if (!lowercase.isEmpty()) {
            boolean mixed = lettersStartingUppercase(options);
            drafts.add(draft(DefaultOptionRuleCheck.RULE_CAPITAL, "mayuscula",
                    mixed ? FindingSeverity.MEDIUM : FindingSeverity.LOW, FindingResolution.RULE, statement, options,
                    new EvidencePart("En minúscula", String.join(" · ", lowercase)),
                    "El hueco abre la oración y " + (mixed ? "unas opciones van en mayúscula y otras no: la forma"
                            + " delata la respuesta." : "las opciones van en minúscula.")
                            + " Se pasan todas a mayúscula a la vez, nunca una sola.",
                    markers));
        }
        List<String> lowercaseI = optionsOf(issues, OptionIssueKind.LOWERCASE_I);
        if (!lowercaseI.isEmpty()) {
            drafts.add(draft(DefaultOptionRuleCheck.RULE_CAPITAL, "i", FindingSeverity.LOW, FindingResolution.RULE,
                    statement, options, new EvidencePart("Con «i» en minúscula", String.join(" · ", lowercaseI)),
                    "El pronombre «I» va en minúscula: se escribe «I» en todas las opciones a la vez.", markers));
        }
        List<String> dashes = optionsOf(issues, OptionIssueKind.DASH_AT_SENTENCE_START);
        if (!dashes.isEmpty()) {
            drafts.add(draft(DefaultOptionRuleCheck.RULE_CAPITAL, "guion", FindingSeverity.LOW,
                    FindingResolution.PANEL, statement, options,
                    new EvidencePart("Guion", String.join(" · ", dashes)),
                    "El hueco abre la oración y una opción es el guion de no poner nada: con él la oración empieza en"
                            + " minúscula. Se rearma en la mesa.",
                    markers));
        }
    }

    private static List<String> optionsOf(List<OptionIssue> issues, OptionIssueKind kind) {
        return issues.stream().filter(i -> i.getKind() == kind).map(OptionIssue::getOption)
                .collect(Collectors.toList());
    }

    /** Whether some option opens with a capital: then the lowercase ones are a mix that gives the answer away. */
    private static boolean lettersStartingUppercase(String options) {
        for (String option : options.split(" · ")) {
            String text = option.strip();
            for (int i = 0; i < text.length(); i++) {
                if (Character.isLetter(text.charAt(i))) {
                    if (Character.isUpperCase(text.charAt(i))) {
                        return true;
                    }
                    break;
                }
            }
        }
        return false;
    }

    private static FindingDraft draft(String rule, String marker, FindingSeverity severity,
            FindingResolution resolution, String statement, String options, EvidencePart extra, String observation,
            Set<String> markers) {
        List<EvidencePart> examined = new ArrayList<>();
        examined.add(new EvidencePart("Ejercicio", statement));
        examined.add(new EvidencePart("Opciones", options));
        if (extra != null) {
            examined.add(extra);
        }
        // F-HALL-R014: rule + exercise + the option it marks; the same mark twice in one rule
        // (two pairs of twins on the same option) gets its number.
        String unique = marker;
        for (int n = 2; !markers.add(rule + "|" + unique); n++) {
            unique = marker + " (" + n + ")";
        }
        return new FindingDraft(rule, unique, severity, resolution,
                new FindingEvidence(examined, statement + " → " + observation, List.of()));
    }

    /** The options as the student sees them, the correct one with an asterisk. */
    private static String options(AuditableQuiz quiz) {
        List<String> labels = new ArrayList<>();
        if (quiz.getMultipleChoice() != null && quiz.getMultipleChoice().getItems() != null) {
            for (MultipleChoiceItemEntity item : quiz.getMultipleChoice().getItems()) {
                if (item != null) {
                    String label = item.getLabel() == null || item.getLabel().isBlank() ? "(vacía)" : item.getLabel();
                    labels.add(item.getIncidence() > 0.0 ? "*" + label : label);
                }
            }
        }
        return labels.isEmpty() ? "(sin opciones)" : String.join(" · ", labels);
    }
