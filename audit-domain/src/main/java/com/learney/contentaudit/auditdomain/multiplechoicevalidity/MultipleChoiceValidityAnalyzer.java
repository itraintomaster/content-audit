    /** The judgment of an exercise; a judge that does not answer leaves it not available. */
    private ChoiceAlternativeJudgment judgmentOf(AuditNode node) {
        ChoiceAlternativeJudgment judgment = null;
        if (judgeRun != null) {
            try {
                judgment = judgeRun.judgmentOf(node);
            } catch (RuntimeException e) {
                judgment = notJudged(node, ChoiceAlternativeJudgmentStatus.FAILED, NOT_JUDGED + ": " + e.getMessage());
            }
        }
        if (judgment == null || judgment.getStatus() == null) {
            judgment = notJudged(node, ChoiceAlternativeJudgmentStatus.NOT_AVAILABLE, NOT_JUDGED);
        }
        return judgment;
    }

