    static final String DESCRIPTION =
            "Compara la pista de cada ejercicio de hueco para escribir con su primera respuesta";

    /** R001: an exercise without hint in a topic where three quarters of its shape carry one. */
    static final String RULE_MISSING_HINT = "missing-hint";

    /** R002: the words of the hint are in the answer, and the answer brings no verb unannounced. */
    static final String RULE_HINT_WORDS = "hint-words";

    /** R003: the subject of the hint is the one of the answer, and none goes unannounced. */
    static final String RULE_HINT_SUBJECT = "hint-subject";

    /** R004: «not» in the hint only if the answer is negative. */
    static final String RULE_HINT_NEGATION = "hint-negation";

    /** R006: the rewrite asks for no word that the sentence it rewrites, the hint or the instructions do not bring. */
    static final String RULE_REWRITE_WORDS = "rewrite-words";

    /** R007: the hint does not give the answer away when the student still has something to decide. */
    static final String RULE_HINT_GIVEAWAY = "hint-giveaway";

