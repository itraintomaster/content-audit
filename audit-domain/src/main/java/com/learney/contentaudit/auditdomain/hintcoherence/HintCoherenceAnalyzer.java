    @Override
    public List<FindingDraft> findingsAt(AuditNode node) {
        if (node == null || node.getTarget() != AuditTarget.QUIZ
                || !(node.getEntity() instanceof AuditableQuiz quiz)
                || !(node.getDiagnoses() instanceof DefaultQuizDiagnoses diagnoses)) {
            return List.of();
        }
        Optional<HintCoherenceDiagnosis> found = diagnoses.getHintCoherenceDiagnosis();
        if (found.isEmpty() || found.get().getIssues() == null) {
            return List.of();
        }
        HintCoherenceDiagnosis diagnosis = found.get();
        String statement = studentViewRenderer.render(quiz).getStatement();
        List<FindingDraft> drafts = new ArrayList<>();
        for (HintIssue issue : diagnosis.getIssues()) {
            List<EvidencePart> examined = new ArrayList<>();
            examined.add(new EvidencePart("Ejercicio", statement));
            examined.add(new EvidencePart("Respuesta", diagnosis.getFirstAnswer()));
            if (diagnosis.getHint() != null) {
                examined.add(new EvidencePart("Pista", diagnosis.getHint()));
            }
            if (issue.getKind() == HintIssueKind.MISSING_HINT) {
                for (String example : hintedExamples(node, diagnosis.getShape(), byTopic(node, diagnosis), 3)) {
                    examined.add(new EvidencePart("Con pista en el tema", example));
                }
            }
            if (issue.getProposedHint() != null) {
                examined.add(new EvidencePart(issue.getResolution() == FindingResolution.PANEL
                        ? "Pista que sale de la respuesta" : "Pista propuesta", issue.getProposedHint()));
            }
            String observation = statement + " → " + diagnosis.getFirstAnswer() + ": "
                    + fault(issue, diagnosis, byTopic(node, diagnosis)) + howItIsFixed(issue);
            String marker = issue.getWord() == null || issue.getWord().isBlank()
                    ? null : issue.getWord().toLowerCase(Locale.ROOT);
            drafts.add(new FindingDraft(issue.getRule(), marker, severityOf(issue.getKind()),
                    issue.getResolution(), new FindingEvidence(examined, observation, List.of())));
        }
        return drafts;
    }

    /**
     * Where the finding goes: the panel when a rule cannot tell what to fix, or has no hint to write because the only
     * one that comes out of the answer would give it away; and otherwise the hint, completed or in base form.
     */
    private static String howItIsFixed(HintIssue issue) {
        boolean panel = issue.getResolution() == FindingResolution.PANEL;
        if (issue.getKind() == HintIssueKind.REWRITE_WORD_NOT_ANNOUNCED) {
            return ". Va a la mesa: quien reescribe fiel da mal";
        }
        if (issue.getKind() == HintIssueKind.LETTER_HINT) {
            return ". Va a la mesa: unas letras no tienen forma base, y el alumno tiene que poder elegir";
        }
        if (issue.getKind() == HintIssueKind.HINT_GIVEAWAY) {
            return panel
                    ? ". Va a la mesa: no se conjuga, y sacar la pista dejaría sin pista un tema que la lleva"
                    : ". Se arregla con el verbo en forma base; la respuesta y su audio no cambian";
        }
        if (panel && issue.getProposedHint() == null) {
            return ". Va a la mesa: la única pista que sale de la respuesta es la respuesta misma";
        }
        return panel
                ? ". Va a la mesa: arreglar la pista cambiaría lo que pide el ejercicio"
                : ". Se arregla completando la pista; la respuesta y su audio no cambian";
    }

    /**
     * R001, R007 and R008 are high: the exercise does not become impossible, it stops teaching (F-HALL-R002); a hint that does not
     * match its answer makes the exercise impossible.
     */
    static FindingSeverity severityOf(HintIssueKind kind) {
        return kind == HintIssueKind.MISSING_HINT || kind == HintIssueKind.HINT_GIVEAWAY
                || kind == HintIssueKind.LETTER_HINT
                ? FindingSeverity.HIGH
                : FindingSeverity.BLOCKING;
    }

    /** Whether the missing hint of this exercise was asked by the whole topic and not by its shape. */
    private boolean byTopic(AuditNode quizNode, HintCoherenceDiagnosis diagnosis) {
        Topic topic = topics.get(quizNode.getParent());
        return topic != null && diagnosis.getShape() != null && !topic.asksForHintInShape(diagnosis.getShape())
                && topic.asksForHintInTopic();
    }

    /** The line that names the fault: «el sujeto I no es you». */
    private static String fault(HintIssue issue, HintCoherenceDiagnosis diagnosis, boolean byTopic) {
        String word = issue.getWord();
        return switch (issue.getKind()) {
            case MISSING_HINT -> "no lleva pista y " + diagnosis.getHintedInTopic() + " de "
                    + diagnosis.getComparableInTopic() + " ejercicios del tema" + (byTopic ? "" : ", del mismo tipo,")
                    + " la llevan";
            case HINT_WORD_ABSENT -> "«" + word + "» de la pista no está en la respuesta";
            case VERB_NOT_ANNOUNCED -> "el verbo " + word + " de la respuesta no está en la pista";
            case SUBJECT_MISMATCH -> "el sujeto " + word + " no es " + answerSubject(diagnosis.getFirstAnswer());
            case SUBJECT_NOT_ANNOUNCED -> "el sujeto " + word + " no lo nombran ni la pista ni el enunciado";
            case NEGATION_WITHOUT_NEGATIVE -> "la pista lleva not y la respuesta no niega";
            case REWRITE_WORD_NOT_ANNOUNCED -> "«" + word + "» no sale de la oración de partida, la pista ni la consigna";
            case HINT_GIVEAWAY -> "la pista «" + word + "» es la respuesta: el alumno sólo la copia";
            case LETTER_HINT -> "la pista «" + word + "» da las primeras letras de la respuesta: el alumno no elige, completa";
        };
    }

    private static final Set<String> SUBJECTS = Set.of("i", "you", "he", "she", "it", "we", "they", "this",
            "that", "these", "those");

    private static String answerSubject(String answer) {
        for (String word : DefaultHintReader.words(answer)) {
            if (SUBJECTS.contains(word.toLowerCase(Locale.ROOT))) {
                return word;
            }
        }
        return "el de la respuesta";
    }

    /**
     * Up to n exercises of the topic that do carry a hint, as the student sees them: of the same
     * shape, or of any shape when the whole topic is the one that asks for the hint.
     */
    private List<String> hintedExamples(AuditNode quizNode, ExerciseShape shape, boolean byTopic, int n) {
        Topic topic = topics.get(quizNode.getParent());
        List<String> examples = new ArrayList<>();
        if (topic == null || shape == null) {
            return examples;
        }
        List<AuditableQuiz> hinted = new ArrayList<>(topic.hinted.getOrDefault(shape, List.of()));
        if (byTopic) {
            for (ExerciseShape other : ExerciseShape.values()) {
                if (other != shape) {
                    hinted.addAll(topic.hinted.getOrDefault(other, List.of()));
                }
            }
        }
        for (AuditableQuiz sibling : hinted) {
            if (examples.size() >= n) {
                break;
            }
            examples.add(studentViewRenderer.render(sibling).getStatement());
        }
        return examples;
    }
