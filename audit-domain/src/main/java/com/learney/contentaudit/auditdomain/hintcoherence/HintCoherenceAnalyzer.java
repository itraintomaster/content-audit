/**
 * FEAT-PISTA: does the hint announce to the student what to write? An errors analyzer
 * (F-PISTA-R005) over the write-in exercises; the multiple choice does not enter: its options
 * already say what to choose (R001).
 *
 * <ul>
 *   <li>R001: in {@link #onKnowledge}, which the engine calls before the exercises of the topic,
 *       it counts how many exercises of each shape carry a hint, and how many of the whole topic;
 *       an exercise without one has a high finding when three quarters or more carry it in its
 *       shape, or in the whole topic (DOUBT-PISTA-UMBRAL, José 30/9; the union of the 1/10). The
 *       shape keeps a topic with few hints of one shape from marking the other, as the 20
 *       transformations of El posesivo; the whole topic catches the few gaps without hint of a
 *       topic of transformations that all carry one, as «We ___ eat eggs every morning.».</li>
 *   <li>R002 to R004: the hint against the first answer, by {@link HintAnswerCheck}: a blocking
 *       finding per word, subject or «not» that does not match.</li>
 *   <li>R006: where the answer is the whole sentence, the words of the rewrite that come neither from
 *       the sentence it rewrites nor from the hint or the instructions, also by {@link HintAnswerCheck}:
 *       a blocking finding per word, at the panel.</li>
 *   <li>R007: the hint of each gap that says what the answers of that gap say and leaves nothing to decide
 *       (no verb, or one already conjugated), also by {@link HintAnswerCheck}: a high finding, marked with the
 *       hint; fixed by rule with the verb in base form, or at the panel when what gives the answer away does
 *       not conjugate.</li>
 *   <li>R008: the hint of a gap that is the first letters of one of its answers, «(o...)» for «of», also by
 *       {@link HintAnswerCheck}: a high finding, marked with the hint, at the panel.</li>
 * </ul>
 *
 * An exercise with a finding scores 0, one without any scores 1. The evidence is the exercise as
 * the student sees it, its answer and the line that names the fault (F-HALL-R003); the identity
 * is the rule and the word (F-HALL-R014).
 */
