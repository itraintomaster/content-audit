    /** The shape and the hint of a write-in exercise. */
    private record Reading(ExerciseShape shape, Optional<ExerciseHint> hint) {
    }

    /** The exercises of a topic and, by shape, how many there are and which carry a hint. */
    private static final class Topic {
        final Map<AuditNode, Reading> readings = new IdentityHashMap<>();
        final Map<ExerciseShape, Integer> comparable = new EnumMap<>(ExerciseShape.class);
        final Map<ExerciseShape, List<AuditableQuiz>> hinted = new EnumMap<>(ExerciseShape.class);

        int comparable(ExerciseShape shape) {
            return comparable.getOrDefault(shape, 0);
        }

        int hinted(ExerciseShape shape) {
            return hinted.getOrDefault(shape, List.of()).size();
        }

        int comparableInTopic() {
            return comparable.values().stream().mapToInt(Integer::intValue).sum();
        }

        int hintedInTopic() {
            return hinted.values().stream().mapToInt(List::size).sum();
        }

        /** Three quarters or more of the exercises of this shape carry a hint; exactly three quarters reach. */
        boolean asksForHintInShape(ExerciseShape shape) {
            return reaches(hinted(shape), comparable(shape));
        }

        /** Three quarters or more of the write-in exercises of the whole topic carry a hint. */
        boolean asksForHintInTopic() {
            return reaches(hintedInTopic(), comparableInTopic());
        }

        /** R001: the shape or the whole topic asks for a hint. */
        boolean asksForHint(ExerciseShape shape) {
            return asksForHintInShape(shape) || asksForHintInTopic();
        }

        private static boolean reaches(int hinted, int all) {
            return all > 0 && hinted * 4 >= all * 3;
        }
    }

    @Override
    public Void onKnowledge(AuditNode node) {
        if (node == null || !(node.getEntity() instanceof AuditableKnowledge knowledge) || node.getChildren() == null) {
            return null;
        }
        SentenceMode mode = knowledge.getSentenceMode();
        Topic topic = new Topic();
        for (AuditNode child : node.getChildren()) {
            if (!(child.getEntity() instanceof AuditableQuiz quiz) || quiz.getMultipleChoice() != null) {
                continue; // R001: the multiple choice is neither counted nor marked
            }
            ExerciseShape shape = hintReader.shapeOf(quiz, mode);
            Optional<ExerciseHint> hint = hintReader.read(quiz, mode);
            topic.readings.put(child, new Reading(shape, hint));
            topic.comparable.merge(shape, 1, Integer::sum);
            if (hint.isPresent()) {
                topic.hinted.computeIfAbsent(shape, s -> new ArrayList<>()).add(quiz);
            }
        }
        topics.put(node, topic);
        return null;
    }

    @Override
    public Void onQuiz(AuditNode node) {
        if (node == null || !(node.getEntity() instanceof AuditableQuiz quiz)) {
            return null;
        }
        Topic topic = topics.get(node.getParent());
        Reading reading = topic != null ? topic.readings.get(node) : null;
        if (reading == null) {
            return null; // a multiple choice: not reached by this analyzer
        }
        List<HintIssue> issues;
        if (reading.hint().isPresent()) {
            // R007 joins R002 to R004: the hint of each gap against the answers of that same gap.
            List<HintIssue> withHint = new ArrayList<>(answerCheck.check(reading.hint().get(), quiz));
            withHint.addAll(answerCheck.checkGiveaway(quiz, reading.shape()));
            issues = withHint;
        } else if (topic.asksForHint(reading.shape())) {
            issues = answerCheck.check(new ExerciseHint(null, List.of(), null, false, false), quiz);
        } else {
            issues = List.of();
        }
        // R008: a hint of letters is not read as a hint by R001 to R007, so it is looked at for every exercise.
        List<HintIssue> letters = answerCheck.checkLetterHint(quiz, reading.shape());
        if (!letters.isEmpty()) {
            List<HintIssue> all = new ArrayList<>(issues);
            all.addAll(letters);
            issues = all;
        }
        if (reading.shape() == ExerciseShape.WHOLE_SENTENCE) {
            // R006: only an answer that is the whole sentence; a gap inside it is R002's (inv. 2).
            List<HintIssue> all = new ArrayList<>(issues);
            all.addAll(answerCheck.checkRewrite(quiz));
            issues = all;
        }
        double score = issues.isEmpty() ? 1.0 : 0.0;
        node.getScores().put(ANALYZER_NAME, score);
        if (!(node.getDiagnoses() instanceof DefaultQuizDiagnoses)) {
            node.setDiagnoses(new DefaultQuizDiagnoses());
        }
        // The counts of the group that decides: the shape, unless only the whole topic asks for a hint.
        boolean byTopic = !topic.asksForHintInShape(reading.shape()) && topic.asksForHintInTopic();
        ((DefaultQuizDiagnoses) node.getDiagnoses()).setHintCoherenceDiagnosis(new HintCoherenceDiagnosis(
                reading.hint().map(ExerciseHint::getText).orElse(null),
                String.join(" · ", DefaultHintReader.firstAnswers(quiz)),
                reading.shape(),
                byTopic ? topic.hintedInTopic() : topic.hinted(reading.shape()),
                byTopic ? topic.comparableInTopic() : topic.comparable(reading.shape()),
                List.copyOf(issues), score));
        return null;
    }

