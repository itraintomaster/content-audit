    private void register(AnalyzerProvider provider) {
        String name = provider.analyzerName();
        if (isBlank(name)) {
            throw new InvalidAnalyzerCardException(String.valueOf(name),
                    "el proveedor no publica un nombre");
        }
        if (providersByName.containsKey(name)) {
            throw new InvalidAnalyzerCardException(name,
                    "dos proveedores publican el mismo nombre");
        }
        AnalyzerDescriptor card = provider.describe();
        if (card == null) {
            throw new InvalidAnalyzerCardException(name, "el proveedor no publica su ficha");
        }
        if (!name.equals(card.getName())) {
            throw new InvalidAnalyzerCardException(name,
                    "la ficha se llama '" + card.getName() + "' y su proveedor publica '" + name + "'");
        }
        validateCard(name, card);
        Optional<AnalyzerPlanBinding> binding = provider.planBinding();
        if (binding == null) {
            binding = Optional.empty();
        }
        binding.ifPresent(b -> validateBinding(name, card, b));

        providersByName.put(name, provider);
        cardsByName.put(name, card);
        bindingsByName.put(name, binding);
    }

    private static void validateCard(String name, AnalyzerDescriptor card) {
        requireText(name, "description", card.getDescription());
        requireValue(name, "target", card.getTarget());
        requireText(name, "question", card.getQuestion());
        requireText(name, "reads", card.getReads());
        requireText(name, "goal", card.getGoal());
        requireValue(name, "family", card.getFamily());
        requireValue(name, "cost", card.getCost());
        requireList(name, "rules", card.getRules());
        requireList(name, "evaluatedTargets", card.getEvaluatedTargets());
        requireList(name, "resolutions", card.getResolutions());

        Set<String> ruleIds = new HashSet<>();
        AnalysisCost highest = null;
        for (AnalyzerRuleCard rule : card.getRules()) {
            if (rule == null) {
                throw new InvalidAnalyzerCardException(name, "campo vacío: rules (una regla nula)");
            }
            requireText(name, "rules.id", rule.getId());
            requireText(name, "rules.description (" + rule.getId() + ")", rule.getDescription());
            requireValue(name, "rules.cost (" + rule.getId() + ")", rule.getCost());
            if (!ruleIds.add(rule.getId())) {
                throw new InvalidAnalyzerCardException(name,
                        "la regla '" + rule.getId() + "' figura dos veces");
            }
            if (highest == null || rule.getCost().ordinal() > highest.ordinal()) {
                highest = rule.getCost();
            }
        }
        for (AuditTarget target : card.getEvaluatedTargets()) {
            if (target == null) {
                throw new InvalidAnalyzerCardException(name, "campo vacío: evaluatedTargets (un nivel nulo)");
            }
        }
        for (FindingResolution resolution : card.getResolutions()) {
            if (resolution == null) {
                throw new InvalidAnalyzerCardException(name, "campo vacío: resolutions (una resolución nula)");
            }
        }
        // R006 inv. 2: the cost of the card is the highest cost of its rules
        // (instant < local model < paid model).
        if (card.getCost() != highest) {
            throw new InvalidAnalyzerCardException(name,
                    "el costo de la ficha (" + card.getCost() + ") no es el mayor de sus reglas ("
                            + highest + ")");
        }
    }

    private static void validateBinding(String name, AnalyzerDescriptor card, AnalyzerPlanBinding binding) {
        requireText(name, "planBinding.taskKind", binding.getTaskKind());
        requireList(name, "planBinding.taskTargets", binding.getTaskTargets());
        for (AuditTarget target : binding.getTaskTargets()) {
            if (!card.getEvaluatedTargets().contains(target)) {
                throw new InvalidAnalyzerCardException(name,
                        "el plan hace tareas en " + target + ", un nivel que la ficha no evalúa");
            }
        }
    }

    private static void requireText(String name, String field, String value) {
        if (isBlank(value)) {
            throw new InvalidAnalyzerCardException(name, "campo vacío: " + field);
        }
    }

    private static void requireValue(String name, String field, Object value) {
        if (value == null) {
            throw new InvalidAnalyzerCardException(name, "campo vacío: " + field);
        }
    }

    private static void requireList(String name, String field, List<?> value) {
        if (value == null || value.isEmpty()) {
            throw new InvalidAnalyzerCardException(name, "campo vacío: " + field);
        }
    }

    private static boolean isBlank(String value) {
        return value == null || value.isBlank();
    }
