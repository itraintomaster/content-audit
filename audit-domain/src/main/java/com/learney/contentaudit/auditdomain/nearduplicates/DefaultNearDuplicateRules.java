    static int editDistance(List<String> a, List<String> b) {
        int[] row = new int[b.size() + 1];
        for (int j = 0; j <= b.size(); j++) {
            row[j] = j;
        }
        for (int i = 1; i <= a.size(); i++) {
            int diagonal = row[0];
            row[0] = i;
            for (int j = 1; j <= b.size(); j++) {
                int above = row[j];
                int substitution = diagonal + (a.get(i - 1).equals(b.get(j - 1)) ? 0 : 1);
                row[j] = Math.min(Math.min(row[j] + 1, row[j - 1] + 1), substitution);
                diagonal = above;
            }
        }
        return row[b.size()];
    }

