    /** A word and its contractions, as spaCy splits them: «don't» is do + not, «I'll» is I + 'll. */
    private static void split(String word, List<String> tokens) {
        if (word.equals("cannot")) {
            tokens.add("can");
            tokens.add("not");
            return;
        }
        if (word.endsWith("n't") && word.length() > 3) {
            String host = word.substring(0, word.length() - 3);
            tokens.add(NEGATED_HOSTS.getOrDefault(host, host));
            tokens.add("not");
            return;
        }
        Matcher clitic = CLITIC.matcher(word);
        if (clitic.matches()) {
            tokens.add(clitic.group(1));
            tokens.add(clitic.group(2));
            return;
        }
        tokens.add(word);
    }

    private static String classOf(List<String> tokens, int i) {
        String token = tokens.get(i);
        String before = i > 0 ? tokens.get(i - 1) : null;
        String after = i + 1 < tokens.size() ? tokens.get(i + 1) : null;
        if (PERSONAL_PRONOUNS.contains(token)) {
            return "PRON";
        }
        if (DEMONSTRATIVES.contains(token)) {
            return "DEM";
        }
        if (POSSESSIVES.contains(token)) {
            return "POSS";
        }
        if (REFLEXIVES.contains(token)) {
            return "REFL";
        }
        if (token.equals("'s")) {
            if ("let".equals(before)) {
                return "PRON"; // let's: let us
            }
            if (before != null && (PERSONAL_PRONOUNS.contains(before) || VERB_S_HOSTS.contains(before))) {
                return isParticiple(after) ? "AUX:have" : "AUX:be";
            }
            return "'s"; // a possessive
        }
        if (token.equals("'d")) {
            return isParticiple(after) ? "AUX:have" : "AUX:will";
        }
        String auxiliary = AUXILIARIES.get(token);
        if (auxiliary != null) {
            return auxiliary;
        }
        return stem(token);
    }

    private static boolean isParticiple(String word) {
        return word != null && (PARTICIPLES.contains(word) || (word.length() > 3 && word.endsWith("ed")));
    }

    /**
     * The stem of a word without its inflection: the -s of the third person and of the plural, the
     * -ed and the -ing, a final e and a doubled consonant. Only for comparing two words: «plays»,
     * «played» and «playing» are «play»; «likes» and «liked», «lik».
     */
    static String stem(String word) {
        String irregular = IRREGULAR_STEMS.get(word);
        if (irregular != null) {
            return irregular;
        }
        if (word.length() <= 3) {
            return word;
        }
        String s = word;
        if (s.endsWith("ies") && s.length() > 4) {
            s = s.substring(0, s.length() - 3) + "y";
        } else if (s.endsWith("oes")) {
            s = s.substring(0, s.length() - 2);
        } else if (s.endsWith("ches") || s.endsWith("shes") || s.endsWith("sses") || s.endsWith("xes")
                || s.endsWith("zes")) {
            s = s.substring(0, s.length() - 2);
        } else if (s.endsWith("s") && !s.endsWith("ss") && !s.endsWith("us") && !s.endsWith("is")) {
            s = s.substring(0, s.length() - 1);
        } else if (s.endsWith("ied") && s.length() > 4) {
            s = s.substring(0, s.length() - 3) + "y";
        } else if (s.endsWith("ed") && s.length() > 4) {
            s = s.substring(0, s.length() - 2);
        } else if (s.endsWith("ing") && s.length() > 5) {
            s = s.substring(0, s.length() - 3);
        }
        if (s.length() > 3 && s.endsWith("e")) {
            s = s.substring(0, s.length() - 1);
        }
        int n = s.length();
        if (n > 3 && s.charAt(n - 1) == s.charAt(n - 2) && !isVowel(s.charAt(n - 1))) {
            s = s.substring(0, n - 1);
        }
        return s;
    }

    private static boolean isVowel(char c) {
        return "aeiouy".indexOf(c) >= 0;
    }

    /**
     * What changes from the first exercise to the second, word for word and without repeating a
     * change: «he → she», «didn't → don't», «You → I, wanted → want, this → that». When the two
     * read with a different number of words in the middle, the whole stretch: «I'm → I am».
     */
    static String difference(List<String> first, List<String> second) {
        int start = 0;
        while (start < first.size() && start < second.size() && first.get(start).equalsIgnoreCase(second.get(start))) {
            start++;
        }
        int endFirst = first.size();
        int endSecond = second.size();
        while (endFirst > start && endSecond > start
                && first.get(endFirst - 1).equalsIgnoreCase(second.get(endSecond - 1))) {
            endFirst--;
            endSecond--;
        }
        List<String> a = first.subList(start, endFirst);
        List<String> b = second.subList(start, endSecond);
        if (a.isEmpty() && b.isEmpty()) {
            return "";
        }
        if (a.size() != b.size()) {
            return (a.isEmpty() ? "—" : String.join(" ", a)) + " → " + (b.isEmpty() ? "—" : String.join(" ", b));
        }
        Set<String> seen = new LinkedHashSet<>();
        List<String> changes = new ArrayList<>();
        for (int i = 0; i < a.size(); i++) {
            if (a.get(i).equalsIgnoreCase(b.get(i))) {
                continue;
            }
            String change = a.get(i) + " → " + b.get(i);
            if (seen.add(change.toLowerCase(Locale.ROOT))) {
                changes.add(change);
            }
        }
        return String.join(", ", changes);
    }

