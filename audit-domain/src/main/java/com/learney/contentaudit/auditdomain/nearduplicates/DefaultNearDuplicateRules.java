    @Override
    public double wordSimilarity(AuditableQuiz first, AuditableQuiz second) {
        List<String> a = read(first).lower();
        List<String> b = read(second).lower();
        int longer = Math.max(Math.max(a.size(), b.size()), 1);
        return 1.0 - (double) editDistance(a, b) / longer;
    }

