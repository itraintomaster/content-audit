    /** The answer with its personal pronouns and demonstratives covered, also before a contraction. */
    static String masked(String answer) {
        if (answer == null) {
            return "";
        }
        Matcher matcher = ANSWER_WORD.matcher(answer);
        StringBuilder out = new StringBuilder();
        while (matcher.find()) {
            String lower = matcher.group().toLowerCase(Locale.ROOT);
            String cover = PERSONAL_PRONOUNS.contains(lower) ? "pron" : DEMONSTRATIVES.contains(lower) ? "dem" : null;
            matcher.appendReplacement(out, Matcher.quoteReplacement(cover != null ? cover : matcher.group()));
        }
        matcher.appendTail(out);
        return out.toString();
    }

