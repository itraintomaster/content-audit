/**
 * F-RONDA1-R003: a whole topic (knowledge) of an analysis as the student sees it. It is a pure
 * read of the report it receives: the topic's instructions and, for every exercise in course
 * order, its view and finished exercise from the one renderer (F-RONDA1-R001), its audio key and
 * the text that audio was recorded with. That text comes only from the recordings registry; when
 * the registry does not know the key it stays null, never rebuilt from the sentence (inv. 2).
 * Which analysis it reads is decided by the caller, which also fills in its id.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
public class DefaultTopicStudentViewQuery implements TopicStudentViewQuery {
    private final QuizStudentViewRenderer studentViewRenderer;

    private final AudioRecordingRegistry recordings;

    public DefaultTopicStudentViewQuery(QuizStudentViewRenderer studentViewRenderer,
            AudioRecordingRegistry recordings) {
        this.studentViewRenderer = studentViewRenderer;
        this.recordings = recordings;
    }

    @Override
    public TopicStudentView viewOf(AuditReport report, String knowledgeId) {
        AuditNode knowledgeNode = report != null && knowledgeId != null
                ? findKnowledge(report.getRoot(), knowledgeId)
                : null;
        if (knowledgeNode == null) {
            throw new StudentViewKnowledgeNotFoundException(knowledgeId);
        }
        AuditableKnowledge knowledge = (AuditableKnowledge) knowledgeNode.getEntity();

        List<StudentQuizEntry> quizzes = new ArrayList<>();
        if (knowledgeNode.getChildren() != null) {
            for (AuditNode quizNode : knowledgeNode.getChildren()) {
                if (!(quizNode.getEntity() instanceof AuditableQuiz quiz)) {
                    continue;
                }
                String audioKey = quiz.getAnswerAudioKey();
                quizzes.add(new StudentQuizEntry(
                        quiz.getId(),
                        studentViewRenderer.render(quiz),
                        studentViewRenderer.finishedSentence(quiz, knowledge.getSentenceMode()),
                        audioKey,
                        recordedText(audioKey)));
            }
        }
        return new TopicStudentView(null, knowledge.getId(), knowledge.getLabel(),
                knowledge.getInstructions(), knowledge.getSentenceMode(), quizzes);
    }

    private String recordedText(String audioKey) {
        if (recordings == null || audioKey == null || audioKey.isBlank()) {
            return null;
        }
        return recordings.recordingOf(audioKey).map(AudioRecording::getRecordedText).orElse(null);
    }

    private static AuditNode findKnowledge(AuditNode node, String knowledgeId) {
        if (node == null) {
            return null;
        }
        if (node.getTarget() == AuditTarget.KNOWLEDGE) {
            if (node.getEntity() instanceof AuditableKnowledge knowledge
                    && knowledgeId.equals(knowledge.getId())) {
                return node;
            }
            // Below a knowledge there are only its quizzes.
            return null;
        }
        if (node.getChildren() != null) {
            for (AuditNode child : node.getChildren()) {
                AuditNode found = findKnowledge(child, knowledgeId);
                if (found != null) {
                    return found;
                }
            }
        }
        return null;
    }
}
