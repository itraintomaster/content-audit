    private List<Finding> ruleFindings(List<Finding> findings) {
        List<Finding> mine = new ArrayList<>();
        for (Finding finding : findings != null ? findings : List.<Finding>of()) {
            if (finding != null && analyzerName().equals(finding.getAnalyzer())
                    && finding.getResolution() == FindingResolution.RULE && finding.getIdentity() != null) {
                mine.add(finding);
            }
        }
        return mine;
    }

    private static ExerciseHint noHint() {
        return new ExerciseHint(null, List.of(), null, false, false);
    }

    /** The hint the answer gives, as the analyzer proposes it for the faults a rule fixes. */
    private static String proposedHint(List<HintIssue> issues) {
        for (HintIssue issue : issues) {
            if (issue.getResolution() == FindingResolution.RULE && issue.getProposedHint() != null) {
                return issue.getProposedHint();
            }
        }
        return null;
    }

    private static String markerOf(String word) {
        return word == null || word.isBlank() ? "" : word.toLowerCase(Locale.ROOT);
    }

    /**
     * The parts with the hint written: replacing the one attached to a gap, or the short one closing the statement; with
     * none, right after the first gap. Null when there is no place to write it without touching the statement.
     */
    private static List<SentencePartEntity> withHint(List<SentencePartEntity> parts, String proposed,
            ExerciseShape shape) {
        String inner = proposed.substring(1, proposed.length() - 1);
        List<SentencePartEntity> written = copy(parts);
        List<Integer> gaps = DefaultHintReader.gaps(written);
        for (int gap : gaps) {
            if (gap + 1 < written.size() && isText(written.get(gap + 1))
                    && replaced(written.get(gap + 1), LEADING_HINT, inner)) {
                return written;
            }
            if (gap > 0 && isText(written.get(gap - 1)) && replaced(written.get(gap - 1), TRAILING_HINT, inner)) {
                return written;
            }
        }
        int last = written.size() - 1;
        if (gaps.get(gaps.size() - 1) < last && isText(written.get(last))
                && replaced(written.get(last), CLOSING_HINT, inner)) {
            return written;
        }
        if (shape == ExerciseShape.WHOLE_SENTENCE || hasUnparenthesizedCue(parts, gaps)) {
            return null;
        }
        int first = gaps.get(0);
        if (first + 1 < written.size() && isText(written.get(first + 1))) {
            SentencePartEntity next = written.get(first + 1);
            String text = next.getText().strip();
            String glue = text.isEmpty() || text.matches("^[.,;:?!].*") ? "" : " ";
            next.setText(proposed + glue + text);
        } else {
            written.add(first + 1, new SentencePartEntity(SentencePartKind.TEXT, proposed, null));
        }
        return written;
    }

    private static boolean replaced(SentencePartEntity part, Pattern where, String inner) {
        Matcher m = where.matcher(part.getText());
        if (!m.find()) {
            return false;
        }
        part.setText(part.getText().substring(0, m.start(1)) + inner + part.getText().substring(m.end(1)));
        return true;
    }

    /** A cue written next to the gap without parentheses, «Our / ours ___»: a hint a rule cannot rewrite. */
    private static boolean hasUnparenthesizedCue(List<SentencePartEntity> parts, List<Integer> gaps) {
        for (int gap : gaps) {
            for (int i : new int[] {gap - 1, gap + 1}) {
                if (i >= 0 && i < parts.size() && isText(parts.get(i))
                        && DefaultHintReader.withoutHints(parts.get(i).getText()).contains("/")) {
                    return true;
                }
            }
        }
        return false;
    }

    private static List<SentencePartEntity> partsOf(QuizTemplateEntity quiz) {
        if (quiz == null || quiz.getForm() == null || quiz.getForm().getSentenceParts() == null) {
            return List.of();
        }
        return quiz.getForm().getSentenceParts();
    }

    private static List<SentencePartEntity> copy(List<SentencePartEntity> parts) {
        List<SentencePartEntity> copy = new ArrayList<>();
        for (SentencePartEntity part : parts) {
            copy.add(part == null ? null : new SentencePartEntity(part.getKind(), part.getText(),
                    part.getOptions() != null ? new ArrayList<>(part.getOptions()) : null));
        }
        return copy;
    }

    private static boolean isText(SentencePartEntity part) {
        return part != null && part.getKind() == SentencePartKind.TEXT && part.getText() != null;
    }

    /** The exercise as the analyzer reads it, with the tokens of the saved sentence the analysis brought. */
    private static AuditableQuiz viewOf(QuizTemplateEntity quiz, List<SentencePartEntity> parts, AuditableQuiz analyzed) {
        return new AuditableQuiz(analyzed != null && analyzed.getTokens() != null ? analyzed.getTokens() : List.of(),
                quiz.getId(), quiz.getTitle(), quiz.getCode(), quiz.getTranslation(), quiz.getSentences(), null,
                quiz.getInstructions(), parts, quiz.getForm() != null ? quiz.getForm().getMultipleChoice() : null,
                quiz.getMiniTheory(), quiz.getAnswerAudioUrl());
    }

    private RuleFixResult declinedAll(QuizTemplateEntity quiz, List<Finding> findings, String reason) {
        List<FindingIdentity> declined = new ArrayList<>();
        for (Finding finding : findings) {
            declined.add(finding.getIdentity());
        }
        return result(quiz, List.of(), declined, reason);
    }

    private static RuleFixResult result(QuizTemplateEntity quiz, List<FindingIdentity> fixed,
            List<FindingIdentity> declined, String detail) {
        return new RuleFixResult(quiz, new ArrayList<>(fixed), new ArrayList<>(declined), detail, new ArrayList<>());
    }
