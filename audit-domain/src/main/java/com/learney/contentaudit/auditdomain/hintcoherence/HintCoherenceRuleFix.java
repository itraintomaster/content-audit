/**
 * F-PISTA-R005 through F-TANDA-R004 (hook E-06): the hint drawn from the first answer -- the base form of its verb, through
 * the table of irregular forms, its subject and its «not» --, written where the hint goes, and nothing else. The hint is
 * between parentheses, so neither the stored sentence nor what the audio says moves.
 *
 * <p>It computes the hint as the analyzer does ({@link DefaultHintAnswerCheck}, over the tokens of the saved sentence the
 * analysis brought), replaces the hint attached to the gap or the one closing the statement, or writes it right after the
 * first gap when the exercise has none. A finding the new hint does not settle comes back declined, and so does every
 * finding when the hint is not between parentheses («Our / ours ___») or when the answer is the whole sentence and has no
 * hint: there is no place to write one without rewriting the statement, which is the panel's.
 */
