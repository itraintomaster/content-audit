    @Override
    public Void onCourseComplete(AuditNode rootNode) {
        int top = lemmaRecurrenceConfig.getTop();

        // Select top N lemmas by count
        List<Map.Entry<String, List<Integer>>> entries = new ArrayList<>(lemmaPositions.entrySet());
        entries.sort(Comparator.<Map.Entry<String, List<Integer>>>comparingInt(e -> e.getValue().size()).reversed());

        int limit = Math.min(top, entries.size());
        List<LemmaStats> lemmaStatsList = new ArrayList<>();
        int normalCount = 0;
        int subExposedCount = 0;
        int overExposedCount = 0;

        for (int i = 0; i < limit; i++) {
            Map.Entry<String, List<Integer>> entry = entries.get(i);
            String lemma = entry.getKey();
            List<Integer> positions = entry.getValue();

            // Exclude lemmas with fewer than 2 occurrences (R006)
            if (positions.size() < 2) {
                continue;
            }

            double mean = intervalCalculator.calculateMeanInterval(positions);
            double stdDev = intervalCalculator.calculateStdDevInterval(positions, mean);
            ExposureStatus status = exposureClassifier.classify(mean, lemmaRecurrenceConfig);

            // F-RECUR-R003: the longest interval between two consecutive occurrences (the first one
            // when two are as long), with the levels of the quizzes where it starts and ends
            List<CefrLevel> levels = lemmaPositionLevels.getOrDefault(lemma, List.of());
            int gapIndex = 0;
            int longestGap = 0;
            for (int p = 0; p + 1 < positions.size(); p++) {
                int gap = positions.get(p + 1) - positions.get(p);
                if (gap > longestGap) {
                    longestGap = gap;
                    gapIndex = p;
                }
            }
            CefrLevel gapFrom = gapIndex < levels.size() ? levels.get(gapIndex) : null;
            CefrLevel gapTo = gapIndex + 1 < levels.size() ? levels.get(gapIndex + 1) : null;

            String pos = lemmaPosTag.getOrDefault(lemma, "");
            LemmaStats stats = new LemmaStats(lemma, pos, positions.size(), mean, stdDev, status, positions,
                    longestGap, gapFrom, gapTo, distinctLevels(levels));
            lemmaStatsList.add(stats);

            if (status == ExposureStatus.NORMAL) {
                normalCount++;
            } else if (status == ExposureStatus.SUB_EXPOSED) {
                subExposedCount++;
            } else if (status == ExposureStatus.OVER_EXPOSED) {
                overExposedCount++;
            }
        }

        int totalCount = lemmaStatsList.size();
        double overallScore = totalCount == 0 ? 0.0
                : Math.round((double) normalCount / totalCount * 100.0) / 100.0;

        ExposureSummary exposureSummary = new ExposureSummary(normalCount, subExposedCount, overExposedCount);
        LemmaRecurrenceResult result = new LemmaRecurrenceResult(lemmaStatsList, exposureSummary, overallScore);
        // F-RECUR-R004: the recurrence within each level travels as detail of the course diagnosis
        LemmaRecurrenceCourseDiagnosis diagnosis = new LemmaRecurrenceCourseDiagnosis(result, levelRecurrences(top));
        lastDiagnosis = diagnosis;

        // lemmaStats is ordered by count descending (already sorted above)
        rootNode.getScores().put(ANALYZER_NAME, overallScore);
        if (rootNode.getDiagnoses() instanceof DefaultCourseDiagnoses courseDiagnoses) {
            courseDiagnoses.setLemmaRecurrenceDiagnosis(diagnosis);
        }
        return null;
    }

    /** F-RECUR-R004: each level measured only with its quizzes, the same thresholds and the same top. */
    private List<LevelRecurrence> levelRecurrences(int top) {
        List<LevelRecurrence> levels = new ArrayList<>();
        for (CefrLevel level : CefrLevel.values()) {
            Integer positions = levelPositionCount.get(level);
            if (positions == null || positions == 0) {
                continue;
            }
            List<Map.Entry<String, List<Integer>>> entries = new ArrayList<>(
                    levelLemmaPositions.getOrDefault(level, Map.of()).entrySet());
            entries.sort(Comparator.<Map.Entry<String, List<Integer>>>comparingInt(e -> e.getValue().size()).reversed());
            int returning = 0;
            int normal = 0;
            int sub = 0;
            int over = 0;
            for (int i = 0; i < Math.min(top, entries.size()); i++) {
                List<Integer> lemmaPositionsInLevel = entries.get(i).getValue();
                if (lemmaPositionsInLevel.size() < 2) {
                    continue;
                }
                returning++;
                ExposureStatus status = exposureClassifier.classify(
                        intervalCalculator.calculateMeanInterval(lemmaPositionsInLevel), lemmaRecurrenceConfig);
                if (status == ExposureStatus.NORMAL) {
                    normal++;
                } else if (status == ExposureStatus.SUB_EXPOSED) {
                    sub++;
                } else if (status == ExposureStatus.OVER_EXPOSED) {
                    over++;
                }
            }
            double share = returning == 0 ? 0.0 : (double) normal / returning;
            levels.add(new LevelRecurrence(level, positions, returning, normal, sub, over, share));
        }
        return levels;
    }

    private static List<CefrLevel> distinctLevels(List<CefrLevel> levels) {
        Set<CefrLevel> distinct = EnumSet.noneOf(CefrLevel.class);
        for (CefrLevel level : levels) {
            if (level != null) {
                distinct.add(level);
            }
        }
        return new ArrayList<>(distinct);
    }

