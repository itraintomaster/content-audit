    /** «movie: 90 veces, vuelve cada 1.005 palabras (meta: más de 50 y hasta 1.000); su hueco más largo, 6.510, va de A1 a A2». */
    /** «7,5 % de las 1.743 palabras analizadas vuelve a un intervalo sano»: the measure of the course. */
    private static String courseMeasure(LemmaRecurrenceResult result) {
        int measured = result.getLemmaStats().size();
        int normal = result.getExposureSummary() != null ? result.getExposureSummary().getNormalCount() : 0;
        double share = measured == 0 ? 0.0 : (double) normal / measured;
        return String.format(Locale.ROOT, "%.1f", share * 100).replace('.', ',') + " % de las "
                + thousands(measured) + " palabras analizadas vuelve a un intervalo sano";
    }

    private FindingDraft lemmaFinding(LemmaStats stats, String course) {
        String goal = "más de " + number(lemmaRecurrenceConfig.getOverExposedThreshold()) + " y hasta "
                + number(lemmaRecurrenceConfig.getSubExposedThreshold());
        String gap = gapText(stats);
        List<EvidencePart> examined = new ArrayList<>();
        examined.add(new EvidencePart("Palabra", stats.getLemma()));
        examined.add(new EvidencePart("Veces", thousands(stats.getCount())));
        examined.add(new EvidencePart("Vuelve cada", number(stats.getMeanInterval()) + " palabras"));
        examined.add(new EvidencePart("Meta", goal));
        examined.add(new EvidencePart("Estado", stats.getExposureStatus() == ExposureStatus.OVER_EXPOSED
                ? "sobre-expuesta" : "poco vista"));
        examined.add(new EvidencePart("Hueco más largo", gap));
        examined.add(new EvidencePart("Curso", course));
        String observation = stats.getLemma() + ": " + thousands(stats.getCount()) + " veces, vuelve cada "
                + number(stats.getMeanInterval()) + " palabras (meta: " + goal + "); su hueco más largo, " + gap;
        return new FindingDraft(RULE_RECURRENCE, stats.getLemma(), FindingSeverity.LOW, FindingResolution.RANK_ONLY,
                new FindingEvidence(examined, observation, List.of()));
    }

    /** «6.510, va de A1 a A2» or «27.780, está en B1». */
    private static String gapText(LemmaStats stats) {
        String length = thousands(stats.getLongestGap());
        CefrLevel from = stats.getLongestGapFromLevel();
        CefrLevel to = stats.getLongestGapToLevel();
        if (from == null || to == null) {
            return length;
        }
        if (from == to) {
            return length + ", está en " + from.name();
        }
        return length + ", va de " + from.name() + " a " + to.name();
    }

    /** A whole number of words with a thousands point: 1005,02 reads 1.005. */
    private static String number(double value) {
        return thousands(Math.round(value));
    }

    private static String thousands(long value) {
        return String.format(Locale.ROOT, "%,d", value).replace(',', '.');
    }

