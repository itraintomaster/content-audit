    /**
     * R004: the translation repeats the word whole and without accents -- a loan or a name the
     * student reads in Spanish, as «sushi», «USB» or «Emily». «adore» in «adoran» is not whole.
     */
    static boolean inTranslation(String translation, String lemma, Set<String> texts) {
        if (translation == null || translation.isBlank()) {
            return false;
        }
        String words = " " + plain(translation).replaceAll("[^a-z0-9]+", " ") + " ";
        Set<String> candidates = new LinkedHashSet<>();
        candidates.add(lemma);
        candidates.addAll(texts);
        for (String candidate : candidates) {
            String plainCandidate = candidate != null ? plain(candidate) : "";
            if (plainCandidate.length() >= 2 && words.contains(" " + plainCandidate + " ")) {
                return true;
            }
        }
        return false;
    }

    /**
     * R004: a noun is repeated by the translation adapted to Spanish spelling, as loans are written:
     * «hamburger» is «hamburguesas», «limousine» «limusina», «pollen» «polen». Both are compared
     * folded (ph f, th t, y i, ou u, one consonant for a double, the Spanish es- before s and gu for
     * g, no final vowels nor plural), from the same first letter: the same, one the start of the
     * other from five letters on («meteor», «meteoritos»), or one letter apart («porcelain»,
     * «porcelana»). Only a noun: an adjective or an adverb that looks Spanish is a cognate the student
     * still has to know («allergic», «diligently»), and a verb never, not even one the tagger reads as
     * a noun where the sentence uses it as a verb (see {@link #usedAsVerb}): «adore» and «adoran» keep
     * marking, as the 077 asked.
     */
    static boolean adaptedInTranslation(String translation, List<NlpToken> tokens, String pos, String lemma,
            Set<String> texts) {
        if (translation == null || translation.isBlank() || !"NOUN".equals(pos) || usedAsVerb(tokens, lemma, pos)) {
            return false;
        }
        Set<String> english = new LinkedHashSet<>();
        english.add(foldEnglish(lemma));
        for (String text : texts) {
            english.add(foldEnglish(text));
        }
        english.removeIf(word -> word.length() < 4);
        if (english.isEmpty()) {
            return false;
        }
        Matcher matcher = SPANISH_WORD.matcher(translation);
        while (matcher.find()) {
            for (String spanish : foldSpanish(matcher.group())) {
                for (String word : english) {
                    if (spanish.isEmpty() || word.charAt(0) != spanish.charAt(0)) {
                        continue;
                    }
                    if (word.equals(spanish) || sameStem(word, spanish) || editDistance(word, spanish) <= 1) {
                        return true;
                    }
                }
            }
        }
        return false;
    }

    /**
     * R004: the sentence uses the word as a verb, whatever the tagger says: it is written with -ed or
     * -ing on its lemma, or it comes right after a subject pronoun (I, he, she, we, they), the «to»
     * of an infinitive or a negation, adverbs in between -- «They adore cats», «to adore»,
     * «don't really adore».
     */
    static boolean usedAsVerb(List<NlpToken> tokens, String lemma, String pos) {
        if (tokens == null || lemma == null) {
            return false;
        }
        String lowerLemma = lower(lemma);
        NlpToken previous = null;
        for (NlpToken token : tokens) {
            if (token == null || token.getText() == null || token.getText().isBlank()
                    || "SPACE".equals(token.getPosTag())) {
                continue;
            }
            boolean same = token.getLemma() != null && token.getLemma().equalsIgnoreCase(lemma)
                    && (pos == null || pos.equals(token.getPosTag()));
            if (same) {
                String text = lower(token.getText());
                boolean verbEnding = !text.equals(lowerLemma) && (text.endsWith("ed") || text.endsWith("ing"));
                if (verbEnding || previous != null && beforeAVerb(previous)) {
                    return true;
                }
            }
            if (!"ADV".equals(token.getPosTag())) {
                previous = token;
            }
        }
        return false;
    }

    /** A subject pronoun, the «to» of an infinitive or a negation: what only a verb follows. */
    private static boolean beforeAVerb(NlpToken previous) {
        String text = lower(previous.getText());
        if (SUBJECT_PRONOUNS.contains(text)) {
            return true;
        }
        return "PART".equals(previous.getPosTag()) && (text.equals("to") || text.equals("not") || text.equals("n't"));
    }

    static String foldEnglish(String word) {
        String folded = plain(word == null ? "" : word);
        folded = folded.replace("ph", "f").replace("th", "t").replace("gh", "g").replace("ou", "u")
                .replace("y", "i").replace("k", "c");
        return stripFinalVowels(singleConsonants(folded));
    }

    static Set<String> foldSpanish(String word) {
        String plainWord = plain(word);
        Set<String> forms = new LinkedHashSet<>();
        forms.add(plainWord);
        if (plainWord.length() > 4 && plainWord.endsWith("s")) {
            forms.add(plainWord.substring(0, plainWord.length() - 1));
        }
        if (plainWord.length() > 5 && plainWord.endsWith("es")) {
            forms.add(plainWord.substring(0, plainWord.length() - 2));
        }
        Set<String> folded = new LinkedHashSet<>();
        for (String form : forms) {
            String f = form.replaceFirst("^es(?=[b-df-hj-np-tv-z])", "s")
                    .replace("gue", "ge").replace("gui", "gi").replace("qu", "c");
            folded.add(stripFinalVowels(singleConsonants(f)));
        }
        return folded;
    }

    /** One folded word is the start of the other, from five letters on: «meteor», «meteorit». */
    private static boolean sameStem(String english, String spanish) {
        boolean englishShorter = english.length() <= spanish.length();
        String shorter = englishShorter ? english : spanish;
        String longer = englishShorter ? spanish : english;
        return shorter.length() >= 5 && longer.startsWith(shorter);
    }

    private static String singleConsonants(String word) {
        return word.replaceAll("([b-df-hj-np-tv-z])\\1+", "$1");
    }

    private static String stripFinalVowels(String word) {
        return word.replaceAll("[aeiou]+$", "");
    }

    static int editDistance(String a, String b) {
        int[] previous = new int[b.length() + 1];
        for (int j = 0; j <= b.length(); j++) {
            previous[j] = j;
        }
        for (int i = 1; i <= a.length(); i++) {
            int[] current = new int[b.length() + 1];
            current[0] = i;
            for (int j = 1; j <= b.length(); j++) {
                int substitution = previous[j - 1] + (a.charAt(i - 1) == b.charAt(j - 1) ? 0 : 1);
                current[j] = Math.min(substitution, Math.min(previous[j] + 1, current[j - 1] + 1));
            }
            previous = current;
        }
        return previous[b.length()];
    }

    /** Lower case, without accents: «Canapé» reads «canape». */
    private static String plain(String text) {
        String decomposed = Normalizer.normalize(text, Normalizer.Form.NFD);
        return decomposed.replaceAll("\\p{M}+", "").toLowerCase(Locale.ROOT);
    }

    private static String lower(String text) {
        return text == null ? "" : text.toLowerCase(Locale.ROOT);
    }

    /** The written forms of the word in the sentence: «lives» for live. */
    private static Set<String> textsOf(List<NlpToken> tokens, String lemma, String pos) {
        Set<String> texts = new LinkedHashSet<>();
        for (NlpToken token : tokens) {
            if (token == null || token.getText() == null || token.getLemma() == null) {
                continue;
            }
            boolean sameLemma = token.getLemma().equalsIgnoreCase(lemma);
            boolean samePos = pos == null || pos.equals(token.getPosTag());
            if (sameLemma && samePos) {
                texts.add(token.getText());
            }
        }
        return texts;
    }

    private TaughtWords taughtWords(AuditNode knowledgeNode) {
        if (knowledgeNode == null || knowledgeNode.getEntity() == null) {
            return null;
        }
        String id = knowledgeNode.getEntity().getId();
        if (id == null) {
            return topicTeachingResolver.taughtWords(knowledgeNode);
        }
        return taughtByKnowledge.computeIfAbsent(id, k -> topicTeachingResolver.taughtWords(knowledgeNode));
    }

    private static CefrLevel levelOf(AuditNode quizNode) {
        Optional<AuditNode> milestone = quizNode.ancestor(AuditTarget.MILESTONE);
        if (milestone.isEmpty() || !(milestone.get().getEntity() instanceof AuditableMilestone level)
                || level.getLabel() == null) {
            return null;
        }
        try {
            return CefrLevel.valueOf(level.getLabel());
        } catch (IllegalArgumentException e) {
            return null;
        }
    }

