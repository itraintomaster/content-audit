    private List<OffLevelWord> offLevelWords(AuditableQuiz quiz, CefrLevel level, TaughtWords taught) {
        List<OffLevelWord> words = new ArrayList<>();
        List<NlpToken> tokens = quiz.getTokens();
        if (tokens == null || tokens.isEmpty()) {
            return words;
        }
        SentenceLexicalScore score = sentenceLexicalScorer.score(tokens, level);
        Set<String> seen = new HashSet<>();
        for (MisplacedLemma misplaced : orEmpty(score.getMisplacedLemmas())) {
            if (misplaced.getLemmaAndPos() == null || misplaced.getExpectedLevel() == null) {
                continue;
            }
            // R002: two or more levels above the quiz, with C1 = 5 and C2 = 6
            if (misplaced.getExpectedLevel().ordinal() - level.ordinal() < MIN_DISTANCE) {
                continue;
            }
            String lemma = misplaced.getLemmaAndPos().getLemma();
            String pos = misplaced.getLemmaAndPos().getPos();
            if (taught(taught, lemma, textsOf(tokens, lemma, pos)) || !seen.add(lemma + "|" + pos)) {
                continue;
            }
            Integer rank = misplaced.getCocaRank() != null && misplaced.getCocaRank() > 0
                    ? misplaced.getCocaRank() : null;
            words.add(new OffLevelWord(lemma, pos, OffLevelReason.ABOVE_LEVEL, misplaced.getExpectedLevel(), rank));
        }
        for (OutOfCatalogWord outOfCatalog : orEmpty(score.getOutOfCatalogWords())) {
            if (outOfCatalog.getLemma() == null || !inStrongBand(outOfCatalog.getFrequencyRank(), level)) {
                continue;
            }
            String lemma = outOfCatalog.getLemma();
            String pos = outOfCatalog.getObservedPos();
            Set<String> texts = textsOf(tokens, lemma, pos);
            if (taught(taught, lemma, texts) || inTranslation(quiz.getTranslation(), lemma, texts)
                    || !seen.add(lemma + "|" + pos)) {
                continue;
            }
            words.add(new OffLevelWord(lemma, pos, OffLevelReason.OUT_OF_CATALOG, null, outOfCatalog.getFrequencyRank()));
        }
        return words;
    }

    /**
     * R002: out of the catalog and in the strong-discount band of F-LABS-R034 for the quiz level --
     * no rank, or a rank beyond the mild band -- with the bounds of the lemma-absence configuration.
     */
    private boolean inStrongBand(Integer rank, CefrLevel level) {
        return rank == null || rank <= 0 || rank > lemmaAbsenceConfig.getOutOfCatalogMildDiscountRankBound(level);
    }

    /** R003: the topic teaches it -- a word of its title's terms, or a frequent lemma of its answers. */
    private static boolean taught(TaughtWords taught, String lemma, Set<String> texts) {
        if (taught == null || lemma == null) {
            return false;
        }
        String lowerLemma = lemma.toLowerCase(Locale.ROOT);
        List<String> terms = taught.getTitleTerms() != null ? taught.getTitleTerms() : List.of();
        if (terms.contains(lowerLemma)) {
            return true;
        }
        for (String text : texts) {
            if (terms.contains(text.toLowerCase(Locale.ROOT))) {
                return true;
            }
        }
        return taught.getFrequentAnswers() != null && taught.getFrequentAnswers().contains(lowerLemma);
    }

    /**
     * R004: the translation repeats the word whole and without accents -- a loan or a name the
     * student reads in Spanish, as «sushi», «USB» or «Emily». «adore» in «adoran» is not whole.
     */
    static boolean inTranslation(String translation, String lemma, Set<String> texts) {
        if (translation == null || translation.isBlank()) {
            return false;
        }
        String words = " " + plain(translation).replaceAll("[^a-z0-9]+", " ") + " ";
        Set<String> candidates = new LinkedHashSet<>();
        candidates.add(lemma);
        candidates.addAll(texts);
        for (String candidate : candidates) {
            String plainCandidate = candidate != null ? plain(candidate) : "";
            if (plainCandidate.length() >= 2 && words.contains(" " + plainCandidate + " ")) {
                return true;
            }
        }
        return false;
    }

    /** Lower case, without accents: «Canapé» reads «canape». */
    private static String plain(String text) {
        String decomposed = Normalizer.normalize(text, Normalizer.Form.NFD);
        return decomposed.replaceAll("\\p{M}+", "").toLowerCase(Locale.ROOT);
    }

    /** The written forms of the word in the sentence: «lives» for live. */
    private static Set<String> textsOf(List<NlpToken> tokens, String lemma, String pos) {
        Set<String> texts = new LinkedHashSet<>();
        for (NlpToken token : tokens) {
            if (token == null || token.getText() == null || token.getLemma() == null) {
                continue;
            }
            boolean sameLemma = token.getLemma().equalsIgnoreCase(lemma);
            boolean samePos = pos == null || pos.equals(token.getPosTag());
            if (sameLemma && samePos) {
                texts.add(token.getText());
            }
        }
        return texts;
    }

    private TaughtWords taughtWords(AuditNode knowledgeNode) {
        if (knowledgeNode == null || knowledgeNode.getEntity() == null) {
            return null;
        }
        String id = knowledgeNode.getEntity().getId();
        if (id == null) {
            return topicTeachingResolver.taughtWords(knowledgeNode);
        }
        return taughtByKnowledge.computeIfAbsent(id, k -> topicTeachingResolver.taughtWords(knowledgeNode));
    }

    private static CefrLevel levelOf(AuditNode quizNode) {
        Optional<AuditNode> milestone = quizNode.ancestor(AuditTarget.MILESTONE);
        if (milestone.isEmpty() || !(milestone.get().getEntity() instanceof AuditableMilestone level)
                || level.getLabel() == null) {
            return null;
        }
        try {
            return CefrLevel.valueOf(level.getLabel());
        } catch (IllegalArgumentException e) {
            return null;
        }
    }

