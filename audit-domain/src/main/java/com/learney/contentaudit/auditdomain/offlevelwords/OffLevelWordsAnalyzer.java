    private static FindingDraft finding(OffLevelWord word, CefrLevel quizLevel, String sentence,
            String asTheStudentSeesIt) {
        String quizLevelName = quizLevel != null ? quizLevel.name() : "su nivel";
        List<EvidencePart> examined = new ArrayList<>();
        examined.add(new EvidencePart("Oración", sentence));
        if (asTheStudentSeesIt != null && !asTheStudentSeesIt.isBlank() && !asTheStudentSeesIt.equals(sentence)) {
            examined.add(new EvidencePart("Como la ve el alumno", asTheStudentSeesIt));
        }
        examined.add(new EvidencePart("Palabra", word.getLemma()));
        String observation;
        if (word.getReason() == OffLevelReason.OUT_OF_CATALOG) {
            String rank = word.getFrequencyRank() != null ? "puesto " + thousands(word.getFrequencyRank()) : "sin puesto";
            examined.add(new EvidencePart("Nivel de la palabra", "fuera del EVP"));
            examined.add(new EvidencePart("Puesto COCA", word.getFrequencyRank() != null
                    ? thousands(word.getFrequencyRank()) : "sin puesto"));
            observation = word.getLemma() + " está fuera del EVP (" + rank + "); el ejercicio es " + quizLevelName;
        } else {
            String levelName = word.getCatalogLevel() != null ? word.getCatalogLevel().name() : "otro nivel";
            examined.add(new EvidencePart("Nivel de la palabra", levelName));
            if (word.getFrequencyRank() != null) {
                examined.add(new EvidencePart("Puesto COCA", thousands(word.getFrequencyRank())));
            }
            observation = word.getLemma() + " es " + levelName + "; el ejercicio es " + quizLevelName;
        }
        examined.add(new EvidencePart("Nivel del ejercicio", quizLevelName));
        return new FindingDraft(RULE_OFF_LEVEL, word.getLemma() + "|" + word.getPos(), FindingSeverity.MEDIUM,
                FindingResolution.PANEL, new FindingEvidence(examined, observation, List.of()));
    }

    /** The finished sentence, the one lemma-absence measures. */
    private static String sentenceOf(AuditableQuiz quiz) {
        if (quiz.getSentences() != null && !quiz.getSentences().isEmpty() && quiz.getSentences().get(0) != null
                && !quiz.getSentences().get(0).isBlank()) {
            return quiz.getSentences().get(0);
        }
        if (quiz.getLabel() != null && !quiz.getLabel().isBlank()) {
            return quiz.getLabel();
        }
        return quiz.getId() != null ? quiz.getId() : "(sin oración)";
    }

    /** D-14: the statement with its gap, as the student sees it (F-RONDA1-R001). */
    private String statementOf(AuditableQuiz quiz) {
        if (studentViewRenderer == null) {
            return null;
        }
        QuizStudentView view = studentViewRenderer.render(quiz);
        return view != null ? view.getStatement() : null;
    }

    private static <T> List<T> orEmpty(List<T> list) {
        return list != null ? list : List.of();
    }

    private static String thousands(int value) {
        return String.format(Locale.ROOT, "%,d", value).replace(',', '.');
    }
