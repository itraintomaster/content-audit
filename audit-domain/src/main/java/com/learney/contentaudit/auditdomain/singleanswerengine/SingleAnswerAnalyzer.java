    /**
     * Reads and classifies the verdict of one exercise and leaves on it its score, its diagnosis
     * and its findings. Everything is computed before anything is written, so an exercise whose
     * verdict cannot be read or classified is left untouched and the caller declares it not
     * evaluated.
     */
    private boolean judge(AuditNode unit, EvaluationResolution resolution) {
        if (resolution == null || (resolution.getKind() != EvaluationResolutionKind.REUSED
                && resolution.getKind() != EvaluationResolutionKind.EVALUATED)) {
            return false;
        }
        if (!(unit.getEntity() instanceof AuditableQuiz quiz)) {
            return false;
        }
        SingleAnswerOutcome outcome;
        try {
            SingleAnswerVerdict verdict = verdictReader.read(resolution.getPayload());
            if (verdict == null) {
                return false;
            }
            outcome = classifier.classify(verdict, quiz,
                    resolution.getKind() == EvaluationResolutionKind.REUSED);
        } catch (RuntimeException e) {
            return false;
        }
        if (outcome == null) {
            return false;
        }

        if (unit.getScores() == null) {
            unit.setScores(new LinkedHashMap<>());
        }
        unit.getScores().put(ANALYZER_NAME, outcome.getScore());
        if (!(unit.getDiagnoses() instanceof DefaultQuizDiagnoses)) {
            unit.setDiagnoses(new DefaultQuizDiagnoses());
        }
        ((DefaultQuizDiagnoses) unit.getDiagnoses()).setSingleAnswerDiagnosis(outcome.getDiagnosis());
        findings.put(unit, outcome.getFindings() != null ? new ArrayList<>(outcome.getFindings()) : List.of());
        return true;
    }

    /**
     * F-HALL-R008 / F-UNICA-R005 inv. 4: reached but not evaluated -- without score and without
     * finding, so no average and no count takes it for a passing exercise.
     */
    private void markUnevaluated(AuditNode unit) {
        if (unit.getScores() != null) {
            unit.getScores().remove(ANALYZER_NAME);
        }
        findings.remove(unit);
        if (unit.getUnevaluatedBy() == null) {
            unit.setUnevaluatedBy(new ArrayList<>());
        }
        if (!unit.getUnevaluatedBy().contains(ANALYZER_NAME)) {
            unit.getUnevaluatedBy().add(ANALYZER_NAME);
        }
    }
