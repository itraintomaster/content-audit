    /** A hint: a parenthesized block of the text. */
    private static final Pattern HINT = Pattern.compile("\\([^)]*\\)");

    /** An «a / b» list of the text, as the course writes its choices. */
    private static final Pattern CHOICE =
            Pattern.compile("(?<![\\w'’])([\\w'’]+(?:\\s*/\\s*[\\w'’-]+)+)(?![\\w'’])");

    /** A closed sentence: it ends in «.», «?» or «!», maybe followed by a closing quote. */
    private static final Pattern END = Pattern.compile("[.?!]['\"”’]?\\s*$");

    /** A closed sentence followed by a label that ends in «:» or «=»: «… border. Link type:». */
    private static final Pattern SENTENCE_THEN_LABEL = Pattern.compile("^(.*[.?!]['\"”’]?)\\s+([^.?!]*[:=])\\s*$",
            Pattern.DOTALL);

    /** The speaker of a dialogue: «A:», «B:». */
    private static final Pattern SPEAKER = Pattern.compile("^[A-Z]:$");

    /** A dialogue whose next turn is the gap: «… B:». */
    private static final Pattern DIALOGUE_TURN = Pattern.compile("(?:^|\\s)[A-Z]:\\s*$");

    /** A contraction that glues to the word before it. */
    private static final Pattern CONTRACTION = Pattern.compile("^(?:['’](?:s|re|m|ve|d|ll)|n['’]t)(?![\\w])",
            Pattern.CASE_INSENSITIVE);

    /** The answers of a judgment exercise. */
    private static final Set<String> JUDGMENT_LABELS = Set.of("correct", "not correct", "incorrect", "right",
            "wrong");

    /** The answers of a judgment that say the sentence is wrong on purpose. */
    private static final Set<String> WRONG_ON_PURPOSE = Set.of("not correct", "incorrect", "wrong");

    /** A multiple choice option that means «no word». */
    private static final Set<String> NOTHING = Set.of("-", "–", "—");

    /** More combinations of answers than this are not worth reading: the first ones stand for them. */
    private static final int MAX_COMBINATIONS = 64;

    @Override
    public List<FinishedSentence> read(AuditableQuiz quiz, SentenceMode mode) {
        if (quiz == null || quiz.getSentenceParts() == null) {
            return List.of();
        }
        List<SentencePartEntity> parts = new ArrayList<>();
        for (SentencePartEntity part : quiz.getSentenceParts()) {
            if (part != null && part.getKind() != null) {
                parts.add(part);
            }
        }
        List<Integer> gaps = new ArrayList<>();
        for (int i = 0; i < parts.size(); i++) {
            if (parts.get(i).getKind() == SentencePartKind.CLOZE) {
                gaps.add(i);
            }
        }
        if (gaps.isEmpty()) {
            return List.of();
        }
        List<FinishedSentence> sentences = quiz.getMultipleChoice() != null
                ? readMultipleChoice(parts, gaps.get(0), quiz.getMultipleChoice())
                : readCloze(parts, gaps, mode);
        return deduplicated(sentences);
    }

    // -------------------------------------------------------------------------
    // Multiple choice: the correct option in its gap
    // -------------------------------------------------------------------------

    private static List<FinishedSentence> readMultipleChoice(List<SentencePartEntity> parts, int gap,
            MultipleChoiceEntity multipleChoice) {
        Optional<MultipleChoiceItemEntity> correct = multipleChoice.correctItem();
        if (correct == null || correct.isEmpty() || correct.get().getLabel() == null) {
            // Without a correct option there is nothing to read: that is FEAT-OMVAL's.
            return List.of();
        }
        String option = correct.get().getLabel().strip();
        String before = cleanText(rawText(parts, 0, gap));
        String after = cleanText(rawText(parts, gap + 1, parts.size()));

        if (after.isEmpty()) {
            boolean judgment = isJudgment(multipleChoice);
            if (judgment && WRONG_ON_PURPOSE.contains(option.toLowerCase(Locale.ROOT))) {
                // Inv. 4: its sentence is wrong on purpose; nothing to read.
                return List.of();
            }
            Optional<String> labelled = sentenceBeforeLabel(before);
            if (labelled.isPresent() || judgment) {
                // Inv. 4: the option is a label put after the sentence.
                return sentenceAlone(labelled.orElse(before));
            }
        }
        String answer = NOTHING.contains(option) ? "" : option;
        Builder builder = new Builder();
        appendFixed(builder, parts, 0, gap);
        builder.answer(answer);
        appendFixed(builder, parts, gap + 1, parts.size());
        return List.of(builder.build(0));
    }

    private static boolean isJudgment(MultipleChoiceEntity multipleChoice) {
        if (multipleChoice.getItems() == null) {
            return false;
        }
        for (MultipleChoiceItemEntity item : multipleChoice.getItems()) {
            if (item != null && item.getLabel() != null
                    && JUDGMENT_LABELS.contains(item.getLabel().strip().toLowerCase(Locale.ROOT))) {
                return true;
            }
        }
        return false;
    }

    // -------------------------------------------------------------------------
    // Cloze: one sentence per accepted answer
    // -------------------------------------------------------------------------

    private static List<FinishedSentence> readCloze(List<SentencePartEntity> parts, List<Integer> gaps,
            SentenceMode mode) {
        List<List<String>> answers = new ArrayList<>();
        for (int gap : gaps) {
            answers.add(variants(parts.get(gap).getOptions()));
        }
        int first = gaps.get(0);
        String rawBefore = rawText(parts, 0, first);
        // What the student reads around the gap: without hints nor lists.
        String before = cleanText(rawBefore);
        String after = cleanText(rawText(parts, first + 1, parts.size()));
        boolean oneGap = gaps.size() == 1;

        if (oneGap && after.isEmpty()) {
            // Inv. 5: an «a / b» list inside a closed sentence and the gap after it.
            List<FinishedSentence> inPlace = answerInPlaceOfTheList(withoutHints(rawBefore), answers.get(0));
            if (!inPlace.isEmpty()) {
                return inPlace;
            }
            // Inv. 4: an answer after «=» or «:» put after a closed sentence leaves the sentence alone.
            Optional<String> labelled = labelAfterSentence(before);
            if (labelled.isPresent()) {
                return sentenceAlone(labelled.get());
            }
        }

        boolean closedBefore = END.matcher(before).find() && after.isEmpty();
        boolean dialogueTurn = DIALOGUE_TURN.matcher(before).find();
        String firstAnswer = answers.get(0).isEmpty() ? "" : answers.get(0).get(0);
        boolean answerIsSentence = isSentence(firstAnswer);
        if (oneGap && !dialogueTurn && closedBefore && !answerIsSentence && mode != SentenceMode.REWRITE
                && words(before) >= 3) {
            // The answer is a piece of the sentence before it (the student names a word of it):
            // the sentence is what is read.
            return sentenceAlone(before);
        }
        // A rewrite topic also has exercises whose gap sits inside the sentence: those are read
        // whole like any other. Only a gap after a closed starting sentence, or an answer that is a
        // sentence of its own, is the whole sentence -- even a short one, «Look up.».
        boolean whole = oneGap && !dialogueTurn && (answerIsSentence || closedBefore);
        if (whole) {
            // Inv. 2: the answer is the whole sentence; the starting sentence is not read.
            List<FinishedSentence> sentences = new ArrayList<>();
            for (int a = 0; a < answers.get(0).size(); a++) {
                Builder builder = new Builder();
                builder.answer(answers.get(0).get(a));
                appendFixed(builder, parts, first + 1, parts.size());
                sentences.add(builder.build(a));
            }
            return sentences;
        }

        // Every combination of the accepted answers of the gaps, in order.
        List<FinishedSentence> sentences = new ArrayList<>();
        int[] index = new int[answers.size()];
        int total = 1;
        for (List<String> options : answers) {
            total = Math.min(MAX_COMBINATIONS, total * Math.max(1, options.size()));
        }
        for (int combination = 0; combination < total; combination++) {
            Builder builder = new Builder();
            int gapNumber = 0;
            for (SentencePartEntity part : parts) {
                if (part.getKind() == SentencePartKind.CLOZE) {
                    List<String> options = answers.get(gapNumber);
                    builder.answer(options.isEmpty() ? "" : options.get(index[gapNumber]));
                    gapNumber++;
                } else {
                    builder.fixed(cleanText(part.getText()));
                }
            }
            sentences.add(builder.build(combination));
            for (int g = answers.size() - 1; g >= 0; g--) {
                index[g]++;
                if (index[g] < Math.max(1, answers.get(g).size())) {
                    break;
                }
                index[g] = 0;
            }
        }
        return sentences;
    }

    /**
     * Inv. 5: «Something / anything was wrong with the telephone.» answered «Something» reads
     * «Something was wrong with the telephone.», with the capital the list has.
     */
    private static List<FinishedSentence> answerInPlaceOfTheList(String rawBefore, List<String> answers) {
        if (!END.matcher(rawBefore).find()) {
            return List.of();
        }
        Matcher list = CHOICE.matcher(rawBefore);
        if (!list.find()) {
            return List.of();
        }
        Set<String> choices = new LinkedHashSet<>();
        for (String choice : list.group(1).split("\\s*/\\s*")) {
            choices.add(choice.strip().toLowerCase(Locale.ROOT));
        }
        if (answers.isEmpty() || !choices.contains(answers.get(0).strip().toLowerCase(Locale.ROOT))) {
            return List.of();
        }
        boolean capital = Character.isUpperCase(list.group(1).charAt(0));
        List<FinishedSentence> sentences = new ArrayList<>();
        for (int a = 0; a < answers.size(); a++) {
            String answer = answers.get(a).strip();
            if (answer.isEmpty() || !choices.contains(answer.toLowerCase(Locale.ROOT))) {
                continue;
            }
            String placed = (capital ? Character.toUpperCase(answer.charAt(0)) : Character.toLowerCase(answer.charAt(0)))
                    + answer.substring(1);
            Builder builder = new Builder();
            builder.fixed(cleanText(rawBefore.substring(0, list.start(1))));
            builder.answer(placed);
            builder.fixed(cleanText(rawBefore.substring(list.end(1))));
            sentences.add(builder.build(a));
        }
        return sentences;
    }

