    /** «… border. Link type:» → «… border.»; a closed sentence alone is itself. */
    private static Optional<String> sentenceBeforeLabel(String rawBefore) {
        String text = rawBefore.strip();
        if (END.matcher(text).find()) {
            return Optional.of(text);
        }
        return labelAfterSentence(text);
    }

    /**
     * «… sentence. Verb in infinitive =» → «… sentence.». The turn of a dialogue («A: … B:») is not
     * a label.
     */
    private static Optional<String> labelAfterSentence(String rawBefore) {
        Matcher labelled = SENTENCE_THEN_LABEL.matcher(rawBefore.strip());
        if (labelled.matches() && !SPEAKER.matcher(labelled.group(2).strip()).matches()) {
            return Optional.of(labelled.group(1));
        }
        return Optional.empty();
    }

    private static List<FinishedSentence> sentenceAlone(String rawSentence) {
        Builder builder = new Builder();
        builder.fixed(cleanText(rawSentence));
        FinishedSentence sentence = builder.build(0);
        return sentence.getText().isBlank() ? List.of() : List.of(sentence);
    }

    private static String rawText(List<SentencePartEntity> parts, int from, int to) {
        StringBuilder text = new StringBuilder();
        for (int i = from; i < to; i++) {
            SentencePartEntity part = parts.get(i);
            if (part.getKind() == SentencePartKind.TEXT && part.getText() != null) {
                if (text.length() > 0) {
                    text.append(' ');
                }
                text.append(part.getText());
            }
        }
        return text.toString().strip();
    }

    private static void appendFixed(Builder builder, List<SentencePartEntity> parts, int from, int to) {
        for (int i = from; i < to; i++) {
            SentencePartEntity part = parts.get(i);
            if (part.getKind() == SentencePartKind.TEXT) {
                builder.fixed(cleanText(part.getText()));
            }
        }
    }

    /** The text without its hints, keeping its «a / b» lists (inv. 5 needs them). */
    private static String withoutHints(String text) {
        return normalize(HINT.matcher(text != null ? text : "").replaceAll(" "));
    }

    /** Inv. 1: the text without its hints and its «a / b» lists, in one line, signs glued. */
    static String cleanText(String text) {
        if (text == null) {
            return "";
        }
        String clean = HINT.matcher(text).replaceAll(" ");
        clean = CHOICE.matcher(clean).replaceAll(" ");
        return normalize(clean);
    }

    /** One space between words, none before a sign, contractions glued (inv. 3). */
    private static String normalize(String text) {
        String clean = text.replaceAll("\\s+", " ").strip();
        clean = clean.replaceAll("\\s+([.?!,;:])", "$1");
        clean = clean.replaceAll("(\\w)\\s+((?:['’](?:s|re|m|ve|d|ll)|n['’]t)\\b)", "$1$2");
        return clean;
    }

    /** The accepted answers of a gap: every entry split on «|» only, in order. */
    private static List<String> variants(List<String> options) {
        List<String> variants = new ArrayList<>();
        if (options == null) {
            return variants;
        }
        for (String entry : options) {
            if (entry == null) {
                continue;
            }
            for (String variant : entry.split("\\|", -1)) {
                variants.add(variant.strip());
            }
        }
        return variants;
    }

    /** A sentence of its own: three words or more, a capital and its closing sign. */
    private static boolean isSentence(String answer) {
        String text = answer != null ? answer.strip() : "";
        return words(text) >= 3 && Character.isUpperCase(text.charAt(0)) && END.matcher(text).find();
    }

    private static int words(String text) {
        String stripped = text != null ? text.strip() : "";
        return stripped.isEmpty() ? 0 : stripped.split("\\s+").length;
    }

    /** The same text twice in an exercise is read once, the first time it appears. */
    private static List<FinishedSentence> deduplicated(List<FinishedSentence> sentences) {
        List<FinishedSentence> unique = new ArrayList<>();
        Set<String> seen = new LinkedHashSet<>();
        for (FinishedSentence sentence : sentences) {
            if (sentence.getText() == null || sentence.getText().isBlank()) {
                continue;
            }
            if (seen.add(sentence.getText())) {
                unique.add(sentence);
            }
        }
        return unique;
    }

    // -------------------------------------------------------------------------
    // Building a sentence while keeping where each answer sits
    // -------------------------------------------------------------------------

    /**
     * Joins the fixed text and the answers in order with one space, none before a sign and none
     * before a contraction, and keeps the place of each answer in the joined text (inv. 3, R004).
     */
    private static final class Builder {
        private final StringBuilder text = new StringBuilder();
        private final List<AnswerSpan> answers = new ArrayList<>();

        void fixed(String piece) {
            append(piece);
        }

        void answer(String piece) {
            String clean = normalize(piece != null ? piece : "");
            int start = append(clean);
            if (!clean.isEmpty()) {
                answers.add(new AnswerSpan(start, start + clean.length(), clean));
            }
        }

        /** Appends a piece and returns where it starts. */
        private int append(String piece) {
            if (piece == null || piece.isEmpty()) {
                return text.length();
            }
            if (text.length() > 0 && needsSpace(text.charAt(text.length() - 1), piece)) {
                text.append(' ');
            }
            int start = text.length();
            text.append(piece);
            return start;
        }

        private static boolean needsSpace(char last, String piece) {
            char first = piece.charAt(0);
            if (".?!,;:".indexOf(first) >= 0) {
                return false;
            }
            if (Character.isLetterOrDigit(last) && CONTRACTION.matcher(piece).find()) {
                return false;
            }
            return !Character.isWhitespace(last);
        }

        FinishedSentence build(int answerIndex) {
            return new FinishedSentence(text.toString(), answerIndex, new ArrayList<>(answers));
        }
    }
