/**
 * F-GRAMA-R001: the finished sentence -- what the student reads after answering -- once per
 * accepted answer, with where each answer sits in it. It is the reading of Gramática and
 * Naturalidad, never the plain sentence of the course (which stays as it is, F-HALL-R013) nor the
 * finished exercise of the student view (A-01, frozen for the judges: hook B-20).
 *
 * <ul>
 *   <li>Without hints: the parentheses and the «a / b» lists of the text are left out, and the
 *       option «-» of a multiple choice leaves no text (inv. 1).</li>
 *   <li>When the answer is the whole sentence -- a rewrite, or an answer that is a sentence of its
 *       own after a closed sentence -- only the answer is read, never the starting sentence; a
 *       dialogue is read whole (inv. 2).</li>
 *   <li>Contractions go glued to their word and signs without a space before (inv. 3).</li>
 *   <li>An option that is a label put after the sentence («Link type: sequence», «correct») or an
 *       answer after «=» or «:» leaves the sentence alone; a judgment whose answer is «not correct»
 *       is not read, its sentence is wrong on purpose (inv. 4).</li>
 *   <li>An «a / b» list inside a closed sentence with the gap after it gets the answer in its
 *       place, with the capital of the list: the text the audio was recorded with (inv. 5).</li>
 * </ul>
 *
 * It reads nothing but the exercise and keeps no state: the same exercise gives the same sentences
 * byte for byte in any run (hook B-22).
 */
