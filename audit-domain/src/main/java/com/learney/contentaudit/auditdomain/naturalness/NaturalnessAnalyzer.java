/**
 * FEAT-NATUR: would a native speaker say this sentence this way? It asks one model per finished
 * sentence and marks the most doubtful of each level for the judges to start there. It never counts
 * an error: its findings only rank (R003).
 *
 * <ul>
 *   <li>R001: it reads the finished sentence of the first accepted answer; a sentence without a verb
 *       or of one word does not reach, and nobody is asked about it.</li>
 *   <li>The exercises are gathered while the tree is walked and resolved all at once when the course
 *       closes, through the judges' runtime (FEAT-JEXAM): the plan, {@code resolveAll}, the coverage
 *       and the cost of what is pending. A declared set and the exam run work without code of its
 *       own.</li>
 *   <li>With llama3 in Ollama (the route the gate decision says is available): the number is
 *       ln(P(no)/P(yes)) and a number above the fixed threshold of the level marks the exercise
 *       (R002, R003). Without it, the same question goes to claude -p and its «no» marks (R008), with
 *       no number and no threshold.</li>
 *   <li>F-MLOCAL-R006: a version without an approved exam publishes nothing -- every exercise it
 *       reaches stays not evaluated, with the reason in the run's row --; the exam run always
 *       publishes.</li>
 *   <li>R005: per level, the marked exercises from the most to the least doubtful -- with claude -p,
 *       in the order of the course --, a list any judge reads as its declared set.</li>
 * </ul>
 */
