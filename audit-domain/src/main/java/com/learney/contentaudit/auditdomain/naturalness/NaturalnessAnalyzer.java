    /** R001: a sentence of two words or more, with a verb. */
    static boolean reaches(String sentence, List<NlpToken> tokens) {
        if (sentence == null || sentence.strip().split("\\s+").length < 2 || tokens == null) {
            return false;
        }
        for (NlpToken token : tokens) {
            if (token != null && token.getPosTag() != null && VERB_TAGS.contains(token.getPosTag())) {
                return true;
            }
        }
        return false;
    }

    /** The level of the exercise, as its milestone names it: «A1», «B2». */
    private static String levelOf(AuditNode quiz) {
        Optional<AuditNode> milestone = quiz.ancestor(AuditTarget.MILESTONE);
        if (milestone.isPresent() && milestone.get().getEntity() instanceof AuditableMilestone level) {
            String name = level.getLabel() != null && !level.getLabel().isBlank() ? level.getLabel() : level.getCode();
            return name != null ? name.strip().toUpperCase(Locale.ROOT) : null;
        }
        return null;
    }

    private static SentenceMode modeOf(AuditNode quizNode) {
        AuditNode knowledge = quizNode.getParent();
        if (knowledge != null && knowledge.getEntity() instanceof AuditableKnowledge topic
                && topic.getSentenceMode() != null) {
            return topic.getSentenceMode();
        }
        return SentenceMode.FILL;
    }

    private static String oneDecimal(double value) {
        return String.format(SPANISH, "%.1f", value);
    }

    /** F-HALL-R008: reached but not evaluated -- without score, diagnosis nor finding. */
    private void markUnevaluated(AuditNode node) {
        if (node.getScores() != null) {
            node.getScores().remove(ANALYZER_NAME);
        }
        findings.remove(node);
        if (node.getUnevaluatedBy() == null) {
            node.setUnevaluatedBy(new ArrayList<>());
        }
        if (!node.getUnevaluatedBy().contains(ANALYZER_NAME)) {
            node.getUnevaluatedBy().add(ANALYZER_NAME);
        }
    }

