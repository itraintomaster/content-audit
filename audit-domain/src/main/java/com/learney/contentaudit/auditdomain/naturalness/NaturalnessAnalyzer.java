    private Outcome localOutcome(Reached r, String payload, String examinedVersion, boolean reused) {
        Optional<Double> number = scorer.number(payload);
        if (number.isEmpty()) {
            return null;
        }
        Optional<Double> threshold = config.thresholdFor(examinedVersion, r.level());
        boolean marked = threshold.isPresent() && number.get() > threshold.get();
        NaturalnessDiagnosis diagnosis = new NaturalnessDiagnosis(r.sentence(), r.level(), number.get(),
                threshold.orElse(null), marked, reused, false);
        String observation = marked
                ? "El modelo local duda que un nativo diga «" + r.sentence() + "» (" + oneDecimal(number.get())
                        + "; umbral de " + r.level() + ": " + oneDecimal(threshold.get()) + ")"
                : null;
        return new Outcome(diagnosis, RULE_UNLIKELY_SENTENCE, observation);
    }

    private Outcome alternativeOutcome(Reached r, String payload, boolean reused) {
        Optional<Boolean> nativeWouldSay = scorer.nativeWouldSay(payload);
        if (nativeWouldSay.isEmpty()) {
            return null;
        }
        boolean marked = !nativeWouldSay.get();
        NaturalnessDiagnosis diagnosis = new NaturalnessDiagnosis(r.sentence(), r.level(), null, null, marked, reused,
                true);
        String observation = marked
                ? "claude -p contesta que un nativo no diría «" + r.sentence() + "» (sin Ollama)"
                : null;
        return new Outcome(diagnosis, RULE_NATIVE_SAYS_NO, observation);
    }

    /** Score 1 always: a mark only ranks (F-HALL-R004 inv. 2); the finding goes with a mark. */
    private void publish(Reached r, Outcome outcome) {
        AuditNode node = r.node();
        if (node.getScores() == null) {
            node.setScores(new LinkedHashMap<>());
        }
        node.getScores().put(ANALYZER_NAME, 1.0);
        if (!(node.getDiagnoses() instanceof DefaultQuizDiagnoses)) {
            node.setDiagnoses(new DefaultQuizDiagnoses());
        }
        ((DefaultQuizDiagnoses) node.getDiagnoses()).setNaturalnessDiagnosis(outcome.diagnosis());
        if (outcome.diagnosis().isMarked()) {
            findings.put(node, new FindingDraft(outcome.rule(), "", FindingSeverity.LOW, FindingResolution.RANK_ONLY,
                    new FindingEvidence(List.of(new EvidencePart("Oración terminada", r.sentence())),
                            outcome.observation(), List.of())));
        }
    }

    /**
     * R005: per level, in the order of the course, its marked exercises -- with llama3 from the most
     * to the least doubtful and, with equal numbers, in the order of the course; with claude -p, in
     * the order of the course.
     */
    private NaturalnessQueueDiagnosis queueOf(List<AuditNode> planned, Map<AuditNode, Reached> byNode,
            List<Reached> marked, Map<Reached, Double> numbers, String examinedVersion, boolean local) {
        Map<String, List<Reached>> byLevel = new LinkedHashMap<>();
        for (AuditNode unit : planned) {
            byLevel.computeIfAbsent(byNode.get(unit).level(), level -> new ArrayList<>());
        }
        for (Reached r : marked) {
            byLevel.computeIfAbsent(r.level(), level -> new ArrayList<>()).add(r);
        }
        List<NaturalnessLevelQueue> levels = new ArrayList<>();
        for (Map.Entry<String, List<Reached>> level : byLevel.entrySet()) {
            List<Reached> ordered = new ArrayList<>(level.getValue());
            Comparator<Reached> courseOrder = Comparator.comparingInt(Reached::order);
            if (local) {
                ordered.sort(Comparator.<Reached>comparingDouble(r -> -numbers.getOrDefault(r, 0.0))
                        .thenComparing(courseOrder));
            } else {
                ordered.sort(courseOrder);
            }
            List<String> ids = new ArrayList<>();
            for (Reached r : ordered) {
                ids.add(r.quizId());
            }
            Double threshold = local ? config.thresholdFor(examinedVersion, level.getKey()).orElse(null) : null;
            levels.add(new NaturalnessLevelQueue(level.getKey(), threshold, ids));
        }
        return new NaturalnessQueueDiagnosis(examinedVersion, levels, !local);
    }

    /** Why something stayed not evaluated, in the order of F-MLOCAL-R003, R006 and R008. */
    private String reasonOf(boolean local, boolean publishes, EvaluationRunPolicy policy, EvaluationSession session,
            int pending, int failed, int unreadable) {
        if (pending + failed + unreadable == 0) {
            return null;
        }
        if (!local && (opened == null || opened.getJudgeVersion() == null)) {
            String alternative = opened != null && opened.getStanding() != null ? opened.getStanding().getReason() : null;
            return REASON_NO_TOOL + (gateDecision != null ? gateDecision.getReason() : "")
                    + (alternative != null ? "; claude -p: " + alternative : "");
        }
        if (!publishes) {
            return local
                    ? gateDecision.getReason()
                    : (opened.getStanding() != null ? opened.getStanding().getReason() : null);
        }
        Optional<String> stopped = session != null ? session.unavailableReason() : Optional.empty();
        if (stopped != null && stopped.isPresent()) {
            String tool = local && gateDecision.getStatus() != null ? gateDecision.getStatus().getTool() : "claude -p";
            return tool + REASON_STOPPED + stopped.get();
        }
        if (pending > 0) {
            if (!local && policy != null && policy.getMaxNewEvaluations() == 0) {
                return REASON_NO_BUDGET;
            }
            return "se acabó el tope de naturalness: quedan " + pending + " consultas pendientes";
        }
        if (failed > 0) {
            return "falló la consulta de " + failed + " oraciones";
        }
        return unreadable + " oraciones con " + REASON_UNREADABLE;
    }

