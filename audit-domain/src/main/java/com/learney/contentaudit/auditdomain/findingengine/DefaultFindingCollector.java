/**
 * Collects, right after an analyzer walked the tree and before anything is aggregated, the
 * findings of every node the analyzer evaluated: the levels its card declares and on which it
 * left its own score. Each draft is checked against the card and stamped with what only the
 * engine knows -- analyzer, node, cost of its rule and identity -- so F-HALL-R001, R002, R006
 * inv. 2 and R014 hold by construction. Breaking the contract is a programming error and stops
 * the run ({@link FindingContractViolationException}); it is never isolated like a judge that
 * fails to answer.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
public class DefaultFindingCollector implements FindingCollector {

    /** The course node has no entity; its id is the same one the plan uses for it. */
    static final String COURSE_NODE_ID = "root";

    static final String COURSE_NODE_LABEL = "Curso";

    private static final Comparator<Finding> RULE_THEN_MARKER = Comparator
            .comparing(Finding::getRule)
            .thenComparing(f -> f.getIdentity().getMarker(),
                    Comparator.nullsFirst(Comparator.<String>naturalOrder()));

    @Override
    public void collect(AuditNode root, ContentAnalyzer analyzer, AnalyzerDescriptor card) {
        if (root == null) {
            return;
        }
        walk(root, analyzer, card);
    }

    private void walk(AuditNode node, ContentAnalyzer analyzer, AnalyzerDescriptor card) {
        if (card.getEvaluatedTargets() != null && card.getEvaluatedTargets().contains(node.getTarget())) {
            collectAt(node, analyzer, card);
        }
        if (node.getChildren() != null) {
            for (AuditNode child : node.getChildren()) {
                walk(child, analyzer, card);
            }
        }
    }

    private void collectAt(AuditNode node, ContentAnalyzer analyzer, AnalyzerDescriptor card) {
        String analyzerName = card.getName();
        Double score = node.getScores() != null ? node.getScores().get(analyzerName) : null;
        if (score == null) {
            // Not evaluated here: a container that only receives an average, a quiz the judge
            // left pending or failed (F-HALL-R001 inv. 2). Nothing to ask.
            return;
        }
        FindingNodeRef nodeRef = nodeRef(node);
        String nodeId = nodeRef.getNodeId();

        List<FindingDraft> drafts = analyzer.findingsAt(node);
        if (drafts == null) {
            throw new FindingContractViolationException(analyzerName, nodeId,
                    "findingsAt devolvió null en lugar de una lista");
        }

        List<Finding> stamped = new ArrayList<>();
        Set<String> identities = new HashSet<>();
        boolean countsAsError = false;
        for (FindingDraft draft : drafts) {
            Finding finding = stamp(draft, card, nodeRef);
            if (!identities.add(finding.getIdentity().getKey())) {
                throw new FindingContractViolationException(analyzerName, nodeId,
                        "dos hallazgos con la misma identidad: " + finding.getIdentity().getKey());
            }
            if (finding.getResolution() != FindingResolution.RANK_ONLY) {
                countsAsError = true;
            }
            stamped.add(finding);
        }

        boolean passes = score >= 1.0;
        if (card.getFamily() == AnalyzerFamily.ERRORS) {
            // F-HALL-R004 inv. 1 and 2: a finding that counts as error and a score below 1 go
            // together; a finding that only ranks never lowers the score.
            if (countsAsError && passes) {
                throw new FindingContractViolationException(analyzerName, nodeId,
                        "un hallazgo que cuenta como error en un nodo con puntaje " + score);
            }
            if (!countsAsError && !passes) {
                throw new FindingContractViolationException(analyzerName, nodeId,
                        "puntaje " + score + " menor que 1 sin un hallazgo que cuente como error");
            }
        } else {
            // F-HALL-R001: every node it evaluated below 1 has a finding; none that passes has one.
            if (!passes && stamped.isEmpty()) {
                throw new FindingContractViolationException(analyzerName, nodeId,
                        "puntaje " + score + " menor que 1 sin ningún hallazgo");
            }
            if (passes && !stamped.isEmpty()) {
                throw new FindingContractViolationException(analyzerName, nodeId,
                        "hallazgos en un nodo que pasa, con puntaje " + score);
            }
        }

        if (stamped.isEmpty()) {
            return;
        }
        stamped.sort(RULE_THEN_MARKER);
        if (node.getFindings() == null) {
            node.setFindings(new ArrayList<>());
        }
        // The engine calls the collector analyzer by analyzer in catalog order, so appending
        // keeps the findings of a node in catalog order of their analyzer (F-HALL-R014).
        node.getFindings().addAll(stamped);
    }

    private Finding stamp(FindingDraft draft, AnalyzerDescriptor card, FindingNodeRef nodeRef) {
        String analyzerName = card.getName();
        String nodeId = nodeRef.getNodeId();
        if (draft == null) {
            throw new FindingContractViolationException(analyzerName, nodeId, "un hallazgo nulo");
        }
        AnalyzerRuleCard rule = findRule(card, draft.getRule());
        if (rule == null) {
            throw new FindingContractViolationException(analyzerName, nodeId,
                    "la regla '" + draft.getRule() + "' no figura en su ficha");
        }
        if (draft.getSeverity() == null) {
            throw new FindingContractViolationException(analyzerName, nodeId,
                    "un hallazgo de la regla '" + draft.getRule() + "' sin gravedad");
        }
        if (draft.getResolution() == null) {
            throw new FindingContractViolationException(analyzerName, nodeId,
                    "un hallazgo de la regla '" + draft.getRule() + "' sin resolución");
        }
        if (card.getResolutions() == null || !card.getResolutions().contains(draft.getResolution())) {
            throw new FindingContractViolationException(analyzerName, nodeId,
                    "la resolución " + draft.getResolution() + " no figura en su ficha");
        }
        FindingEvidence evidence = checkedEvidence(draft, analyzerName, nodeId);

        String marker = draft.getMarker() != null && !draft.getMarker().isBlank()
                ? draft.getMarker() : null;
        String key = analyzerName + "|" + rule.getId() + "|" + nodeId
                + (marker != null ? "|" + marker : "");
        return new Finding(analyzerName, rule.getId(), nodeRef, draft.getSeverity(), evidence,
                draft.getResolution(), rule.getCost(), new FindingIdentity(key, marker));
    }

    private FindingEvidence checkedEvidence(FindingDraft draft, String analyzerName, String nodeId) {
        FindingEvidence evidence = draft.getEvidence();
        if (evidence == null || evidence.getExamined() == null || evidence.getExamined().isEmpty()) {
            throw new FindingContractViolationException(analyzerName, nodeId,
                    "un hallazgo de la regla '" + draft.getRule() + "' sin nada examinado en su evidencia");
        }
        for (EvidencePart part : evidence.getExamined()) {
            if (part == null || isBlank(part.getLabel()) || isBlank(part.getText())) {
                throw new FindingContractViolationException(analyzerName, nodeId,
                        "un hallazgo de la regla '" + draft.getRule() + "' con una parte examinada vacía");
            }
        }
        if (isBlank(evidence.getObservation())) {
            throw new FindingContractViolationException(analyzerName, nodeId,
                    "un hallazgo de la regla '" + draft.getRule() + "' sin observación");
        }
        List<FindingNodeRef> related = evidence.getRelatedNodes() != null
                ? new ArrayList<>(evidence.getRelatedNodes()) : new ArrayList<>();
        return new FindingEvidence(new ArrayList<>(evidence.getExamined()), evidence.getObservation(),
                related);
    }

    private static AnalyzerRuleCard findRule(AnalyzerDescriptor card, String ruleId) {
        if (ruleId == null || card.getRules() == null) {
            return null;
        }
        for (AnalyzerRuleCard rule : card.getRules()) {
            if (rule != null && ruleId.equals(rule.getId())) {
                return rule;
            }
        }
        return null;
    }

    static FindingNodeRef nodeRef(AuditNode node) {
        if (node.getEntity() == null) {
            return new FindingNodeRef(node.getTarget(), COURSE_NODE_ID, COURSE_NODE_LABEL);
        }
        String id = node.getEntity().getId() != null ? node.getEntity().getId() : COURSE_NODE_ID;
        String label = node.getEntity().getLabel() != null ? node.getEntity().getLabel() : id;
        return new FindingNodeRef(node.getTarget(), id, label);
    }

    private static boolean isBlank(String value) {
        return value == null || value.isBlank();
    }
}
