    /** Written, inflected regularly, by lemma, or through the table of irregular forms. */
    private boolean matches(String hintWord, String text, String lemma) {
        if (hintWord == null || hintWord.isEmpty() || text == null) {
            return false;
        }
        if (text.equals(hintWord) || hintWord.equals(lemma)) {
            return true;
        }
        if (hintWord.length() >= 3) {
            for (String stem : stems(hintWord)) {
                if (text.startsWith(stem)) {
                    return true;
                }
            }
        }
        return irregularForms.formsOf(hintWord).contains(text)
                || (lemma != null && irregularForms.formsOf(lemma).contains(hintWord))
                || irregularForms.formsOf(text).contains(hintWord);
    }

    /** see → see; hate → hat (hated); try → tri (tried); stop → stopp (stopped). */
    private static Set<String> stems(String word) {
        Set<String> stems = new LinkedHashSet<>();
        stems.add(word);
        int n = word.length();
        if (n >= 4 && word.endsWith("e")) {
            stems.add(word.substring(0, n - 1));
        }
        if (n >= 3 && word.endsWith("y")) {
            stems.add(word.substring(0, n - 1) + "i");
        }
        if (n >= 3 && "aeiouwyx".indexOf(word.charAt(n - 1)) < 0 && "aeiou".indexOf(word.charAt(n - 2)) >= 0) {
            stems.add(word + word.charAt(n - 1));
        }
        stems.removeIf(s -> s.length() < 3);
        return stems;
    }

