/**
 * Compares the hint with the first answer (F-PISTA-R002 to R004), against the tokens and lemmas
 * the course already brings ({@code AuditableQuiz.tokens}, the shared tokenizer on the saved
 * sentence): nothing new is lemmatized. A hint word is in the answer as written, inflected
 * (see → sees, seeing; quiet → quieter; nice → nicely), through its lemma (went → go) or through
 * the closed table of irregular forms, which knows what the shared lemmatizer misses (swum, drunk,
 * best) and which word is a past participle (DOUBT-PISTA-LEMATIZADOR, option A).
 *
 * <p>Each issue carries the fix by rule already computed: the hint drawn from the first answer,
 * with its subject, its «not» and its base words; and its resolution, by the kind of fault
 * (DOUBT-PISTA-CUANDO-MESA, option A, in this one place): a hint word that is not in the answer
 * goes to the panel, because fixing the hint would change what the exercise asks; the rest is
 * fixed by rule, completing the hint, and the answer and its audio stay as they are.
 *
 * <p>Called with a hint without text, it is an exercise that must carry one and does not
 * (R001): the only issue is the missing hint, with the hint the answer gives.
 */
