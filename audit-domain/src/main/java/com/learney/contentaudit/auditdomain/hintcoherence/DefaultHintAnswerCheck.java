    /** The first answer of every gap and the tokens of the saved sentence that belong to it. */
    private final class Answer {
        private final List<String> texts;
        private final List<NlpToken> sentence;
        private final Set<String> words = new LinkedHashSet<>();

        Answer(List<String> texts, List<NlpToken> sentence) {
            this.texts = texts;
            this.sentence = sentence;
            for (String text : texts) {
                Matcher m = ANSWER_WORD.matcher(text.toLowerCase(Locale.ROOT));
                while (m.find()) {
                    String word = m.group();
                    words.add(word);
                    Matcher clitic = CLITIC.matcher(word);
                    if (clitic.matches()) {
                        String host = clitic.group(1);
                        String piece = clitic.group(2);
                        if (piece.equals("n't")) {
                            // spaCy cuts «haven't» into have + n't, «can't» into ca + n't
                            words.add(host);
                        } else if (!host.isEmpty()) {
                            words.add(host);
                        }
                        words.add(piece);
                    }
                }
            }
        }

        List<String> texts() {
            return texts;
        }

        /**
         * The tokens of the saved sentence that belong to the answer: where the words of each first
         * answer appear in a row, cut as the shared tokenizer cuts them («haven't» is have + n't);
         * if they do not, every token that is a word of the answer.
         */
        private List<Integer> answerIndexes() {
            Set<Integer> indexes = new LinkedHashSet<>();
            List<String> sentenceWords = new ArrayList<>();
            for (NlpToken token : sentence) {
                sentenceWords.add(lower(token.getText()));
            }
            for (String text : texts) {
                List<String> answerWords = tokenizerWords(text);
                int at = answerWords.isEmpty() ? -1 : indexOf(sentenceWords, answerWords);
                if (at >= 0) {
                    for (int i = at; i < at + answerWords.size(); i++) {
                        indexes.add(i);
                    }
                } else {
                    for (int i = 0; i < sentenceWords.size(); i++) {
                        if (answerWords.contains(sentenceWords.get(i))) {
                            indexes.add(i);
                        }
                    }
                }
            }
            return new ArrayList<>(indexes);
        }

        /** Whether a hint word is in the answer: written, inflected, by lemma or irregular form. */
        boolean contains(String word) {
            for (NlpToken token : sentence) {
                if (matches(word, lower(token.getText()), lower(token.getLemma()))) {
                    return true;
                }
            }
            for (String piece : words) {
                Set<String> lemmas = CLITIC_LEMMAS.get(piece);
                if (lemmas != null) {
                    for (String lemma : lemmas) {
                        if (lemma.equals(word) || irregularForms.formsOf(lemma).contains(word)) {
                            return true;
                        }
                    }
                    continue;
                }
                if (matches(word, piece, piece)) {
                    return true;
                }
            }
            return false;
        }

        /** The verbs of the answer that are not auxiliaries, by the tag of the shared tokenizer. */
        List<NlpToken> verbs() {
            List<NlpToken> verbs = new ArrayList<>();
            for (int i : answerIndexes()) {
                NlpToken token = sentence.get(i);
                if (!"VERB".equals(token.getPosTag())) {
                    continue;
                }
                String lemma = lower(token.getLemma());
                if (GRAMMATICAL_VERBS.contains(lemma)) {
                    continue;
                }
                if (lemma.equals("have") && auxiliaryHave(i)) {
                    continue; // «'ve swum», «would have drunk», «have to go»
                }
                verbs.add(token);
            }
            return verbs;
        }

        private boolean auxiliaryHave(int index) {
            for (int j = index + 1; j < sentence.size(); j++) {
                NlpToken next = sentence.get(j);
                String text = lower(next.getText());
                if ("ADV".equals(next.getPosTag()) || "PART".equals(next.getPosTag()) && !text.equals("to")) {
                    continue;
                }
                return text.equals("to") || text.equals("got") || text.equals("been")
                        || irregularForms.isPastParticiple(text) || (text.length() > 3 && text.endsWith("ed"));
            }
            return false;
        }

        /** The subject pronouns of the answer: never one right after a verb or a preposition. */
        List<String> subjects() {
            List<String> subjects = new ArrayList<>();
            for (int i : answerIndexes()) {
                NlpToken token = sentence.get(i);
                String text = lower(token.getText());
                if (!ANSWER_SUBJECTS.contains(text) || !"PRON".equals(token.getPosTag())) {
                    continue;
                }
                if (i > 0) {
                    String before = sentence.get(i - 1).getPosTag();
                    if ("VERB".equals(before) || "ADP".equals(before)) {
                        continue; // «told you», «for her»: an object
                    }
                }
                if (!subjects.contains(text)) {
                    subjects.add(text);
                }
            }
            return subjects;
        }

        /** The words of the answer with meaning, for a hint drawn from an answer without verbs. */
        List<NlpToken> contentTokens() {
            List<NlpToken> content = new ArrayList<>();
            for (int i : answerIndexes()) {
                NlpToken token = sentence.get(i);
                String tag = token.getPosTag();
                if ("NOUN".equals(tag) || "PROPN".equals(tag) || "ADJ".equals(tag) || "ADV".equals(tag)
                        || "VERB".equals(tag) || "NUM".equals(tag)) {
                    content.add(token);
                }
            }
            return content;
        }

        List<String> plainWords() {
            List<String> plain = new ArrayList<>();
            for (String text : texts) {
                for (String word : DefaultHintReader.words(text)) {
                    String lower = word.toLowerCase(Locale.ROOT);
                    if (!DefaultHintReader.FUNCTION_WORDS.contains(lower)
                            && !DefaultHintReader.SUBJECT_PRONOUNS.contains(lower) && !plain.contains(lower)) {
                        plain.add(lower);
                    }
                }
            }
            return plain;
        }
    }

    private static final Pattern TOKENIZER_WORD = Pattern.compile("[A-Za-z0-9:']+");

    /** The words of an answer as the shared tokenizer cuts them: «haven't» → have, n't; «It's» → it, 's. */
    private static List<String> tokenizerWords(String text) {
        List<String> words = new ArrayList<>();
        Matcher m = TOKENIZER_WORD.matcher(text == null ? "" : text.toLowerCase(Locale.ROOT));
        while (m.find()) {
            String word = m.group();
            Matcher clitic = CLITIC.matcher(word);
            if (clitic.matches() && !clitic.group(1).isEmpty()) {
                words.add(clitic.group(1));
                words.add(clitic.group(2));
            } else {
                words.add(word);
            }
        }
        return words;
    }

    /** Where a run of words starts inside the words of the sentence, or -1. */
    private static int indexOf(List<String> sentence, List<String> run) {
        for (int start = 0; start + run.size() <= sentence.size(); start++) {
            boolean all = true;
            for (int k = 0; k < run.size(); k++) {
                if (!sentence.get(start + k).equals(run.get(k))) {
                    all = false;
                    break;
                }
            }
            if (all) {
                return start;
            }
        }
        return -1;
    }

