    /**
     * «(you / see)» for «Who ___ (I / see)?» answered «are you seeing»: the subject of the
     * answer, its «not», the words of the hint that are in it and the base form of every verb the
     * hint did not announce; an answer without verbs gives the base form of its words («(spoon)»).
     */
    private String propose(ExerciseHint hint, Answer answer) {
        List<String> slots = new ArrayList<>();
        List<String> subjects = answer.subjects();
        if (!subjects.isEmpty()) {
            String subject = subjects.get(0);
            slots.add(subject.equals("i") ? "I" : subject);
        }
        if (NEGATION.matcher(String.join(" ", answer.texts())).find()) {
            slots.add("not");
        }
        int fixed = slots.size();
        if (hint != null && hint.getWords() != null && !hint.isChoice()) {
            for (String word : hint.getWords()) {
                if (answer.contains(word) && !slots.contains(word)) {
                    slots.add(word);
                }
            }
        }
        for (NlpToken verb : answer.verbs()) {
            String lemma = lower(verb.getLemma());
            boolean announced = slots.subList(fixed, slots.size()).stream()
                    .anyMatch(w -> matches(w, lower(verb.getText()), lemma));
            if (!announced && !slots.contains(lemma)) {
                slots.add(lemma);
            }
        }
        if (slots.size() == fixed) {
            for (NlpToken token : answer.contentTokens()) {
                String lemma = "PROPN".equals(token.getPosTag()) ? token.getLemma() : lower(token.getLemma());
                if (!slots.contains(lemma)) {
                    slots.add(lemma);
                }
            }
        }
        if (slots.size() == fixed) {
            for (String word : answer.plainWords()) {
                if (!slots.contains(word)) {
                    slots.add(word);
                }
            }
        }
        return slots.isEmpty() ? null : "(" + String.join(" / ", slots) + ")";
    }

