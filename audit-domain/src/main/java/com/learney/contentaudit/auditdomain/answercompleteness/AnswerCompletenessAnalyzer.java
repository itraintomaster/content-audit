    @Override
    public List<FindingDraft> findingsAt(AuditNode node) {
        if (node == null || node.getTarget() != AuditTarget.QUIZ
                || !(node.getEntity() instanceof AuditableQuiz quiz)
                || !(node.getDiagnoses() instanceof DefaultQuizDiagnoses diagnoses)) {
            return List.of();
        }
        Optional<AnswerCompletenessDiagnosis> found = diagnoses.getAnswerCompletenessDiagnosis();
        if (found.isEmpty()) {
            return List.of();
        }
        AnswerCompletenessDiagnosis diagnosis = found.get();
        String statement = studentViewRenderer.render(quiz).getStatement();
        List<FindingDraft> drafts = new ArrayList<>();
        Set<String> markers = new LinkedHashSet<>();
        for (MissingAcceptedForm form : diagnosis.getMissingForms()) {
            String accepted = String.join(" | ", acceptedOf(quiz, form.getGapIndex()));
            boolean limit = equates(form.getEquivalenceClass());
            List<EvidencePart> examined = new ArrayList<>(List.of(new EvidencePart("Ejercicio", statement),
                    new EvidencePart("Acepta", accepted), new EvidencePart("Falta", form.getMissingForm())));
            String where;
            if (limit) {
                String missingRule = missingCorrectorRule(quiz, form);
                examined.add(new EvidencePart("Le falta al corrector", missingRule));
                where = "El corrector ya iguala esta clase y sigue sin aceptarla: se arregla en el corrector y no en"
                        + " el curso, " + missingRule;
            } else {
                where = "La iguala el corrector nuevo: se arregla en el corrector y no en el curso";
            }
            String observation = statement + " → acepta " + accepted + "; falta " + form.getMissingForm() + ". "
                    + where + "; la primera respuesta y su audio no cambian.";
            // R005: the identity is the form; the same form missing in two gaps gets the second gap's number.
            String rule = ruleOf(form.getEquivalenceClass());
            String marker = form.getMissingForm().toLowerCase(Locale.ROOT);
            if (!markers.add(rule + "|" + marker)) {
                marker = marker + " (hueco " + (form.getGapIndex() + 1) + ")";
                markers.add(rule + "|" + marker);
            }
            drafts.add(new FindingDraft(rule, marker, form.getSeverity(),
                    limit ? FindingResolution.RANK_ONLY : FindingResolution.RULE,
                    new FindingEvidence(examined, observation, List.of())));
        }
        Map<FormRequestSource, Integer> bySource = new EnumMap<>(FormRequestSource.class);
        for (FormRequest request : diagnosis.getFormRequests()) {
            boolean instructions = request.getSource() == FormRequestSource.INSTRUCTIONS;
            String sourceName = instructions ? "consigna" : "miniteoria";
            int n = bySource.merge(request.getSource(), 1, Integer::sum);
            String marker = n == 1 ? sourceName : sourceName + "-" + n;
            String form = request.getRequestedForm() == RequestedForm.SHORT ? "la forma contraída" : "la forma larga";
            List<EvidencePart> examined = List.of(
                    new EvidencePart(instructions ? "Consigna" : "Miniteoría",
                            instructions ? quiz.getInstructions() : quiz.getMiniTheory()),
                    new EvidencePart("Pide", request.getPhrase()));
            String observation = (instructions ? "La consigna" : "La miniteoría") + " pide " + form + ": «"
                    + request.getPhrase() + "». "
                    + (request.isRemovableByRule()
                            ? "Se arregla sacando el pedido; el audio no cambia."
                            : "El pedido es la lección del ejercicio: va a la mesa.");
            drafts.add(new FindingDraft(RULE_FORM_REQUEST, marker, FindingSeverity.LOW,
                    request.isRemovableByRule() ? FindingResolution.RULE : FindingResolution.PANEL,
                    new FindingEvidence(examined, observation, List.of())));
        }
        return drafts;
    }

    static String ruleOf(FormEquivalenceClass equivalenceClass) {
        return switch (equivalenceClass) {
            case CONTRACTION -> RULE_CONTRACTED_AND_LONG;
            case BE_NEGATION -> RULE_BE_NEGATIONS;
            case SPELLING, PREPOSITION -> RULE_SPELLINGS;
        };
    }

    /**
     * Whether the corrector installed already equates a class: then a missing form of it is a
     * limit of the corrector, a rule it lacks; if not, the new corrector fixes it.
     */
    private boolean equates(FormEquivalenceClass equivalenceClass) {
        return equated.computeIfAbsent(equivalenceClass, c -> switch (c) {
            case CONTRACTION -> correctorMatcher.sameAnswer("I do not know.", "I don't know.");
            case BE_NEGATION -> correctorMatcher.sameAnswer("It isn't here.", "It's not here.");
            case SPELLING -> correctorMatcher.sameAnswer("travelled", "traveled");
            case PREPOSITION -> correctorMatcher.sameAnswer("I'll wait until five.", "I'll wait till five.");
        });
    }

