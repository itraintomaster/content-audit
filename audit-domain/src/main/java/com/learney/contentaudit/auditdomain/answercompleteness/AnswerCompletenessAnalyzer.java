/**
 * FEAT-RESPC: does the corrector accept every form of the answer, and no instructions ask for
 * one? An errors analyzer over the write-in exercises; the multiple choice is FEAT-OMVAL's (R006).
 *
 * <ul>
 *   <li>R002 to R004: for every accepted answer of every gap, its equivalent forms -- contracted
 *       and long, the other short negation of be, the other spelling of the closed list, till and
 *       until --, each asked to the corrector's comparison with the sentence around the gap. Every
 *       form it rejects is a finding identified by the form (R005).</li>
 *   <li>R007: the instructions the student sees and the mini theory, asked whether they request a
 *       form.</li>
 * </ul>
 *
 * The severity of a missing form is high if the mini theory or the statement shows it, low if it
 * is the long form of a short answer («No, it isn't»), and medium otherwise. It is fixed by rule:
 * in the corrector, when it is of a class the new corrector equates, or adding it after «|» when
 * the corrector installed already equates the class and still rejects it, a limit as «has
 * trained». The first answer does not change, and neither does its audio.
 */
