    static final String ANALYZER_NAME = "answer-completeness";

    static final String DESCRIPTION =
            "Arma las formas equivalentes de cada respuesta aceptada y las compara como el corrector";

    /** R002: the contracted and the long form are both accepted. */
    static final String RULE_CONTRACTED_AND_LONG = "contracted-and-long-forms";

    /** R003: the two short negations of be are both accepted. */
    static final String RULE_BE_NEGATIONS = "be-short-negations";

    /** R004: both spellings of the closed list, and until and till, are accepted. */
    static final String RULE_SPELLINGS = "spellings-and-till";

    /** R007: no instructions and no mini theory ask for a form. */
    static final String RULE_FORM_REQUEST = "form-request";

    private static final Pattern SHORT_ANSWER = Pattern.compile("(?i)\\b(yes|no),?\\s+[a-z]+$");

