    @Override
    public Void onQuiz(AuditNode node) {
        if (node == null || !(node.getEntity() instanceof AuditableQuiz quiz) || quiz.getMultipleChoice() != null) {
            return null; // R006: only the write-in exercises
        }
        String statement = studentViewRenderer.render(quiz).getStatement();
        List<MissingAcceptedForm> missing = new ArrayList<>();
        Set<String> seen = new LinkedHashSet<>();
        List<SentencePartEntity> parts = quiz.getSentenceParts() != null ? quiz.getSentenceParts() : List.of();
        int gapIndex = -1;
        for (int i = 0; i < parts.size(); i++) {
            SentencePartEntity part = parts.get(i);
            if (part == null || part.getKind() != SentencePartKind.CLOZE) {
                continue;
            }
            gapIndex++;
            List<String> options = part.getOptions();
            if (options == null || options.isEmpty()) {
                continue;
            }
            // The sentence around the gap as the corrector reads it: the text parts next to it.
            String before = textOf(parts, i - 1);
            String after = textOf(parts, i + 1);
            GapContext context = new GapContext(before, after);
            String wordBefore = lastWord(withoutHints(before));
            boolean shortAnswer = SHORT_ANSWER.matcher(withoutHints(before).strip()).find()
                    && withoutHints(after).chars().noneMatch(Character::isLetter);
            for (String accepted : alternatives(options)) {
                for (EquivalentForm form : formGenerator.generate(accepted, wordBefore)) {
                    if (correctorMatcher.accepts(context, options, form.getForm())) {
                        continue;
                    }
                    if (!seen.add(gapIndex + "|" + compact(form.getForm()))) {
                        continue;
                    }
                    missing.add(new MissingAcceptedForm(gapIndex, accepted, form.getForm(),
                            form.getEquivalenceClass(),
                            severity(form.getForm(), accepted, quiz.getMiniTheory(), statement, shortAnswer)));
                }
            }
        }
        List<FormRequest> requests = requestDetector.detect(quiz.getInstructions(), quiz.getMiniTheory());
        double score = missing.isEmpty() && requests.isEmpty() ? 1.0 : 0.0;
        node.getScores().put(ANALYZER_NAME, score);
        if (!(node.getDiagnoses() instanceof DefaultQuizDiagnoses)) {
            node.setDiagnoses(new DefaultQuizDiagnoses());
        }
        ((DefaultQuizDiagnoses) node.getDiagnoses()).setAnswerCompletenessDiagnosis(new AnswerCompletenessDiagnosis(
                List.copyOf(missing), List.copyOf(requests), correctorMatcher.tableVersion(), score));
        return null;
    }

    /** R005: high if the mini theory or the statement shows it; low if the long form of a short answer. */
    private static FindingSeverity severity(String form, String accepted, String miniTheory, String statement,
            boolean shortAnswer) {
        if (shows(miniTheory, form) || shows(statement, form)) {
            return FindingSeverity.HIGH;
        }
        if (shortAnswer && !form.contains("'") && accepted.contains("'")) {
            return FindingSeverity.LOW;
        }
        return FindingSeverity.MEDIUM;
    }

    private static boolean shows(String text, String form) {
        if (text == null || text.isBlank() || form.isBlank()) {
            return false;
        }
        String haystack = unify(text.replace("$", "")).toLowerCase(Locale.ROOT);
        String needle = unify(form).toLowerCase(Locale.ROOT).replaceAll("[.!?]+$", "");
        return Pattern.compile("(?<![a-z'])" + Pattern.quote(needle) + "(?![a-z'])").matcher(haystack).find();
    }

