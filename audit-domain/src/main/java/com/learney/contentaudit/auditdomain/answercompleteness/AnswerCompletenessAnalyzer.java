    private static List<String> acceptedOf(AuditableQuiz quiz, int gapIndex) {
        List<SentencePartEntity> parts = quiz.getSentenceParts() != null ? quiz.getSentenceParts() : List.of();
        int g = -1;
        for (SentencePartEntity part : parts) {
            if (part != null && part.getKind() == SentencePartKind.CLOZE && ++g == gapIndex) {
                return alternatives(part.getOptions() != null ? part.getOptions() : List.of());
            }
        }
        return List.of();
    }

    /** The accepted answers, split on «|» only (F-RESPC-R001). */
    static List<String> alternatives(List<String> options) {
        List<String> alternatives = new ArrayList<>();
        for (String option : options) {
            if (option == null) {
                continue;
            }
            for (String alternative : option.split("\\|", -1)) {
                if (!alternative.isBlank() && !alternatives.contains(alternative.strip())) {
                    alternatives.add(alternative.strip());
                }
            }
        }
        return alternatives;
    }

    private static String textOf(List<SentencePartEntity> parts, int index) {
        if (index < 0 || index >= parts.size()) {
            return "";
        }
        SentencePartEntity part = parts.get(index);
        return part != null && part.getKind() == SentencePartKind.TEXT && part.getText() != null ? part.getText() : "";
    }

    private static String withoutHints(String text) {
        return text.replaceAll("\\([^)]*\\)", " ").replaceAll("\\s+", " ").strip();
    }

    private static String lastWord(String text) {
        Matcher m = Pattern.compile("[A-Za-z'’]+").matcher(text);
        String last = "";
        while (m.find()) {
            last = m.group();
        }
        return last;
    }

    private static String unify(String text) {
        return text.replace('’', '\'').replace('‘', '\'').replace('′', '\'').replace('`', '\'');
    }

    private static String compact(String text) {
        return unify(text).toLowerCase(Locale.ROOT).replaceAll("[\\s!?:;,.\\-_'\"]", "");
    }
