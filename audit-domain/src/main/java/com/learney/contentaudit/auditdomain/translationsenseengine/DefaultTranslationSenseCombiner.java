/**
 * F-TRSEN-R003 / R004, José's option C of 30/9 (DOUBT-TRSEN-COMBINAR): how the two verdicts of a
 * quiz become its outcome.
 *
 * <ul>
 *   <li>Both pass: no finding, score 1.</li>
 *   <li>Both fail: one finding per condition either judge marked, resolved at the panel, with the
 *       higher of the two severities -- never blocking: the translation is seen after answering,
 *       so a blocking one is taken as high --, and in its evidence the failing fragment and the
 *       line in Spanish of each judge that marked it. The score is the one the configuration gives
 *       to the highest severity.</li>
 *   <li>They disagree: a single {@code judges-disagree} finding that only ranks, with both
 *       verdicts in its evidence, and score 1: the quiz goes to the tray to be untied, and the
 *       count of errors is not inflated by disagreements.</li>
 * </ul>
 *
 * A failing verdict of both judges that names no condition cannot be shown as an error: it is
 * rejected, so the analyzer leaves the quiz unevaluated instead of inventing a condition.
 */
