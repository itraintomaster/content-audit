    /** The failures a finding can show: with a condition and a severity. */
    private static List<TranslationSenseFailure> usableFailures(TranslationSenseVerdict verdict) {
        List<TranslationSenseFailure> usable = new ArrayList<>();
        if (verdict == null || verdict.getFailures() == null) {
            return usable;
        }
        for (TranslationSenseFailure failure : verdict.getFailures()) {
            if (failure != null && failure.getCondition() != null && failure.getSeverity() != null) {
                usable.add(failure);
            }
        }
        return usable;
    }

    /** The failing fragment and the judge's line in Spanish, with the severity the judge gave. */
    private static String describe(TranslationSenseFailure failure) {
        String fragment = isBlank(failure.getFragment()) ? null : quoted(failure.getFragment().strip());
        String line = isBlank(failure.getEvidence()) ? null : failure.getEvidence().strip();
        String text;
        if (fragment != null && line != null) {
            text = fragment + ": " + line;
        } else if (fragment != null) {
            text = fragment;
        } else if (line != null) {
            text = line;
        } else {
            text = "marcó «" + conditionName(failure.getCondition()) + "» sin señalar el fragmento";
        }
        return text + " (" + severityName(failure.getSeverity()) + ")";
    }

    private static String quoted(String fragment) {
        return fragment.startsWith("«") ? fragment : "«" + fragment + "»";
    }

    /** Never blocking (F-TRSEN-R004): a blocking failure of a judge is taken as high. */
    private static FindingSeverity asFindingSeverity(FindingSeverity severity) {
        return severity == FindingSeverity.BLOCKING ? FindingSeverity.HIGH : severity;
    }

    /** BLOCKING is the highest severity and LOW the lowest (declaration order of the enum). */
    private static FindingSeverity higher(FindingSeverity current, FindingSeverity candidate) {
        if (candidate == null) {
            return current;
        }
        if (current == null || candidate.ordinal() < current.ordinal()) {
            return candidate;
        }
        return current;
    }

    static String ruleOf(TranslationSenseCondition condition) {
        return switch (condition) {
            case SAME_MEANING -> RULE_SAME_MEANING;
            case NATIVE_WOULD_SAY -> RULE_NATIVE_WOULD_SAY;
            case WORDS_GO_TOGETHER -> RULE_WORDS_GO_TOGETHER;
            case LEVEL_REGISTER -> RULE_LEVEL_REGISTER;
        };
    }

    private static String headline(TranslationSenseCondition condition) {
        return switch (condition) {
            case SAME_MEANING -> "El inglés y la traducción no dicen lo mismo";
            case NATIVE_WOULD_SAY -> "Un nativo no lo diría así";
            case WORDS_GO_TOGETHER -> "Hay palabras que no van juntas";
            case LEVEL_REGISTER -> "El registro no es del nivel";
        };
    }

    private static String conditionName(TranslationSenseCondition condition) {
        if (condition == null) {
            return "una condición";
        }
        return switch (condition) {
            case SAME_MEANING -> "dicen lo mismo";
            case NATIVE_WOULD_SAY -> "un nativo lo diría así";
            case WORDS_GO_TOGETHER -> "las palabras van juntas";
            case LEVEL_REGISTER -> "registro del nivel";
        };
    }

    private static String severityName(FindingSeverity severity) {
        if (severity == null) {
            return "sin gravedad";
        }
        return switch (severity) {
            case BLOCKING -> "bloqueante";
            case HIGH -> "alta";
            case MEDIUM -> "media";
            case LOW -> "baja";
        };
    }

    private static boolean isBlank(String value) {
        return value == null || value.isBlank();
    }
