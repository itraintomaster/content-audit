    static final String RULE_SAME_MEANING = "same-meaning";

    static final String RULE_NATIVE_WOULD_SAY = "native-would-say";

    static final String RULE_WORDS_GO_TOGETHER = "words-go-together";

    static final String RULE_LEVEL_REGISTER = "level-register";

    static final String RULE_JUDGES_DISAGREE = "judges-disagree";

    static final String FROM_ENGLISH = "Juez desde el inglés";

    static final String FROM_TRANSLATION = "Juez desde la traducción";

    private final TranslationSenseConfig config;

    public DefaultTranslationSenseCombiner(TranslationSenseConfig config) {
        this.config = config;
    }

    @Override
    public TranslationSenseOutcome combine(TranslationSenseVerdict fromEnglish,
            TranslationSenseVerdict fromTranslation) {
        if (fromEnglish == null || fromTranslation == null) {
            throw new IllegalArgumentException("translation-sense needs the verdicts of both judges");
        }
        boolean englishPasses = fromEnglish.isPasses();
        boolean translationPasses = fromTranslation.isPasses();
        if (englishPasses && translationPasses) {
            return new TranslationSenseOutcome(TranslationSenseAgreement.BOTH_PASS, List.of(), 1.0);
        }
        if (!englishPasses && !translationPasses) {
            return bothFail(fromEnglish, fromTranslation);
        }
        return split(fromEnglish, fromTranslation);
    }

    // -------------------------------------------------------------------------
    // Both fail: one finding per condition, counting as error
    // -------------------------------------------------------------------------

    private TranslationSenseOutcome bothFail(TranslationSenseVerdict fromEnglish,
            TranslationSenseVerdict fromTranslation) {
        Map<TranslationSenseCondition, List<JudgeFailure>> byCondition = new EnumMap<>(TranslationSenseCondition.class);
        collect(byCondition, FROM_ENGLISH, fromEnglish);
        collect(byCondition, FROM_TRANSLATION, fromTranslation);
        if (byCondition.isEmpty()) {
            throw new IllegalStateException("translation-sense: both judges say the quiz fails without naming "
                    + "any condition with its severity, so there is no finding to show");
        }

        List<FindingDraft> findings = new ArrayList<>();
        FindingSeverity highest = null;
        for (Map.Entry<TranslationSenseCondition, List<JudgeFailure>> entry : byCondition.entrySet()) {
            TranslationSenseCondition condition = entry.getKey();
            FindingSeverity severity = null;
            List<EvidencePart> examined = new ArrayList<>();
            String firstLine = null;
            for (JudgeFailure judgeFailure : entry.getValue()) {
                TranslationSenseFailure failure = judgeFailure.failure();
                severity = higher(severity, asFindingSeverity(failure.getSeverity()));
                examined.add(new EvidencePart(judgeFailure.judge(), describe(failure)));
                if (firstLine == null && !isBlank(failure.getEvidence())) {
                    firstLine = failure.getEvidence().strip();
                }
            }
            String observation = headline(condition) + (firstLine != null ? ": " + firstLine : "");
            findings.add(new FindingDraft(ruleOf(condition), null, severity, FindingResolution.PANEL,
                    new FindingEvidence(examined, observation, List.of())));
            highest = higher(highest, severity);
        }
        return new TranslationSenseOutcome(TranslationSenseAgreement.BOTH_FAIL, List.copyOf(findings),
                config.getScoreFor(highest));
    }

    private static void collect(Map<TranslationSenseCondition, List<JudgeFailure>> byCondition, String judge,
            TranslationSenseVerdict verdict) {
        for (TranslationSenseFailure failure : usableFailures(verdict)) {
            byCondition.computeIfAbsent(failure.getCondition(), c -> new ArrayList<>())
                    .add(new JudgeFailure(judge, failure));
        }
    }

