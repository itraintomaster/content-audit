/**
 * F-MCVALE-R002 and R003: turns the verdict of the judge «otra opción también vale» into what the
 * multiple choice analyzer needs and nothing else -- a {@code JUDGED} judgment with the findings of
 * the rule {@code another-option-valid}, the judge's score as data and the provenance.
 *
 * <ul>
 *   <li>One finding per incorrect option the judge says also counts, marked with the option as the
 *       student sees it: high when it is just as valid, medium when it is defensible but less
 *       natural. An option the judge lists twice gives one finding, with the worse severity; a label
 *       that is no option of the exercise, or that is the correct option itself, gives none.</li>
 *   <li>One blocking finding marked {@value #CORRECT_MARKER} when the option marked correct is not
 *       valid (the inverted key, as {@code …47cc} of the fixed exam): the student cannot get it
 *       right.</li>
 *   <li>Before anything, an option that is the same answer as the correct one in another form
 *       («isn't» and «is not», a capital letter) is dropped with the corrector's comparison, in the
 *       context of the gap: it goes to {@code droppedAsForm} and gives no finding, because a rule of
 *       the multiple choice analyzer marks it and it is never counted twice (F-JEXAM-R012).</li>
 *   <li>The score is 1 without findings and otherwise the configured one for the most severe
 *       (F-MCVALE-R003); it is data: the score of the exercise is decided by the analyzer that hosts
 *       the judge (F-OMVAL-R005).</li>
 * </ul>
 *
 * Every finding is resolved at the panel and its evidence shows the exercise as the student sees it
 * -- the instructions, the statement with «___» and its hint, the options with the correct one
 * marked -- plus the option at stake and the judge's reason.
 */
