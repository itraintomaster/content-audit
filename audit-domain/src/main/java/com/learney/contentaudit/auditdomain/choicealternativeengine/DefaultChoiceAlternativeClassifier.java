    private static FindingDraft optionAlsoValid(List<EvidencePart> seen, AlsoValid option, String correctLabel,
            boolean correctValid, ChoiceAlternativeVerdict verdict) {
        List<EvidencePart> examined = new ArrayList<>(seen);
        String shown = shownLabel(option.label(), option.index());
        examined.add(new EvidencePart("Otra opción que también vale", shown));
        addIfPresent(examined, "Razón del juez", firstNonBlank(option.reason(), verdict.getRationale()));

        boolean medium = option.severity() == FindingSeverity.MEDIUM;
        String observation;
        if (isBlank(correctLabel)) {
            observation = "«" + shown + "» " + (medium ? "es defendible" : "también vale") + " en este contexto";
        } else if (!correctValid) {
            // The inverted key: the option that counts is this one, not the one marked correct.
            observation = "«" + shown + "» " + (medium ? "es defendible" : "vale") + " en este contexto y la "
                    + "marcada como correcta, «" + correctLabel + "», no";
        } else if (medium) {
            observation = "«" + shown + "» es defendible en este contexto, aunque menos natural que «" + correctLabel
                    + "», la marcada como correcta";
        } else {
            observation = "«" + shown + "» también vale en este contexto, igual que «" + correctLabel
                    + "», la marcada como correcta, y el ejercicio acepta una sola";
        }
        return new FindingDraft(RULE, shown, option.severity(), FindingResolution.PANEL,
                new FindingEvidence(examined, observation, List.of()));
    }

    private static FindingDraft correctNotValid(List<EvidencePart> seen, String correctLabel,
            ChoiceAlternativeVerdict verdict, Map<Integer, AlsoValid> alsoValid) {
        List<EvidencePart> examined = new ArrayList<>(seen);
        addIfPresent(examined, "Marcada como correcta", correctLabel);
        addIfPresent(examined, "Por qué no vale", firstNonBlank(verdict.getCorrectProblem(), verdict.getRationale()));
        List<String> valid = new ArrayList<>();
        for (AlsoValid option : alsoValid.values()) {
            valid.add("«" + shownLabel(option.label(), option.index()) + "»");
        }
        addIfPresent(examined, "Opciones que sí valen", String.join(", ", valid));

        String observation = "La opción marcada como correcta"
                + (isBlank(correctLabel) ? "" : ", «" + correctLabel + "»,")
                + " no vale en este contexto: el alumno no puede acertar"
                + (valid.isEmpty() ? "" : "; vale " + String.join(", ", valid));
        return new FindingDraft(RULE, CORRECT_MARKER, FindingSeverity.BLOCKING, FindingResolution.PANEL,
                new FindingEvidence(examined, observation, List.of()));
    }

    /**
     * An incorrect option that also counts is high when the judge says it is just as valid and
     * medium when it is defensible: blocking belongs only to the inverted key and low is not in
     * this judge's scale. Without a severity, an option that is valid is taken as just as valid.
     */
    static FindingSeverity severityOfAlternative(FindingSeverity severity) {
        if (severity == FindingSeverity.MEDIUM || severity == FindingSeverity.LOW) {
            return FindingSeverity.MEDIUM;
        }
        return FindingSeverity.HIGH;
    }

    private static FindingSeverity worst(List<FindingDraft> findings) {
        FindingSeverity worst = null;
        for (FindingDraft finding : findings) {
            if (worst == null || finding.getSeverity().ordinal() < worst.ordinal()) {
                worst = finding.getSeverity();
            }
        }
        return worst;
    }

