    @Override
    public ChoiceAlternativeJudgment classify(ChoiceAlternativeVerdict verdict, AuditableQuiz quiz,
            EvaluationResolution resolution) {
        if (verdict == null) {
            throw new IllegalArgumentException("No hay veredicto que clasificar");
        }
        List<MultipleChoiceItemEntity> items = itemsOf(quiz);
        MultipleChoiceItemEntity correct = correctOf(quiz);
        String correctLabel = correct != null ? correct.getLabel() : null;
        GapContext context = gapContext(quiz);

        // F-MCVALE-R002: the incorrect options that also count, in the student's order.
        Map<Integer, AlsoValid> alsoValid = new TreeMap<>();
        List<String> droppedAsForm = new ArrayList<>();
        List<ChoiceAlternativeOption> alternatives = verdict.getValidAlternatives() != null
                ? verdict.getValidAlternatives()
                : List.of();
        for (ChoiceAlternativeOption alternative : alternatives) {
            if (alternative == null) {
                continue;
            }
            int index = indexOfOption(items, alternative.getLabel());
            if (index < 0 || items.get(index) == correct) {
                // Not an option the student can choose, or the correct one itself.
                continue;
            }
            String label = items.get(index).getLabel();
            if (correctLabel != null && correctorMatcher.sameAnswer(context, correctLabel, label)) {
                // F-JEXAM-R012: the same answer in another form is marked by the multiple choice
                // analyzer's own rule, never by this judge.
                if (!droppedAsForm.contains(label)) {
                    droppedAsForm.add(label);
                }
                continue;
            }
            FindingSeverity severity = severityOfAlternative(alternative.getSeverity());
            AlsoValid previous = alsoValid.get(index);
            if (previous == null) {
                alsoValid.put(index, new AlsoValid(index, label, severity, alternative.getReason()));
            } else if (severity.ordinal() < previous.severity().ordinal()) {
                alsoValid.put(index, new AlsoValid(index, label, severity,
                        isBlank(alternative.getReason()) ? previous.reason() : alternative.getReason()));
            }
        }

        // F-MCVALE-R003: the inverted key is blocking, whatever else counts.
        boolean correctInvalid = correct != null && !verdict.isCorrectIsValid();

        QuizStudentView view = quiz != null ? studentViewRenderer.render(quiz) : null;
        List<EvidencePart> seen = exerciseAsSeen(quiz, view, items, correct);
        List<FindingDraft> findings = new ArrayList<>();
        if (correctInvalid) {
            findings.add(correctNotValid(seen, correctLabel, verdict, alsoValid));
        }
        for (AlsoValid option : alsoValid.values()) {
            findings.add(optionAlsoValid(seen, option, correctLabel, !correctInvalid, verdict));
        }

        Double score = findings.isEmpty() ? SCORE_WITHOUT_FINDINGS : config.getScoreFor(worst(findings));
        return new ChoiceAlternativeJudgment(
                quiz != null ? quiz.getId() : null,
                ChoiceAlternativeJudgmentStatus.JUDGED,
                verdict,
                List.copyOf(droppedAsForm),
                List.copyOf(findings),
                score,
                resolution != null ? resolution.getEvaluatorVersion() : null,
                resolution != null && resolution.getKind() == EvaluationResolutionKind.REUSED,
                null);
    }

