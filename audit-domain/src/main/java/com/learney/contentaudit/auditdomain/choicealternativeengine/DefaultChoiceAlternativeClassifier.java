    private static List<MultipleChoiceItemEntity> itemsOf(AuditableQuiz quiz) {
        MultipleChoiceEntity multipleChoice = quiz != null ? quiz.getMultipleChoice() : null;
        List<MultipleChoiceItemEntity> items = new ArrayList<>();
        if (multipleChoice == null || multipleChoice.getItems() == null) {
            return items;
        }
        for (MultipleChoiceItemEntity item : multipleChoice.getItems()) {
            if (item != null) {
                items.add(item);
            }
        }
        return items;
    }

    private static MultipleChoiceItemEntity correctOf(AuditableQuiz quiz) {
        MultipleChoiceEntity multipleChoice = quiz != null ? quiz.getMultipleChoice() : null;
        return multipleChoice != null ? multipleChoice.correctItem().orElse(null) : null;
    }

    /**
     * The option a label of the judge names: the one written exactly so, or else the first one
     * equal to it without surrounding spaces, quotes or case; -1 when it names none.
     */
    static int indexOfOption(List<MultipleChoiceItemEntity> items, String label) {
        if (label == null) {
            return -1;
        }
        for (int i = 0; i < items.size(); i++) {
            if (label.equals(items.get(i).getLabel())) {
                return i;
            }
        }
        String wanted = loose(label);
        if (wanted.isEmpty()) {
            return -1;
        }
        for (int i = 0; i < items.size(); i++) {
            if (wanted.equals(loose(items.get(i).getLabel()))) {
                return i;
            }
        }
        return -1;
    }

    private static String loose(String text) {
        if (text == null) {
            return "";
        }
        String unquoted = WRAPPING_QUOTES.matcher(text.strip()).replaceAll("");
        return unquoted.strip().replaceAll("\\s+", " ").toLowerCase(Locale.ROOT);
    }

    /** The sentence around the gap, without its hints, as the corrector reads it (F-RESPC-R001). */
    static GapContext gapContext(AuditableQuiz quiz) {
        List<SentencePartEntity> parts = quiz != null && quiz.getSentenceParts() != null
                ? quiz.getSentenceParts()
                : List.of();
        int gap = -1;
        for (int i = 0; i < parts.size(); i++) {
            SentencePartEntity part = parts.get(i);
            if (part != null && part.getKind() == SentencePartKind.CLOZE) {
                gap = i;
                break;
            }
        }
        if (gap < 0) {
            return new GapContext("", "");
        }
        return new GapContext(textOf(parts.subList(0, gap)), textOf(parts.subList(gap + 1, parts.size())));
    }

    private static String textOf(List<SentencePartEntity> parts) {
        List<String> texts = new ArrayList<>();
        for (SentencePartEntity part : parts) {
            if (part == null || part.getKind() != SentencePartKind.TEXT || part.getText() == null) {
                continue;
            }
            String text = HINT.matcher(part.getText()).replaceAll(" ").strip();
            if (!text.isEmpty()) {
                texts.add(text);
            }
        }
        return String.join(" ", texts).replaceAll("\\s+", " ").strip();
    }

    // -------------------------------------------------------------------------
    // Text helpers
    // -------------------------------------------------------------------------

    private static void addIfPresent(List<EvidencePart> parts, String label, String text) {
        if (!isBlank(text)) {
            parts.add(new EvidencePart(label, text));
        }
    }

    private static String firstNonBlank(String... values) {
        for (String value : values) {
            if (!isBlank(value)) {
                return value;
            }
        }
        return null;
    }

    private static boolean isBlank(String value) {
        return value == null || value.isBlank();
    }
