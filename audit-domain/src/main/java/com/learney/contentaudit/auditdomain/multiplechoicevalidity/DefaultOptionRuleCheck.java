    private static void capitals(List<MultipleChoiceItemEntity> items, Gap gap, List<OptionIssue> issues) {
        if (gap.opensSentence()) {
            List<MultipleChoiceItemEntity> dashes = new ArrayList<>();
            for (MultipleChoiceItemEntity item : items) {
                if (isDash(label(item))) {
                    dashes.add(item);
                }
            }
            if (!dashes.isEmpty()) {
                // The dash leaves the sentence starting in lowercase: the panel rearms the
                // exercise, and with it the capital of the other options.
                for (MultipleChoiceItemEntity dash : dashes) {
                    issues.add(new OptionIssue(RULE_CAPITAL, OptionIssueKind.DASH_AT_SENTENCE_START, label(dash), null,
                            dash.getIncidence() > 0.0));
                }
            } else {
                for (MultipleChoiceItemEntity item : items) {
                    String text = label(item).strip();
                    int first = firstLetter(text);
                    if (first >= 0 && Character.isLowerCase(text.charAt(first))) {
                        issues.add(new OptionIssue(RULE_CAPITAL, OptionIssueKind.LOWERCASE_SENTENCE_START,
                                label(item), null, item.getIncidence() > 0.0));
                    }
                }
            }
        }
        for (MultipleChoiceItemEntity item : items) {
            if (LOWERCASE_I.matcher(label(item)).find()) {
                issues.add(new OptionIssue(RULE_CAPITAL, OptionIssueKind.LOWERCASE_I, label(item), null,
                        item.getIncidence() > 0.0));
            }
        }
    }

