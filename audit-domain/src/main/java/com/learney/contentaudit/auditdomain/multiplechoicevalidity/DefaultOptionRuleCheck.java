    private static void article(List<MultipleChoiceItemEntity> items, Gap gap, List<OptionIssue> issues) {
        Matcher m = ARTICLE_BEFORE.matcher(withoutHints(gap.allBefore));
        if (!m.find()) {
            return;
        }
        String article = m.group(1);
        boolean asksVowel = article.equalsIgnoreCase("an");
        for (MultipleChoiceItemEntity item : items) {
            String text = label(item).strip();
            if (text.isEmpty() || !Character.isLetter(text.charAt(0))) {
                continue;
            }
            if (startsWithVowelSound(text) != asksVowel) {
                issues.add(new OptionIssue(RULE_ARTICLE, OptionIssueKind.ARTICLE_GIVES_AWAY, label(item), article,
                        item.getIncidence() > 0.0));
            }
        }
    }

    static boolean startsWithVowelSound(String word) {
        String w = word.strip();
        if (VOWEL_SOUND_H.matcher(w).find()) {
            return true;
        }
        if (CONSONANT_SOUND.matcher(w).find()) {
            return false;
        }
        return !w.isEmpty() && "aeiou".indexOf(Character.toLowerCase(w.charAt(0))) >= 0;
    }

    // -------------------------------------------------------------------------

    private static String label(MultipleChoiceItemEntity item) {
        return item.getLabel() != null ? item.getLabel() : "";
    }

    static boolean isDash(String label) {
        return DASHES.contains(label.strip());
    }

    private static int firstLetter(String text) {
        for (int i = 0; i < text.length(); i++) {
            if (Character.isLetter(text.charAt(i))) {
                return i;
            }
        }
        return -1;
    }

    static String withoutHints(String text) {
        return HINT.matcher(text == null ? "" : text).replaceAll(" ").replaceAll("\\s+", " ").strip();
    }

    /**
     * The gap of the exercise and the text around it: the text parts right next to it, as the
     * corrector reads them (R002), and all the text before and after it (R003, R004).
     */
    static final class Gap {
        final String before;
        final String after;
        final String allBefore;
        final String allAfter;

        private Gap(String before, String after, String allBefore, String allAfter) {
            this.before = before;
            this.after = after;
            this.allBefore = allBefore;
            this.allAfter = allAfter;
        }

        static Gap of(List<SentencePartEntity> parts) {
            List<SentencePartEntity> list = parts != null ? parts : List.of();
            int gap = -1;
            for (int i = 0; i < list.size(); i++) {
                if (list.get(i) != null && list.get(i).getKind() == SentencePartKind.CLOZE) {
                    gap = i;
                    break;
                }
            }
            if (gap < 0) {
                return new Gap("", "", "", "");
            }
            StringBuilder allBefore = new StringBuilder();
            for (int i = 0; i < gap; i++) {
                allBefore.append(' ').append(text(list.get(i)));
            }
            StringBuilder allAfter = new StringBuilder();
            for (int i = gap + 1; i < list.size(); i++) {
                SentencePartEntity part = list.get(i);
                allAfter.append(' ')
                        .append(part != null && part.getKind() == SentencePartKind.CLOZE ? "___" : text(part));
            }
            return new Gap(adjacentText(list, gap - 1), adjacentText(list, gap + 1), allBefore.toString().strip(),
                    allAfter.toString().strip());
        }

        /** R003: first, or after a final mark or «A:» / «B:», and what follows ends in a final mark. */
        boolean opensSentence() {
            String b = withoutHints(allBefore);
            String a = withoutHints(allAfter);
            return ENDS_A_SENTENCE.matcher(a).find() && (b.isEmpty() || OPENS_AFTER.matcher(b).find());
        }

        private static String adjacentText(List<SentencePartEntity> parts, int index) {
            if (index < 0 || index >= parts.size()) {
                return "";
            }
            SentencePartEntity part = parts.get(index);
            return part != null && part.getKind() == SentencePartKind.TEXT ? text(part) : "";
        }

        private static String text(SentencePartEntity part) {
            return part != null && part.getText() != null ? part.getText() : "";
        }
    }
