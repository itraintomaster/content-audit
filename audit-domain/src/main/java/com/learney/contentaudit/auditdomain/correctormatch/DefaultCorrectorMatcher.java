    static String normalizeWritten(String s) {
        String lowercased = s.toLowerCase(Locale.ROOT);
        StringBuilder sb = new StringBuilder(lowercased.length());
        for (int i = 0; i < lowercased.length(); i++) {
            char c = lowercased.charAt(i);
            switch (c) {
                case ' ', '!', '?', ':', ';', ',', '.', '-', '_', '\'', '"', '`', '′', '‘', '’',
                        '“', '”' -> {
                    // removed, as the corrector removes them
                }
                default -> sb.append(c);
            }
        }
        String decomposed = Normalizer.normalize(sb, Normalizer.Form.NFD);
        StringBuilder withoutMarks = new StringBuilder(decomposed.length());
        decomposed.codePoints().forEach(cp -> {
            if (Character.getType(cp) != Character.NON_SPACING_MARK) {
                withoutMarks.appendCodePoint(cp);
            }
        });
        return Normalizer.normalize(withoutMarks, Normalizer.Form.NFC);
    }

    /** The hints between parentheses are not part of the sentence around the gap. */
    static String withoutHints(String s) {
        if (s == null) {
            return "";
        }
        StringBuilder sb = new StringBuilder(s.length());
        int depth = 0;
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c == '(') {
                if (depth == 0) {
                    sb.append(' ');
                }
                depth++;
            } else if (c == ')' && depth > 0) {
                depth--;
            } else if (depth == 0) {
                sb.append(c);
            }
        }
        return sb.toString();
    }

