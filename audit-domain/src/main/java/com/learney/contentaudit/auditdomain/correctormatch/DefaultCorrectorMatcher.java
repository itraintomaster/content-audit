    private String readLong(String sentence) {
        String s = unifyApostrophes(sentence);
        List<Token> tokens = tokenize(s);
        StringBuilder out = new StringBuilder(s.length() + 16);
        int cursor = 0;
        for (int i = 0; i < tokens.size(); i++) {
            Read read = readToken(tokens, i);
            if (read == null) {
                continue;
            }
            out.append(s, cursor, tokens.get(i).start);
            out.append(' ').append(read.reading()).append(' ');
            cursor = tokens.get(read.last()).end;
            i = read.last();
        }
        out.append(s.substring(cursor));
        return out.toString();
    }

    private List<Token> tokenize(String s) {
        List<Token> tokens = new ArrayList<>();
        int i = 0;
        while (i < s.length()) {
            int cp = s.codePointAt(i);
            int size = Character.charCount(cp);
            if (isBoundary(cp)) {
                tokens.add(new Token(i, i + size, s.substring(i, i + size), "", true));
                i += size;
            } else if (startsAWord(s, i)) {
                int j = i;
                while (j < s.length()) {
                    int next = s.codePointAt(j);
                    if (!isWordRune(next)) {
                        break;
                    }
                    j += Character.charCount(next);
                }
                String raw = s.substring(i, j);
                Token token = new Token(i, j, raw, raw.toLowerCase(Locale.ROOT), false);
                splitClitics(token, withApostrophe(token.lower));
                tokens.add(token);
                i = j;
            } else {
                i += size;
            }
        }
        return tokens;
    }

    private static boolean isBoundary(int cp) {
        return ".,;:!?/¿¡…—–".indexOf(cp) >= 0;
    }

    private static boolean isWordRune(int cp) {
        return Character.isLetter(cp) || Character.isDigit(cp) || cp == '\'' || cp == '-';
    }

    /** A word starts with a letter or a digit, or with an apostrophe followed by a letter. */
    private static boolean startsAWord(String s, int i) {
        int cp = s.codePointAt(i);
        if (Character.isLetter(cp) || Character.isDigit(cp)) {
            return true;
        }
        int size = Character.charCount(cp);
        if (cp != '\'' || i + size >= s.length()) {
            return false;
        }
        return Character.isLetter(s.codePointAt(i + size));
    }

    private String withApostrophe(String word) {
        String contracted = withoutApostrophe.get(word);
        return contracted != null ? contracted : word;
    }

    /**
     * Separates what is contracted from the word: «shouldn't've» is should with n't and 've. If
     * what is left is not a clean word («o'clock», «boys'»), nothing is contracted.
     */
    private void splitClitics(Token token, String word) {
        String host = word;
        List<String> clitics = new ArrayList<>();
        while (true) {
            boolean found = false;
            for (String suffix : cliticSuffixes) {
                if (host.endsWith(suffix)) {
                    host = host.substring(0, host.length() - suffix.length());
                    clitics.add(0, suffix);
                    found = true;
                    break;
                }
            }
            if (!found && host.endsWith("n't")
                    && negatedAuxiliaries.containsKey(host.substring(0, host.length() - 3))) {
                host = host.substring(0, host.length() - 3);
                clitics.add(0, "n't");
                found = true;
            }
            if (!found) {
                break;
            }
        }
        if (clitics.isEmpty() || !isCleanHost(host)) {
            token.host = word;
            token.clitics = List.of();
            return;
        }
        token.host = host;
        token.clitics = clitics;
    }

    private static boolean isCleanHost(String host) {
        for (int i = 0; i < host.length(); ) {
            int cp = host.codePointAt(i);
            if (!Character.isLetter(cp) && cp != '-') {
                return false;
            }
            i += Character.charCount(cp);
        }
        return true;
    }

    /**
     * Reads word i: its long form and the last word it covers (a negative question takes its
     * subject too: «doesn't she» is «does she not»). Null when it has no long form, or when which
     * one cannot be told: then the word stays as written.
     */
    private Read readToken(List<Token> tokens, int i) {
        Token t = tokens.get(i);
        if (t.boundary) {
            return null;
        }
        if (t.clitics.isEmpty()) {
            return readPlainWord(tokens, i);
        }
        if (t.clitics.size() == 1 && t.clitics.get(0).equals("n't")) {
            return readNegation(tokens, i);
        }

        String host = t.host;
        if (host.isEmpty() && i > 0 && !tokens.get(i - 1).boundary) {
            host = tokens.get(i - 1).lower;
        }

        List<String> parts = new ArrayList<>();
        if (!t.host.isEmpty()) {
            parts.add(hostWord(t));
        }
        List<String> after = followingWords(tokens, i);
        for (int k = 0; k < t.clitics.size(); k++) {
            List<String> next = new ArrayList<>(tentativeLongForms(t.clitics.subList(k + 1, t.clitics.size())));
            next.addAll(after);
            String reading = readClitic(t.clitics.get(k), host, next);
            if (reading == null) {
                return null;
            }
            parts.add(reading);
        }
        return new Read(String.join(" ", parts), i);
    }

    /** A word without anything contracted: a listed spelling, or till. The rest stays as it is. */
    private Read readPlainWord(List<Token> tokens, int i) {
        String lower = tokens.get(i).lower;
        String american = spellings.get(lower);
        if (american != null) {
            return new Read(american, i);
        }
        String preposition = prepositions.get(lower);
        if (preposition != null && isThePreposition(tokens, i)) {
            return new Read(preposition, i);
        }
        return null;
    }

    /**
     * till is until, but not when it is the noun («the till») or the verb («They till the land»,
     * «to till the soil»): the word before tells.
     */
    private static boolean isThePreposition(List<Token> tokens, int i) {
        if (i > 0 && !tokens.get(i - 1).boundary) {
            String before = tokens.get(i - 1).lower;
            return !(DETERMINERS.contains(before) || POSSESSIVES.contains(before)
                    || SUBJECT_PRONOUNS.contains(before) || MODALS.contains(before) || before.equals("to"));
        }
        return true;
    }

    private String hostWord(Token t) {
        if (t.clitics.get(0).equals("n't")) {
            return negatedAuxiliaries.get(t.host);
        }
        return t.host;
    }

    /** The words that follow, up to the next sign that cuts the sentence. */
    private static List<String> followingWords(List<Token> tokens, int i) {
        List<String> words = new ArrayList<>();
        for (int j = i + 1; j < tokens.size() && !tokens.get(j).boundary; j++) {
            words.add(tokens.get(j).lower);
        }
        return words;
    }

    /** What each contracted part says, to look at what follows another in the same word. */
    private List<String> tentativeLongForms(List<String> clitics) {
        List<String> words = new ArrayList<>(clitics.size());
        for (String clitic : clitics) {
            if (clitic.equals("n't")) {
                words.add(notReading);
                continue;
            }
            List<String> readings = cliticReadings.get(clitic);
            words.add(readings != null && readings.size() == 1 ? readings.get(0) : clitic);
        }
        return words;
    }

    private String readClitic(String clitic, String host, List<String> next) {
        if (clitic.equals("n't")) {
            return notReading;
        }
        List<String> readings = cliticReadings.get(clitic);
        if (readings == null) {
            return null;
        }
        return switch (clitic) {
            case "'ve" -> allowed(readings, readHave(next));
            case "'s" -> allowed(readings, readApostropheS(host, next));
            case "'d" -> allowed(readings, readApostropheD(host, next));
            default -> readings.size() == 1 ? readings.get(0) : null;
        };
    }

    /** The long form the grammar chose, if the table has it. */
    private static String allowed(List<String> readings, String reading) {
        return reading != null && readings.contains(reading) ? reading : null;
    }

    /**
     * An auxiliary with «n't». In a question the not goes after the subject: «Doesn't she
     * dance?» is «Does she not dance?», and «Does not she dance?» is still wrong.
     */
    private Read readNegation(List<Token> tokens, int i) {
        String aux = negatedAuxiliaries.get(tokens.get(i).host);
        int prev = i - 1;
        boolean atStart = prev < 0 || tokens.get(prev).boundary;
        String before = atStart ? "" : tokens.get(prev).lower;
        boolean asking = atStart || QUESTION_WORDS.contains(before) || CONJUNCTIONS.contains(before);
        int next = i + 1;
        boolean hasNext = next < tokens.size() && !tokens.get(next).boundary;

        if (asking && hasNext && SUBJECT_PRONOUNS.contains(tokens.get(next).lower)) {
            if (!invertsNegativeQuestions) {
                return null;
            }
            String auxiliary = aux.equals("are") && tokens.get(next).lower.equals("i") ? "am" : aux;
            return new Read(auxiliary + " " + tokens.get(next).lower + " " + notReading, next);
        }

        // At the start, without a pronoun behind, it is a question with another subject («Didn't
        // the dogs eat?») or an order («Don't be late»). The order is opened; the question is not:
        // its long form takes the not after a subject that can be long.
        if (atStart || QUESTION_WORDS_BEFORE_THE_SUBJECT.contains(before)) {
            if (aux.equals("do") && atStart && (!hasNext || !startsANounPhrase(tokens.get(next)))) {
                return new Read("do " + notReading, i);
            }
            return null;
        }
        return new Read(aux + " " + notReading, i);
    }

    private static boolean startsANounPhrase(Token t) {
        if (DETERMINERS.contains(t.lower) || POSSESSIVES.contains(t.lower) || isNumber(t.lower)) {
            return true;
        }
        int first = t.raw.isEmpty() ? 0 : t.raw.codePointAt(0);
        return Character.isUpperCase(first) && !t.lower.equals("i");
    }

    /**
     * «'ve»: if what follows is something you have («I've a car»), have is to own, which is not
     * contracted in American English, and it stays as written.
     */
    private static String readHave(List<String> next) {
        if (!next.isEmpty() && (POSSESSION_STARTERS.contains(next.get(0)) || isNumber(next.get(0)))) {
            return null;
        }
        return "have";
    }

    /** «'s»: us after let, and otherwise is or has by what follows. */
    private static String readApostropheS(String host, List<String> next) {
        if (host.equals("let")) {
            return "us";
        }
        if (PRONOUN_HOSTS.contains(host)) {
            return readSAfterPronoun(host, next);
        }
        return readSAfterNoun(next);
    }

    /** How far the adverbs that do not tell anything go, and whether they said degree or ever. */
    private record Skipped(int k, boolean degree, boolean ever) {
    }

    private static String readSAfterPronoun(String host, List<String> next) {
        Skipped skipped = skipAdverbs(next, 0);
        int k = skipped.k();
        boolean ever = skipped.ever();
        if (skipped.degree()) {
            return "is"; // «She's very tired»
        }

        boolean inverted = false;
        if (QUESTION_HOSTS.contains(host) && k < next.size() && INVERTED_SUBJECTS.contains(next.get(k))) {
            inverted = true; // «Where's he gone?»
            Skipped more = skipAdverbs(next, k + 1);
            k = more.k();
            if (more.degree()) {
                return "is";
            }
            ever = ever || more.ever();
        }

        if (k == next.size()) {
            if (inverted || (k > 0 && next.get(k - 1).equals("not"))) {
                return "is"; // «Where's he?», «No, it's not.»
            }
            return null; // at the end of the sentence it is not contracted: no way to know
        }

        String word = next.get(k);
        List<String> rest = next.subList(k + 1, next.size());
        if (word.equals("been") || word.equals("got") || word.equals("gotten")) {
            return "has";
        }
        if (isGerund(word)) {
            return "is";
        }
        if (isParticiple(word)) {
            return readSBeforeParticiple(word, rest, inverted, ever);
        }
        if (QUESTION_HOSTS.contains(host) && !inverted && participleAhead(rest)) {
            return null; // «Where's the cat gone?»: the subject is long and cannot be told
        }
        return "is";
    }

    /** Between is and has when a participle comes after «'s». */
    private static String readSBeforeParticiple(String word, List<String> rest, boolean inverted, boolean ever) {
        boolean object = objectFollows(word, rest);
        if ((word.equals("used") || word.equals("supposed")) && !rest.isEmpty() && rest.get(0).equals("to")) {
            return "is"; // «She's used to running», «It's supposed to snow»
        }
        if (ever) {
            return "has"; // «the best film she's ever seen»
        }
        if (ADJECTIVE_PARTICIPLES.contains(word)) {
            return object ? "has" : "is"; // «She's made a cake» / «It's crowded»
        }
        if (object || inverted || INTRANSITIVE_PARTICIPLES.contains(word)) {
            return "has"; // «She's broken her leg», «What's she done?», «He's arrived»
        }
        if (!rest.isEmpty() && rest.get(0).equals("by")) {
            return "is"; // «the garden that's maintained by the gardener»: passive
        }
        return null; // «It's broken»: it can be both
    }

    /**
     * «'s» after a noun, which is almost always a possessive («Mary's house»). It is opened only
     * when what follows cannot go after a possessive.
     */
    private static String readSAfterNoun(List<String> next) {
        int k = 0;
        boolean negated = false;
        boolean perfect = false;
        boolean ever = false;
        while (k < next.size() && SKIPPED_ADVERBS.contains(next.get(k))) {
            switch (next.get(k)) {
                case "not" -> negated = true;
                case "ever" -> {
                    perfect = true;
                    ever = true;
                }
                case "just", "already", "never", "recently", "finally" -> perfect = true;
                default -> {
                    // an adverb that says nothing about is or has
                }
            }
            k++;
        }
        if (negated) {
            return readSAfterPronoun("", next); // «Peter's not coming»: a possessive takes no not
        }
        if (k == next.size()) {
            return null;
        }
        String word = next.get(k);
        List<String> rest = next.subList(k + 1, next.size());
        if (word.equals("been") || word.equals("got") || word.equals("gotten")) {
            return "has"; // «Tom's been sleeping»
        }
        if (word.equals("a") || word.equals("an") || word.equals("the") || PLACE_WORDS.contains(word)) {
            return "is"; // «Mary's a doctor», «Mary's in the kitchen»
        }
        if (isGerund(word) && !rest.isEmpty() && continuesAGerund(rest.get(0))) {
            return "is"; // «Peter's reading a book»; «Peter's reading glasses» stays
        }
        if (isParticiple(word) && perfect) {
            return readSBeforeParticiple(word, rest, false, ever); // «My brother's just bought a car»
        }
        return null;
    }

    /** «'d»: had before a participle or better, would before a verb in its base form. */
    private static String readApostropheD(String host, List<String> next) {
        if (QUESTION_WORDS_BEFORE_THE_SUBJECT.contains(host) || host.equals("what")) {
            return null; // «Where'd you go?» is did
        }
        int k = skipAdverbs(next, 0).k();
        if (k == next.size()) {
            return null;
        }
        String word = next.get(k);
        if (word.equals("better") || word.equals("been") || word.equals("got") || word.equals("gotten")) {
            return "had";
        }
        if (word.equals("rather") || word.equals("have") || word.equals("be")) {
            return "would";
        }
        if (PARTICIPLES_LIKE_THE_BASE.contains(word)) {
            return null; // «She'd read the book» can be both
        }
        if (isParticiple(word)) {
            return "had";
        }
        if (isGerund(word) || isNotAVerb(word)) {
            return null;
        }
        return "would";
    }

    private static Skipped skipAdverbs(List<String> next, int from) {
        int k = from;
        boolean degree = false;
        boolean ever = false;
        while (k < next.size() && (SKIPPED_ADVERBS.contains(next.get(k)) || DEGREE_ADVERBS.contains(next.get(k)))) {
            if (DEGREE_ADVERBS.contains(next.get(k))) {
                degree = true;
            }
            if (next.get(k).equals("ever")) {
                ever = true;
            }
            k++;
        }
        return new Skipped(k, degree, ever);
    }

    private static boolean isGerund(String word) {
        return word.length() >= 5 && word.endsWith("ing");
    }

    private static boolean isParticiple(String word) {
        if (IRREGULAR_PARTICIPLES.contains(word)) {
            return true;
        }
        return word.length() > 3 && word.endsWith("ed") && !NOT_PARTICIPLES.contains(word);
    }

    private static boolean isNumber(String word) {
        if (NUMBERS.contains(word)) {
            return true;
        }
        return !word.isEmpty() && Character.isDigit(word.codePointAt(0));
    }

    /** Whether the object of the participle follows it: then the verb is active and «'s» is has. */
    private static boolean objectFollows(String participle, List<String> rest) {
        if (rest.isEmpty()) {
            return false;
        }
        String word = rest.get(0);
        if (NAMING_PARTICIPLES.contains(participle)) {
            return OBJECT_PRONOUNS.contains(word);
        }
        if (DETERMINERS.contains(word) || POSSESSIVES.contains(word) || OBJECT_PRONOUNS.contains(word)
                || isNumber(word)) {
            return true;
        }
        return !PREPOSITIONS.contains(word) && !PARTICLES.contains(word) && !SKIPPED_ADVERBS.contains(word)
                && !DEGREE_ADVERBS.contains(word) && !OTHER_ADVERBS.contains(word)
                && !CONJUNCTIONS.contains(word) && !SUBJECT_PRONOUNS.contains(word);
    }

    private static boolean participleAhead(List<String> rest) {
        for (int j = 0; j < rest.size() && j < 2; j++) {
            if (isParticiple(rest.get(j)) && !ADJECTIVE_PARTICIPLES.contains(rest.get(j))) {
                return true;
            }
        }
        return false;
    }

    private static boolean continuesAGerund(String word) {
        return DETERMINERS.contains(word) || POSSESSIVES.contains(word) || OBJECT_PRONOUNS.contains(word)
                || PREPOSITIONS.contains(word) || AFTER_A_GERUND.contains(word);
    }

    private static boolean isNotAVerb(String word) {
        return DETERMINERS.contains(word) || POSSESSIVES.contains(word) || OBJECT_PRONOUNS.contains(word)
                || SUBJECT_PRONOUNS.contains(word) || PREPOSITIONS.contains(word) || PARTICLES.contains(word)
                || isNumber(word);
    }

