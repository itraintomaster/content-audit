import java.util.List;
import java.util.Map;
import javax.annotation.processing.Generated;

/**
 * F-UNICA-R001: what the single-answer judge reads is exactly what the student sees before
 * answering, and its fingerprint is exactly that.
 *
 * <ul>
 *   <li>{@code title}: the title of the quiz copy, the one the app shows above the exercise;</li>
 *   <li>{@code instructions}: the instructions of the quiz copy, the ones the app shows -- never the
 *       topic's;</li>
 *   <li>{@code exercise}: the statement with «___» in every gap and its hint, as the student view
 *       renders it (F-RONDA1-R001);</li>
 *   <li>{@code acceptedAnswers}: one line per gap, «Hueco N: a | b», the answers already split on
 *       «|».</li>
 * </ul>
 *
 * The translation, the mini theory and the audio are shown only after answering, so they never
 * enter: changing them never pays again. An absent value is {@code ""}, never null, and the map
 * has these four keys in this order and nothing else -- changing them after paying pays again.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
public class DefaultSingleAnswerSubjectBuilder implements SingleAnswerSubjectBuilder {

    static final String TITLE = "title";

    static final String INSTRUCTIONS = "instructions";

    static final String EXERCISE = "exercise";

    static final String ACCEPTED_ANSWERS = "acceptedAnswers";

    private final QuizStudentViewRenderer studentViewRenderer;

    public DefaultSingleAnswerSubjectBuilder(QuizStudentViewRenderer studentViewRenderer) {
        this.studentViewRenderer = studentViewRenderer;
    }

    @Override
    public EvaluationSubject build(AuditNode quizNode) {
        if (quizNode == null || !(quizNode.getEntity() instanceof AuditableQuiz quiz)) {
            throw new IllegalArgumentException("single-answer juzga ejercicios: el nodo no tiene uno");
        }
        QuizStudentView view = studentViewRenderer.render(quiz);

        Map<String, String> content = new LinkedHashMap<>();
        content.put(TITLE, orEmpty(quiz.getLabel()));
        content.put(INSTRUCTIONS, orEmpty(quiz.getInstructions()));
        content.put(EXERCISE, orEmpty(view != null ? view.getStatement() : null));
        content.put(ACCEPTED_ANSWERS, acceptedAnswers(view != null ? view.getGaps() : null));
        return new EvaluationSubject(quiz.getId(), content);
    }

    /** One line per gap, in the order of the statement, numbered from 1 as the verdict numbers them. */
    private static String acceptedAnswers(List<StudentGapView> gaps) {
        if (gaps == null) {
            return "";
        }
        List<String> lines = new ArrayList<>();
        for (int i = 0; i < gaps.size(); i++) {
            StudentGapView gap = gaps.get(i);
            List<String> accepted = gap != null && gap.getAcceptedAnswers() != null
                    ? gap.getAcceptedAnswers()
                    : List.of();
            lines.add("Hueco " + (i + 1) + ": " + String.join(" | ", accepted));
        }
        return String.join("\n", lines);
    }

    private static String orEmpty(String value) {
        return value != null ? value : "";
    }
}
