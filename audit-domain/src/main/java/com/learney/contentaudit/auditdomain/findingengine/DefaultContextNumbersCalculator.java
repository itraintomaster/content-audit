    private static List<AnalyzerScore> analyzerScores(AuditNode node, List<AnalyzerDescriptor> cards) {
        List<AnalyzerScore> result = new ArrayList<>();
        Map<String, Double> scores = node.getScores();
        if (scores == null || scores.isEmpty()) {
            return result;
        }
        for (AnalyzerDescriptor card : cards) {
            String name = card.getName();
            Double score = scores.get(name);
            String prefix = name + "/";
            List<SubMetricScore> subMetrics = new ArrayList<>();
            for (Map.Entry<String, Double> entry : scores.entrySet()) {
                if (entry.getKey().startsWith(prefix) && entry.getValue() != null) {
                    subMetrics.add(new SubMetricScore(entry.getKey().substring(prefix.length()),
                            entry.getValue()));
                }
            }
            if (score == null && subMetrics.isEmpty()) {
                continue;
            }
            result.add(new AnalyzerScore(name, card.getFamily(), score, subMetrics));
        }
        return result;
    }

    private static Double vocabularyScore(List<AnalyzerScore> analyzerScores) {
        double sum = 0.0;
        int count = 0;
        for (AnalyzerScore s : analyzerScores) {
            if (s.getFamily() == AnalyzerFamily.VOCABULARY && s.getScore() != null) {
                sum += s.getScore();
                count++;
            }
        }
        return count == 0 ? null : sum / count;
    }

