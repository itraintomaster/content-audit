    private static Tally quizTally(AuditNode quiz, List<AnalyzerDescriptor> errorCards,
            List<AuditNode> ancestors) {
        Tally tally = new Tally(errorCards.size());
        tally.quizzes = 1;
        FindingSeverity highest = null;
        boolean anyError = false;
        boolean notFullyEvaluated = false;
        for (int i = 0; i < errorCards.size(); i++) {
            AnalyzerDescriptor card = errorCards.get(i);
            String name = card.getName();
            List<AuditTarget> evaluatedTargets = card.getEvaluatedTargets() != null
                    ? card.getEvaluatedTargets() : List.of();

            boolean evaluatedHere = false;
            boolean notEvaluated = false;
            boolean withError = false;
            boolean marked = false;
            FindingSeverity analyzerHighest = null;

            // The quiz itself and every ancestor at a level the card evaluates: a finding
            // there counts in this quiz, and so does a declaration of "not evaluated".
            List<AuditNode> chain = new ArrayList<>(ancestors);
            chain.add(quiz);
            for (AuditNode node : chain) {
                if (!evaluatedTargets.contains(node.getTarget())) {
                    continue;
                }
                if (node.getUnevaluatedBy() != null && node.getUnevaluatedBy().contains(name)) {
                    notEvaluated = true;
                }
                if (node.getScores() != null && node.getScores().containsKey(name)) {
                    evaluatedHere = true;
                }
                if (node.getFindings() != null) {
                    for (Finding finding : node.getFindings()) {
                        if (!name.equals(finding.getAnalyzer())) {
                            continue;
                        }
                        if (finding.getResolution() == FindingResolution.RANK_ONLY) {
                            marked = true;
                        } else {
                            withError = true;
                            analyzerHighest = higher(analyzerHighest, finding.getSeverity());
                        }
                    }
                }
            }

            boolean reached = evaluatedHere || notEvaluated;
            if (!reached) {
                continue;
            }
            tally.reached[i]++;
            if (notEvaluated) {
                tally.notEvaluated[i]++;
                notFullyEvaluated = true;
                continue;
            }
            tally.evaluated[i]++;
            if (withError) {
                tally.withError[i]++;
                anyError = true;
                highest = higher(highest, analyzerHighest);
            }
            if (marked) {
                tally.marked[i]++;
            }
        }
        if (anyError) {
            tally.withAnyError = 1;
            tally.countSeverity(highest);
        }
        if (notFullyEvaluated) {
            tally.notFullyEvaluated = 1;
        }
        return tally;
    }

    /** BLOCKING is the highest severity and LOW the lowest (declaration order of the enum). */
    private static FindingSeverity higher(FindingSeverity a, FindingSeverity b) {
        if (a == null) {
            return b;
        }
        if (b == null) {
            return a;
        }
        return a.ordinal() <= b.ordinal() ? a : b;
    }

    /** Additive counts of a node: the sum of its children's, a quiz counting once. */
    private static final class Tally {
        int quizzes;
        int withAnyError;
        int blocking;
        int high;
        int medium;
        int low;
        int notFullyEvaluated;
        final int[] reached;
        final int[] evaluated;
        final int[] notEvaluated;
        final int[] withError;
        final int[] marked;

        Tally(int analyzers) {
            reached = new int[analyzers];
            evaluated = new int[analyzers];
            notEvaluated = new int[analyzers];
            withError = new int[analyzers];
            marked = new int[analyzers];
        }

        void add(Tally other) {
            quizzes += other.quizzes;
            withAnyError += other.withAnyError;
            blocking += other.blocking;
            high += other.high;
            medium += other.medium;
            low += other.low;
            notFullyEvaluated += other.notFullyEvaluated;
            for (int i = 0; i < reached.length; i++) {
                reached[i] += other.reached[i];
                evaluated[i] += other.evaluated[i];
                notEvaluated[i] += other.notEvaluated[i];
                withError[i] += other.withError[i];
                marked[i] += other.marked[i];
            }
        }

        void countSeverity(FindingSeverity severity) {
            if (severity == null) {
                return;
            }
            switch (severity) {
                case BLOCKING -> blocking++;
                case HIGH -> high++;
                case MEDIUM -> medium++;
                case LOW -> low++;
            }
        }

        ErrorCounts toErrorCounts(List<AnalyzerDescriptor> errorCards) {
            List<AnalyzerErrorCounts> perAnalyzer = new ArrayList<>();
            for (int i = 0; i < errorCards.size(); i++) {
                double share = evaluated[i] > 0 ? (double) withError[i] / evaluated[i] : 0.0;
                perAnalyzer.add(new AnalyzerErrorCounts(errorCards.get(i).getName(), reached[i],
                        evaluated[i], notEvaluated[i], withError[i], share, marked[i]));
            }
            double anyShare = quizzes > 0 ? (double) withAnyError / quizzes : 0.0;
            return new ErrorCounts(quizzes, withAnyError, anyShare,
                    new SeverityCounts(blocking, high, medium, low), notFullyEvaluated, perAnalyzer);
        }
    }
