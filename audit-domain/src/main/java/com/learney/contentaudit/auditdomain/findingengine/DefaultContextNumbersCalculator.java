/**
 * Publishes, once and inside the engine, the numbers of every node of an already aggregated
 * tree, from the cards of what ran:
 * <ul>
 *   <li>F-HALL-R009: the vocabulary score is the plain average of the scores the vocabulary
 *       analyzers have on the node, one per analyzer -- never a judge, never a sub-metric.</li>
 *   <li>F-HALL-R010: each analyzer's score is published with its sub-metrics (the COCA
 *       quarters) nested under it, so no average can take them for an analyzer.</li>
 *   <li>F-HALL-R008: the errors are counted per quiz, once, and summed up the tree; every
 *       percentage is recomputed from the sums. A finding on a container (a knowledge, as the
 *       mini-theory) counts in every quiz below it (DOUBT-HALLAZGO-DE-TEMA, option A).</li>
 * </ul>
 */
