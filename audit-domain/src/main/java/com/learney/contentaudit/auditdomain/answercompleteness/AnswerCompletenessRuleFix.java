    private static String markerOf(Finding finding) {
        String marker = finding.getIdentity().getMarker();
        return marker == null ? "" : marker;
    }

    private static String evidence(Finding finding, String label) {
        if (finding.getEvidence() == null || finding.getEvidence().getExamined() == null) {
            return null;
        }
        for (EvidencePart part : finding.getEvidence().getExamined()) {
            if (part != null && label.equals(part.getLabel())) {
                return part.getText();
            }
        }
        return null;
    }

    /** The missing form as the evidence shows it, or as the mark keeps it, without the gap it names. */
    private static String missingForm(Finding finding) {
        String shown = evidence(finding, "Falta");
        if (shown != null && !shown.isBlank()) {
            return shown.strip();
        }
        String marker = markerOf(finding);
        Matcher m = GAP_MARK.matcher(marker);
        String form = m.matches() ? m.group(1) : marker;
        return form.isBlank() ? null : form.strip();
    }

    /**
     * The index in the parts of the gap the form is missing from: the one the mark names («(hueco 2)»), the one whose
     * accepted answers the evidence shows, or the first.
     */
    private static int gapOf(List<SentencePartEntity> parts, Finding finding) {
        List<Integer> gaps = new ArrayList<>();
        for (int i = 0; i < parts.size(); i++) {
            if (parts.get(i) != null && parts.get(i).getKind() == SentencePartKind.CLOZE
                    && parts.get(i).getOptions() != null && !parts.get(i).getOptions().isEmpty()) {
                gaps.add(i);
            }
        }
        if (gaps.isEmpty()) {
            return -1;
        }
        Matcher m = GAP_MARK.matcher(markerOf(finding));
        if (m.matches()) {
            int n = Integer.parseInt(m.group(2)) - 1;
            return n >= 0 && n < gaps.size() ? gaps.get(n) : -1;
        }
        String accepted = evidence(finding, "Acepta");
        if (accepted != null) {
            for (int gap : gaps) {
                if (String.join(" | ", AnswerCompletenessAnalyzer.alternatives(parts.get(gap).getOptions()))
                        .equals(accepted)) {
                    return gap;
                }
            }
        }
        return gaps.get(0);
    }

    /**
     * The text without the sentence that asks for a form, or null when it is not there. In the instructions it is the
     * standard sentence that opens them; anywhere else, the sentence as the evidence shows it.
     */
    static String withoutRequest(String text, String phrase, boolean instructions) {
        if (text == null || text.isBlank()) {
            return null;
        }
        List<String> candidates = new ArrayList<>();
        if (phrase != null && !phrase.isBlank()) {
            candidates.add(phrase.strip());
        }
        for (FormRequest request : new DefaultFormRequestDetector().detect(instructions ? text : null,
                instructions ? null : text)) {
            if (request.isRemovableByRule()) {
                candidates.add(request.getPhrase());
            }
        }
        for (String candidate : candidates) {
            int at = text.toLowerCase(Locale.ROOT).indexOf(candidate.toLowerCase(Locale.ROOT));
            if (at >= 0) {
                String rest = text.substring(0, at) + " " + text.substring(at + candidate.length());
                return rest.replaceAll("[ \\t]+", " ").replaceAll(" +\\n", "\n").replaceAll("\\n +", "\n").strip();
            }
        }
        return null;
    }

    private static String textOf(List<SentencePartEntity> parts, int index) {
        if (index < 0 || index >= parts.size()) {
            return "";
        }
        SentencePartEntity part = parts.get(index);
        return part != null && part.getKind() == SentencePartKind.TEXT && part.getText() != null ? part.getText() : "";
    }

    private static List<SentencePartEntity> copy(List<SentencePartEntity> parts) {
        List<SentencePartEntity> copy = new ArrayList<>();
        for (SentencePartEntity part : parts) {
            copy.add(part == null ? null : new SentencePartEntity(part.getKind(), part.getText(),
                    part.getOptions() != null ? new ArrayList<>(part.getOptions()) : null));
        }
        return copy;
    }
