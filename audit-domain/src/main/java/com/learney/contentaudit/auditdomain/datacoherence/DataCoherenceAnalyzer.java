    /**
     * Whether the recording says the same as a text of today: compared without case, spaces,
     * signs or accents, the contracted and the long form taken as equal, and one containing the
     * other also matching -- the audio may say only the answer, or the answer with its starting
     * sentence.
     */
    static boolean saysTheSame(String recorded, String spoken) {
        for (String a : readings(recorded)) {
            for (String b : readings(spoken)) {
                if (a.isEmpty() || b.isEmpty()) {
                    continue;
                }
                if (a.equals(b)) {
                    return true;
                }
                String shorter = a.length() <= b.length() ? a : b;
                String longer = shorter == a ? b : a;
                if (shorter.length() >= 3 && longer.contains(shorter)) {
                    return true;
                }
            }
        }
        return false;
    }

    /** The text read in its long form: one reading per meaning of «'s» and «'d». */
    static Set<String> readings(String text) {
        Set<String> readings = new LinkedHashSet<>();
        if (text == null) {
            return readings;
        }
        String t = Normalizer.normalize(text.toLowerCase(Locale.ROOT).replace('’', '\'').replace('‘', '\''),
                Normalizer.Form.NFD);
        t = MARKS.matcher(t).replaceAll("");
        t = t.replaceAll("\\bwon't\\b", "will not").replaceAll("\\bcan't\\b", "can not")
                .replaceAll("\\bshan't\\b", "shall not").replaceAll("\\bcannot\\b", "can not")
                .replaceAll("n't\\b", " not").replaceAll("'re\\b", " are").replaceAll("'m\\b", " am")
                .replaceAll("'ve\\b", " have").replaceAll("'ll\\b", " will");
        for (String s : t.contains("'s") ? List.of(" is", " has", "s") : List.of("'s")) {
            String withS = t.replace("'s", s);
            for (String d : withS.contains("'d") ? List.of(" would", " had") : List.of("'d")) {
                readings.add(NOT_A_LETTER.matcher(withS.replace("'d", d)).replaceAll(""));
            }
        }
        return readings;
    }

