    @Override
    public List<FindingDraft> findingsAt(AuditNode node) {
        if (node == null || node.getTarget() != AuditTarget.QUIZ
                || !(node.getEntity() instanceof AuditableQuiz quiz)) {
            return List.of();
        }
        Optional<DataCoherenceDiagnosis> found = diagnosisOf(node);
        if (found.isEmpty() || found.get().getIssues() == null) {
            return List.of();
        }
        String statement = studentViewRenderer.render(quiz).getStatement();
        List<FindingDraft> drafts = new ArrayList<>();
        Set<String> markers = new LinkedHashSet<>();
        for (CopyMismatch issue : found.get().getIssues()) {
            String today = text(issue.getExpected());
            String there = text(issue.getFound());
            List<EvidencePart> examined = new ArrayList<>();
            examined.add(new EvidencePart("Ejercicio", text(statement)));
            FindingSeverity severity;
            FindingResolution resolution;
            String marker;
            String observation;
            switch (issue.getKind()) {
                case SAVED_SENTENCE_DIFFERS -> {
                    boolean tree = issue.getCopy() == ExerciseCopy.TREE_SENTENCE;
                    String which = tree ? "oración guardada (árbol)" : "oración guardada (producción)";
                    examined.add(new EvidencePart(tree ? "Oración guardada (árbol)" : "Oración guardada (producción)",
                            there));
                    examined.add(new EvidencePart("Hoy", today));
                    severity = FindingSeverity.MEDIUM;
                    resolution = FindingResolution.RULE;
                    marker = tree ? "arbol" : "produccion";
                    observation = which + ": \"" + there + "\"; hoy: \"" + today + "\". Se vuelve a armar desde las"
                            + " partes.";
                }
                case SLASH_IN_ANSWER -> {
                    examined.add(new EvidencePart("Respuesta", there));
                    examined.add(new EvidencePart("Con «|»", today));
                    severity = FindingSeverity.BLOCKING;
                    resolution = FindingResolution.RULE;
                    marker = "respuesta";
                    observation = "la respuesta \"" + there + "\" lleva «/» y el corrector sólo separa en «|»: el alumno"
                            + " tendría que tipear la barra. La barra pasa a «|».";
                }
                case SLASH_IN_AUDIO -> {
                    examined.add(new EvidencePart("Audio", there));
                    examined.add(new EvidencePart("Hoy", today));
                    severity = FindingSeverity.MEDIUM;
                    resolution = FindingResolution.RULE;
                    marker = "audio";
                    observation = "audio: \"" + there + "\"; hoy: \"" + today + "\". El audio lee la barra: se regraba"
                            + " con el texto de hoy.";
                }
                case AUDIO_DIFFERS -> {
                    examined.add(new EvidencePart("Audio", there));
                    examined.add(new EvidencePart("Hoy", today));
                    severity = FindingSeverity.MEDIUM;
                    resolution = FindingResolution.PANEL;
                    marker = "audio";
                    observation = "audio: \"" + there + "\"; hoy: \"" + today + "\". No se sabe cuál copia está bien:"
                            + " va a la mesa.";
                }
                case NO_AUDIO_KEY -> {
                    examined.add(new EvidencePart("Hoy", today));
                    severity = FindingSeverity.LOW;
                    resolution = FindingResolution.RULE;
                    marker = "audio-sin-clave";
                    observation = "no tiene clave de audio: se graba con el texto de hoy, \"" + today + "\".";
                }
                case SHARED_AUDIO_KEY -> {
                    examined.add(new EvidencePart("Clave", there));
                    examined.add(new EvidencePart("Hoy", today));
                    severity = FindingSeverity.LOW;
                    resolution = FindingResolution.RULE;
                    marker = "audio-compartido";
                    observation = "comparte la clave de audio " + there + ": se graba uno propio con el texto de hoy.";
                }
                default -> {
                    examined.add(new EvidencePart("Clave", there));
                    examined.add(new EvidencePart("Hoy", today));
                    severity = FindingSeverity.LOW;
                    resolution = FindingResolution.RULE;
                    marker = "audio-desconocido";
                    observation = "el registro de grabaciones no sabe con qué texto se grabó " + there + ": se graba"
                            + " con el texto de hoy.";
                }
            }
            String unique = marker;
            for (int n = 2; !markers.add(issue.getRule() + "|" + unique); n++) {
                unique = marker + " (" + n + ")";
            }
            drafts.add(new FindingDraft(issue.getRule(), unique, severity, resolution,
                    new FindingEvidence(examined, text(statement) + " → " + observation, List.of())));
        }
        return drafts;
    }

