    private static SentenceMode modeOf(AuditNode node) {
        AuditNode parent = node.getParent();
        if (parent != null && parent.getEntity() instanceof AuditableKnowledge knowledge
                && knowledge.getSentenceMode() != null) {
            return knowledge.getSentenceMode();
        }
        return SentenceMode.FILL;
    }

    /** The first accepted answer of the first gap of a written exercise: a rewrite may save it alone. */
    private static String firstAnswer(AuditableQuiz quiz) {
        if (quiz.getMultipleChoice() != null || quiz.getSentenceParts() == null) {
            return null;
        }
        for (SentencePartEntity part : quiz.getSentenceParts()) {
            if (part != null && part.getKind() == SentencePartKind.CLOZE) {
                List<String> options = part.getOptions();
                return options == null || options.isEmpty() || options.get(0) == null ? null
                        : options.get(0).split("\\|")[0].strip();
            }
        }
        return null;
    }

    private static void addIfPresent(List<String> list, String text) {
        if (text != null && !text.isBlank() && !list.contains(text)) {
            list.add(text);
        }
    }

    private static String firstOf(List<String> list) {
        return list == null || list.isEmpty() ? null : list.get(0);
    }

    private static String text(String text) {
        return text == null || text.isBlank() ? "(sin texto)" : text;
    }
