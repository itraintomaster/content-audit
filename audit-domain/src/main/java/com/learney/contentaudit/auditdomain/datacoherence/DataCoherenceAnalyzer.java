    @Override
    public Void onQuiz(AuditNode node) {
        if (node == null || !(node.getEntity() instanceof AuditableQuiz quiz)) {
            return null;
        }
        SentenceMode mode = modeOf(node);
        List<CopyMismatch> issues = new ArrayList<>();

        // R002.1: an accepted answer with «/».
        for (SentencePartEntity part : quiz.getSentenceParts() != null ? quiz.getSentenceParts()
                : List.<SentencePartEntity>of()) {
            if (part != null && part.getKind() == SentencePartKind.CLOZE && part.getOptions() != null) {
                for (String option : part.getOptions()) {
                    if (option != null && option.contains("/")) {
                        issues.add(new CopyMismatch(RULE_NO_SLASH, CopyMismatchKind.SLASH_IN_ANSWER,
                                ExerciseCopy.ACCEPTED_ANSWER, option.replaceAll("\\s*/\\s*", "|"), option));
                    }
                }
            }
        }

        // R001: the two saved sentences against the exercise built with its first answer -- the
        // answer alone or the whole exercise, whatever the topic (DOUBT-DATOS-718, A): a rewrite
        // saved as its answer alone is not a difference. With «/» in an answer the sentence is
        // rebuilt anyway once the slash becomes «|», so it is not counted twice.
        List<String> built = new ArrayList<>();
        addIfPresent(built, studentViewRenderer.finishedSentence(quiz, mode));
        addIfPresent(built, studentViewRenderer.finishedSentence(quiz, SentenceMode.FILL));
        addIfPresent(built, studentViewRenderer.finishedSentence(quiz, SentenceMode.REWRITE));
        if (!built.isEmpty() && issues.isEmpty()) {
            addIfPresent(built, firstAnswer(quiz));
            savedSentence(firstOf(quiz.getSentences()), built, ExerciseCopy.TREE_SENTENCE, issues);
            Optional<List<String>> production = productionSentences != null
                    ? productionSentences.savedSentences(quiz.getId()) : Optional.empty();
            production.ifPresent(sentences ->
                    savedSentence(firstOf(sentences), built, ExerciseCopy.PRODUCTION_SENTENCE, issues));
        }

        // R004 (no key, unknown recording), R002.2 and R003 over the recorded text.
        if (stage == DataCoherenceStage.PREPUBLICATION) {
            checkAudio(node, quiz, mode, issues);
        }
        write(node, issues);
        return null;
    }

    private void checkAudio(AuditNode node, AuditableQuiz quiz, SentenceMode mode, List<CopyMismatch> issues) {
        List<String> spoken = spokenTextBuilder.spokenTexts(quiz, mode);
        String today = spoken.isEmpty() ? null : spoken.get(0);
        String key = quiz.getAnswerAudioKey() != null ? quiz.getAnswerAudioKey().strip() : "";
        if (key.isEmpty()) {
            issues.add(new CopyMismatch(RULE_AUDIO_KNOWN, CopyMismatchKind.NO_AUDIO_KEY, ExerciseCopy.AUDIO, today,
                    null));
        } else {
            byAudioKey.computeIfAbsent(key, k -> new ArrayList<>()).add(node);
            Optional<AudioRecording> recording = recordings != null ? recordings.recordingOf(key) : Optional.empty();
            String recorded = recording.map(AudioRecording::getRecordedText).orElse(null);
            if (recorded == null || recorded.isBlank()) {
                issues.add(new CopyMismatch(RULE_AUDIO_KNOWN, CopyMismatchKind.UNKNOWN_RECORDING, ExerciseCopy.AUDIO,
                        today, key));
            } else if (recorded.contains("/")) {
                issues.add(new CopyMismatch(RULE_NO_SLASH, CopyMismatchKind.SLASH_IN_AUDIO, ExerciseCopy.AUDIO, today,
                        recorded));
            } else if (!spoken.isEmpty() && spoken.stream().noneMatch(s -> saysTheSame(recorded, s))) {
                issues.add(new CopyMismatch(RULE_AUDIO_MATCHES, CopyMismatchKind.AUDIO_DIFFERS, ExerciseCopy.AUDIO,
                        today, recorded));
            }
        }
    }

