    /** R004: a key two exercises share, seen once the whole course went by. */
    @Override
    public Void onCourseComplete(AuditNode rootNode) {
        if (stage == DataCoherenceStage.CONTENT) return null;
        for (Map.Entry<String, List<AuditNode>> entry : byAudioKey.entrySet()) {
            List<AuditNode> sharing = entry.getValue();
            if (sharing.size() < 2) {
                continue;
            }
            for (AuditNode node : sharing) {
                List<String> others = new ArrayList<>();
                for (AuditNode other : sharing) {
                    if (other != node) {
                        others.add(other.getEntity().getId());
                    }
                }
                List<CopyMismatch> issues = new ArrayList<>(diagnosisOf(node).map(DataCoherenceDiagnosis::getIssues)
                        .orElse(List.of()));
                String today = firstOf(spokenTextBuilder.spokenTexts((AuditableQuiz) node.getEntity(), modeOf(node)));
                issues.add(new CopyMismatch(RULE_AUDIO_KNOWN, CopyMismatchKind.SHARED_AUDIO_KEY, ExerciseCopy.AUDIO,
                        today, entry.getKey() + " (también en " + String.join(", ", others) + ")"));
                write(node, issues);
            }
        }
        return null;
    }

    private void write(AuditNode node, List<CopyMismatch> issues) {
        double score = issues.isEmpty() ? 1.0 : 0.0;
        node.getScores().put(ANALYZER_NAME, score);
        if (!(node.getDiagnoses() instanceof DefaultQuizDiagnoses)) {
            node.setDiagnoses(new DefaultQuizDiagnoses());
        }
        ((DefaultQuizDiagnoses) node.getDiagnoses()).setDataCoherenceDiagnosis(new DataCoherenceDiagnosis(
                List.copyOf(issues), stage == DataCoherenceStage.PREPUBLICATION && recordings != null
                        ? recordings.version() : null, score));
        node.getMetadata().put("dataCoherenceStage", stage.name());
    }

    private static Optional<DataCoherenceDiagnosis> diagnosisOf(AuditNode node) {
        return node.getDiagnoses() instanceof DefaultQuizDiagnoses diagnoses
                ? diagnoses.getDataCoherenceDiagnosis() : Optional.empty();
    }

    private void savedSentence(String saved, List<String> built, ExerciseCopy copy, List<CopyMismatch> issues) {
        if (saved == null || saved.isBlank()) {
            return;
        }
        for (String candidate : built) {
            if (correctorMatcher.sameAnswer(saved, candidate)) {
                return;
            }
        }
        issues.add(new CopyMismatch(RULE_SAVED_SENTENCE, CopyMismatchKind.SAVED_SENTENCE_DIFFERS, copy, built.get(0),
                saved));
    }

