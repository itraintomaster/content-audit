    /** F-JEXAM-R006: every topic at once, up to N consultations in flight, never one by one. */
    private List<EvaluationResolution> resolveAll(List<EvaluationRequest> requests, EvaluationRunPolicy policy) {
        if (requests.isEmpty()) {
            return List.of();
        }
        List<EvaluationSession> sessions = opened.getSessions();
        EvaluationSession session = sessions != null && !sessions.isEmpty() ? sessions.get(0) : null;
        if (session == null) {
            // No evaluator to ask: whatever is not resolved stays pending.
            return pendingFor(requests);
        }
        int maxConcurrent = policy != null && policy.getMaxConcurrentEvaluations() != null
                ? Math.max(1, policy.getMaxConcurrentEvaluations()) : 1;
        try {
            List<EvaluationResolution> resolutions = session.resolveAll(requests, maxConcurrent);
            return resolutions != null ? resolutions : pendingFor(requests);
        } catch (RuntimeException e) {
            // F-QINST-R007: a failure of the batch leaves its topics unevaluated, never the run.
            return pendingFor(requests);
        }
    }

    private static List<EvaluationResolution> pendingFor(List<EvaluationRequest> requests) {
        List<EvaluationResolution> pending = new ArrayList<>();
        for (int i = 0; i < requests.size(); i++) {
            pending.add(new EvaluationResolution(EvaluationResolutionKind.PENDING, null, null, null));
        }
        return pending;
    }

    /** One outcome per exercise of the topic, in its order: anything else is not this topic's. */
    private static void checkAligned(List<MiniTheoryQuizOutcome> outcomes, List<AuditNode> exercises) {
        if (outcomes == null || outcomes.size() != exercises.size()) {
            throw new IllegalStateException("El reparto no trae un resultado por ejercicio del tema");
        }
        for (int i = 0; i < exercises.size(); i++) {
            MiniTheoryQuizOutcome outcome = outcomes.get(i);
            if (outcome == null || !Objects.equals(outcome.getQuizId(), exercises.get(i).getEntity().getId())) {
                throw new IllegalStateException("El reparto no sigue el orden de los ejercicios del tema");
            }
        }
    }

    /** Score, diagnosis and findings in each exercise: the topic and above get them by aggregation. */
    private void apply(List<AuditNode> exercises, List<MiniTheoryQuizOutcome> outcomes) {
        for (int i = 0; i < exercises.size(); i++) {
            AuditNode exercise = exercises.get(i);
            MiniTheoryQuizOutcome outcome = outcomes.get(i);
            if (exercise.getScores() == null) {
                exercise.setScores(new LinkedHashMap<>());
            }
            exercise.getScores().put(ANALYZER_NAME, outcome.getScore());
            if (!(exercise.getDiagnoses() instanceof DefaultQuizDiagnoses)) {
                exercise.setDiagnoses(new DefaultQuizDiagnoses());
            }
            ((DefaultQuizDiagnoses) exercise.getDiagnoses()).setMiniTheoryDiagnosis(outcome.getDiagnosis());
            findingsByExercise.put(exercise,
                    outcome.getFindings() != null ? new ArrayList<>(outcome.getFindings()) : new ArrayList<>());
        }
    }

    /**
     * F-MINIT-R005 / F-HALL-R008: every exercise of the topic reached and not evaluated -- no score,
     * no finding, no diagnosis of mini-theory, and declared so.
     */
    /** Marks every exercise of the topic as not evaluated by this judge and says how many they are. */
    private int markUnevaluated(AuditNode topic) {
        List<AuditNode> exercises = DefaultMiniTheorySubjectBuilder.exercisesOf(topic);
        for (AuditNode exercise : exercises) {
            if (exercise.getScores() != null) {
                exercise.getScores().remove(ANALYZER_NAME);
            }
            if (exercise.getDiagnoses() instanceof DefaultQuizDiagnoses quizDiagnoses) {
                quizDiagnoses.setMiniTheoryDiagnosis(null);
            }
            findingsByExercise.remove(exercise);
            if (exercise.getUnevaluatedBy() == null) {
                exercise.setUnevaluatedBy(new ArrayList<>());
            }
            if (!exercise.getUnevaluatedBy().contains(ANALYZER_NAME)) {
                exercise.getUnevaluatedBy().add(ANALYZER_NAME);
            }
        }
        return exercises.size();
    }
