/**
 * FEAT-MINIT: the mini-theory judge, one consultation per topic (F-MINIT-R001) and the score, the
 * findings and the diagnosis in each exercise (F-MINIT-R003/R004).
 *
 * <ul>
 *   <li>{@link #onKnowledge} only gathers the topics -- the traversal reaches a topic before its
 *       exercises, and its children are its exercises. A topic without any mini theory has nothing
 *       to judge and is not a unit of this judge.</li>
 *   <li>{@link #onCourseComplete} asks the common runtime what each topic asks (its declared set,
 *       its exam, its re-evaluation: a topic answers to its own id and to the ids of its
 *       exercises), resolves every topic at once, N at a time and never more than the budget, which
 *       counts topics (F-MINIT-R005), and spreads each verdict over the exercises of its topic. The
 *       exercises of a topic without verdict -- pending, failed, or whose verdict cannot be read or
 *       spread -- stay without score, finding or diagnosis and declared not evaluated by
 *       mini-theory; one topic never stops the others.</li>
 *   <li>Its coverage counts topics ({@link AuditTarget#KNOWLEDGE}) and goes to the course with the
 *       other judges'. The exercises they contain are counted by the numbers of every node, from
 *       the scores and the «not evaluated» this judge leaves in each exercise.</li>
 * </ul>
 */
