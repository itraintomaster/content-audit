/**
 * F-UNICA-R002 to R004: what the judge listed, against what the corrector already accepts.
 *
 * <ol>
 *   <li>Every listed answer the corrector already accepts for its gap -- the contracted or long
 *       form, the British or American spelling of the closed list, until or till, whatever it
 *       already ignores -- is not another answer (F-JEXAM-R012): it is dropped, stays visible in
 *       the diagnosis and gives no finding, whatever the judge said about it. The rule never
 *       depends on the model following its guide: the corrector's comparison decides it, with the
 *       text around the gap ({@link GapContext}, without the hints) and the gap's accepted answers
 *       split on «|».</li>
 *   <li>What is left gives one finding per answer, marked with the answer -- with its gap, «Hueco
 *       2: …», when the exercise has more than one: an answer the instruction or the hint offers
 *       only ranks and names answer-completeness as the one that fixes it with a rule (R003); any
 *       other is an error with its severity, resolved at the panel (R004). An answer the judge
 *       repeats for the same gap counts once.</li>
 *   <li>The score is 1 without a different valid answer and, otherwise, the configuration's for
 *       the gravest of them.</li>
 * </ol>
 *
 * An answer without a kind is a different valid one (the second class is «any other»); one
 * without a severity weighs as medium, the least grave the judge can give. A gap number the
 * exercise does not have points to its only gap when it has one; with several, the answer is
 * dropped if the corrector accepts it in any of them.
 */
