    /**
     * What each judge is asked about each quiz, in the order of the course; {@code null} means
     * that judge is not asked at all. Only a quiz the budget reaches is asked in a mode that can
     * consult, and only to the judges whose verdict it needs; everything else only reuses, so the
     * sessions -- each opened with the whole budget -- never consult more than the budget in total.
     */
    private static EvaluationRequestMode[][] shareBudgetInPairs(List<EvaluationRequestMode> modes,
            EvaluationSubject[] subjects, List<EvaluationSession> sessions, int budget) {
        int size = subjects.length;
        EvaluationRequestMode[][] asked = new EvaluationRequestMode[JUDGES][size];
        List<Set<Map<String, String>>> scheduled = List.of(new HashSet<>(), new HashSet<>());
        int remaining = budget;
        boolean exhausted = false;
        for (int i = 0; i < size; i++) {
            EvaluationSubject subject = subjects[i];
            if (subject == null) {
                // What the judges would read could not be built: never asked, left unevaluated.
                continue;
            }
            EvaluationRequestMode mode = i < modes.size() && modes.get(i) != null
                    ? modes.get(i)
                    : EvaluationRequestMode.REUSE_OR_EVALUATE;
            if (mode == EvaluationRequestMode.REUSE_ONLY) {
                asked[FROM_ENGLISH][i] = EvaluationRequestMode.REUSE_ONLY;
                asked[FROM_TRANSLATION][i] = EvaluationRequestMode.REUSE_ONLY;
                continue;
            }
            if (exhausted || remaining == 0) {
                // Nothing more can be consulted in this run: every quiz from here on only reuses,
                // without asking the ledger what each one would cost.
                exhausted = true;
                for (int judge = 0; judge < JUDGES; judge++) {
                    asked[judge][i] = withoutBudget(mode, sessions.get(judge), subject);
                }
                continue;
            }
            boolean[] needs = new boolean[JUDGES];
            int cost = 0;
            for (int judge = 0; judge < JUDGES; judge++) {
                needs[judge] = needsConsultation(mode, sessions.get(judge), subject, scheduled.get(judge));
                if (needs[judge]) {
                    cost++;
                }
            }
            if (cost <= remaining) {
                remaining -= cost;
                for (int judge = 0; judge < JUDGES; judge++) {
                    if (needs[judge]) {
                        asked[judge][i] = mode;
                        scheduled.get(judge).add(subject.getContent());
                    } else {
                        asked[judge][i] = EvaluationRequestMode.REUSE_ONLY;
                    }
                }
                continue;
            }
            // This quiz does not fit: it and every quiz after it only reuse.
            exhausted = true;
            for (int judge = 0; judge < JUDGES; judge++) {
                asked[judge][i] = withoutBudget(mode, sessions.get(judge), subject);
            }
        }
        return asked;
    }

    /**
     * Whether the judge must be consulted on this quiz: a quiz that may reuse needs it only when the
     * judge has no verdict for exactly this content and none is already scheduled in this run; a
     * forced or preferred re-evaluation asks each judge for a new verdict.
     */
    private static boolean needsConsultation(EvaluationRequestMode mode, EvaluationSession session,
            EvaluationSubject subject, Set<Map<String, String>> scheduled) {
        if (mode == EvaluationRequestMode.REUSE_OR_EVALUATE) {
            return !scheduled.contains(subject.getContent()) && !session.recorded(subject);
        }
        return true;
    }

