    /** Every finding shows first what both judges read, then what the judges said. */
    private static List<FindingDraft> withWhatTheJudgesRead(List<FindingDraft> findings, Map<String, String> content) {
        if (findings == null || findings.isEmpty()) {
            return List.of();
        }
        List<EvidencePart> read = whatTheJudgesRead(content);
        List<FindingDraft> result = new ArrayList<>();
        for (FindingDraft finding : findings) {
            FindingEvidence evidence = finding.getEvidence();
            List<EvidencePart> examined = new ArrayList<>(read);
            String observation = null;
            List<FindingNodeRef> related = new ArrayList<>();
            if (evidence != null) {
                if (evidence.getExamined() != null) {
                    examined.addAll(evidence.getExamined());
                }
                observation = evidence.getObservation();
                if (evidence.getRelatedNodes() != null) {
                    related.addAll(evidence.getRelatedNodes());
                }
            }
            result.add(new FindingDraft(finding.getRule(), finding.getMarker(), finding.getSeverity(),
                    finding.getResolution(), new FindingEvidence(examined, observation, related)));
        }
        return List.copyOf(result);
    }

    private static List<EvidencePart> whatTheJudgesRead(Map<String, String> content) {
        List<EvidencePart> parts = new ArrayList<>();
        if (content == null) {
            return parts;
        }
        addPart(parts, "Nivel", content.get(DefaultTranslationSenseSubjectBuilder.CEFR_LEVEL));
        addPart(parts, "Consigna", content.get(DefaultTranslationSenseSubjectBuilder.INSTRUCTIONS));
        addPart(parts, "Ejercicio", content.get(DefaultTranslationSenseSubjectBuilder.EXERCISE));
        String sentences = content.get(DefaultTranslationSenseSubjectBuilder.ACCEPTED_SENTENCES);
        if (sentences != null && !sentences.isBlank()) {
            List<String> lines = new ArrayList<>();
            for (String line : sentences.split("\n")) {
                if (!line.isBlank()) {
                    lines.add(line.strip());
                }
            }
            addPart(parts, lines.size() > 1 ? "Oraciones aceptadas" : "Oración", String.join(" · ", lines));
        }
        addPart(parts, "Traducción", content.get(DefaultTranslationSenseSubjectBuilder.TRANSLATION));
        return parts;
    }

    private static void addPart(List<EvidencePart> parts, String label, String text) {
        if (text != null && !text.isBlank()) {
            parts.add(new EvidencePart(label, text.strip()));
        }
    }
