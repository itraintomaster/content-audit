    private static boolean hasVerdict(EvaluationResolution resolution) {
        return resolution != null
                && (resolution.getKind() == EvaluationResolutionKind.REUSED
                        || resolution.getKind() == EvaluationResolutionKind.EVALUATED)
                && resolution.getPayload() != null;
    }

    /**
     * F-HALL-R004: a score below 1 goes with a finding that counts as error and a score of 1 with
     * none; an outcome that breaks it would stop the whole audit, so its quiz stays unevaluated.
     */
    private static boolean consistent(TranslationSenseOutcome outcome) {
        List<FindingDraft> findings = outcome.getFindings() != null ? outcome.getFindings() : List.of();
        boolean countsAsError = false;
        for (FindingDraft finding : findings) {
            if (finding == null || finding.getResolution() == null) {
                return false;
            }
            if (finding.getResolution() != FindingResolution.RANK_ONLY) {
                countsAsError = true;
            }
        }
        return countsAsError == (outcome.getScore() < 1.0);
    }

    /** The version of the pair of judges that gave the two verdicts, as the runtime composes it. */
    private static String pairVersion(EvaluationResolution fromEnglish, EvaluationResolution fromTranslation) {
        String english = fromEnglish.getEvaluatorVersion();
        String translation = fromTranslation.getEvaluatorVersion();
        if (english == null || english.isBlank() || translation == null || translation.isBlank()) {
            return null;
        }
        return english + VERSION_JOINER + translation;
    }

    private void write(AuditNode node, Judged judged) {
        if (node.getScores() == null) {
            node.setScores(new LinkedHashMap<>());
        }
        node.getScores().put(ANALYZER_NAME, judged.score());
        if (!(node.getDiagnoses() instanceof DefaultQuizDiagnoses)) {
            node.setDiagnoses(new DefaultQuizDiagnoses());
        }
        ((DefaultQuizDiagnoses) node.getDiagnoses()).setTranslationSenseDiagnosis(judged.diagnosis());
        findingsByQuiz.put(node, judged.findings());
    }

    /** F-HALL-R008 / F-QINST-R004: reached but not evaluated -- no score, no diagnosis, no finding. */
    private static void markUnevaluated(AuditNode node) {
        if (node.getScores() != null) {
            node.getScores().remove(ANALYZER_NAME);
        }
        if (node.getUnevaluatedBy() == null) {
            node.setUnevaluatedBy(new ArrayList<>());
        }
        if (!node.getUnevaluatedBy().contains(ANALYZER_NAME)) {
            node.getUnevaluatedBy().add(ANALYZER_NAME);
        }
    }

