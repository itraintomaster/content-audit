    /**
     * One judge, all its quizzes at once. A session that breaks instead of answering leaves its
     * quizzes without that judge's verdict and never stops the run.
     */
    private static void resolve(EvaluationSession session, EvaluationSubject[] subjects,
            EvaluationRequestMode[] asked, EvaluationResolution[] resolved, int maxConcurrent) {
        List<EvaluationRequest> requests = new ArrayList<>();
        List<Integer> positions = new ArrayList<>();
        for (int i = 0; i < subjects.length; i++) {
            if (subjects[i] != null && asked[i] != null) {
                requests.add(new EvaluationRequest(subjects[i], asked[i]));
                positions.add(i);
            }
        }
        if (requests.isEmpty()) {
            return;
        }
        List<EvaluationResolution> answers;
        try {
            answers = session.resolveAll(requests, maxConcurrent);
        } catch (RuntimeException e) {
            return;
        }
        if (answers == null) {
            return;
        }
        for (int k = 0; k < positions.size() && k < answers.size(); k++) {
            resolved[positions.get(k)] = answers.get(k);
        }
    }

