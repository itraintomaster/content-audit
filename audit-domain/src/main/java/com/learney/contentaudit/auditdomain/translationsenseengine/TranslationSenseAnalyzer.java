    /** Both verdicts read and combined, or {@code null} when the quiz stays unevaluated. */
    private Judged judge(EvaluationSubject subject, EvaluationResolution fromEnglish,
            EvaluationResolution fromTranslation) {
        if (subject == null || !hasVerdict(fromEnglish) || !hasVerdict(fromTranslation)) {
            return null;
        }
        try {
            TranslationSenseVerdict english = verdictReader.read(fromEnglish.getPayload());
            TranslationSenseVerdict translation = verdictReader.read(fromTranslation.getPayload());
            if (english == null || translation == null) {
                return null;
            }
            TranslationSenseOutcome outcome = combiner.combine(english, translation);
            if (outcome == null || outcome.getAgreement() == null || !consistent(outcome)) {
                return null;
            }
            boolean reused = fromEnglish.getKind() == EvaluationResolutionKind.REUSED
                    && fromTranslation.getKind() == EvaluationResolutionKind.REUSED;
            TranslationSenseDiagnosis diagnosis = new TranslationSenseDiagnosis(english, translation,
                    outcome.getAgreement(), outcome.getScore(), reused);
            return new Judged(outcome.getScore(), diagnosis,
                    withWhatTheJudgesRead(outcome.getFindings(), subject.getContent()),
                    pairVersion(fromEnglish, fromTranslation));
        } catch (RuntimeException e) {
            return null;
        }
    }

