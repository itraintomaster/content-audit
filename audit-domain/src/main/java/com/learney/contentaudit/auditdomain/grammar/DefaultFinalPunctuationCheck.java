package com.learney.contentaudit.auditdomain.grammar;

import com.learney.contentaudit.auditdomain.NlpToken;
import com.learney.contentaudit.auditdomain.finding.FindingResolution;
import com.learney.contentaudit.auditdomain.finding.FindingSeverity;
import com.learney.contentaudit.auditdomain.finishedsentence.FinishedSentence;
import java.util.List;
import java.util.Locale;
import java.util.Optional;
import java.util.Set;
import java.util.regex.Pattern;
import javax.annotation.processing.Generated;

/**
 * F-GRAMA-R003: every finished sentence closes with its sign. A sentence with a verb, of three
 * words or more and starting with a capital, that does not end in «.», «?» or «!» has a low
 * finding; so does a question that starts with an auxiliary and its subject and ends in a period.
 * «With a verb» and «auxiliary» come from the spaCy tokens the exercise already carries, so no
 * second analyzer of language is needed. Both are fixed by a rule: the sign goes in, «?» for a
 * question and «.» otherwise (R005).
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
class DefaultFinalPunctuationCheck implements FinalPunctuationCheck {

    static final String RULE = "final-punctuation";

    /** A sentence closes in one of these, maybe followed by a closing quote. */
    private static final Pattern CLOSED = Pattern.compile("[.?!]['\"”’)]*\\s*$");

    private static final Pattern ENDS_IN_PERIOD = Pattern.compile("\\.['\"”’)]*\\s*$");

    /** «boxes? (I'm holding the boxes).» without its hint: the question closed, and the hint's period. */
    private static final Pattern CLOSED_BEFORE_A_HINT = Pattern.compile("[?!]['\"”’)]*\\s*\\.['\"”’)]*\\s*$");

    private static final Set<String> VERB_TAGS = Set.of("VERB", "AUX");

    /** What can be the subject right after the auxiliary of a question. */
    private static final Set<String> SUBJECT_TAGS = Set.of("PRON", "PROPN", "NOUN", "DET", "NUM");

    /** The auxiliaries that open a yes/no question, in case the tokens do not tag them. */
    private static final Set<String> AUXILIARIES = Set.of("do", "does", "did", "is", "are", "am", "was", "were",
            "have", "has", "had", "can", "could", "will", "would", "shall", "should", "may", "might", "must",
            "don't", "doesn't", "didn't", "isn't", "aren't", "wasn't", "weren't", "haven't", "hasn't",
            "hadn't", "can't", "couldn't", "won't", "wouldn't", "shouldn't");

    /** The subjects a question can open with, when spaCy did not tag the word. */
    private static final Set<String> SUBJECT_PRONOUNS = Set.of("i", "you", "he", "she", "it", "we", "they", "this",
            "that", "these", "those", "there", "anyone", "anybody", "someone", "somebody", "everyone", "everybody");

    @Override
    public Optional<GrammarIssue> check(FinishedSentence sentence, List<NlpToken> tokens) {
        if (sentence == null || sentence.getText() == null || sentence.getAnswerIndex() > 0) {
            // The corrector ignores the signs, so only the solution -- the first accepted answer,
            // the one the student reads -- has to close with its own; another accepted form without
            // its period is no error the student sees.
            return Optional.empty();
        }
        String text = sentence.getText().strip();
        if (CLOSED_BEFORE_A_HINT.matcher(text).find()) {
            return Optional.empty();
        }
        String[] words = text.isEmpty() ? new String[0] : text.split("\\s+");
        if (words.length < 3) {
            return Optional.empty();
        }
        // The question is the last sentence of the text: «Can you hear me clearly? if not, I can speak
        // louder.» ends in a statement, not in a question.
        String[] segments = text.split("(?<=[.?!])\\s+");
        String last = segments[segments.length - 1];
        String[] lastWords = last.split("\\s+");
        boolean question = lastWords.length >= 2 && startsWithAuxiliaryAndSubject(lastWords, tokens);
        if (!CLOSED.matcher(text).find()) {
            // A sentence with a verb and a capital that does not close with its sign.
            if (!Character.isUpperCase(text.charAt(0)) || !hasVerb(tokens)) {
                return Optional.empty();
            }
            // The sign of the last sentence: «A: Is Emily walking? B: Yes, she is» closes with «.».
            String sign = question ? "?" : ".";
            return Optional.of(issue(text, "falta el signo final: «" + sign + "»"));
        }
        if (question && ENDS_IN_PERIOD.matcher(text).find()) {
            // A question -- an auxiliary and its subject first -- that closes with a period.
            return Optional.of(issue(text, "es una pregunta y cierra con punto: va «?»"));
        }
        return Optional.empty();
    }

    private static GrammarIssue issue(String sentence, String explanation) {
        return new GrammarIssue(RULE, null, "", sentence, GrammarIssuePlacement.PUNCTUATION, FindingSeverity.LOW,
                FindingResolution.RULE, explanation);
    }

    private static boolean hasVerb(List<NlpToken> tokens) {
        if (tokens == null) {
            return false;
        }
        for (NlpToken token : tokens) {
            if (token != null && token.getPosTag() != null && VERB_TAGS.contains(token.getPosTag())) {
                return true;
            }
        }
        return false;
    }

    /** «Did Michael …», «Are these …»: an auxiliary first and its subject right after. */
    private static boolean startsWithAuxiliaryAndSubject(String[] words, List<NlpToken> tokens) {
        String first = bare(words[0]);
        String second = bare(words[1]);
        if (!AUXILIARIES.contains(first)) {
            return false;
        }
        String firstTag = tagOf(first, tokens);
        if (firstTag != null && !"AUX".equals(firstTag)) {
            // «Have a glass of water.»: spaCy tags the imperative VERB and the auxiliary of a question
            // AUX («Have you eaten?», «Did Michael …», «Is it …»).
            return false;
        }
        String secondTag = tagOf(second, tokens);
        if (secondTag != null) {
            return SUBJECT_TAGS.contains(secondTag);
        }
        // Without its tag, only what is a subject by its form: a subject pronoun or a name.
        return SUBJECT_PRONOUNS.contains(second)
                || (!words[1].isEmpty() && Character.isUpperCase(words[1].charAt(0)));
    }

    /** The tag spaCy gave the first token with this text, if any. */
    private static String tagOf(String word, List<NlpToken> tokens) {
        if (tokens == null) {
            return null;
        }
        for (NlpToken token : tokens) {
            if (token != null && token.getText() != null && bare(token.getText()).equals(word)) {
                return token.getPosTag();
            }
        }
        return null;
    }

    private static String bare(String word) {
        return word.toLowerCase(Locale.ROOT).replaceAll("^[^\\p{L}\\p{N}']+|[^\\p{L}\\p{N}']+$", "");
    }
}
