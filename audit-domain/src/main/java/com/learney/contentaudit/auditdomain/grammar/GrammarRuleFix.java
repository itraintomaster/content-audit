    /** What a finding of the tool marks, read from its mark «rule of LanguageTool|text». */
    private enum TextFault { REPEAT, SPACE, UNKNOWN }

    private static final Pattern DOUBLED = Pattern.compile("(?i)^\\s*(.+?)\\s+\\1\\s*$");

    private static TextFault kindOf(Finding finding) {
        String marker = finding.getIdentity().getMarker();
        String text = marker == null ? "" : marker.substring(marker.indexOf('|') + 1);
        if (DOUBLED.matcher(text).matches()) {
            return TextFault.REPEAT;
        }
        if (GLUED_SENTENCE.matcher(text).find()) {
            return TextFault.SPACE;
        }
        return TextFault.UNKNOWN;
    }

