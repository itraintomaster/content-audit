    private static String textOf(List<SentencePartEntity> parts, int index) {
        if (index < 0 || index >= parts.size()) {
            return "";
        }
        SentencePartEntity part = parts.get(index);
        return part != null && part.getKind() == SentencePartKind.TEXT && part.getText() != null ? part.getText() : "";
    }

    private static String withoutHints(String text) {
        return text == null ? "" : HINT.matcher(text).replaceAll(" ").replaceAll("\\s+", " ").strip();
    }

    private static List<String> words(String text) {
        List<String> words = new ArrayList<>();
        Matcher m = WORD.matcher(text == null ? "" : text);
        while (m.find()) {
            words.add(m.group());
        }
        return words;
    }

    private static List<String> lower(List<String> words) {
        return Arrays.asList(words.stream().map(w -> w.toLowerCase(Locale.ROOT).replace('’', '\'')).toArray(String[]::new));
    }

    private static List<SentencePartEntity> copy(List<SentencePartEntity> parts) {
        List<SentencePartEntity> copy = new ArrayList<>();
        for (SentencePartEntity part : parts) {
            copy.add(part == null ? null : new SentencePartEntity(part.getKind(), part.getText(),
                    part.getOptions() != null ? new ArrayList<>(part.getOptions()) : null));
        }
        return copy;
    }
