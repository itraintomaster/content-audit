    /**
     * Takes out the words an accepted answer repeats from the text right after the gap (at its end) or right before it
     * (at its start), and returns the repeated words. A part of the answer leaves the answer; when the whole first
     * answer is what the text repeats («in August» before «in August last year.»), the repetition leaves the text,
     * since an answer is never left empty.
     */
    private static List<String> withoutGluedRepeats(List<SentencePartEntity> parts) {
        List<String> repeated = new ArrayList<>();
        for (int i = 0; i < parts.size(); i++) {
            SentencePartEntity part = parts.get(i);
            if (part == null || part.getKind() != SentencePartKind.CLOZE || part.getOptions() == null
                    || part.getOptions().isEmpty() || part.getOptions().get(0) == null) {
                continue;
            }
            List<String> after = words(withoutHints(textOf(parts, i + 1)));
            List<String> before = words(withoutHints(textOf(parts, i - 1)));
            List<String> first = words(part.getOptions().get(0).split("\\|", -1)[0]);
            if (!first.isEmpty() && overlap(first, after, true) == first.size()) {
                parts.get(i + 1).setText(withoutLeadingWords(parts.get(i + 1).getText(), first.size()));
                addOnce(repeated, String.join(" ", first));
                continue;
            }
            if (!first.isEmpty() && overlap(first, before, false) == first.size()) {
                parts.get(i - 1).setText(withoutTrailingWords(parts.get(i - 1).getText(), first.size()));
                addOnce(repeated, String.join(" ", first));
                continue;
            }
            List<String> options = new ArrayList<>();
            for (String option : part.getOptions()) {
                List<String> alternatives = new ArrayList<>();
                for (String alternative : option == null ? new String[0] : option.split("\\|", -1)) {
                    String kept = alternative;
                    List<String> answer = words(alternative);
                    int tail = overlap(answer, after, true);
                    int head = overlap(answer, before, false);
                    if (tail > 0 && tail < answer.size()) {
                        kept = cutEnd(alternative, tail);
                        addOnce(repeated, String.join(" ", answer.subList(answer.size() - tail, answer.size())));
                    } else if (head > 0 && head < answer.size()) {
                        kept = cutStart(alternative, head);
                        addOnce(repeated, String.join(" ", answer.subList(0, head)));
                    }
                    alternatives.add(kept);
                }
                options.add(option == null ? null : String.join("|", alternatives));
            }
            part.setOptions(options);
        }
        return repeated;
    }

    private static void addOnce(List<String> list, String value) {
        if (!list.contains(value)) {
            list.add(value);
        }
    }

    /** The text without its first n words outside the hints, a hint before them kept where it was. */
    private static String withoutLeadingWords(String text, int n) {
        List<int[]> spans = wordSpansOutsideHints(text);
        if (spans.size() < n) {
            return text;
        }
        String cut = text.substring(0, spans.get(0)[0]) + text.substring(spans.get(n - 1)[1]).stripLeading();
        return tidy(cut);
    }

    /** The text without its last n words outside the hints. */
    private static String withoutTrailingWords(String text, int n) {
        List<int[]> spans = wordSpansOutsideHints(text);
        if (spans.size() < n) {
            return text;
        }
        String cut = text.substring(0, spans.get(spans.size() - n)[0]).stripTrailing()
                + text.substring(spans.get(spans.size() - 1)[1]);
        return tidy(cut);
    }

    private static List<int[]> wordSpansOutsideHints(String text) {
        List<int[]> spans = new ArrayList<>();
        Matcher hint = HINT.matcher(text);
        List<int[]> hints = new ArrayList<>();
        while (hint.find()) {
            hints.add(new int[] {hint.start(), hint.end()});
        }
        Matcher word = WORD.matcher(text);
        while (word.find()) {
            int at = word.start();
            if (hints.stream().noneMatch(h -> at >= h[0] && at < h[1])) {
                spans.add(new int[] {word.start(), word.end()});
            }
        }
        return spans;
    }

    private static String tidy(String text) {
        return text.replaceAll("\\s+([.?!,;:])", "$1").replaceAll("\\s{2,}", " ").strip();
    }

    /** How many words the end of the answer repeats from the start of the text after (or its start from the end before). */
    private static int overlap(List<String> answer, List<String> text, boolean atEnd) {
        for (int k = Math.min(answer.size(), text.size()); k > 0; k--) {
            List<String> mine = atEnd ? answer.subList(answer.size() - k, answer.size()) : answer.subList(0, k);
            List<String> theirs = atEnd ? text.subList(0, k) : text.subList(text.size() - k, text.size());
            if (lower(mine).equals(lower(theirs))) {
                return k;
            }
        }
        return 0;
    }

    /** The alternative without its last words, keeping the spaces it had around «|». */
    private static String cutEnd(String alternative, int words) {
        Matcher m = WORD.matcher(alternative);
        List<Integer> starts = new ArrayList<>();
        while (m.find()) {
            starts.add(m.start());
        }
        String kept = alternative.substring(0, starts.get(starts.size() - words)).stripTrailing();
        return kept + trailingSpace(alternative);
    }

    /** The alternative without its first words, keeping the spaces it had around «|». */
    private static String cutStart(String alternative, int words) {
        Matcher m = WORD.matcher(alternative);
        int end = 0;
        for (int n = 0; n < words && m.find(); n++) {
            end = m.end();
        }
        return leadingSpace(alternative) + alternative.substring(end).stripLeading();
    }

    private static String leadingSpace(String text) {
        return text.substring(0, text.length() - text.stripLeading().length());
    }

    private static String trailingSpace(String text) {
        return text.substring(text.stripTrailing().length());
    }

    /** The sentence with the first doubled occurrence of the words said only once: «making noise noise» → «making noise». */
    private static String withoutDoubled(String sentence, String words) {
        if (sentence == null) {
            return null;
        }
        Pattern doubled = Pattern.compile("(?i)\\b(" + Pattern.quote(words) + ")\\s+" + Pattern.quote(words) + "\\b");
        return doubled.matcher(sentence).replaceFirst("$1");
    }

