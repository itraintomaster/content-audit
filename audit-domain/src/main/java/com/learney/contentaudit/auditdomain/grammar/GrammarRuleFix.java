    private static boolean spaceAfterPeriods(List<SentencePartEntity> parts) {
        boolean changed = false;
        for (SentencePartEntity part : parts) {
            if (part != null && part.getKind() == SentencePartKind.TEXT && part.getText() != null) {
                String spaced = outsideHints(part.getText());
                if (!spaced.equals(part.getText())) {
                    part.setText(spaced);
                    changed = true;
                }
            }
        }
        return changed;
    }

    /** The text with the space after a period that glues two sentences, never inside a hint. */
    private static String outsideHints(String text) {
        StringBuilder sb = new StringBuilder();
        Matcher hint = HINT.matcher(text);
        int from = 0;
        while (hint.find()) {
            sb.append(GLUED_SENTENCE.matcher(text.substring(from, hint.start())).replaceAll("$1 $2"));
            sb.append(hint.group());
            from = hint.end();
        }
        sb.append(GLUED_SENTENCE.matcher(text.substring(from)).replaceAll("$1 $2"));
        return sb.toString();
    }

    /**
     * Writes the final mark at the end of the statement, before a hint that closes it, and returns it; null when the
     * statement already ends with one.
     */
    private static String finalMark(List<SentencePartEntity> parts) {
        String finished = finishedSentence(parts);
        if (finished.isBlank() || FINAL_MARK.matcher(finished).find()) {
            return null;
        }
        List<String> words = words(finished);
        String mark = !words.isEmpty() && QUESTION_OPENERS.contains(words.get(0).toLowerCase(Locale.ROOT)) ? "?" : ".";
        SentencePartEntity last = parts.get(parts.size() - 1);
        if (last != null && last.getKind() == SentencePartKind.TEXT && last.getText() != null) {
            String text = last.getText();
            Matcher closing = CLOSING_HINT.matcher(text);
            if (closing.find() && !text.substring(0, closing.start()).isBlank()) {
                last.setText(text.substring(0, closing.start()).stripTrailing() + mark + text.substring(closing.start()));
            } else {
                last.setText(text.stripTrailing() + mark);
            }
        } else {
            parts.add(new SentencePartEntity(SentencePartKind.TEXT, mark, null));
        }
        return mark;
    }

    /** The statement with the first answer in each gap, without hints. */
    private static String finishedSentence(List<SentencePartEntity> parts) {
        StringBuilder sb = new StringBuilder();
        for (SentencePartEntity part : parts) {
            if (part == null) {
                continue;
            }
            if (part.getKind() == SentencePartKind.CLOZE) {
                List<String> options = part.getOptions();
                sb.append(' ').append(options != null && !options.isEmpty() && options.get(0) != null
                        ? options.get(0).split("\\|", -1)[0].strip() : "");
            } else if (part.getText() != null) {
                sb.append(' ').append(withoutHints(part.getText()));
            }
        }
        return sb.toString().replaceAll("\\s+", " ").strip();
    }

