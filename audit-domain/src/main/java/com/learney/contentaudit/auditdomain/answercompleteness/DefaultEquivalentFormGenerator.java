    private static void negations(String low, String cased, Map<String, FormEquivalenceClass> out) {
        Matcher m = NEGATION.matcher(low);
        if (m.find()) {
            String token = m.group(1);
            String longForm = switch (token) {
                case "won't" -> "will not";
                case "can't" -> "cannot";
                case "shan't" -> "shall not";
                default -> token.substring(0, token.length() - 3) + " not";
            };
            String[] post = low.substring(m.end()).strip().split("\\s+");
            if (m.start() == 0 && post.length > 0 && INVERTED.contains(post[0])) {
                // «Doesn't she dance?» → «Does she not dance?»: the not goes after the subject;
                // «aren't I» is «am I not»
                String aux = longForm.split(" ")[0];
                if (aux.equals("are") && post[0].equals("i")) {
                    aux = "am";
                }
                StringBuilder inverted = new StringBuilder(aux).append(' ').append(post[0]).append(" not");
                for (int i = 1; i < post.length; i++) {
                    inverted.append(' ').append(post[i]);
                }
                add(out, inverted.toString(), FormEquivalenceClass.CONTRACTION);
            } else if (m.start() == 0 && startsANounPhrase(firstWord(cased, m.end()))) {
                // «Didn't the dogs eat?»: the long form takes the not after a subject that can be long,
                // so it is not generated; «didn't visit» and the order «Don't be late» are opened
                return;
            } else {
                add(out, low.substring(0, m.start()) + longForm + low.substring(m.end()), FormEquivalenceClass.CONTRACTION);
            }
        }
        Matcher l = LONG_NEGATION.matcher(low);
        if (l.find()) {
            String aux = l.group(1);
            String shortForm = switch (aux) {
                case "will" -> "won't";
                case "cannot", "can" -> "can't";
                case "shall" -> "shan't";
                default -> aux + "n't";
            };
            add(out, low.substring(0, l.start()) + shortForm + low.substring(l.end()), FormEquivalenceClass.CONTRACTION);
        }
        Matcher c = CANNOT.matcher(low);
        if (c.find()) {
            add(out, low.substring(0, c.start()) + "can't" + low.substring(c.end()), FormEquivalenceClass.CONTRACTION);
        }
    }

