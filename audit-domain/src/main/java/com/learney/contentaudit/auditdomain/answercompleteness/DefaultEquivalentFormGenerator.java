    /** A whole sentence: capital first, final mark, two words or more. */
    private static boolean isSentence(String text) {
        String t = text.strip();
        return t.length() > 1 && Character.isUpperCase(t.charAt(0)) && t.split("\\s+").length >= 2
                && ".?!".indexOf(t.charAt(t.length() - 1)) >= 0;
    }

    private static String bare(String word) {
        return word == null ? "" : word.replaceAll("[.,!?;:]", "");
    }

    /** A noun phrase opens with a determiner, a possessive or a capital name («Isn't John there?»). */
    private static boolean startsANounPhrase(String word) {
        String w = bare(word);
        if (w.isEmpty()) {
            return false;
        }
        return NOUN_PHRASE_STARTERS.contains(w.toLowerCase(Locale.ROOT))
                || (Character.isUpperCase(w.charAt(0)) && !w.equals("I"));
    }

    /** The first word of the text from position from, as written. */
    private static String firstWord(String text, int from) {
        String rest = text.substring(Math.min(from, text.length())).strip();
        return rest.isEmpty() ? "" : rest.split("\\s+")[0];
    }

    /** Whether the word before position at is an auxiliary that went before its subject. */
    private static boolean invertedBefore(String low, int at) {
        String head = low.substring(0, Math.max(0, at)).strip();
        if (head.isEmpty()) {
            return false;
        }
        String last = head.substring(head.lastIndexOf(' ') + 1);
        return QUESTION_AUXILIARIES.contains(bare(last));
    }

    private boolean isParticiple(String word) {
        String bare = word == null ? "" : word.replaceAll("[.,!?]", "");
        return irregularForms.isPastParticiple(bare) || (bare.length() > 3 && bare.endsWith("ed"));
    }

    private static void add(Map<String, FormEquivalenceClass> out, String form, FormEquivalenceClass equivalenceClass) {
        out.putIfAbsent(form.replaceAll("\\s+", " ").strip(), equivalenceClass);
    }

    /** The case of the accepted answer: its capital first letter, and «I». */
    private static String restoreCase(String form, String original) {
        String result = form.replaceAll("(?<![A-Za-z'])i(?![A-Za-z])", "I");
        if (!original.isEmpty() && Character.isUpperCase(original.charAt(0)) && !result.isEmpty()) {
            result = Character.toUpperCase(result.charAt(0)) + result.substring(1);
        }
        return result;
    }

    private static String unifyApostrophes(String text) {
        return text.replace('’', '\'').replace('‘', '\'').replace('′', '\'').replace('`', '\'');
    }

    /** Lower case without spaces, signs or apostrophes, as the corrector compares letters. */
    private static String compact(String text) {
        return text.toLowerCase(Locale.ROOT).replaceAll("[\\s!?:;,.\\-_'\"`]", "");
    }
