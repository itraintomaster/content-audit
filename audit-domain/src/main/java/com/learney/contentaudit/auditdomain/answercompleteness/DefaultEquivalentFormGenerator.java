    private static void spellings(String low, Map<String, FormEquivalenceClass> out) {
        Matcher m = Pattern.compile("[a-z]+").matcher(low);
        while (m.find()) {
            String word = m.group();
            String other = AMERICAN.containsKey(word) ? AMERICAN.get(word) : BRITISH.get(word);
            if (other != null) {
                add(out, low.replaceAll("\\b" + word + "\\b", other), FormEquivalenceClass.SPELLING);
            }
        }
    }

    private static void tillAndUntil(String low, Map<String, FormEquivalenceClass> out) {
        if (Pattern.compile("\\buntil\\b").matcher(low).find()) {
            add(out, low.replaceAll("\\buntil\\b", "till"), FormEquivalenceClass.PREPOSITION);
        }
        if (Pattern.compile("\\btill\\b").matcher(low).find()) {
            add(out, low.replaceAll("\\btill\\b", "until"), FormEquivalenceClass.PREPOSITION);
        }
    }

