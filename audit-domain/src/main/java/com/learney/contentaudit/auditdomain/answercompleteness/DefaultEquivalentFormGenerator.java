    private void contractedToLong(String low, String before, Map<String, FormEquivalenceClass> out) {
        Matcher m = CONTRACTED.matcher(low);
        while (m.find()) {
            String subject = m.group(1);
            String contracted = m.group(2);
            if ("let".equals(subject)) {
                continue;
            }
            String[] rest = low.substring(m.end()).strip().split("\\s+");
            int k = 0;
            boolean ever = false;
            boolean degree = false;
            while (k < rest.length && ADVERBS_BEFORE_THE_VERB.contains(bare(rest[k]))) {
                ever |= bare(rest[k]).equals("ever");
                degree |= DEGREE_ADVERBS.contains(bare(rest[k]));
                k++;
            }
            String next = k < rest.length ? bare(rest[k]) : "";
            boolean outside = subject == null;
            boolean noun = !outside && !PRONOUNS.contains(subject);
            if (outside && before.isEmpty()) {
                continue;
            }
            String afterNext = k + 1 < rest.length ? bare(rest[k + 1]) : "";
            String longForm;
            if (contracted.equals("'s")) {
                if (noun && !(next.endsWith("ing") || isParticiple(next) || Set.of("not", "been", "got", "just",
                        "already", "never", "always", "a", "an", "the").contains(next))) {
                    continue; // «Mary's house»: a possessive
                }
                if ((next.equals("used") || next.equals("supposed")) && afterNext.equals("to")) {
                    longForm = "is"; // «It's supposed to snow»
                } else if (degree) {
                    longForm = "is"; // «She's very tired»
                } else if (Set.of("been", "got", "gotten").contains(next)) {
                    longForm = "has";
                } else if (isParticiple(next)) {
                    boolean adjective = ADJECTIVE_PARTICIPLES.contains(next) && !OBJECT_STARTERS.contains(afterNext);
                    longForm = ever || !adjective ? "has" : "is"; // «he's ever used»; «It's crowded»
                } else {
                    longForm = "is";
                }
            } else if (contracted.equals("'d")) {
                if (PARTICIPLES_LIKE_THE_BASE.contains(next)) {
                    continue; // «She'd run quickly»: would or had, it cannot be told
                }
                longForm = isParticiple(next) || next.equals("better") || next.equals("been") ? "had" : "would";
            } else {
                longForm = LONG_OF.get(contracted);
            }
            String form = outside
                    ? (longForm + low.substring(m.end())).strip()
                    : (low.substring(0, m.start(2)) + " " + longForm + low.substring(m.end())).strip();
            add(out, form, FormEquivalenceClass.CONTRACTION);
        }
    }

    private void longToContracted(String low, String before, Map<String, FormEquivalenceClass> out) {
        Matcher m = LONG_AUX.matcher(low);
        while (m.find()) {
            String subject = m.group(1);
            String aux = m.group(2);
            String[] rest = low.substring(m.end()).strip().split("\\s+");
            String next = rest.length > 0 ? rest[0] : "";
            String bare = next.replaceAll("[.,!?]", "");
            if (Set.of("has", "have", "had").contains(aux)
                    && !(isParticiple(bare) || Set.of("got", "been", "better").contains(bare))) {
                continue; // have as the main verb is not contracted
            }
            if (next.isEmpty() || !Character.isLetter(next.charAt(0))) {
                continue; // at the end of the clause it is not contracted («than he is.»)
            }
            if (PRONOUNS.contains(bare) && !Set.of("that", "there", "this").contains(bare)) {
                continue; // «is he», «have you»: a question
            }
            if (subject != null && invertedBefore(low, m.start(1))) {
                continue; // «Won't they have been…?»: the auxiliary of the question already went first
            }
            String form;
            if (subject == null) {
                if (m.start() != 0 || before.isEmpty() || !PRONOUNS.contains(before)) {
                    continue;
                }
                form = (SHORT_OF.get(aux) + low.substring(m.end())).strip();
            } else {
                if (!CONTRACTING_SUBJECTS.contains(subject)) {
                    continue; // a noun subject: only contracted to long; nor «which's» or «this's»
                }
                if (subject.equals("i") && !aux.equals("am") && !Set.of("have", "will", "would", "had").contains(aux)) {
                    continue;
                }
                if (aux.equals("am") && !subject.equals("i")) {
                    continue;
                }
                form = low.substring(0, m.start(2) - 1) + SHORT_OF.get(aux) + low.substring(m.end());
            }
            add(out, form, FormEquivalenceClass.CONTRACTION);
        }
    }

