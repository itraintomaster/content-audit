    private List<FindingDraft> levelFindings(AuditNode node, double score) {
        CefrLevel level = levelOf(node);
        List<FindingDraft> drafts = new ArrayList<>();
        for (LemmaExposure word : underExposedOf(level, node)) {
            drafts.add(wordFinding(word));
        }
        if (drafts.isEmpty()) {
            // Never expected: a level below 1 has at least one word below its threshold.
            String label = level != null ? level.name() : "El nivel";
            drafts.add(new FindingDraft(RULE_UNDER_EXPOSED, null, FindingSeverity.LOW, FindingResolution.RANK_ONLY,
                    new FindingEvidence(List.of(new EvidencePart("Puntaje", percent(score))),
                            label + " tiene palabras que aparecen en menos oraciones que las que pide su banda",
                            List.of())));
        }
        return drafts;
    }

    /** The under-exposed words of a level node, in the order the level publishes them (R004). */
    private List<LemmaExposure> underExposedOf(CefrLevel level, AuditNode levelNode) {
        LemmaCountResult result = resultFor(levelNode);
        if (result != null) {
            return underExposedWords(result, level);
        }
        // No course result at hand: the level's own list, with the uniform threshold.
        List<LemmaExposure> words = new ArrayList<>();
        if (level != null && levelNode.getDiagnoses() instanceof DefaultLevelDiagnoses levelDiagnoses
                && levelDiagnoses.getLemmaCountDiagnosis().isPresent()) {
            words.addAll(listedWords(levelDiagnoses.getLemmaCountDiagnosis().get().getLevelResult(), level,
                    lemmaCountConfig.getThreshold()));
        }
        return words;
    }

    /**
     * The under-exposed words of a level in the order it publishes them (R004): from the table of
     * the result or, in a result of before the bands, from the level's own list with its uniform
     * threshold.
     */
    private static List<LemmaExposure> underExposedWords(LemmaCountResult result, CefrLevel level) {
        List<LemmaExposure> words = new ArrayList<>();
        if (level == null) {
            return words;
        }
        if (result.getExposures() != null && !result.getExposures().isEmpty()) {
            for (LemmaExposure e : result.getExposures()) {
                if (e.getAssignedLevel() == level && e.getScore() < 1.0) {
                    words.add(e);
                }
            }
            return words;
        }
        if (result.getLevels() != null) {
            for (LevelLemmaCountResult levelResult : result.getLevels()) {
                if (levelResult.getLevel() == level) {
                    words.addAll(listedWords(levelResult, level, result.getThresholdN()));
                }
            }
        }
        return words;
    }

    private static List<LemmaExposure> listedWords(LevelLemmaCountResult levelResult, CefrLevel level,
            int threshold) {
        List<LemmaExposure> words = new ArrayList<>();
        if (levelResult == null || levelResult.getSubExposedLemmas() == null) {
            return words;
        }
        for (LemmaCountStats s : levelResult.getSubExposedLemmas()) {
            if (s.getLemmaAndPos() != null) {
                words.add(new LemmaExposure(s.getLemmaAndPos(), level, s.getCount(), null, null, threshold,
                        s.getScore(), List.of()));
            }
        }
        return words;
    }

    private LemmaCountResult resultFor(AuditNode node) {
        if (lastResult != null) {
            return lastResult;
        }
        AuditNode root = node;
        while (root != null && root.getParent() != null) {
            root = root.getParent();
        }
        if (root != null && root.getDiagnoses() instanceof DefaultCourseDiagnoses courseDiagnoses) {
            return courseDiagnoses.getLemmaCountDiagnosis().map(LemmaCountCourseDiagnosis::getResult).orElse(null);
        }
        return null;
    }

    private FindingDraft wordFinding(LemmaExposure word) {
        String lemma = word.getLemmaAndPos().getLemma();
        String pos = word.getLemmaAndPos().getPos();
        String level = word.getAssignedLevel().name();
        List<EvidencePart> examined = new ArrayList<>();
        examined.add(new EvidencePart("Palabra", lemma));
        examined.add(new EvidencePart("Categoría", pos != null && !pos.isBlank() ? pos : "sin categoría"));
        examined.add(new EvidencePart("Nivel", level));
        examined.add(new EvidencePart("Oraciones", word.getCount() + " de " + word.getThreshold()));
        if (word.getBand() != null) {
            examined.add(new EvidencePart("Banda", word.getBand()));
        }
        examined.add(new EvidencePart("Puesto COCA",
                word.getCocaRank() != null ? thousands(word.getCocaRank()) : "sin puesto"));
        List<FindingNodeRef> topics = new ArrayList<>();
        List<String> topicLabels = new ArrayList<>();
        for (String knowledgeId : word.getKnowledgeIds() != null ? word.getKnowledgeIds() : List.<String>of()) {
            String label = knowledgeLabels.getOrDefault(knowledgeId, knowledgeId);
            topics.add(new FindingNodeRef(AuditTarget.KNOWLEDGE, knowledgeId, label));
            topicLabels.add(label != null ? label : knowledgeId);
        }
        if (!topicLabels.isEmpty()) {
            examined.add(new EvidencePart("Temas", String.join(" · ", topicLabels)));
        }
        String observation = lemma + " (" + level + "): " + sentences(word.getCount()) + " de " + word.getThreshold()
                + (word.getBand() != null ? "; banda " + bandPhrase(word.getBand()) : "");
        return new FindingDraft(RULE_UNDER_EXPOSED, lemma + "|" + pos, FindingSeverity.LOW,
                FindingResolution.RANK_ONLY, new FindingEvidence(examined, observation, topics));
    }

