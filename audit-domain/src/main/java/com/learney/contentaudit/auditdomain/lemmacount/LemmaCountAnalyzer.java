        AuditableQuiz quiz = (AuditableQuiz) node.getEntity();
        if (quiz == null || quiz.getTokens() == null) {
            return null;
        }
        String quizId = quiz.getId();
        // Track distinct content-word lemmas seen in this quiz (R004: one sentence = one count)
        Set<LemmaAndPos> seenInThisQuiz = new HashSet<>();
        for (NlpToken token : quiz.getTokens()) {
            if (token == null || token.getLemma() == null || token.getLemma().isEmpty()) {
                continue;
            }
            if (!contentWordFilter.isContentWord(token)) {
                continue;
            }
            LemmaAndPos lp = new LemmaAndPos(token.getLemma(), token.getPosTag());
            seenInThisQuiz.add(lp);
        }
        // For each distinct lemma in this quiz, record this quiz ID (R004, R005)
        for (LemmaAndPos lp : seenInThisQuiz) {
            lemmaQuizIds.computeIfAbsent(lp, k -> new HashSet<>()).add(quizId);
        }
        // F-POCOV-R005: the knowledge of this quiz, in the order the course is walked
        Optional<AuditNode> knowledge = node.ancestor(AuditTarget.KNOWLEDGE);
        if (knowledge.isPresent() && knowledge.get().getEntity() != null
                && knowledge.get().getEntity().getId() != null) {
            String knowledgeId = knowledge.get().getEntity().getId();
            knowledgeLabels.putIfAbsent(knowledgeId, knowledge.get().getEntity().getLabel());
            for (LemmaAndPos lp : seenInThisQuiz) {
                lemmaKnowledgeIds.computeIfAbsent(lp, k -> new LinkedHashSet<>()).add(knowledgeId);
            }
        }
        return null;
