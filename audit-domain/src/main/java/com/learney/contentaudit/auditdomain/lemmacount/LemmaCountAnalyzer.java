    @Override
    public Void onCourseComplete(AuditNode rootNode) {
        int thresholdN = lemmaCountConfig.getThreshold();
        List<LemmaCountBand> bands = lemmaCountConfig.getBands() != null
                ? List.copyOf(lemmaCountConfig.getBands()) : List.of();

        // Build LemmaCountStats for each lemma (R006, R009-R011), with the threshold of its band
        Map<CefrLevel, List<LemmaCountStats>> statsByLevel = new EnumMap<>(CefrLevel.class);
        List<UnassignedLemmaEntry> unassigned = new ArrayList<>();
        List<LemmaExposure> exposures = new ArrayList<>();

        for (Map.Entry<LemmaAndPos, Set<String>> entry : lemmaQuizIds.entrySet()) {
            LemmaAndPos lp = entry.getKey();
            int count = entry.getValue().size();
            Optional<CefrLevel> level = lemmaCefrLevelResolver.resolve(lp, Optional.empty());

            if (level.isPresent()) {
                // F-POCOV-R001 inv. 3: the band comes from the COCA rank of the EVP catalog
                Integer cocaRank = cocaRankOf(lp);
                LemmaCountBand band = bandFor(cocaRank, bands);
                int threshold = band != null ? band.getThreshold() : thresholdN;
                double score = Math.min((double) count / threshold, 1.0);
                LemmaCountStats stats = new LemmaCountStats(lp, count, score, level);
                statsByLevel.computeIfAbsent(level.get(), k -> new ArrayList<>()).add(stats);
                Set<String> knowledgeIds = lemmaKnowledgeIds.getOrDefault(lp, Collections.emptySet());
                exposures.add(new LemmaExposure(lp, level.get(), count, cocaRank,
                        band != null ? band.getName() : null, threshold, score, new ArrayList<>(knowledgeIds)));
            } else {
                // R011: no CEFR from any source -> unassigned group
                unassigned.add(new UnassignedLemmaEntry(lp, count));
            }
        }
        // F-POCOV-R004: by level, then band, then fewer sentences, then ascending COCA rank
        exposures.sort(exposureOrder(bands));

        // Compute per-level results (R012)
        List<LevelLemmaCountResult> levelResults = new ArrayList<>();
        for (CefrLevel level : CefrLevel.values()) {
            List<LemmaCountStats> statsForLevel = statsByLevel.getOrDefault(level, Collections.emptyList());
            if (statsForLevel.isEmpty()) {
                continue;
            }
            double levelScore = statsForLevel.stream()
                    .mapToDouble(LemmaCountStats::getScore)
                    .average()
                    .orElse(0.0);

            List<LemmaCountStats> subExposed = new ArrayList<>();
            for (LemmaCountStats s : statsForLevel) {
                if (s.getScore() < 1.0) {
                    subExposed.add(s);
                }
            }
            // Sort sub-exposed by count ascending (most urgent first per R017)
            subExposed.sort(Comparator.comparingInt(LemmaCountStats::getCount));

            levelResults.add(new LevelLemmaCountResult(level, levelScore, statsForLevel.size(), subExposed));
        }

        // Compute course score (R013, R014)
        Optional<Double> courseScore = levelResults.isEmpty()
                ? Optional.empty()
                : Optional.of(levelResults.stream()
                        .mapToDouble(LevelLemmaCountResult::getScore)
                        .average()
                        .orElse(0.0));

        LemmaCountResult result = new LemmaCountResult(thresholdN, courseScore, levelResults, unassigned,
                bands, exposures);
        lastResult = result;

        // Write course-level score and diagnosis (R015)
        double scoreValue = courseScore.orElse(0.0);
        rootNode.getScores().put(ANALYZER_NAME, scoreValue);
        if (rootNode.getDiagnoses() instanceof DefaultCourseDiagnoses) {
            DefaultCourseDiagnoses cd = (DefaultCourseDiagnoses) rootNode.getDiagnoses();
            cd.setLemmaCountDiagnosis(new LemmaCountCourseDiagnosis(result));
        }

        // Write per-milestone (level) diagnosis (R017)
        List<AuditNode> milestoneNodes = rootNode.getChildren() != null
                ? rootNode.getChildren() : Collections.emptyList();
        for (LevelLemmaCountResult lvl : levelResults) {
            AuditNode milestoneNode = findMilestoneNodeForLevel(milestoneNodes, lvl.getLevel());
            if (milestoneNode != null) {
                milestoneNode.getScores().put(ANALYZER_NAME, lvl.getScore());
                if (milestoneNode.getDiagnoses() instanceof DefaultLevelDiagnoses) {
                    DefaultLevelDiagnoses ld = (DefaultLevelDiagnoses) milestoneNode.getDiagnoses();
                    ld.setLemmaCountDiagnosis(new LemmaCountLevelDiagnosis(lvl));
                }
            }
        }

        return null;
    }

    private Integer cocaRankOf(LemmaAndPos lp) {
        Optional<Integer> rank = lemmaCefrLevelResolver.resolveCocaRank(lp);
        return rank != null && rank.isPresent() && rank.get() > 0 ? rank.get() : null;
    }

    /**
     * The band of a word: the first whose top rank holds its rank; the last band has no top and
     * also takes the words without a rank. Null when the configuration has no bands (tests only),
     * and then the word uses the uniform threshold.
     */
    static LemmaCountBand bandFor(Integer cocaRank, List<LemmaCountBand> bands) {
        if (bands == null || bands.isEmpty()) {
            return null;
        }
        for (LemmaCountBand band : bands) {
            if (band.getMaxCocaRank() == null) {
                return band;
            }
            if (cocaRank != null && cocaRank <= band.getMaxCocaRank()) {
                return band;
            }
        }
        return bands.get(bands.size() - 1);
    }

    private static Comparator<LemmaExposure> exposureOrder(List<LemmaCountBand> bands) {
        Map<String, Integer> bandIndex = new HashMap<>();
        for (int i = 0; i < bands.size(); i++) {
            bandIndex.putIfAbsent(bands.get(i).getName(), i);
        }
        return Comparator.comparingInt((LemmaExposure e) -> e.getAssignedLevel().ordinal())
                .thenComparingInt(e -> e.getBand() != null ? bandIndex.getOrDefault(e.getBand(), bands.size()) : 0)
                .thenComparingInt(LemmaExposure::getCount)
                .thenComparingInt(e -> e.getCocaRank() != null ? e.getCocaRank() : Integer.MAX_VALUE)
                .thenComparing(e -> e.getLemmaAndPos().getLemma(), Comparator.nullsFirst(Comparator.naturalOrder()))
                .thenComparing(e -> e.getLemmaAndPos().getPos(), Comparator.nullsFirst(Comparator.naturalOrder()));
    }

    private AuditNode findMilestoneNodeForLevel(List<AuditNode> milestoneNodes, CefrLevel level) {
        for (AuditNode node : milestoneNodes) {
            if (node.getEntity() instanceof AuditableMilestone) {
                AuditableMilestone milestone = (AuditableMilestone) node.getEntity();
                try {
                    CefrLevel nodeLevel = CefrLevel.valueOf(milestone.getLabel());
                    if (level.equals(nodeLevel)) {
                        return node;
                    }
                } catch (IllegalArgumentException | NullPointerException ignored) {
                }
            }
        }
        return null;
    }

