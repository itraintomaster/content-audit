    private List<FindingDraft> courseFindings(AuditNode root, double score) {
        LemmaCountResult result = resultFor(root);
        Set<CefrLevel> levelsWithNode = levelsWithNode(root);
        List<FindingDraft> drafts = new ArrayList<>();
        if (result != null && result.getLevels() != null) {
            for (LevelLemmaCountResult level : result.getLevels()) {
                if (level.getScore() >= 1.0) {
                    continue;
                }
                drafts.add(courseLevelFinding(result, level, levelsWithNode.contains(level.getLevel())));
            }
        }
        if (drafts.isEmpty()) {
            // A course below 1 without levels below 1 has no word with a level at all.
            drafts.add(new FindingDraft(RULE_UNDER_EXPOSED, null, FindingSeverity.LOW, FindingResolution.RANK_ONLY,
                    new FindingEvidence(List.of(new EvidencePart("Puntaje", percent(score))),
                            "El curso no tiene palabras con nivel que contar", List.of())));
        }
        return drafts;
    }

    private FindingDraft courseLevelFinding(LemmaCountResult result, LevelLemmaCountResult level, boolean hasNode) {
        String name = level.getLevel().name();
        List<LemmaExposure> words = underExposedWords(result, level.getLevel());
        int below = level.getSubExposedLemmas() != null ? level.getSubExposedLemmas().size() : words.size();
        List<EvidencePart> examined = new ArrayList<>();
        examined.add(new EvidencePart("Nivel", name));
        examined.add(new EvidencePart("Puntaje", percent(level.getScore())));
        examined.add(new EvidencePart("Poco vistas", below + " de " + level.getTotalLemmas() + " palabras"));
        examined.add(new EvidencePart("Umbral", thresholdsText(result)));
        result.getCourseScore().ifPresent(course -> examined.add(new EvidencePart("Curso", percent(course))));
        List<String> named = new ArrayList<>();
        for (LemmaExposure word : words) {
            if (hasNode && named.size() >= EVIDENCE_EXAMPLES) {
                break;
            }
            named.add(word.getLemmaAndPos().getLemma() + " (" + word.getCount() + " de " + word.getThreshold() + ")");
        }
        if (!named.isEmpty()) {
            examined.add(new EvidencePart(hasNode ? "Las primeras" : "Palabras", String.join(", ", named)));
        }
        String observation;
        if (hasNode) {
            observation = name + " da " + percent(level.getScore()) + ": " + below + " de sus "
                    + level.getTotalLemmas() + " palabras aparecen en menos oraciones que las que pide su banda";
        } else if (words.size() == 1) {
            LemmaExposure word = words.get(0);
            observation = name + " no es un nivel del curso: su palabra poco vista es "
                    + word.getLemmaAndPos().getLemma() + " (" + sentences(word.getCount()) + " de "
                    + word.getThreshold() + ")";
        } else {
            observation = name + " no es un nivel del curso: sus " + below + " palabras poco vistas son "
                    + String.join(", ", named);
        }
        return new FindingDraft(RULE_UNDER_EXPOSED, name, FindingSeverity.LOW, FindingResolution.RANK_ONLY,
                new FindingEvidence(examined, observation, List.of()));
    }

    private static Set<CefrLevel> levelsWithNode(AuditNode root) {
        Set<CefrLevel> levels = new HashSet<>();
        if (root.getChildren() == null) {
            return levels;
        }
        for (AuditNode child : root.getChildren()) {
            CefrLevel level = levelOf(child);
            if (level != null) {
                levels.add(level);
            }
        }
        return levels;
    }

    private static CefrLevel levelOf(AuditNode node) {
        if (node == null || node.getEntity() == null || node.getEntity().getLabel() == null) {
            return null;
        }
        try {
            return CefrLevel.valueOf(node.getEntity().getLabel());
        } catch (IllegalArgumentException e) {
            return null;
        }
    }

    /** «8 oraciones (1.000 más comunes) · 6 (hasta 2.000) · …», each band's threshold, or the uniform one. */
    private static String thresholdsText(LemmaCountResult result) {
        if (result.getBands() == null || result.getBands().isEmpty()) {
            return result.getThresholdN() + " oraciones";
        }
        List<String> parts = new ArrayList<>();
        for (LemmaCountBand band : result.getBands()) {
            parts.add((parts.isEmpty() ? band.getThreshold() + " oraciones" : String.valueOf(band.getThreshold()))
                    + " (" + band.getName() + ")");
        }
        return String.join(" · ", parts);
    }

    /** «de las 1.000 más comunes», «hasta 2.000»: the band as it reads after «banda». */
    static String bandPhrase(String bandName) {
        if (bandName != null && !bandName.isEmpty() && Character.isDigit(bandName.charAt(0))) {
            return "de las " + bandName;
        }
        return bandName;
    }

    private static String sentences(int count) {
        return count == 1 ? "1 oración" : count + " oraciones";
    }

    private static String thousands(int value) {
        return String.format(Locale.ROOT, "%,d", value).replace(',', '.');
    }

    private static String percent(double fraction) {
        return String.format(Locale.ROOT, "%.1f", fraction * 100).replace('.', ',') + " %";
    }

