package com.learney.contentaudit.auditdomain.naturalness;

import com.learney.contentaudit.auditdomain.localtools.YesNoModel;
import com.learney.contentaudit.auditdomain.localtools.YesNoProbabilities;
import com.learney.contentaudit.evaluationledgerdomain.EvaluationEmitted;
import com.learney.contentaudit.evaluationledgerdomain.EvaluationFailureKind;
import com.learney.contentaudit.evaluationledgerdomain.EvaluationNotEmitted;
import com.learney.contentaudit.evaluationledgerdomain.EvaluationOutcome;
import com.learney.contentaudit.evaluationledgerdomain.EvaluationSubject;
import com.learney.contentaudit.evaluationledgerdomain.Evaluator;
import java.util.Optional;
import javax.annotation.processing.Generated;

/**
 * F-NATUR-R002 and F-MLOCAL-R002 inv. 2: one consultation per sentence to the local model, kept in
 * the ledger of evaluations. Its id carries the examined version -- the model with its digest and the
 * method of the question --, so every version has its own file and none reuses what another one
 * recorded; its version is that same examined version, so the judges' runtime brakes it on the same
 * exam as the gate. It records the two probabilities and not the number: if the arithmetic changes,
 * nothing is asked again. It never throws: a model that fails is an unavailable evaluator.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
class NaturalnessEvaluator implements Evaluator {

    /** The key of the content: the finished sentence, exactly what the model is asked about. */
    static final String SENTENCE = "sentence";

    private final YesNoModel yesNoModel;

    private final NaturalnessConfig config;

    private final String examinedVersion;

    public NaturalnessEvaluator(YesNoModel yesNoModel, NaturalnessConfig config,
            String examinedVersion) {
        this.yesNoModel = yesNoModel;
        this.config = config;
        this.examinedVersion = examinedVersion;
    }

    @Override
    public String evaluatorId() {
        return NaturalnessAnalyzer.ANALYZER_NAME + " · " + examinedVersion;
    }

    @Override
    public EvaluationOutcome evaluate(EvaluationSubject subject) {
        String sentence = subject != null && subject.getContent() != null ? subject.getContent().get(SENTENCE) : null;
        if (sentence == null || sentence.isBlank()) {
            return new EvaluationNotEmitted(EvaluationFailureKind.OUTPUT_UNUSABLE, "no hay oración para preguntar");
        }
        try {
            YesNoProbabilities answer = yesNoModel.ask(config.system(), config.question(sentence));
            if (answer == null) {
                return new EvaluationNotEmitted(EvaluationFailureKind.OUTPUT_UNUSABLE, "el modelo no contestó");
            }
            return new EvaluationEmitted("{\"yes\":" + Double.toString(answer.getYesProbability()) + ",\"no\":"
                    + Double.toString(answer.getNoProbability()) + "}");
        } catch (RuntimeException e) {
            return new EvaluationNotEmitted(EvaluationFailureKind.EVALUATOR_UNAVAILABLE,
                    "el modelo local dejó de responder: " + e.getMessage());
        }
    }

    @Override
    public Optional<String> evaluatorVersion() {
        return Optional.ofNullable(examinedVersion);
    }
}
