    private static Kind classify(String candidate) {
        String text = candidate == null ? "" : candidate.strip();
        if (text.isEmpty() || text.matches(".*[.?!].*")) {
            return null; // a context note is a sentence: «(Michael visited Luis.)»
        }
        if (text.contains("/")) {
            return slots(text).isEmpty() ? null : Kind.WORDS;
        }
        if (isLabel(text)) {
            return null;
        }
        return text.split("\\s+").length >= 4 ? Kind.DESCRIPTIVE : Kind.WORDS;
    }

    /** A tense name, an instruction or a note: not words to write. */
    static boolean isLabel(String text) {
        String stripped = text.strip();
        if (stripped.equals("UK") || stripped.equals("US")) {
            return true;
        }
        String lower = stripped.toLowerCase(Locale.ROOT);
        return TENSE.matcher(lower).matches() || NOTES.contains(lower)
                || (INSTRUCTION.matcher(lower).find() && !lower.contains("/"))
                || lower.contains("plural") || lower.contains("countable");
    }

    /** The options or parts of a hint separated by «/», without the ones that are labels. */
    static List<String> slots(String hint) {
        List<String> slots = new ArrayList<>();
        for (String slot : hint.split("/")) {
            String stripped = slot.strip();
            if (!stripped.isEmpty() && !isLabel(stripped)) {
                slots.add(stripped);
            }
        }
        return slots;
    }

    /** «(the fish)» in «The cats ate the fish.»: it points at the sentence, it announces nothing. */
    private static boolean pointsAtTheSource(String hint, Set<String> sourceWords) {
        List<String> content = new ArrayList<>();
        for (String word : words(hint)) {
            String lower = word.toLowerCase(Locale.ROOT);
            if (!FUNCTION_WORDS.contains(lower)) {
                content.add(lower);
            }
        }
        return !content.isEmpty() && sourceWords.containsAll(content);
    }

    private static ExerciseHint build(List<Read> hints, List<String> answers) {
        List<String> texts = new ArrayList<>();
        String subject = null;
        boolean negated = false;
        boolean choice = false;
        boolean comparable = false;
        List<String> words = new ArrayList<>();
        for (Read hint : hints) {
            texts.add(hint.parenthesized() ? "(" + hint.text().strip() + ")" : hint.text().strip());
            if (hint.kind() != Kind.WORDS) {
                continue;
            }
            List<String> slots = slots(hint.text());
            if (slots.size() == 1 && SUBJECT_PRONOUNS.contains(slots.get(0).toLowerCase(Locale.ROOT))) {
                if (subject == null) {
                    subject = slots.get(0); // «(I)»: the subject to answer with
                }
                continue;
            }
            for (String slot : slots) {
                for (String word : words(slot)) {
                    if (word.equalsIgnoreCase("not")) {
                        negated = true;
                    }
                }
            }
            String hintSubject = null;
            if (slots.size() >= 2) {
                String first = slots.get(0);
                if (SUBJECT_PRONOUNS.contains(first.toLowerCase(Locale.ROOT))
                        || (NAME.matcher(first).matches() && first.split("\\s+").length <= 3)) {
                    hintSubject = first;
                }
            }
            if (subject == null && hintSubject != null) {
                subject = hintSubject;
            }
            if (slots.size() >= 2 && slots.stream().noneMatch(s -> s.equalsIgnoreCase("not"))
                    && isOneOf(answers, slots)) {
                choice = true; // «(good / well)» answered «well»: the answer is one of its options
                continue;
            }
            comparable = true;
            for (String slot : slots) {
                if (slot.equals(hintSubject)) {
                    continue;
                }
                for (String word : words(slot)) {
                    String lower = word.toLowerCase(Locale.ROOT);
                    Matcher clitic = CLITIC.matcher(lower);
                    if (clitic.matches()) {
                        lower = clitic.group(1); // «You're / kind person»: the clitic is grammar
                    }
                    if (lower.isEmpty() || lower.equals("not") || FUNCTION_WORDS.contains(lower)
                            || SUBJECT_PRONOUNS.contains(lower)) {
                        continue;
                    }
                    words.add(lower);
                }
            }
        }
        return new ExerciseHint(String.join(" ", texts), List.copyOf(words), subject, negated,
                choice && !comparable);
    }

    private static boolean isOneOf(List<String> answers, List<String> slots) {
        for (String answer : answers) {
            String normalized = compact(answer);
            for (String slot : slots) {
                if (!normalized.isEmpty() && normalized.equals(compact(slot))) {
                    return true;
                }
            }
        }
        return false;
    }

