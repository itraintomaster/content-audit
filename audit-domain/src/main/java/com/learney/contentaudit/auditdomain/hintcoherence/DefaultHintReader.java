    static List<SentencePartEntity> parts(AuditableQuiz quiz) {
        return quiz != null && quiz.getSentenceParts() != null ? quiz.getSentenceParts() : List.of();
    }

    static List<Integer> gaps(List<SentencePartEntity> parts) {
        List<Integer> gaps = new ArrayList<>();
        for (int i = 0; i < parts.size(); i++) {
            if (parts.get(i) != null && parts.get(i).getKind() == SentencePartKind.CLOZE) {
                gaps.add(i);
            }
        }
        return gaps;
    }

    /** The first accepted answer of every gap (F-QSENT-R018): what the audio says. */
    static List<String> firstAnswers(AuditableQuiz quiz) {
        List<String> answers = new ArrayList<>();
        List<SentencePartEntity> parts = parts(quiz);
        for (int gap : gaps(parts)) {
            List<String> options = parts.get(gap).getOptions();
            if (options != null && !options.isEmpty() && options.get(0) != null) {
                answers.add(options.get(0).split("\\|", -1)[0].strip());
            } else if (quiz.getMultipleChoice() != null) {
                answers.add(quiz.getMultipleChoice().correctItem().map(MultipleChoiceItemEntity::getLabel)
                        .orElse(""));
            } else {
                answers.add("");
            }
        }
        return answers;
    }

    /** The text of the parts between from and to, without hints, as one line. */
    static String fixedText(List<SentencePartEntity> parts, int from, int to) {
        StringBuilder sb = new StringBuilder();
        for (int i = from; i < to && i < parts.size(); i++) {
            if (isText(parts.get(i))) {
                sb.append(' ').append(withoutHints(parts.get(i).getText()));
            }
        }
        return sb.toString().replaceAll("\\s+", " ").strip();
    }

    /** True when nothing but hints comes before the first gap: the gap opens the sentence. */
    static boolean gapOpensTheStatement(AuditableQuiz quiz) {
        List<SentencePartEntity> parts = parts(quiz);
        List<Integer> gaps = gaps(parts);
        return !gaps.isEmpty() && fixedText(parts, 0, gaps.get(0)).isEmpty();
    }

    static String withoutHints(String text) {
        if (text == null) {
            return "";
        }
        return HINT.matcher(text).replaceAll(" ").replaceAll("\\s+", " ").strip();
    }

    static List<String> words(String text) {
        List<String> words = new ArrayList<>();
        if (text == null) {
            return words;
        }
        Matcher m = WORD.matcher(text);
        while (m.find()) {
            words.add(m.group());
        }
        return words;
    }

    /** An answer that is a sentence: capital first, final mark, two words or more. */
    static boolean isSentence(String answer) {
        String text = answer == null ? "" : answer.strip();
        if (text.isEmpty() || !Character.isUpperCase(text.charAt(0)) || words(text).size() < 2) {
            return false;
        }
        char last = text.charAt(text.length() - 1);
        return last == '.' || last == '?' || last == '!';
    }

    private static boolean endsASentence(String text) {
        String stripped = text.strip();
        if (stripped.isEmpty()) {
            return false;
        }
        char last = stripped.charAt(stripped.length() - 1);
        return last == '.' || last == '?' || last == '!' || last == ':';
    }

    /** Lower case without spaces, signs or apostrophes, as the corrector compares letters. */
    static String compact(String text) {
        return text == null ? "" : text.toLowerCase(Locale.ROOT).replaceAll("[\\s!?:;,.\\-_'\"`’‘]", "");
    }

    private static boolean isText(SentencePartEntity part) {
        return part != null && part.getKind() == SentencePartKind.TEXT;
    }

    private static String text(SentencePartEntity part) {
        return part.getText() != null ? part.getText() : "";
    }
