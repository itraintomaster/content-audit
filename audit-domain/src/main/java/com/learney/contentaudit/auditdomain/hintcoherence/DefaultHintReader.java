/**
 * Reads the hint of an exercise from its parts, as FEAT-PISTA defines it: the text between
 * parentheses attached to the gap (F-QSENT-R007) or, when the answer is the whole sentence, the
 * text between parentheses of the statement and the statement of words separated by «/» («She /
 * assist you.»). A tense name («(present simple)»), an instruction («(be extra polite)») or a
 * context note («(the listener doesn't know which man)») is not a hint, and the sentence to be
 * transformed never is (DOUBT-PISTA-TRANSFORMAR, José 30/9).
 *
 * <p>What it reads is kept as the words to compare with the answer -- without the subject and
 * «not», which have their own rules -- and with whether it is a choice («(good / well)»: the
 * answer is one of its options). A hint that describes instead of announcing words («(bicycle
 * that belongs to his sister)») or that points at a part of the sentence to transform («(the
 * fish)» in «The cats ate the fish.») is a hint, so it counts for R001, but has no words to
 * compare.
 */
