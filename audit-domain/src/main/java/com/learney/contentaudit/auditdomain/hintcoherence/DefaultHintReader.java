    /** The subject pronouns of R003. */
    static final Set<String> SUBJECT_PRONOUNS = Set.of("i", "you", "he", "she", "it", "we", "they");

    /** Words of a hint that announce nothing to write: articles and the like. */
    static final Set<String> FUNCTION_WORDS = Set.of("the", "a", "an", "to", "some", "any", "of");

    private static final Pattern HINT = Pattern.compile("\\(([^)]*)\\)");

    private static final Pattern WORD = Pattern.compile("[A-Za-z][A-Za-z'-]*");

    private static final Pattern CLITIC = Pattern.compile("^([a-z]+)('s|'re|'ve|'ll|'d|'m|n't)$");

    /** Tense names: «present simple», «(use the past continuous)», «third conditional». */
    private static final Pattern TENSE = Pattern.compile(
            "^(use (the )?)?(the )?(present|past|future)( perfect)?( simple| continuous| progressive)( tense)?$"
                    + "|^(use (the )?)?(the )?(present|past|future) perfect( tense)?$"
                    + "|^(use (the )?)?(the )?(present|past|future) tense$"
                    + "|^(first|second|third|zero|mixed) conditional$"
                    + "|^(passive|active)( voice)?$");

    /** Instructions and position notes: «use the present simple», «be extra polite», «mid». */
    private static final Pattern INSTRUCTION = Pattern.compile(
            "^(use (the|a|an|your|my)\\b|be extra\\b|emphasi[sz]e\\b|make it\\b|before the\\b|after the\\b)");

    /** Register, time and grammar notes that are not words to write. */
    private static final Set<String> NOTES = Set.of("formal", "informal", "polite", "now", "in general",
            "countable", "uncountable", "no plural form", "short form", "short forms", "long form",
            "long forms", "mid", "100%");

    /** A statement of words separated by «/» may open with a label: «Be going to: They not / paint…». */
    private static final Pattern LABEL = Pattern.compile("^[A-Za-z ]+:\\s*");

    private static final Pattern SLASH_CUE_BEFORE = Pattern.compile(
            "([A-Za-z'-]+(?: [A-Za-z'-]+)?\\s*/\\s*[A-Za-z'-]+(?: [A-Za-z'-]+)?)\\s*$");

    private static final Pattern SLASH_CUE_AFTER = Pattern.compile(
            "^([A-Za-z'-]+(?: [A-Za-z'-]+)?\\s*/\\s*[A-Za-z'-]+(?: [A-Za-z'-]+)?)\\b");

    /** A name or a noun phrase that can be the subject of a slash hint: «Peter», «the students». */
    private static final Pattern NAME = Pattern.compile(
            "^(?!(?:What|Where|When|Who|Whom|Whose|Why|How|Which)$)"
                    + "(?:[A-Z][a-z]+|(?:[Tt]he|[Mm]y|[Yy]our|[Hh]is|[Hh]er|[Oo]ur|[Tt]heir|[Tt]hat|[Tt]his) [a-z]+.*)$");

    private enum Kind { WORDS, DESCRIPTIVE, POINTER }

    private record Candidate(String text, boolean parenthesized) {
    }

    private record Read(String text, boolean parenthesized, Kind kind) {
    }

    @Override
    public Optional<ExerciseHint> read(AuditableQuiz quiz, SentenceMode mode) {
        List<SentencePartEntity> parts = parts(quiz);
        List<Integer> gaps = gaps(parts);
        if (gaps.isEmpty()) {
            return Optional.empty();
        }
        ExerciseShape shape = shapeOf(quiz, mode);
        List<Candidate> candidates = shape == ExerciseShape.GAP_IN_SENTENCE
                ? gapCandidates(parts, gaps)
                : wholeSentenceCandidates(parts, gaps);

        Set<String> sourceWords = new LinkedHashSet<>();
        for (SentencePartEntity part : parts) {
            if (part != null && part.getKind() == SentencePartKind.TEXT) {
                for (String word : words(withoutHints(part.getText()))) {
                    sourceWords.add(word.toLowerCase(Locale.ROOT));
                }
            }
        }

        List<Read> hints = new ArrayList<>();
        for (Candidate candidate : candidates) {
            Kind kind = classify(candidate.text());
            if (kind == null) {
                continue;
            }
            if (shape == ExerciseShape.WHOLE_SENTENCE && candidate.parenthesized() && kind == Kind.WORDS
                    && !candidate.text().contains("/") && pointsAtTheSource(candidate.text(), sourceWords)) {
                kind = Kind.POINTER;
            }
            hints.add(new Read(candidate.text(), candidate.parenthesized(), kind));
        }
        if (hints.isEmpty()) {
            return Optional.empty();
        }
        return Optional.of(build(hints, firstAnswers(quiz)));
    }

    @Override
    public ExerciseShape shapeOf(AuditableQuiz quiz, SentenceMode mode) {
        List<SentencePartEntity> parts = parts(quiz);
        List<Integer> gaps = gaps(parts);
        if (gaps.isEmpty()) {
            return ExerciseShape.GAP_IN_SENTENCE;
        }
        String before = fixedText(parts, 0, gaps.get(0));
        String after = fixedText(parts, gaps.get(gaps.size() - 1) + 1, parts.size());
        if (after.chars().anyMatch(Character::isLetterOrDigit)) {
            return ExerciseShape.GAP_IN_SENTENCE;
        }
        List<String> answers = firstAnswers(quiz);
        String last = answers.isEmpty() ? "" : answers.get(answers.size() - 1);
        if ((before.isEmpty() || endsASentence(before)) && words(last).size() >= 2) {
            return ExerciseShape.WHOLE_SENTENCE;
        }
        if (mode == SentenceMode.REWRITE && isSentence(last)) {
            return ExerciseShape.WHOLE_SENTENCE;
        }
        return ExerciseShape.GAP_IN_SENTENCE;
    }

