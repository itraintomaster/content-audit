    static final String NOT_IN_PHOTO = "el ejercicio no está en la foto del curso";

    static final String NOT_EVALUATED = "el juez no lo evaluó en esta corrida";

    static final String NOT_REACHED = "el juez no juzga este ejercicio";

    @Override
    public List<JudgeExamVerdict> export(AuditReport report, AnalyzerDescriptor card,
            Set<String> caseIds, JudgeCoverageDiagnosis coverage) {
        List<JudgeExamVerdict> verdicts = new ArrayList<>();
        if (caseIds == null || caseIds.isEmpty() || card == null) {
            return verdicts;
        }
        String judgeName = card.getName();
        LocalToolRunDiagnosis run = runOf(report, judgeName);
        String judgeVersion = coverage != null && coverage.getStanding() != null
                ? coverage.getStanding().getJudgeVersion()
                : (run != null ? run.getExaminedVersion() : null);
        boolean everyRule = card.getTools() != null && !card.getTools().isEmpty();
        Map<String, AuditNode> quizzes = quizzesById(report != null ? report.getRoot() : null);

        for (String caseId : caseIds) {
            AuditNode node = quizzes.get(caseId);
            if (node == null) {
                verdicts.add(notJudged(caseId, judgeName, judgeVersion, NOT_IN_PHOTO));
                continue;
            }
            if (contains(node.getUnevaluatedBy(), judgeName) || contains(node.getPartiallyEvaluatedBy(), judgeName)) {
                verdicts.add(notJudged(caseId, judgeName, judgeVersion, unevaluatedDetail(coverage, run)));
                continue;
            }
            List<Finding> paid = examinedFindingsOf(node, judgeName, everyRule);
            boolean scored = node.getScores() != null && node.getScores().get(judgeName) != null;
            if (!scored && paid.isEmpty()) {
                verdicts.add(notJudged(caseId, judgeName, judgeVersion, NOT_REACHED));
                continue;
            }
            List<Finding> counting = new ArrayList<>();
            for (Finding finding : paid) {
                if (finding.getResolution() != FindingResolution.RANK_ONLY) {
                    counting.add(finding);
                }
            }
            if (!counting.isEmpty()) {
                verdicts.add(verdict(caseId, judgeName, judgeVersion, JudgeExamOutcome.FAILS, counting));
            } else if (!paid.isEmpty()) {
                // A finding that only ranks (judges-disagree) is not one that counts: no worst severity.
                JudgeExamVerdict marked = verdict(caseId, judgeName, judgeVersion, JudgeExamOutcome.MARKED, paid);
                marked.setWorstSeverity(null);
                verdicts.add(marked);
            } else {
                verdicts.add(new JudgeExamVerdict(caseId, judgeName, judgeVersion, JudgeExamOutcome.PASSES, null,
                        List.of(), ""));
            }
        }
        return verdicts;
    }

    private static JudgeExamVerdict verdict(String caseId, String judgeName, String judgeVersion,
            JudgeExamOutcome outcome, List<Finding> findings) {
        FindingSeverity worst = null;
        Set<String> rules = new LinkedHashSet<>();
        List<String> details = new ArrayList<>();
        for (Finding finding : findings) {
            if (finding.getSeverity() != null && (worst == null || finding.getSeverity().ordinal() < worst.ordinal())) {
                worst = finding.getSeverity();
            }
            rules.add(finding.getRule());
            details.add(describe(finding));
        }
        return new JudgeExamVerdict(caseId, judgeName, judgeVersion, outcome, worst, new ArrayList<>(rules),
                String.join(" · ", details));
    }

    private static String describe(Finding finding) {
        StringBuilder sb = new StringBuilder(finding.getRule());
        String marker = finding.getIdentity() != null ? finding.getIdentity().getMarker() : null;
        if (marker != null && !marker.isBlank()) {
            sb.append(" «").append(marker).append('»');
        }
        String observation = finding.getEvidence() != null ? finding.getEvidence().getObservation() : null;
        if (observation != null && !observation.isBlank()) {
            sb.append(": ").append(observation);
        }
        return sb.toString();
    }

    private static JudgeExamVerdict notJudged(String caseId, String judgeName, String judgeVersion, String detail) {
        return new JudgeExamVerdict(caseId, judgeName, judgeVersion, JudgeExamOutcome.NOT_JUDGED, null, List.of(),
                detail);
    }

    private static String unevaluatedDetail(JudgeCoverageDiagnosis coverage, LocalToolRunDiagnosis run) {
        String reason = coverage != null ? coverage.getUnavailableReason() : null;
        if ((reason == null || reason.isBlank()) && run != null) {
            reason = run.getReason();
        }
        return reason != null && !reason.isBlank() ? NOT_EVALUATED + ": " + reason : NOT_EVALUATED;
    }

    /** The findings the exam looks at: those of the paid-model rules or, with a local tool, all of them. */
    private static List<Finding> examinedFindingsOf(AuditNode node, String judgeName, boolean everyRule) {
        List<Finding> examined = new ArrayList<>();
        if (node.getFindings() == null) {
            return examined;
        }
        for (Finding finding : node.getFindings()) {
            if (finding != null && judgeName.equals(finding.getAnalyzer())
                    && (everyRule || finding.getCost() == AnalysisCost.PAID_MODEL)) {
                examined.add(finding);
            }
        }
        return examined;
    }

    /** The row of an analyzer with a local tool in the run (hook B-03), if it left one. */
    private static LocalToolRunDiagnosis runOf(AuditReport report, String analyzerName) {
        if (report == null || report.getRoot() == null
                || !(report.getRoot().getDiagnoses() instanceof CourseDiagnoses diagnoses)
                || diagnoses.getLocalToolRuns() == null) {
            return null;
        }
        for (LocalToolRunDiagnosis run : diagnoses.getLocalToolRuns()) {
            if (run != null && analyzerName.equals(run.getAnalyzer())) {
                return run;
            }
        }
        return null;
    }

    private static Map<String, AuditNode> quizzesById(AuditNode root) {
        Map<String, AuditNode> quizzes = new HashMap<>();
        if (root == null) {
            return quizzes;
        }
        Deque<AuditNode> pending = new ArrayDeque<>();
        pending.push(root);
        while (!pending.isEmpty()) {
            AuditNode node = pending.pop();
            if (node.getTarget() == AuditTarget.QUIZ && node.getEntity() != null && node.getEntity().getId() != null) {
                quizzes.putIfAbsent(node.getEntity().getId(), node);
            }
            if (node.getChildren() != null) {
                for (AuditNode child : node.getChildren()) {
                    if (child != null) {
                        pending.push(child);
                    }
                }
            }
        }
        return quizzes;
    }

    private static boolean contains(List<String> names, String name) {
        return names != null && names.contains(name);
    }
