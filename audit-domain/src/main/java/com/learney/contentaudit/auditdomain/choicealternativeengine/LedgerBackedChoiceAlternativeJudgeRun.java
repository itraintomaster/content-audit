    @Override
    public ChoiceAlternativeJudgment judgmentOf(AuditNode quizNode) {
        if (quizNode == null || !requestedNodes.contains(quizNode)) {
            return null;
        }
        if (!settled.contains(quizNode)) {
            resolveAll();
        }
        return judgments.get(quizNode);
    }

