    private ChoiceAlternativeJudgment judge(AuditNode unit, EvaluationRequestMode mode,
            EvaluationResolution resolution, EvaluationSession session) {
        EvaluationResolutionKind kind = resolution != null ? resolution.getKind() : null;
        if (kind == EvaluationResolutionKind.REUSED || kind == EvaluationResolutionKind.EVALUATED) {
            try {
                ChoiceAlternativeVerdict verdict = verdictReader.read(resolution.getPayload());
                if (verdict == null) {
                    throw new IllegalStateException("el lector no devolvió ningún veredicto");
                }
                ChoiceAlternativeJudgment judgment = classifier.classify(verdict, quizOf(unit), resolution);
                if (judgment == null) {
                    throw new IllegalStateException("el clasificador no devolvió ningún juicio");
                }
                return judgment;
            } catch (RuntimeException e) {
                return notJudged(unit, ChoiceAlternativeJudgmentStatus.FAILED, REASON_UNREADABLE + messageOf(e));
            }
        }
        if (kind == EvaluationResolutionKind.PENDING) {
            if (opened.getJudgeVersion() == null) {
                return notJudged(unit, ChoiceAlternativeJudgmentStatus.NOT_AVAILABLE, noVersionReason());
            }
            return notJudged(unit, ChoiceAlternativeJudgmentStatus.PENDING, pendingReason(mode, session));
        }
        // FAILED, or a resolution the session never gave.
        String serviceReason = session.unavailableReason().orElse(null);
        return notJudged(unit, ChoiceAlternativeJudgmentStatus.FAILED, serviceReason != null
                ? REASON_CONSULTATION_FAILED + serviceReason
                : REASON_UNUSABLE_OUTPUT);
    }

    /**
     * Why an exercise stayed pending: outside the declared set, after a service failure (the cause
     * and how to solve it, F-JEXAM-R011), the exam brake of a course run (F-JEXAM-R003) or simply
     * the budget (F-JEXAM-R010).
     */
    private String pendingReason(EvaluationRequestMode mode, EvaluationSession session) {
        if (mode == EvaluationRequestMode.REUSE_ONLY) {
            return REASON_OUTSIDE_SET;
        }
        String serviceReason = session.unavailableReason().orElse(null);
        if (serviceReason != null) {
            return REASON_SERVICE_STOPPED + serviceReason;
        }
        JudgeExamStanding standing = opened.getStanding();
        EvaluationRunPolicy policy = opened.getEffectivePolicy();
        boolean courseRun = policy == null || policy.getPurpose() != EvaluationRunPurpose.EXAM;
        if (courseRun && standing != null && !standing.isConsultsOnCourse() && standing.getReason() != null) {
            return standing.getReason();
        }
        return REASON_NO_BUDGET;
    }

    private String noVersionReason() {
        JudgeExamStanding standing = opened.getStanding();
        return standing != null && standing.getReason() != null && !standing.getReason().isBlank()
                ? standing.getReason()
                : REASON_NO_VERSION;
    }

    private void record(AuditNode unit, ChoiceAlternativeJudgment judgment) {
        judgments.put(unit, judgment);
        if (judgment.getStatus() == ChoiceAlternativeJudgmentStatus.JUDGED) {
            evaluated++;
            if (judgment.getEvaluatorVersion() != null) {
                // One evaluator: the version of the verdict is the version of the judge.
                verdictsByVersion.merge(judgment.getEvaluatorVersion(), 1, Integer::sum);
            }
        } else {
            notEvaluated++;
        }
    }

    private static ChoiceAlternativeJudgment notJudged(AuditNode unit, ChoiceAlternativeJudgmentStatus status,
            String reason) {
        AuditableQuiz quiz = quizOf(unit);
        return new ChoiceAlternativeJudgment(quiz != null ? quiz.getId() : null, status, null, List.of(), List.of(),
                null, null, false, reason);
    }

