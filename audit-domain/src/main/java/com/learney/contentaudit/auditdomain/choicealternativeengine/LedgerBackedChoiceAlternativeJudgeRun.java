/**
 * One run of the judge «otra opción también vale» inside the multiple choice analyzer, in two
 * times, so its consultations go several at a time (F-JEXAM-R006):
 *
 * <ol>
 *   <li>{@link #request} in the analyzer's {@code onQuiz}: it only takes note of each multiple
 *       choice exercise. Anything else -- a CLOZE, a node that is not an exercise -- is ignored:
 *       neither judged nor counted (F-MCVALE-R001). An exercise asked twice counts once.</li>
 *   <li>{@link #resolveAll} in the analyzer's {@code onCourseComplete}: the common runtime plans
 *       what each exercise asks (the declared set, the area, or in an exam only the exercises of the
 *       file), each one is turned into what the judge reads and the session resolves them all
 *       together, reusing by the fingerprint without budget, consulting within the run's budget and
 *       stopping after a service failure (F-MCVALE-R005).</li>
 *   <li>{@link #judgmentOf} gives each requested exercise its judgment, always the same however many
 *       times it is asked; {@link #coverage} gives the common coverage of the judge.</li>
 * </ol>
 *
 * The judgment of an exercise is {@code JUDGED} (reused or evaluated: verdict, findings and score),
 * {@code PENDING} (the budget did not reach it, the exam brake, outside the declared set or after a
 * service failure), {@code FAILED} (the judge failed or answered something unusable, or its verdict
 * could not be read: never recorded, consulted again in a later run) or {@code NOT_AVAILABLE} (the
 * judge states no version). The last three carry their reason and neither score nor findings: the
 * analyzer declares the exercise evaluated halfway (F-RONDA1-R006). No exercise ever throws.
 *
 * <p>The name every session is opened with is the host analyzer's (multiple-choice-validity), so
 * the budget, the exam brake and the exam are that analyzer's (F-MCVALE-R004).
 */
