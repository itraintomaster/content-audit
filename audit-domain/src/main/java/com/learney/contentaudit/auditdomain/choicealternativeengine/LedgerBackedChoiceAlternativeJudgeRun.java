    /** The multiple choice exercise of a node, or null when the node is anything else. */
    private static AuditableQuiz quizOf(AuditNode node) {
        if (node != null && node.getEntity() instanceof AuditableQuiz quiz && quiz.getMultipleChoice() != null) {
            return quiz;
        }
        return null;
    }

    /** The judge has a single evaluator; without it there is no session and nothing to consult. */
    private static EvaluationSession sessionOf(JudgeSessions opened) {
        List<EvaluationSession> sessions = opened.getSessions();
        return sessions != null && !sessions.isEmpty() ? sessions.get(0) : null;
    }

    private static int maxConcurrent(EvaluationRunPolicy policy) {
        Integer value = policy != null ? policy.getMaxConcurrentEvaluations() : null;
        return value != null ? Math.max(1, value) : 1;
    }

    private static String messageOf(RuntimeException e) {
        return e.getMessage() != null && !e.getMessage().isBlank() ? e.getMessage() : e.getClass().getSimpleName();
    }
