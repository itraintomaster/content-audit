    /**
     * Resolves every exercise requested and not resolved yet, all together within the run's
     * budget and with the run's consultations at a time. Calling it again resolves only what was
     * requested since: nothing is consulted twice.
     */
    @Override
    public void resolveAll() {
        everResolved = true;
        EvaluationRunPolicy policy = opened.getEffectivePolicy();
        JudgeRequestPlan plan = runtime.plan(new ArrayList<>(requested), policy);
        unmatchedDeclaredIds = plan.getUnmatchedDeclaredIds() != null
                ? new ArrayList<>(plan.getUnmatchedDeclaredIds())
                : null;

        List<AuditNode> units = new ArrayList<>();
        List<EvaluationRequestMode> modes = new ArrayList<>();
        List<AuditNode> plannedUnits = plan.getUnits() != null ? plan.getUnits() : List.of();
        for (int i = 0; i < plannedUnits.size(); i++) {
            AuditNode unit = plannedUnits.get(i);
            if (unit == null || judgments.containsKey(unit) || quizOf(unit) == null) {
                continue;
            }
            units.add(unit);
            modes.add(plan.getModes() != null && i < plan.getModes().size() && plan.getModes().get(i) != null
                    ? plan.getModes().get(i)
                    : EvaluationRequestMode.REUSE_OR_EVALUATE);
        }
        // Whatever the plan left out (in an exam, the exercises outside the file) is neither asked
        // nor counted, and is never planned again.
        settled.addAll(requested);
        if (units.isEmpty()) {
            return;
        }
        reached += units.size();

        EvaluationSession session = sessionOf(opened);
        if (session == null) {
            for (AuditNode unit : units) {
                record(unit, notJudged(unit, ChoiceAlternativeJudgmentStatus.NOT_AVAILABLE, noVersionReason()));
            }
            return;
        }

        // What the judge reads of each exercise; one that cannot be built fails alone.
        List<AuditNode> asked = new ArrayList<>();
        List<EvaluationRequest> requests = new ArrayList<>();
        for (int i = 0; i < units.size(); i++) {
            AuditNode unit = units.get(i);
            try {
                EvaluationSubject subject = subjectBuilder.build(unit);
                asked.add(unit);
                requests.add(new EvaluationRequest(subject, modes.get(i)));
            } catch (RuntimeException e) {
                record(unit, notJudged(unit, ChoiceAlternativeJudgmentStatus.FAILED, REASON_NOT_BUILT + messageOf(e)));
            }
        }
        if (requests.isEmpty()) {
            return;
        }

        List<EvaluationResolution> resolutions;
        try {
            resolutions = session.resolveAll(requests, maxConcurrent(policy));
        } catch (RuntimeException e) {
            // Never an exception for an exercise: the whole batch stays failed, to be consulted
            // again in a later run.
            for (AuditNode unit : asked) {
                record(unit, notJudged(unit, ChoiceAlternativeJudgmentStatus.FAILED,
                        REASON_CONSULTATION_FAILED + messageOf(e)));
            }
            return;
        }

        for (int i = 0; i < asked.size(); i++) {
            AuditNode unit = asked.get(i);
            EvaluationResolution resolution = resolutions != null && i < resolutions.size() ? resolutions.get(i) : null;
            record(unit, judge(unit, requests.get(i).getMode(), resolution, session));
        }
    }

