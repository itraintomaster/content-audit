    private static Map<String, List<MiniTheoryAssessment>> assessmentsByQuizId(List<MiniTheoryAssessment> assessments) {
        Map<String, List<MiniTheoryAssessment>> byQuizId = new LinkedHashMap<>();
        for (MiniTheoryAssessment assessment : assessments) {
            if (assessment == null || assessment.getQuizId() == null || assessment.getQuizId().isBlank()) {
                throw new IllegalArgumentException("El veredicto trae una evaluación sin quizId");
            }
            byQuizId.computeIfAbsent(assessment.getQuizId(), id -> new ArrayList<>()).add(assessment);
        }
        for (Map.Entry<String, List<MiniTheoryAssessment>> entry : byQuizId.entrySet()) {
            List<MiniTheoryAssessment> ofQuiz = entry.getValue();
            if (ofQuiz.size() == 1) {
                continue;
            }
            Set<MiniTheoryProblem> problems = EnumSet.noneOf(MiniTheoryProblem.class);
            for (MiniTheoryAssessment assessment : ofQuiz) {
                MiniTheoryProblem problem = problemOf(assessment);
                if (problem == null) {
                    throw new IllegalArgumentException("El veredicto da por buena la miniteoría del quizId "
                            + entry.getKey() + " y además le marca problemas");
                }
                if (!problems.add(problem)) {
                    throw new IllegalArgumentException("El veredicto repite el problema " + problem
                            + " en el quizId " + entry.getKey());
                }
            }
        }
        return byQuizId;
    }

    /** The worst first: the order of the judge's criteria, which already goes from the worst to the mildest. */
