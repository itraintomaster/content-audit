    /**
     * The problem of an assessment: the one it names; a rule that does not hold without naming one
     * is a false rule; one that holds without a problem reproaches nothing.
     */
    static MiniTheoryProblem problemOf(MiniTheoryAssessment assessment) {
        if (assessment == null) {
            return null;
        }
        if (assessment.getProblem() != null) {
            return assessment.getProblem();
        }
        return assessment.isHolds() ? null : MiniTheoryProblem.FALSE_RULE;
    }

    private static Set<Integer> targets(MiniTheoryProblem problem, MiniTheoryErrorScope scope,
            List<Integer> shown, List<Integer> named, int size) {
        Set<Integer> targets = new LinkedHashSet<>();
        if (problem == MiniTheoryProblem.FALSE_RULE || problem == MiniTheoryProblem.OVERSTATED) {
            if (scope == MiniTheoryErrorScope.WHOLE_TOPIC) {
                for (int e = 1; e <= size; e++) {
                    targets.add(e);
                }
            } else {
                targets.addAll(shown);
            }
        } else {
            // F-MINIT-R003: the exercise that contradicts it, or falls outside it, counts only there.
            targets.addAll(named);
        }
        return targets;
    }

    /** The exercises the verdict names (E1 is 1), without repeats, in its order; all of the topic. */
    private static List<Integer> namedExercises(MiniTheoryAssessment assessment, int size) {
        Set<Integer> named = new LinkedHashSet<>();
        if (assessment.getExercises() != null) {
            for (Integer e : assessment.getExercises()) {
                if (e == null || e < 1 || e > size) {
                    throw new IllegalArgumentException("El veredicto nombra el ejercicio E" + e + " y el tema tiene "
                            + size);
                }
                named.add(e);
            }
        }
        return new ArrayList<>(named);
    }

    /** F-MINIT-R004: high if false or contradicted, medium if overstated, low if it does not cover. */
    static FindingSeverity severityOf(MiniTheoryProblem problem) {
        return switch (problem) {
            case FALSE_RULE, CONTRADICTED_BY_EXERCISE -> FindingSeverity.HIGH;
            case OVERSTATED -> FindingSeverity.MEDIUM;
            case NOT_COVERING_EXERCISE -> FindingSeverity.LOW;
        };
    }

    static String ruleOf(MiniTheoryProblem problem) {
        return switch (problem) {
            case FALSE_RULE -> RULE_FALSE;
            case OVERSTATED -> RULE_OVERSTATED;
            case CONTRADICTED_BY_EXERCISE -> RULE_CONTRADICTING;
            case NOT_COVERING_EXERCISE -> RULE_UNCOVERED;
        };
    }

    private static FindingSeverity gravest(List<FindingDraft> drafts) {
        FindingSeverity gravest = null;
        for (FindingDraft draft : drafts) {
            FindingSeverity severity = draft.getSeverity();
            if (severity != null && (gravest == null || severity.ordinal() < gravest.ordinal())) {
                gravest = severity;
            }
        }
        return gravest;
    }

