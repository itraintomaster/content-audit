    static MiniTheoryProblem problemOf(MiniTheoryAssessment assessment) {
        if (assessment == null) {
            throw new IllegalArgumentException("El veredicto trae una evaluación vacía");
        }
        if (assessment.isHolds()) {
            if (assessment.getProblem() != null) {
                throw new IllegalArgumentException("Una miniteoría aprobada no puede traer problema");
            }
            return null;
        }
        if (assessment.getProblem() == null) {
            throw new IllegalArgumentException("Una miniteoría reprobada debe clasificar su problema");
        }
        return assessment.getProblem();
    }

