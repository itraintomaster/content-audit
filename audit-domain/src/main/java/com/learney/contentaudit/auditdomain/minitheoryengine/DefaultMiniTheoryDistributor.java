/**
 * F-MINIT-R003/R004: the verdict of a topic, spread over its exercises -- the score, the findings
 * and the diagnosis of mini-theory live in each exercise, never in the topic.
 *
 * <p>It numbers the topic exactly as {@link DefaultMiniTheorySubjectBuilder} does (the M and E
 * numbers of the verdict are the ones of the content the judge read). For each assessment with a
 * problem:
 * <ul>
 *   <li>a false rule ({@code false-rule}, high) or an overstated one ({@code overstated-rule},
 *       medium) counts in the exercises that show it with {@link MiniTheoryErrorScope#SHOWN_ONLY},
 *       and in every exercise of the topic with {@link MiniTheoryErrorScope#WHOLE_TOPIC};</li>
 *   <li>an exercise that contradicts it ({@code contradicting-exercise}, high) or falls outside it
 *       ({@code uncovered-exercise}, low) counts only in the exercises the verdict names, whatever
 *       the scope.</li>
 * </ul>
 * A verdict that reproaches a mini theory or an exercise the topic does not have, or a
 * contradiction without the exercise that contradicts, does not belong to the content that was
 * judged: it is rejected, and the analyzer leaves the topic unevaluated instead of guessing.
 * The severity comes from the problem, never from the model, and is never blocking. Every finding
 * goes to the panel and is marked with the text of its mini theory, so the panel resolves together,
 * with one rewrite, every exercise of the same mini theory (F-MINIT-R007). An exercise scores 1
 * without finding and, otherwise, what the configuration gives for its gravest one.
 */
