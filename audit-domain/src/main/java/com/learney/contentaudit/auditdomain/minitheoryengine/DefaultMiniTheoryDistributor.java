    private FindingDraft draft(MiniTheoryProblem problem, String text, MiniTheoryAssessment assessment,
            int exercise, List<Integer> shown, List<Integer> named, List<AuditNode> exercises, SentenceMode mode) {
        List<EvidencePart> examined = new ArrayList<>();
        examined.add(new EvidencePart("Miniteoría", text));
        if (!isBlank(assessment.getCounterexample())) {
            examined.add(new EvidencePart("Contraejemplo", assessment.getCounterexample()));
        }
        if (!isBlank(assessment.getExplanation())) {
            examined.add(new EvidencePart(explanationLabel(problem), assessment.getExplanation()));
        }
        examined.add(new EvidencePart("Ejercicio E" + exercise, asSeen(exercises.get(exercise - 1), mode)));

        List<FindingNodeRef> related = new ArrayList<>();
        for (int other : named) {
            if (other == exercise) {
                continue;
            }
            AuditNode node = exercises.get(other - 1);
            examined.add(new EvidencePart("Ejercicio E" + other, asSeen(node, mode)));
            related.add(refOf(node));
        }

        String observation = observation(problem, shown.contains(exercise), shown, assessment);
        return new FindingDraft(ruleOf(problem), text, severityOf(problem), FindingResolution.PANEL,
                new FindingEvidence(examined, observation, related));
    }

    /**
     * Two assessments of the same mini theory with the same problem on the same exercise are one
     * finding (its identity is analyzer, rule, exercise and text): what the second adds joins the
     * evidence of the first.
     */
    private static void merge(Map<String, FindingDraft> byIdentity, FindingDraft draft) {
        String key = draft.getRule() + "|" + draft.getMarker();
        FindingDraft first = byIdentity.get(key);
        if (first == null) {
            byIdentity.put(key, draft);
            return;
        }
        List<EvidencePart> examined = new ArrayList<>(first.getEvidence().getExamined());
        for (EvidencePart part : draft.getEvidence().getExamined()) {
            if (!containsPart(examined, part)) {
                examined.add(part);
            }
        }
        List<FindingNodeRef> related = new ArrayList<>(first.getEvidence().getRelatedNodes());
        for (FindingNodeRef ref : draft.getEvidence().getRelatedNodes()) {
            if (!related.contains(ref)) {
                related.add(ref);
            }
        }
        String observation = first.getEvidence().getObservation();
        if (!observation.equals(draft.getEvidence().getObservation())) {
            observation = observation + " · " + draft.getEvidence().getObservation();
        }
        byIdentity.put(key, new FindingDraft(first.getRule(), first.getMarker(), first.getSeverity(),
                first.getResolution(), new FindingEvidence(examined, observation, related)));
    }

    private static boolean containsPart(List<EvidencePart> parts, EvidencePart part) {
        for (EvidencePart existing : parts) {
            if (existing.getLabel().equals(part.getLabel()) && existing.getText().equals(part.getText())) {
                return true;
            }
        }
        return false;
    }

    /** One line, in Spanish, that names the problem with the words of the exercise. */
    private static String observation(MiniTheoryProblem problem, boolean showsIt, List<Integer> shown,
            MiniTheoryAssessment assessment) {
        String whose = showsIt
                ? "La miniteoría que muestra este ejercicio"
                : "Una miniteoría del tema (la muestran " + DefaultMiniTheorySubjectBuilder.exerciseNumbers(shown) + ")";
        String line = switch (problem) {
            case FALSE_RULE -> whose + " afirma como regla del inglés algo falso";
            case OVERSTATED -> whose + " exagera: dice «siempre» o «nunca» donde hay excepciones comunes";
            case CONTRADICTED_BY_EXERCISE -> showsIt
                    ? "Este ejercicio contradice la miniteoría que muestra"
                    : "Este ejercicio contradice una miniteoría del tema (la muestran "
                            + DefaultMiniTheorySubjectBuilder.exerciseNumbers(shown) + ")";
            case NOT_COVERING_EXERCISE -> whose + " es cierta, pero no cubre el caso de este ejercicio";
        };
        if (!isBlank(assessment.getExplanation())) {
            line = line + ": " + assessment.getExplanation().strip();
        }
        if (!isBlank(assessment.getCounterexample())) {
            line = line + " (contraejemplo: «" + assessment.getCounterexample().strip() + "»)";
        }
        return line;
    }

    private static String explanationLabel(MiniTheoryProblem problem) {
        return switch (problem) {
            case FALSE_RULE -> "Lo que tiene de falso";
            case OVERSTATED -> "Lo que exagera";
            case CONTRADICTED_BY_EXERCISE -> "Cómo la contradice";
            case NOT_COVERING_EXERCISE -> "Lo que no cubre";
        };
    }

    /**
     * The exercise as the student reads it once answered (F-CIERRE-R003): its finished sentence from
     * the student view, without the hint, and, in a multiple choice, its options in the student's
     * order with the correct one marked -- never the internal format of the course.
     */
    private String asSeen(AuditNode exercise, SentenceMode mode) {
        AuditableQuiz quiz = (AuditableQuiz) exercise.getEntity();
        String sentence = studentViewRenderer.finishedSentence(quiz, mode);
        if (isBlank(sentence)) {
            sentence = !isBlank(quiz.getLabel()) ? quiz.getLabel() : String.valueOf(quiz.getId());
        }
        if (quiz.getMultipleChoice() == null) {
            return sentence.strip();
        }
        QuizStudentView view = studentViewRenderer.render(quiz);
        List<String> options = new ArrayList<>();
        if (view != null && view.getOptions() != null) {
            for (StudentOptionView option : view.getOptions()) {
                if (option == null) {
                    continue;
                }
                options.add((option.getLabel() != null ? option.getLabel() : "")
                        + (option.isCorrect() ? " (correcta)" : ""));
            }
        }
        return options.isEmpty()
                ? sentence.strip()
                : sentence.strip() + " (opciones: " + String.join(", ", options) + ")";
    }

    /** How the course finishes the exercises of the topic; a fill-in when the topic does not say. */
    private static SentenceMode sentenceModeOf(AuditNode knowledgeNode) {
        if (knowledgeNode != null && knowledgeNode.getEntity() instanceof AuditableKnowledge knowledge
                && knowledge.getSentenceMode() != null) {
            return knowledge.getSentenceMode();
        }
        return SentenceMode.FILL;
    }

    private static FindingNodeRef refOf(AuditNode exercise) {
        String id = exercise.getEntity().getId();
        String label = exercise.getEntity().getLabel();
        return new FindingNodeRef(AuditTarget.QUIZ, id, label != null ? label : id);
    }

    private static boolean isBlank(String value) {
        return value == null || value.isBlank();
    }
