/**
 * F-RESPC-R007: no instructions and no mini theory ask for a form (José, 30/9: «No quiero más
 * ejercicios cuyas instrucciones pidan "short-form" o "long-form". Que acepte siempre ambas.»).
 *
 * <p>A request is a sentence of the instructions the student sees, or of the mini theory of the
 * exercise, that tells to use or avoid the contracted or the long form: an instruction verb
 * (usa, escribe, utiliza, evita, sin…) and a form («$short forms$», «formas cortas», «sin
 * contracciones», «$long forms$»). «Escribe la respuesta corta» asks for no form, and a mini
 * theory that only names one («arranca con el auxiliar en $short form$») does not ask
 * (DOUBT-RESPC-DESCRIBE, option A).
 *
 * <p>The standard sentence that opens the instructions since #1152 («Usa $short forms$ si es
 * posible.», «Usa $long forms$.») is removed by a rule; any other request is the lesson itself,
 * as in Contracciones, and goes to the panel (DOUBT-RESPC-CONTRACCIONES, option A).
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
class DefaultFormRequestDetector implements FormRequestDetector {

    /** The standard sentences of be/scripts/unificar-short-forms.py (#1152). */
    private static final List<String> STANDARD = List.of("usa $short forms$ si es posible.", "usa $long forms$.");

    private static final Pattern SHORT = Pattern.compile(
            "short[- ]?forms?|formas? cortas?|contracciones?(?! de)|contraíd[ao]s?", Pattern.CASE_INSENSITIVE);

    private static final Pattern LONG = Pattern.compile(
            "long[- ]?forms?|formas? largas?|sin contracci|sin \\$?short", Pattern.CASE_INSENSITIVE);

    private static final Pattern REQUEST_VERB = Pattern.compile(
            "\\b(usa|usá|use|utiliza|utilizá|emplea|escribe|escribí|completa|completá|evita|evitá|sin)\\b",
            Pattern.CASE_INSENSITIVE | Pattern.UNICODE_CASE);

    /** A sentence: up to a final mark followed by a space or the end. */
    private static final Pattern SENTENCE = Pattern.compile("[^.!?]+(?:[.!?]+(?=\\s|$)|$)");

    @Override
    public List<FormRequest> detect(String instructions, String miniTheory) {
        List<FormRequest> requests = new ArrayList<>();
        requests.addAll(requestsIn(instructions, FormRequestSource.INSTRUCTIONS));
        requests.addAll(requestsIn(miniTheory, FormRequestSource.MINI_THEORY));
        return requests;
    }

    private static List<FormRequest> requestsIn(String text, FormRequestSource source) {
        List<FormRequest> requests = new ArrayList<>();
        if (text == null || text.isBlank()) {
            return requests;
        }
        java.util.regex.Matcher m = SENTENCE.matcher(text.strip());
        while (m.find()) {
            String sentence = m.group().strip();
            if (sentence.isEmpty()) {
                continue;
            }
            boolean asksLong = LONG.matcher(sentence).find();
            boolean asksShort = !asksLong && SHORT.matcher(sentence).find();
            if (!(asksLong || asksShort) || !REQUEST_VERB.matcher(sentence).find()) {
                continue;
            }
            boolean removable = source == FormRequestSource.INSTRUCTIONS
                    && STANDARD.contains(sentence.toLowerCase(Locale.ROOT));
            requests.add(new FormRequest(source, asksLong ? RequestedForm.LONG : RequestedForm.SHORT, sentence,
                    removable));
        }
        return requests;
    }
}
