    @Override
    public JudgeRequestPlan plan(List<AuditNode> units, EvaluationRunPolicy policy) {
        List<AuditNode> planned = new ArrayList<>();
        List<EvaluationRequestMode> modes = new ArrayList<>();
        Set<String> declared = policy != null ? policy.getReevaluationSubjectIds() : null;
        EvaluationRunPurpose purpose = purposeOf(policy);
        Set<String> matched = new HashSet<>();

        for (AuditNode unit : units != null ? units : List.<AuditNode>of()) {
            if (unit == null) {
                continue;
            }
            Set<String> hits = declared != null ? declaredIdsOf(unit, declared) : Set.of();
            matched.addAll(hits);
            if (purpose == EvaluationRunPurpose.EXAM) {
                // F-JEXAM-R001: an exam asks only the units of its file; any other unit of the
                // photo is neither asked nor counted.
                if (!hits.isEmpty()) {
                    planned.add(unit);
                    modes.add(EvaluationRequestMode.REUSE_OR_EVALUATE);
                }
                continue;
            }
            planned.add(unit);
            if (purpose == EvaluationRunPurpose.READING) {
                modes.add(EvaluationRequestMode.REUSE_ONLY);
                continue;
            }
            if (declared != null) {
                // F-QINST-R018, for every judge: the declared set is consulted again, the rest only
                // reuses whatever it has.
                modes.add(hits.isEmpty() ? EvaluationRequestMode.REUSE_ONLY
                        : purpose == EvaluationRunPurpose.REANALYSIS ? EvaluationRequestMode.FORCE : EvaluationRequestMode.PREFER_NEW);
            } else if (policy != null && policy.isReevaluate() && inScope(unit, policy.getReevaluationScope())) {
                // F-QINST-R012: an explicit re-evaluation by area (or of the whole course).
                modes.add(EvaluationRequestMode.FORCE);
            } else {
                modes.add(EvaluationRequestMode.REUSE_OR_EVALUATE);
            }
        }

        List<String> unmatched = null;
        if (declared != null) {
            unmatched = new ArrayList<>();
            for (String id : declared) {
                if (id != null && !matched.contains(id)) {
                    unmatched.add(id);
                }
            }
            Collections.sort(unmatched);
        }
        return new JudgeRequestPlan(planned, modes, unmatched);
    }

