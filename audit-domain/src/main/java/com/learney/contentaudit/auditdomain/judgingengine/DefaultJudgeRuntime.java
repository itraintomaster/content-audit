    @Override
    public JudgeSessions open(String judgeName, List<Evaluator> evaluators,
            EvaluationRunPolicy policy) {
        // F-JEXAM-R005 / F-QINST-R018 inv. 3: a request that cannot be interpreted is rejected
        // before anything is opened, for every judge.
        rejectUninterpretableSet(judgeName, policy);

        List<Evaluator> judges = evaluators != null ? evaluators : List.of();
        List<String> evaluatorIds = new ArrayList<>();
        for (Evaluator evaluator : judges) {
            evaluatorIds.add(evaluator.evaluatorId());
        }
        String judgeVersion = composeVersion(judges);

        EvaluationRunPurpose purpose = purposeOf(policy);
        int maxConcurrent = policy != null && policy.getMaxConcurrentEvaluations() != null
                ? Math.max(1, policy.getMaxConcurrentEvaluations())
                : Math.max(1, config.getMaxConcurrentEvaluations());
        // F-JEXAM-R010: a run that asks no budget for this judge gets the default, which is 0.
        int requested = policy != null
                ? policy.getMaxNewEvaluations()
                : config.getDefaultMaxNewEvaluations(judgeName);

        JudgeExamStanding standing = standing(judgeName, judgeVersion);
        int effective = Math.max(0, requested);
        if (judgeVersion == null) {
            // No version: nothing to consult with, on the course or in an exam.
            effective = 0;
        } else if (purpose == EvaluationRunPurpose.COURSE && !standing.isConsultsOnCourse()) {
            // F-JEXAM-R003: without an approved exam, no consultation on the course.
            effective = 0;
        }

        EvaluationSessionFactory factory = purpose == EvaluationRunPurpose.EXAM ? examSessions : courseSessions;
        List<EvaluationSession> sessions = new ArrayList<>();
        for (Evaluator evaluator : judges) {
            sessions.add(factory.open(new EvaluationBudget(effective), evaluator));
        }

        EvaluationRunPolicy effectivePolicy = new EvaluationRunPolicy(effective,
                policy != null && policy.isReevaluate(),
                policy != null ? policy.getReevaluationScope() : null,
                policy != null ? policy.getReevaluationSubjectIds() : null,
                purpose, maxConcurrent);
        return new JudgeSessions(judgeName, judgeVersion, evaluatorIds, sessions, standing, effectivePolicy);
    }

    @Override
    public JudgeRequestPlan plan(List<AuditNode> units, EvaluationRunPolicy policy) {
        List<AuditNode> planned = new ArrayList<>();
        List<EvaluationRequestMode> modes = new ArrayList<>();
        Set<String> declared = policy != null ? policy.getReevaluationSubjectIds() : null;
        EvaluationRunPurpose purpose = purposeOf(policy);
        Set<String> matched = new HashSet<>();

        for (AuditNode unit : units != null ? units : List.<AuditNode>of()) {
            if (unit == null) {
                continue;
            }
            Set<String> hits = declared != null ? declaredIdsOf(unit, declared) : Set.of();
            matched.addAll(hits);
            if (purpose == EvaluationRunPurpose.EXAM) {
                // F-JEXAM-R001: an exam asks only the units of its file; any other unit of the
                // photo is neither asked nor counted.
                if (!hits.isEmpty()) {
                    planned.add(unit);
                    modes.add(EvaluationRequestMode.REUSE_OR_EVALUATE);
                }
                continue;
            }
            planned.add(unit);
            if (declared != null) {
                // F-QINST-R018, for every judge: the declared set is consulted again, the rest only
                // reuses whatever it has.
                modes.add(hits.isEmpty() ? EvaluationRequestMode.REUSE_ONLY : EvaluationRequestMode.PREFER_NEW);
            } else if (policy != null && policy.isReevaluate() && inScope(unit, policy.getReevaluationScope())) {
                // F-QINST-R012: an explicit re-evaluation by area (or of the whole course).
                modes.add(EvaluationRequestMode.FORCE);
            } else {
                modes.add(EvaluationRequestMode.REUSE_OR_EVALUATE);
            }
        }

        List<String> unmatched = null;
        if (declared != null) {
            unmatched = new ArrayList<>();
            for (String id : declared) {
                if (id != null && !matched.contains(id)) {
                    unmatched.add(id);
                }
            }
            Collections.sort(unmatched);
        }
        return new JudgeRequestPlan(planned, modes, unmatched);
    }

    @Override
    public JudgeCoverageDiagnosis coverage(JudgeSessions opened, JudgeUnitTally tally) {
        List<EvaluationSession> sessions = opened.getSessions() != null ? opened.getSessions() : List.of();
        List<String> evaluatorIds = opened.getEvaluatorIds() != null ? opened.getEvaluatorIds() : List.of();

        List<EvaluatorCoverage> evaluators = new ArrayList<>();
        int pendingConsultations = 0;
        String unavailableReason = null;
        for (int i = 0; i < sessions.size(); i++) {
            EvaluationSession session = sessions.get(i);
            EvaluationCoverage coverage = session.coverage();
            String evaluatorId = i < evaluatorIds.size() ? evaluatorIds.get(i) : null;
            evaluators.add(new EvaluatorCoverage(evaluatorId, coverage,
                    session.consultedEvaluatorVersion().orElse(null)));
            if (coverage != null) {
                pendingConsultations += coverage.getPending() + coverage.getFailed();
            }
            if (unavailableReason == null) {
                unavailableReason = session.unavailableReason().orElse(null);
            }
        }

        List<JudgeVersionStanding> versions = new ArrayList<>();
        Map<String, Integer> byVersion = tally.getVerdictsByVersion() != null
                ? withoutNullKeys(tally.getVerdictsByVersion())
                : Map.of();
        for (Map.Entry<String, Integer> entry : byVersion.entrySet()) {
            JudgeExamStatus status = standing(opened.getJudgeName(), entry.getKey()).getStatus();
            versions.add(new JudgeVersionStanding(entry.getKey(), entry.getValue() != null ? entry.getValue() : 0,
                    status));
        }

        EvaluationRunPolicy effective = opened.getEffectivePolicy();
        int maxConcurrent = effective != null && effective.getMaxConcurrentEvaluations() != null
                ? Math.max(1, effective.getMaxConcurrentEvaluations())
                : Math.max(1, config.getMaxConcurrentEvaluations());
        JudgeCostEstimate cost = cost(opened.getJudgeName(), evaluatorIds, tally.getNotEvaluated(),
                pendingConsultations, maxConcurrent);

        return new JudgeCoverageDiagnosis(opened.getJudgeName(), tally.getUnit(), tally.getReached(),
                tally.getEvaluated(), tally.getNotEvaluated(), evaluators, opened.getStanding(), versions,
                unavailableReason, cost,
                tally.getUnmatchedDeclaredIds() != null ? new ArrayList<>(tally.getUnmatchedDeclaredIds()) : null);
    }

    /**
     * F-JEXAM-R001 / R003: the standing of a version is its last exam record. Only an approved
     * version consults on the course; the reason says, in Spanish, why the others do not.
     */
    @Override
    public JudgeExamStanding standing(String judgeName, String judgeVersion) {
        if (judgeVersion == null) {
            return new JudgeExamStanding(judgeName, null, JudgeExamStatus.NO_VERSION, false, REASON_NO_VERSION);
        }
        Optional<JudgeExamRecord> latest = examRegistry.latest(judgeName, judgeVersion);
        if (latest == null || latest.isEmpty() || latest.get().getStatus() == null) {
            return new JudgeExamStanding(judgeName, judgeVersion, JudgeExamStatus.NOT_TAKEN, false, REASON_NOT_TAKEN);
        }
        return switch (latest.get().getStatus()) {
            case APPROVED -> new JudgeExamStanding(judgeName, judgeVersion, JudgeExamStatus.APPROVED, true, null);
            case FAILED -> new JudgeExamStanding(judgeName, judgeVersion, JudgeExamStatus.FAILED, false, REASON_FAILED);
            case TAKEN -> new JudgeExamStanding(judgeName, judgeVersion, JudgeExamStatus.TAKEN, false, REASON_TAKEN);
            default -> new JudgeExamStanding(judgeName, judgeVersion, JudgeExamStatus.NOT_TAKEN, false,
                    REASON_NOT_TAKEN);
        };
    }

