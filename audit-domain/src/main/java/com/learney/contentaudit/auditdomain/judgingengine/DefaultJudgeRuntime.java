    private static void rejectUninterpretableSet(String judgeName, EvaluationRunPolicy policy) {
        if (policy == null || policy.getReevaluationSubjectIds() == null) {
            return;
        }
        if (purposeOf(policy) == EvaluationRunPurpose.EXAM) {
            // The exam's file is its set; an empty file is simply an exam with nothing to judge.
            return;
        }
        if (policy.isReevaluate()) {
            // A declared set and a re-evaluation by area (or of the whole course) at once:
            // choosing one would be guessing with the user's money.
            String declaredScope = policy.getReevaluationScope() != null
                    ? policy.getReevaluationScope()
                    : "todo el curso";
            throw new AmbiguousReevaluationScopeException(judgeName, declaredScope);
        }
        if (policy.getReevaluationSubjectIds().isEmpty()) {
            // An empty declared set is never read as "the whole course".
            throw new EmptyReevaluationSetException(judgeName);
        }
    }

    private static EvaluationRunPurpose purposeOf(EvaluationRunPolicy policy) {
        return policy != null && policy.getPurpose() != null ? policy.getPurpose() : EvaluationRunPurpose.COURSE;
    }

    /** The version of each evaluator, in order, joined by «+»; null when any states none. */
    private static String composeVersion(List<Evaluator> evaluators) {
        if (evaluators.isEmpty()) {
            return null;
        }
        List<String> versions = new ArrayList<>();
        for (Evaluator evaluator : evaluators) {
            Optional<String> version = evaluator.evaluatorVersion();
            if (version == null || version.isEmpty() || version.get().isBlank()) {
                return null;
            }
            versions.add(version.get());
        }
        return String.join(VERSION_JOINER, versions);
    }

    /**
     * The declared ids a unit answers to: its own id and, for a topic (mini-theory), the id of
     * each of its exercises.
     */
    private static Set<String> declaredIdsOf(AuditNode unit, Set<String> declared) {
        Set<String> hits = new LinkedHashSet<>();
        String ownId = unit.getEntity() != null ? unit.getEntity().getId() : null;
        if (ownId != null && declared.contains(ownId)) {
            hits.add(ownId);
        }
        if (unit.getTarget() == AuditTarget.KNOWLEDGE && unit.getChildren() != null) {
            for (AuditNode child : unit.getChildren()) {
                String childId = child != null && child.getEntity() != null ? child.getEntity().getId() : null;
                if (childId != null && declared.contains(childId)) {
                    hits.add(childId);
                }
            }
        }
        return hits;
    }

    /** F-QINST-R012: a null scope reaches the whole course; otherwise only that knowledge. */
    private static boolean inScope(AuditNode unit, String scope) {
        if (scope == null) {
            return true;
        }
        AuditNode knowledge = unit.getTarget() == AuditTarget.KNOWLEDGE
                ? unit
                : unit.ancestor(AuditTarget.KNOWLEDGE).orElse(null);
        return knowledge != null && knowledge.getEntity() != null && scope.equals(knowledge.getEntity().getId());
    }

    private static Map<String, Integer> withoutNullKeys(Map<String, Integer> byVersion) {
        Map<String, Integer> result = new TreeMap<>();
        for (Map.Entry<String, Integer> entry : byVersion.entrySet()) {
            if (entry.getKey() != null) {
                result.put(entry.getKey(), entry.getValue());
            }
        }
        return result;
    }

    /**
     * F-JEXAM-R004: what is pending costs one consultation per pending or failed unit of each
     * evaluator (two per exercise in translation-sense), at the measured rate of the judge -- the
     * mean interval between consecutive verdicts of its evaluators within each run, cut at pauses
     * longer than 10 minutes -- or, without history, the configured one; with N at a time the
     * hours divide by N.
     */
    private JudgeCostEstimate cost(String judgeName, List<String> evaluatorIds, int pendingUnits,
            int pendingConsultations, int maxConcurrent) {
        Double measured = measuredRatePerHour(evaluatorIds);
        boolean rateMeasured = measured != null;
        double rate = rateMeasured ? measured : config.getDefaultRatePerHour(judgeName);
        double hoursOneAtATime = rate > 0 ? pendingConsultations / rate : 0.0;
        double hoursConcurrent = hoursOneAtATime / maxConcurrent;
        return new JudgeCostEstimate(pendingUnits, pendingConsultations, rate, rateMeasured, hoursOneAtATime,
                maxConcurrent, hoursConcurrent);
    }

    private Double measuredRatePerHour(List<String> evaluatorIds) {
        if (timeline == null) {
            return null;
        }
        long totalMillis = 0;
        int intervals = 0;
        long pauseMillis = RUN_PAUSE.toMillis();
        for (String evaluatorId : new LinkedHashSet<>(evaluatorIds)) {
            if (evaluatorId == null) {
                continue;
            }
            List<Instant> recorded = timeline.recordedTimes(evaluatorId);
            if (recorded == null || recorded.size() < 2) {
                continue;
            }
            List<Instant> times = new ArrayList<>();
            for (Instant time : recorded) {
                if (time != null) {
                    times.add(time);
                }
            }
            Collections.sort(times);
            for (int i = 1; i < times.size(); i++) {
                long gap = Duration.between(times.get(i - 1), times.get(i)).toMillis();
                if (gap <= pauseMillis) {
                    totalMillis += gap;
                    intervals++;
                }
            }
        }
        if (intervals == 0 || totalMillis <= 0) {
            return null;
        }
        double meanMillis = (double) totalMillis / intervals;
        return 3_600_000.0 / meanMillis;
    }
