    @Override
    public JudgeExamStanding standing(String judgeName, String judgeVersion,
            EvaluationRuntimeIdentity runtimeIdentity, Set<String> compatibleJudgeVersions) {
        EvaluationRuntimeIdentity effectiveRuntime = runtimeIdentity != null
                ? runtimeIdentity
                : EvaluationRuntimeIdentity.legacyUnknown();
        if (judgeVersion == null) {
            return new JudgeExamStanding(judgeName, null, JudgeExamStatus.NO_VERSION, false,
                    REASON_NO_VERSION, effectiveRuntime, acceptedVersions(compatibleJudgeVersions, null));
        }
        Set<String> acceptedVersions = acceptedVersions(compatibleJudgeVersions, judgeVersion);
        Optional<JudgeExamRecord> latest = effectiveRuntime.isExplicit()
                ? examRegistry.latestCompatible(judgeName, acceptedVersions, effectiveRuntime)
                : latestLegacyExam(judgeName, acceptedVersions);
        // Operator acceptance is exact-version and exact-runtime, never inherited through
        // schema aliases. A later measured exam supersedes it; a rehearsal does not revoke it.
        if (promotions != null && effectiveRuntime.isExplicit()) {
            var promoted = promotions.latest(judgeName,judgeVersion,effectiveRuntime);
            if (promoted != null && promoted.isPresent()) {
                var decision=promoted.get();
                var measured=latest==null ? null : latest.orElse(null);
                boolean laterMeasurement=measured!=null
                        && (measured.getStatus()==JudgeExamStatus.APPROVED || measured.getStatus()==JudgeExamStatus.FAILED)
                        && measured.getRecordedAt()!=null && !measured.getRecordedAt().isBefore(decision.promotedAt());
                if (!laterMeasurement)
                    return new JudgeExamStanding(judgeName,judgeVersion,JudgeExamStatus.PROMOTED,true,
                            "Promovido por "+decision.reviewer()+" tras revisión del operador: "+decision.reason()
                                    +(decision.reason().endsWith(".") ? " " : ". ")+"Evidencia: "+decision.evidenceFile(),effectiveRuntime,acceptedVersions);
            }
        }
        if (latest == null || latest.isEmpty() || latest.get().getStatus() == null) {
            return new JudgeExamStanding(judgeName, judgeVersion, JudgeExamStatus.NOT_TAKEN, false,
                    REASON_NOT_TAKEN, effectiveRuntime, acceptedVersions);
        }
        JudgeExamRecord record = latest.get();
        return switch (record.getStatus()) {
            case APPROVED -> new JudgeExamStanding(judgeName, judgeVersion, JudgeExamStatus.APPROVED, true,
                    resultLine(record, "aprobado"), effectiveRuntime, acceptedVersions);
            case FAILED -> {
                String result = resultLine(record, "reprobado");
                yield new JudgeExamStanding(judgeName, judgeVersion, JudgeExamStatus.FAILED, false,
                        result != null ? REASON_FAILED + " (" + result + ")" : REASON_FAILED,
                        effectiveRuntime, acceptedVersions);
            }
            case TAKEN -> new JudgeExamStanding(judgeName, judgeVersion, JudgeExamStatus.TAKEN, false,
                    REASON_TAKEN, effectiveRuntime, acceptedVersions);
            default -> new JudgeExamStanding(judgeName, judgeVersion, JudgeExamStatus.NOT_TAKEN, false,
                    REASON_NOT_TAKEN, effectiveRuntime, acceptedVersions);
        };
    }

    /**
     * Keeps adapters and fakes written before runtime identity source-compatible, but only for an
     * explicitly legacy query. An explicit runtime always uses the scoped registry API above.
     */
    private Optional<JudgeExamRecord> latestLegacyExam(String judgeName, Set<String> acceptedVersions) {
        JudgeExamRecord latest = null;
        for (String version : acceptedVersions) {
            Optional<JudgeExamRecord> candidate = examRegistry.latest(judgeName, version);
            if (candidate == null || candidate.isEmpty()) {
                continue;
            }
            if (latest == null || latest.getRecordedAt() == null
                    || (candidate.get().getRecordedAt() != null
                        && candidate.get().getRecordedAt().isAfter(latest.getRecordedAt()))) {
                latest = candidate.get();
            }
        }
        return Optional.ofNullable(latest);
    }

    /**
     * F-ALDIA-R003: the motors with which this version is enabled, the one of {@code own} first: each
     * motor an exam of the version (or one that is the same) was measured with, or José promoted it
     * with, whose standing consults on the course. Approval stays per motor -- the session still
     * consults only with its own --; this says with which ones the version could, so a version that
     * approved with Gemini is not «sin aprobar» because the course runs with ChatGPT by default.
     */
    private List<JudgeEnablement> enabledWith(String judgeName, String judgeVersion,
            Set<String> compatibleJudgeVersions, JudgeExamStanding own) {
        if (judgeVersion == null) {
            return List.of();
        }
        Set<String> accepted = acceptedVersions(compatibleJudgeVersions, judgeVersion);
        Set<EvaluationRuntimeIdentity> candidates = new LinkedHashSet<>();
        if (own.getRuntimeIdentity().isExplicit()) {
            candidates.add(own.getRuntimeIdentity());
        }
        List<JudgeExamRecord> history = examRegistry != null ? examRegistry.history(judgeName) : null;
        for (JudgeExamRecord record : history != null ? history : List.<JudgeExamRecord>of()) {
            if (record != null && accepted.contains(record.getJudgeVersion())
                    && record.getRuntimeIdentity() != null && record.getRuntimeIdentity().isExplicit()) {
                candidates.add(record.getRuntimeIdentity());
            }
        }
        List<JudgePromotionRecord> promoted = promotions != null ? promotions.history(judgeName) : null;
        for (JudgePromotionRecord promotion : promoted != null ? promoted : List.<JudgePromotionRecord>of()) {
            if (judgeVersion.equals(promotion.judgeVersion())) {
                candidates.add(promotion.runtimeIdentity());
            }
        }
        List<JudgeEnablement> enabled = new ArrayList<>();
        for (EvaluationRuntimeIdentity runtime : candidates) {
            JudgeExamStanding standing = runtime.equals(own.getRuntimeIdentity())
                    ? own
                    : standing(judgeName, judgeVersion, runtime, compatibleJudgeVersions);
            if (standing.isConsultsOnCourse()) {
                enabled.add(new JudgeEnablement(runtime, standing.getStatus(),
                        enabledSince(judgeName, judgeVersion, accepted, runtime, standing.getStatus())));
            }
        }
        return List.copyOf(enabled);
    }

    /** The promotion that enables it, or the last exam with that motor, which approved. */
    private Instant enabledSince(String judgeName, String judgeVersion, Set<String> accepted,
            EvaluationRuntimeIdentity runtime, JudgeExamStatus status) {
        if (status == JudgeExamStatus.PROMOTED && promotions != null) {
            Optional<JudgePromotionRecord> promotion = promotions.latest(judgeName, judgeVersion, runtime);
            return promotion != null ? promotion.map(JudgePromotionRecord::promotedAt).orElse(null) : null;
        }
        Optional<JudgeExamRecord> exam = examRegistry.latestCompatible(judgeName, accepted, runtime);
        return exam != null ? exam.map(JudgeExamRecord::getRecordedAt).orElse(null) : null;
    }

    private static Set<String> acceptedVersions(Set<String> compatibleJudgeVersions,
            String judgeVersion) {
        if (compatibleJudgeVersions != null && !compatibleJudgeVersions.isEmpty()) {
            return Set.copyOf(compatibleJudgeVersions);
        }
        return judgeVersion != null ? Set.of(judgeVersion) : Set.of();
    }

    /**
     * The measured result of an exam in one line: each group as «51 de 186 en la cola del 5 %»,
     * joined by «; », and the verdict with its day, «aprobado el 30/9», in this machine's zone.
     * Null when the record says neither.
     */
    static String resultLine(JudgeExamRecord record, String verdict) {
        List<String> parts = new ArrayList<>();
        if (record.getGroups() != null) {
            List<String> groups = new ArrayList<>();
            for (var group : record.getGroups()) {
                if (group == null || group.getGroup() == null || group.getGroup().isBlank()) {
                    continue;
                }
                groups.add(group.getAsExpected() + " de " + group.getCases() + " en " + group.getGroup().strip());
            }
            if (!groups.isEmpty()) {
                parts.add(String.join("; ", groups));
            }
        }
        if (record.getRecordedAt() != null) {
            java.time.LocalDate day = record.getRecordedAt().atZone(java.time.ZoneId.systemDefault()).toLocalDate();
            parts.add(verdict + " el " + day.getDayOfMonth() + "/" + day.getMonthValue());
        }
        return parts.isEmpty() ? null : String.join(", ", parts);
    }

