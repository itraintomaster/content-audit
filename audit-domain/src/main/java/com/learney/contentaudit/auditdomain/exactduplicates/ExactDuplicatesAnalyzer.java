    /**
     * R004: the copy and the exercise that stays as the student sees them, with their hint and,
     * in a multiple choice, their options; the finished exercise they share; and «Idéntico a
     * &lt;id&gt; del mismo tema». The exercise that stays is the other node of the finding.
     */
    @Override
    public List<FindingDraft> findingsAt(AuditNode node) {
        if (node == null || node.getTarget() != AuditTarget.QUIZ
                || !(node.getEntity() instanceof AuditableQuiz copy)
                || !(node.getDiagnoses() instanceof DefaultQuizDiagnoses diagnoses)) {
            return List.of();
        }
        Optional<ExactDuplicateDiagnosis> found = diagnoses.getExactDuplicateDiagnosis();
        if (found.isEmpty()) {
            return List.of();
        }
        ExactDuplicateDiagnosis diagnosis = found.get();
        AuditNode keptNode = keptOf.get(node);
        AuditableQuiz kept = keptNode != null && keptNode.getEntity() instanceof AuditableQuiz quiz ? quiz : null;
        String identical = "Idéntico a " + diagnosis.getKeptQuizId() + " del mismo tema";
        List<EvidencePart> examined = new ArrayList<>();
        examined.add(new EvidencePart("Copia", asSeen(copy)));
        if (kept != null) {
            examined.add(new EvidencePart("Queda", asSeen(kept)));
        }
        examined.add(new EvidencePart("Ejercicio terminado", diagnosis.getFinishedExercise()));
        examined.add(new EvidencePart("Idéntico", identical));
        List<FindingNodeRef> related = new ArrayList<>();
        if (kept != null) {
            related.add(new FindingNodeRef(AuditTarget.QUIZ, kept.getId(),
                    kept.getLabel() != null ? kept.getLabel() : kept.getId()));
        }
        String observation = asSeen(copy) + " · " + identical.substring(0, 1).toLowerCase() + identical.substring(1)
                + ": «" + diagnosis.getFinishedExercise() + "». Sobra una copia: se reemplaza en la mesa por un"
                + " ejercicio nuevo.";
        return List.of(new FindingDraft(RULE_EXACT_DUPLICATE, diagnosis.getKeptQuizId(), FindingSeverity.LOW,
                FindingResolution.PANEL, new FindingEvidence(examined, observation, related)));
    }

    /** The exercise as the student sees it, with its options if it is a multiple choice. */
    private String asSeen(AuditableQuiz quiz) {
        String statement = studentViewRenderer.render(quiz).getStatement();
        if (quiz.getMultipleChoice() == null || quiz.getMultipleChoice().getItems() == null) {
            return statement;
        }
        List<String> options = new ArrayList<>();
        for (MultipleChoiceItemEntity item : quiz.getMultipleChoice().getItems()) {
            if (item != null && item.getLabel() != null) {
                options.add(item.getLabel());
            }
        }
        return options.isEmpty() ? statement : statement + " (" + String.join(" · ", options) + ")";
    }
