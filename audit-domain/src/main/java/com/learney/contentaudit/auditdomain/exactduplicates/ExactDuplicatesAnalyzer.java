    static final String ANALYZER_NAME = "exact-duplicates";

    static final String DESCRIPTION = "Compara los ejercicios de cada tema por su ejercicio terminado, como el corrector,"
            + " y marca cada copia del que viene antes";

    /** R001 to R004: two exercises of a topic that finish the same. */
    static final String RULE_EXACT_DUPLICATE = "exact-duplicate";

    private final CorrectorMatcher correctorMatcher;

    private final QuizStudentViewRenderer studentViewRenderer;

    /** Each copy of this run with the exercise of its topic that stays. */
    private final Map<AuditNode, AuditNode> keptOf = new IdentityHashMap<>();

    public ExactDuplicatesAnalyzer(CorrectorMatcher correctorMatcher,
            QuizStudentViewRenderer studentViewRenderer) {
        this.correctorMatcher = correctorMatcher;
        this.studentViewRenderer = studentViewRenderer;
    }

    @Override
    public Void onKnowledge(AuditNode node) {
        if (node == null || node.getChildren() == null) {
            return null;
        }
        List<AuditNode> seen = new ArrayList<>();
        List<String> seenFinished = new ArrayList<>();
        for (AuditNode child : node.getChildren()) {
            if (child == null || !(child.getEntity() instanceof AuditableQuiz quiz)) {
                continue;
            }
            String finished = studentViewRenderer.finishedSentence(quiz, SentenceMode.FILL);
            if (finished == null || finished.isBlank()) {
                continue; // nothing to compare: a multiple choice without a correct option is FEAT-OMVAL's
            }
            AuditNode kept = null;
            for (int i = 0; i < seen.size() && kept == null; i++) {
                if (correctorMatcher.sameAnswer(finished, seenFinished.get(i))) {
                    kept = seen.get(i);
                }
            }
            double score;
            if (kept == null) {
                seen.add(child);
                seenFinished.add(finished);
                score = 1.0;
            } else {
                keptOf.put(child, kept);
                score = 0.0;
                if (!(child.getDiagnoses() instanceof DefaultQuizDiagnoses)) {
                    child.setDiagnoses(new DefaultQuizDiagnoses());
                }
                ((DefaultQuizDiagnoses) child.getDiagnoses()).setExactDuplicateDiagnosis(
                        new ExactDuplicateDiagnosis(kept.getEntity().getId(), finished, score));
            }
            child.getScores().put(ANALYZER_NAME, score);
        }
        return null;
    }

