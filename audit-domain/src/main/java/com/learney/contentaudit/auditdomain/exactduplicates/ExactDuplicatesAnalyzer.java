/**
 * FEAT-DUPEX: do two exercises of the same topic say the same? An errors analyzer that compares
 * the siblings of each topic by their finished exercise -- the statement as the student sees it,
 * without the hint, with the first answer or the correct option and with the starting sentence
 * of a rewrite -- compared as the corrector (R001).
 *
 * <p>In {@link #onKnowledge}, which the engine calls with the exercises in the order of the
 * course, each one is compared with the ones before it: the first of a group of equal exercises
 * stays without finding and scores 1, and each of the others is a copy that scores 0, with a low
 * finding for the panel that names the one that stays (R002, R003). Equal exercises of different
 * topics are never compared.
 */
