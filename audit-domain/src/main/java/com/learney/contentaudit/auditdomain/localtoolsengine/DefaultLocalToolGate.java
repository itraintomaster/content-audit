    private static Set<String> compatibleVersions(LocalToolStatus status, String methodId,
            EvaluationRuntimeIdentity runtimeIdentity, Set<String> compatibleMethodIds) {
        var versions = new LinkedHashSet<String>();
        versions.add(examinedVersion(status, methodId));
        // A process alias cannot establish who took an exam whose runtime is unknown.
        if (runtimeIdentity != null && runtimeIdentity.isExplicit() && compatibleMethodIds != null) {
            for (String alias : compatibleMethodIds) if (alias != null && !alias.isBlank())
                versions.add(examinedVersion(status, alias));
        }
        return Set.copyOf(versions);
    }

    /**
     * The examined version always names its tool: an Ollama model already does
     * («llama3:8b@365c0bd3c000»), a library gets the name in front («LanguageTool 6.8»).
     */
    static String examinedVersion(LocalToolStatus status, String methodId) {
        String version = status.getVersion() != null ? status.getVersion().strip() : "";
        String tool = status.getTool() != null ? status.getTool().strip() : "";
        String toolWord = tool.isEmpty() ? "" : tool.split("\\s+")[0];
        String named = toolWord.isEmpty() || version.startsWith(toolWord) ? version
                : (version.isEmpty() ? toolWord : toolWord + " " + version);
        return methodId == null || methodId.isBlank() ? named : named + VERSION_SEPARATOR + methodId;
    }

    /** status() is cheap and never throws by contract; a broken probe still leaves a status. */
    private static LocalToolStatus statusOf(LocalTool tool) {
        if (tool == null) {
            return new LocalToolStatus(null, null, false, REASON_TOOL_UNAVAILABLE + "no hay herramienta", null);
        }
        try {
            LocalToolStatus status = tool.status();
            return status != null
                    ? status
                    : new LocalToolStatus(null, null, false, REASON_TOOL_BROKEN + "sin estado", null);
        } catch (RuntimeException e) {
            return new LocalToolStatus(null, null, false, REASON_TOOL_BROKEN + e.getMessage(), null);
        }
    }

    /** R003: what is missing and how it is installed, in one line. */
    private static String unavailableReason(LocalToolStatus status) {
        StringBuilder reason = new StringBuilder(REASON_TOOL_UNAVAILABLE);
        reason.append(status.getTool() != null ? status.getTool() : "la herramienta").append(" no está disponible");
        if (status.getUnavailableReason() != null && !status.getUnavailableReason().isBlank()) {
            reason.append(" (").append(status.getUnavailableReason().strip()).append(')');
        }
        if (status.getInstallHint() != null && !status.getInstallHint().isBlank()) {
            reason.append("; se instala con: ").append(status.getInstallHint().strip());
        }
        return reason.toString();
    }

