/**
 * F-NIVFR-R003 and F-SEMAF-R004: what a topic teaches, read only from the course, never from a
 * list written by hand (F-LABS-R035).
 *
 * <ul>
 *   <li>The words of the English terms of its title, the ones between {@code $}: «$Invest time$ +
 *       gerundio» teaches invest and time; a term with an apostrophe also teaches the word before
 *       it, so «$Let's$» teaches let.</li>
 *   <li>The lemmas that are part of the answer of at least 3 quizzes of the topic and of 20 % or
 *       more of them: the gap's answers or, in a multiple choice, its correct option (0.2), read
 *       on the tokens the quiz already carries, so nothing is tokenized again. A word of the
 *       sentence outside the answer never counts.</li>
 * </ul>
 */
