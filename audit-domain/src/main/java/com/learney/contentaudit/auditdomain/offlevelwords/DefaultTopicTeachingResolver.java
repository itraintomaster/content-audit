public class DefaultTopicTeachingResolver implements TopicTeachingResolver {

    /** At least this many quizzes of the topic have the lemma in their answer. */
    static final int MIN_QUIZZES = 3;

    /** And they are at least this share of the topic's quizzes. */
    static final double MIN_SHARE = 0.20;

    private static final Pattern TITLE_TERM = Pattern.compile("\\$([^$]+)\\$");

    private static final Pattern TERM_SEPARATOR = Pattern.compile("[\\s/,]+");

    private static final Pattern ANSWER_WORD = Pattern.compile("[\\p{L}']+");

    private static final String TERM_PUNCTUATION = "'.?!¿¡\"()";

    @Override
    public TaughtWords taughtWords(AuditNode knowledgeNode) {
        if (knowledgeNode == null) {
            return new TaughtWords(null, List.of(), List.of());
        }
        AuditableEntity entity = knowledgeNode.getEntity();
        String knowledgeId = entity != null ? entity.getId() : null;
        String title = entity instanceof AuditableKnowledge knowledge && knowledge.getTitle() != null
                ? knowledge.getTitle() : entity != null ? entity.getLabel() : null;
        return new TaughtWords(knowledgeId, titleTerms(title), frequentAnswers(quizzesOf(knowledgeNode)));
    }

    /** The words of the English terms between {@code $} of the title, lower-cased and in order. */
    static List<String> titleTerms(String title) {
        if (title == null) {
            return List.of();
        }
        Set<String> terms = new LinkedHashSet<>();
        Matcher matcher = TITLE_TERM.matcher(title);
        while (matcher.find()) {
            for (String raw : TERM_SEPARATOR.split(matcher.group(1).toLowerCase(Locale.ROOT))) {
                String word = strip(raw);
                if (word.isEmpty()) {
                    continue;
                }
                terms.add(word);
                int apostrophe = word.indexOf('\'');
                if (apostrophe > 0) {
                    terms.add(word.substring(0, apostrophe));
                }
            }
        }
        return new ArrayList<>(terms);
    }

    /** «let's.» becomes «let's»: the punctuation around a term is not part of it. */
    private static String strip(String word) {
        int from = 0;
        int to = word.length();
        while (from < to && TERM_PUNCTUATION.indexOf(word.charAt(from)) >= 0) {
            from++;
        }
        while (to > from && TERM_PUNCTUATION.indexOf(word.charAt(to - 1)) >= 0) {
            to--;
        }
        return word.substring(from, to);
    }

    private static List<AuditableQuiz> quizzesOf(AuditNode knowledgeNode) {
        List<AuditableQuiz> quizzes = new ArrayList<>();
        if (knowledgeNode.getChildren() != null && !knowledgeNode.getChildren().isEmpty()) {
            for (AuditNode child : knowledgeNode.getChildren()) {
                if (child.getTarget() == AuditTarget.QUIZ && child.getEntity() instanceof AuditableQuiz quiz) {
                    quizzes.add(quiz);
                }
            }
            return quizzes;
        }
        if (knowledgeNode.getEntity() instanceof AuditableKnowledge knowledge && knowledge.getQuizzes() != null) {
            quizzes.addAll(knowledge.getQuizzes());
        }
        return quizzes;
    }

    /** The lemmas in the answer of at least 3 quizzes and of 20 % or more of the topic's quizzes. */
    static List<String> frequentAnswers(List<AuditableQuiz> quizzes) {
        Map<String, Integer> quizzesWithLemma = new LinkedHashMap<>();
        for (AuditableQuiz quiz : quizzes) {
            for (String lemma : answerLemmas(quiz)) {
                quizzesWithLemma.merge(lemma, 1, Integer::sum);
            }
        }
        List<String> frequent = new ArrayList<>();
        int total = quizzes.size();
        for (Map.Entry<String, Integer> entry : quizzesWithLemma.entrySet()) {
            int count = entry.getValue();
            if (count >= MIN_QUIZZES && total > 0 && (double) count / total >= MIN_SHARE) {
                frequent.add(entry.getKey());
            }
        }
        return frequent;
    }

    /** The lemmas of the quiz's tokens whose text is a word of its answer. */
    static Set<String> answerLemmas(AuditableQuiz quiz) {
        Set<String> lemmas = new LinkedHashSet<>();
        Set<String> words = answerWords(quiz);
        if (words.isEmpty() || quiz.getTokens() == null) {
            return lemmas;
        }
        for (NlpToken token : quiz.getTokens()) {
            if (token == null || token.getText() == null || token.getLemma() == null || token.getLemma().isEmpty()) {
                continue;
            }
            if (words.contains(token.getText().toLowerCase(Locale.ROOT))) {
                lemmas.add(token.getLemma().toLowerCase(Locale.ROOT));
            }
        }
        return lemmas;
    }

    /**
     * The words of the answer: every accepted answer of every gap (all its «|» variants) or, in a
     * multiple choice, the label of its correct option -- never a distractor.
     */
    static Set<String> answerWords(AuditableQuiz quiz) {
        Set<String> words = new LinkedHashSet<>();
        if (quiz == null) {
            return words;
        }
        if (quiz.getMultipleChoice() != null) {
            Optional<MultipleChoiceItemEntity> correct = quiz.getMultipleChoice().correctItem();
            correct.ifPresent(item -> addWords(item.getLabel(), words));
            return words;
        }
        if (quiz.getSentenceParts() == null) {
            return words;
        }
        for (SentencePartEntity part : quiz.getSentenceParts()) {
            if (part == null || part.getKind() != SentencePartKind.CLOZE || part.getOptions() == null) {
                continue;
            }
            for (String option : part.getOptions()) {
                addWords(option, words);
            }
        }
        return words;
    }

    private static void addWords(String text, Set<String> words) {
        if (text == null) {
            return;
        }
        Matcher matcher = ANSWER_WORD.matcher(text.toLowerCase(Locale.ROOT));
        while (matcher.find()) {
            words.add(matcher.group());
        }
    }
}
