/**
 * What the audio of an exercise says today, by the rule of the re-recording of 24/8 -- the same
 * one the audio was recorded with ({@code tts_text} and {@code spoken_from_choice_parts} of
 * {@code scripts/regenerate_quiz_audios.py}): one text per accepted answer of the gap (the correct
 * option in a multiple choice), so a recording of another accepted answer also matches
 * (F-DATOS-R003).
 *
 * <ul>
 *   <li>The exercise is built with the answer, without the parenthesis blocks (the hints).</li>
 *   <li>A word-form prompt ({@code stop - stopping}) says only the answer.</li>
 *   <li>A dialogue {@code A: … B: …} says only what B says, without its label; the labels of the
 *       instructions at the start ({@code Fact:}, {@code Guess:}…) and the classifying tails
 *       ({@code Defining}…) are not said, nor the dash of «put nothing».</li>
 *   <li>A cue {@code X / Y} in the text is replaced by the answer when the answer is one of its
 *       alternatives, before or after the gap.</li>
 *   <li>In a rewriting topic the answer alone is also a text the audio may say.</li>
 * </ul>
 */
