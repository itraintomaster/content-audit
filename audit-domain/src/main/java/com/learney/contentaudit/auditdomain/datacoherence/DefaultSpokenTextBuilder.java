    /** The exercise with the answer in the first gap and the first answer in the others. */
    private static String built(List<SentencePartEntity> parts, String answer) {
        StringBuilder sb = new StringBuilder();
        boolean first = true;
        for (SentencePartEntity part : parts) {
            if (part == null) {
                continue;
            }
            String token;
            if (part.getKind() == SentencePartKind.CLOZE) {
                token = first ? answer : firstAnswer(part);
                first = false;
            } else {
                token = part.getText() != null ? part.getText() : "";
            }
            sb.append(' ').append(token);
        }
        return sb.toString();
    }

    private static String firstAnswer(SentencePartEntity part) {
        List<String> options = part.getOptions();
        if (options == null || options.isEmpty() || options.get(0) == null) {
            return "";
        }
        return options.get(0).split("\\|")[0].strip();
    }

    /** {@code tts_text} of the re-recording of 24/8. */
    static String ttsText(String sentence) {
        if (sentence == null) {
            return "";
        }
        Matcher wordForm = WORD_FORM.matcher(sentence.strip());
        if (wordForm.matches()) {
            return wordForm.group(1);
        }
        String t = HINT.matcher(sentence).replaceAll(" ");
        Matcher dialog = DIALOG.matcher(t.strip());
        if (dialog.matches()) {
            t = dialog.group(2);
        }
        t = LABEL.matcher(t.strip()).replaceFirst("");
        t = t.replaceAll("Link type:\\s*", "");
        t = DROP_TAILS.matcher(t.strip()).replaceAll("$1");
        t = t.replaceAll("(^|\\s)-(\\s|$)", " ");
        return polish(t);
    }

    /** {@code polish} of the re-recording of 24/8: contractions stuck back and signs normalized. */
    static String polish(String text) {
        String t = text.replaceAll("\\s+'(ll|s|re|ve|d|m|t)\\b", "'$1");
        t = t.replaceAll("\\s+n't\\b", "n't");
        t = t.replaceAll("\\s+", " ").strip();
        t = t.replaceAll("\\s+([.?!,;:])", "$1");
        return t;
    }

    /**
     * {@code spoken_from_choice_parts} of the re-recording of 24/8, with the answer given for the
     * first gap: a cue {@code X / Y} before its gap is replaced by the answer, which is not said
     * again; one right after the gap is cut when the answer was one of its alternatives; a text
     * that is only a cue is not said. Nothing when the exercise has no cue.
     */
    static String spokenFromChoiceParts(List<SentencePartEntity> parts, String answer) {
        int firstGap = -1;
        for (int i = 0; i < parts.size(); i++) {
            if (parts.get(i) != null && parts.get(i).getKind() == SentencePartKind.CLOZE) {
                firstGap = i;
                break;
            }
        }
        List<String> tokens = new ArrayList<>();
        Set<Integer> consumed = new HashSet<>();
        String previousGap = null;
        boolean anyCue = false;
        for (int i = 0; i < parts.size(); i++) {
            SentencePartEntity part = parts.get(i);
            if (part == null) {
                continue;
            }
            if (part.getKind() == SentencePartKind.TEXT) {
                String original = part.getText() != null ? part.getText() : "";
                String t = HINT.matcher(original).replaceAll(" ");
                if (t.isBlank()) {
                    continue;
                }
                Matcher m = CUE.matcher(t);
                boolean found = m.find();
                anyCue |= found;
                boolean substituted = false;
                if (found && previousGap != null && t.substring(0, m.start()).isBlank()
                        && alternativeOf(previousGap, m)) {
                    t = t.substring(0, m.start()) + t.substring(m.end());
                    substituted = true;
                }
                int next = -1;
                for (int j = i + 1; j < parts.size(); j++) {
                    if (parts.get(j) != null && parts.get(j).getKind() == SentencePartKind.CLOZE) {
                        next = j;
                        break;
                    }
                }
                if (!substituted && found && next >= 0 && !consumed.contains(next)) {
                    String value = next == firstGap ? answer : firstAnswer(parts.get(next));
                    if (alternativeOf(value, m)) {
                        t = t.substring(0, m.start()) + value + t.substring(m.end());
                        consumed.add(next);
                        substituted = true;
                    }
                }
                if (!substituted && found && isCueOnly(original)) {
                    continue;
                }
                if (t.isBlank()) {
                    continue;
                }
                tokens.add(t);
                previousGap = null;
            } else if (part.getKind() == SentencePartKind.CLOZE) {
                if (consumed.contains(i)) {
                    continue;
                }
                String value = i == firstGap ? answer : firstAnswer(part);
                if (value.contains("/")) {
                    value = value.split("\\s*/\\s*")[0].strip();
                }
                previousGap = value;
                if (value.equals("-") || value.isEmpty()) {
                    continue;
                }
                tokens.add(value);
            }
        }
        return anyCue ? polish(String.join(" ", tokens)) : null;
    }

    private static boolean alternativeOf(String value, Matcher cue) {
        String v = value.toLowerCase(Locale.ROOT);
        return v.equals(cue.group(1).toLowerCase(Locale.ROOT)) || v.equals(cue.group(2).toLowerCase(Locale.ROOT));
    }

    private static boolean isCueOnly(String text) {
        String t = text == null ? "" : text.strip();
        return t.contains(" / ") && !FINAL_MARK.matcher(t).find() && t.length() <= 60;
    }
