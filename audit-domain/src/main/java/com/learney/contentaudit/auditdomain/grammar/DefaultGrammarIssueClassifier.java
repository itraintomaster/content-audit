    /** A rule of repetition, or a mark that is the same words twice («in August in August»). */
    private static boolean isRepetition(GrammarMatch match, String marked) {
        if (match.getRuleId() != null && REPETITION_RULES.contains(match.getRuleId())) {
            return true;
        }
        String[] words = marked.strip().toLowerCase(Locale.ROOT).split("\\s+");
        if (words.length < 2 || words.length % 2 != 0) {
            return false;
        }
        int half = words.length / 2;
        for (int i = 0; i < half; i++) {
            if (!words[i].equals(words[half + i])) {
                return false;
            }
        }
        return true;
    }

    /** The mark starts inside an answer and goes on outside it, or the other way round: glued to the gap. */
    private static boolean straddlesAnAnswer(int start, int end, List<AnswerSpan> answers) {
        for (AnswerSpan answer : answers) {
            boolean overlaps = start < answer.getEnd() && end > answer.getStart();
            boolean inside = start >= answer.getStart() && end <= answer.getEnd();
            if (overlaps && !inside) {
                return true;
            }
        }
        return false;
    }

    private static boolean touchesAnAnswer(int start, int end, List<AnswerSpan> answers) {
        for (AnswerSpan answer : answers) {
            if (start < answer.getEnd() && end > answer.getStart()) {
                return true;
            }
            if (start == end && start >= answer.getStart() && start <= answer.getEnd()) {
                return true;
            }
        }
        return false;
    }

    /** «teached → taught (ortografía)»; the missing space shows the period it follows, «11.I → 11. I». */
    private static String explanation(GrammarMatch match, String marked, String text, int start) {
        String kind = RULE_NAMES.getOrDefault(match.getRuleId(),
                CATEGORY_NAMES.getOrDefault(match.getCategoryId(), "error de inglés"));
        String suggestion = match.getSuggestions() != null && !match.getSuggestions().isEmpty()
                ? match.getSuggestions().get(0)
                : null;
        if (MISSING_SPACE.equals(match.getRuleId())) {
            String before = wordBefore(text, start);
            return before + marked + " → " + before + " " + marked.strip() + " (" + kind + ")";
        }
        return suggestion != null
                ? marked + " → " + suggestion + " (" + kind + ")"
                : marked + " (" + kind + ")";
    }

    /** The word glued before a position: «11.» in «…until 11.I…». */
    private static String wordBefore(String text, int position) {
        int from = position;
        while (from > 0 && !Character.isWhitespace(text.charAt(from - 1))) {
            from--;
        }
        return text.substring(from, position);
    }
