package com.learney.contentaudit.agentruntimeinfrastructure.graphexecution;

import com.learney.contentaudit.agentruntimeinfrastructure.AgentDefinitionFound;
import com.learney.contentaudit.agentruntimeinfrastructure.AgentDefinitionLocation;
import com.learney.contentaudit.agentruntimeinfrastructure.AgentDefinitionLocator;
import com.learney.contentaudit.agentruntimeinfrastructure.AgentDefinitionUnresolved;
import com.learney.contentaudit.agentruntimeinfrastructure.AgentGraphRunnerConfig;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import javax.annotation.processing.Generated;

/**
 * Single implementation of the "where does this agent's definition live"
 * question. {@code locate} mirrors lemma-absence-agent's original resolution
 * (config, else CWD — it never populates {@code project_root}); {@code
 * locateUnderProjectRoot} mirrors knowledge-title-agent's (config, else the
 * project root it does populate). Both fall back to the CWD default when
 * neither a configured directory nor a usable project root is available, so
 * together they are the union — not the intersection — of the two prior
 * behaviors. {@link DefaultAgentGraphRunner} is built with the very same
 * instance the version resolvers consult, so the directory it loads the graph
 * from and the directory a consumer digests are the same by construction.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
class DefaultAgentDefinitionLocator implements AgentDefinitionLocator {

    private static final String AGENTS_BASE_DIR = ".sentinel/agents";

    private final AgentGraphRunnerConfig config;

    public DefaultAgentDefinitionLocator(AgentGraphRunnerConfig config) {
        this.config = config;
    }

    @Override
    public AgentDefinitionLocation locate(String agentName) {
        return resolve(resolveBase(null), agentName);
    }

    @Override
    public AgentDefinitionLocation locateUnderProjectRoot(String projectRoot, String agentName) {
        return resolve(resolveBase(projectRoot), agentName);
    }

    private Path resolveBase(String projectRoot) {
        Path configured = config != null ? config.getAgentsBaseDir() : null;
        if (configured != null) {
            return configured;
        }
        if (projectRoot != null && !projectRoot.isBlank()) {
            return Paths.get(projectRoot).resolve(AGENTS_BASE_DIR);
        }
        return Paths.get(AGENTS_BASE_DIR);
    }

    private static AgentDefinitionLocation resolve(Path base, String agentName) {
        Path directory = base.resolve(agentName).toAbsolutePath();
        if (Files.isDirectory(directory)) {
            return new AgentDefinitionFound(directory);
        }
        return new AgentDefinitionUnresolved(agentName, directory);
    }
}
