    /**
     * R003: the suggested words of the topic's level, asked to the same port get suggested-lemmas uses,
     * with a transient LEMMA_ABSENCE task anchored to a quiz of the topic -- never saved nor planned.
     * The port is asked without a limit; the words the topic uses and the red ones go out, and only
     * then the limit cuts, so asking for 10 gives 10 while enough remain (R007: none is red).
     */
    private List<SuggestedLemma> toAdd(AuditReport report, AuditNode knowledge, List<AuditNode> quizzes, CefrLevel level,
            SuggestedLemmaQueryCriteria criteria, Set<String> used, Set<String> redLemmas) {
        SuggestedLemmaQueryCriteria asked = criteria != null ? criteria
                : new SuggestedLemmaQueryCriteria(Optional.empty(), Optional.empty(), Optional.empty(), false,
                        Optional.empty());
        SuggestedLemmaQueryCriteria unlimited = new SuggestedLemmaQueryCriteria(Optional.empty(),
                orEmpty(asked.getPartOfSpeech()), level != null ? Optional.of(level) : orEmpty(asked.getExplicitLevel()),
                asked.isIncludeExposed(), orEmpty(asked.getRegex()));
        String anchor = quizzes.isEmpty() ? knowledge.getEntity().getId() : quizzes.get(0).getEntity().getId();
        RefinementTask transientTask = new RefinementTask("word-lights-" + knowledge.getEntity().getId(), AuditTarget.QUIZ,
                anchor, knowledge.getEntity().getLabel(), DiagnosisKind.LEMMA_ABSENCE, 0, RefinementTaskStatus.PENDING);
        SuggestedLemmaQueryResult result = suggestedLemmaQueryPort.query(report, transientTask, unlimited);
        List<SuggestedLemma> toAdd = new ArrayList<>();
        Optional<Integer> limit = orEmpty(asked.getLimit());
        for (SuggestedLemma lemma : result != null ? orEmpty(result.getSuggestedLemmas()) : List.<SuggestedLemma>of()) {
            if (lemma.getLemma() == null || used.contains(key(lemma.getLemma(), lemma.getPos()))
                    || redLemmas.contains(lemma.getLemma().toLowerCase(Locale.ROOT))) {
                continue;
            }
            if (limit.isPresent() && toAdd.size() >= limit.get()) {
                break;
            }
            toAdd.add(lemma);
        }
        return toAdd;
    }

    /** R004: the topic teaches it -- a word of its title's terms, or a frequent lemma of its answers. */
    private static boolean taught(TaughtWords taught, String lemma, Set<String> texts) {
        if (taught == null) {
            return false;
        }
        String lowerLemma = lemma.toLowerCase(Locale.ROOT);
        List<String> terms = taught.getTitleTerms() != null ? taught.getTitleTerms() : List.of();
        if (terms.contains(lowerLemma)) {
            return true;
        }
        for (String text : texts) {
            if (text != null && terms.contains(text.toLowerCase(Locale.ROOT))) {
                return true;
            }
        }
        return taught.getFrequentAnswers() != null && taught.getFrequentAnswers().contains(lowerLemma);
    }

    private static Optional<AuditNode> findKnowledge(AuditNode node, String knowledgeId) {
        if (node == null || knowledgeId == null) {
            return Optional.empty();
        }
        if (node.getTarget() == AuditTarget.KNOWLEDGE && node.getEntity() != null
                && knowledgeId.equals(node.getEntity().getId())) {
            return Optional.of(node);
        }
        if (node.getChildren() != null) {
            for (AuditNode child : node.getChildren()) {
                Optional<AuditNode> found = findKnowledge(child, knowledgeId);
                if (found.isPresent()) {
                    return found;
                }
            }
        }
        return Optional.empty();
    }

    private static Optional<LemmaCountResult> lemmaCountOf(AuditNode root) {
        if (root == null || !(root.getDiagnoses() instanceof CourseDiagnoses course)) {
            return Optional.empty();
        }
        return course.getLemmaCountDiagnosis().map(LemmaCountCourseDiagnosis::getResult);
    }

    private static CefrLevel levelOf(AuditNode knowledge) {
        Optional<AuditNode> milestone = knowledge.ancestor(AuditTarget.MILESTONE);
        if (milestone.isEmpty() || !(milestone.get().getEntity() instanceof AuditableMilestone level)
                || level.getLabel() == null) {
            return null;
        }
        try {
            return CefrLevel.valueOf(level.getLabel());
        } catch (IllegalArgumentException e) {
            return null;
        }
    }

    private static List<AuditNode> quizzesOf(AuditNode knowledge) {
        List<AuditNode> quizzes = new ArrayList<>();
        if (knowledge.getChildren() != null) {
            for (AuditNode child : knowledge.getChildren()) {
                if (child.getTarget() == AuditTarget.QUIZ && child.getEntity() instanceof AuditableQuiz) {
                    quizzes.add(child);
                }
            }
        }
        return quizzes;
    }

    private static String key(LemmaAndPos lemmaAndPos) {
        return key(lemmaAndPos.getLemma(), lemmaAndPos.getPos());
    }

    private static String key(String lemma, String pos) {
        return lemma + "|" + pos;
    }

    private static <T> List<T> orEmpty(List<T> list) {
        return list != null ? list : List.of();
    }

    private static <T> Optional<T> orEmpty(Optional<T> optional) {
        return optional != null ? optional : Optional.empty();
    }

    /** A content word of the topic while it is being read. */
    private static final class Seen {
        final String lemma;
        final String pos;
        final Set<String> texts = new HashSet<>();
        CefrLevel flaggedLevel;
        boolean outOfCatalog;
        Integer outOfCatalogRank;
        boolean offLevelError;

        Seen(String lemma, String pos) {
            this.lemma = lemma;
            this.pos = pos;
        }
    }
