    /** The lemma-count result of the report, when its course has one. */
    private static Optional<LemmaCountResult> courseLemmaCount(AuditReport report) {
        AuditNode courseRoot = report.getRoot();
        if (courseRoot == null || !(courseRoot.getDiagnoses() instanceof CourseDiagnoses)) {
            return Optional.empty();
        }
        return ((CourseDiagnoses) courseRoot.getDiagnoses()).getLemmaCountDiagnosis()
                .map(LemmaCountCourseDiagnosis::getResult);
    }

    /**
     * F-POCOV-R007: the threshold an exposed word reports: its row's, or the one of the band its
     * COCA rank falls in (the last band also takes the unranked); without bands, the configured one.
     */
    private static int bandThreshold(LemmaExposure exposure, Integer cocaRank, List<LemmaCountBand> bands,
            int configuredThreshold) {
        if (exposure != null && exposure.getThreshold() > 0) {
            return exposure.getThreshold();
        }
        for (LemmaCountBand band : bands) {
            if (band.getMaxCocaRank() == null || (cocaRank != null && cocaRank <= band.getMaxCocaRank())) {
                return band.getThreshold();
            }
        }
        return bands.isEmpty() ? configuredThreshold : bands.get(bands.size() - 1).getThreshold();
    }

    /**
     * Builds a lookup of sub-exposed lemmas from the AuditReport's milestone node for the
     * given level. Navigates the course root's milestone children to find the one whose
     * entity label matches the CefrLevel enum name, then reads its LemmaCountLevelDiagnosis.
     */
    private Map<LemmaAndPos, LemmaCountStats> buildSubExposedLookup(AuditReport report,
            CefrLevel level) {
        Map<LemmaAndPos, LemmaCountStats> result = new HashMap<>();
        AuditNode courseRoot = report.getRoot();
        if (courseRoot == null || courseRoot.getChildren() == null) {
            return result;
        }

        for (AuditNode child : courseRoot.getChildren()) {
            if (child.getTarget() != AuditTarget.MILESTONE) {
                continue;
            }
            AuditableEntity entity = child.getEntity();
            if (!(entity instanceof AuditableMilestone)) {
                continue;
            }
            String label = ((AuditableMilestone) entity).getLabel();
            CefrLevel milestoneLevel;
            try {
                milestoneLevel = CefrLevel.valueOf(label);
            } catch (IllegalArgumentException | NullPointerException ignored) {
                continue;
            }
            if (milestoneLevel != level) {
                continue;
            }

            // Found the milestone for the target level — extract sub-exposed lemmas
            NodeDiagnoses diag = child.getDiagnoses();
            if (!(diag instanceof LevelDiagnoses)) {
                break;
            }
            Optional<LemmaCountLevelDiagnosis> maybeLcd =
                    ((LevelDiagnoses) diag).getLemmaCountDiagnosis();
            if (maybeLcd.isEmpty()) {
                break;
            }
            LevelLemmaCountResult levelResult = maybeLcd.get().getLevelResult();
            if (levelResult == null || levelResult.getSubExposedLemmas() == null) {
                break;
            }
            for (LemmaCountStats stats : levelResult.getSubExposedLemmas()) {
                if (stats.getLemmaAndPos() != null) {
                    result.put(stats.getLemmaAndPos(), stats);
                }
            }
            break;
        }

        return result;
    }

    /**
     * Resolves the threshold to apply for a sub-exposed lemma's triple.
     * Prefers the configured threshold; falls back to deriving from the stat's score.
     */
    private int resolveThreshold(int configuredThreshold, LemmaCountStats stats) {
        if (configuredThreshold > 0) {
            return configuredThreshold;
        }
        // Fallback: score = count / thresholdN → thresholdN = round(count / score)
        if (stats.getScore() > 0.0 && stats.getScore() < 1.0 && stats.getCount() > 0) {
            return (int) Math.round((double) stats.getCount() / stats.getScore());
        }
        return configuredThreshold;
    }
