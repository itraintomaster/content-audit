    private Classification classify(AuditReport report) {
        Classification c = new Classification();
        if (report != null && report.getRoot() != null) {
            walk(report.getRoot(), null, null, c);
        }
        return c;
    }

    private void walk(AuditNode node, AuditNode milestone, AuditNode knowledge, Classification c) {
        AuditTarget target = node.getTarget();
        AuditNode levelNode = target == AuditTarget.MILESTONE ? node : milestone;
        AuditNode topicNode = target == AuditTarget.KNOWLEDGE ? node : knowledge;
        collectForNode(node, levelNode, topicNode, c);
        List<AuditNode> children = node.getChildren();
        if (children != null) {
            for (AuditNode child : children) {
                walk(child, levelNode, topicNode, c);
            }
        }
    }

    private void collectForNode(AuditNode node, AuditNode milestone, AuditNode knowledge, Classification c) {
        AuditTarget target = node.getTarget();
        String nodeId = resolveId(node);
        String nodeLabel = resolveLabel(node);
        Map<String, Double> scores = node.getScores() != null ? node.getScores() : Map.of();
        List<Finding> findings = node.getFindings() != null ? node.getFindings() : List.of();

        List<ScoredTask> nodeTasks = new ArrayList<>();
        List<Finding> waitingForCover = new ArrayList<>();
        Set<String> handled = new LinkedHashSet<>();
        Map<String, Double> errorScores = new LinkedHashMap<>();

        // The vocabulary in the order of the scores of the node, as today; the errors, finding by finding, after it.
        for (Map.Entry<String, Double> entry : scores.entrySet()) {
            String analyzerName = entry.getKey();
            Double score = entry.getValue();
            if (isErrorsAnalyzer(analyzerName) && hasFindingOf(analyzerName, findings)) {
                handled.add(analyzerName);
                errorScores.put(analyzerName, score);
                continue;
            }
            // A score below 1 of an analyzer of errors with no finding on the node: a report saved before the
            // contract of the finding (FEAT-HALL), when the collector did not leave them yet. It keeps the task of
            // before, one per node and without origin; a report made today never gets here (F-HALL-R004 inv. 1).
            if (score == null || score >= 1.0) {
                continue;
            }
            DiagnosisKind kind = taskKindAt(analyzerName, target);
            if (kind == null) {
                continue;
            }
            ScoredTask task = new ScoredTask(score, target, nodeId, nodeLabel, kind);
            task.analyzer = analyzerName;
            attachVocabularyFindings(task, findings, milestone, knowledge);
            nodeTasks.add(task);
        }
        // R002: the findings of the analyzers of errors in the order of their identity, which does not depend on the
        // run, so equal scores are broken by node and by identity. A finding of an analyzer of errors with no score on
        // the node (not expected in a report the collector made) gets the lowest score.
        List<Finding> errorFindings = new ArrayList<>();
        for (Finding finding : findings) {
            if (finding != null && finding.getAnalyzer() != null && isErrorsAnalyzer(finding.getAnalyzer())
                    && (handled.contains(finding.getAnalyzer()) || !scores.containsKey(finding.getAnalyzer()))) {
                errorFindings.add(finding);
            }
        }
        errorFindings.sort(Comparator.comparing(DefaultRefinerEngine::identityKey));
        for (Finding finding : errorFindings) {
            Double score = errorScores.getOrDefault(finding.getAnalyzer(), 0.0);
            classifyFinding(finding, score, node, nodeId, nodeLabel, milestone, knowledge, nodeTasks,
                    waitingForCover, c);
        }
        // R004: what another task of the same exercise already marks.
        for (Finding finding : waitingForCover) {
            String coveringAnalyzer = coveringAnalyzerOf(finding.getAnalyzer());
            DiagnosisKind coveringKind = coveringAnalyzer != null ? taskKindAt(coveringAnalyzer, target) : null;
            ScoredTask cover = null;
            if (coveringKind != null) {
                for (ScoredTask candidate : nodeTasks) {
                    if (candidate.diagnosisKind == coveringKind && coveringAnalyzer.equals(candidate.analyzer)) {
                        cover = candidate;
                        break;
                    }
                }
            }
            if (cover == null) {
                c.unconverted(finding.getAnalyzer(), REASON_NOT_COVERED + " (" + coveringKindName(coveringAnalyzer,
                        coveringKind) + ")");
                continue;
            }
            if (!cover.hasOrigin) {
                initializeOrigin(cover, milestone, knowledge);
            }
            cover.coveredFindings.add(finding);
        }
        c.tasks.addAll(nodeTasks);
    }

    private void classifyFinding(Finding finding, Double score, AuditNode node, String nodeId, String nodeLabel,
            AuditNode milestone, AuditNode knowledge, List<ScoredTask> nodeTasks, List<Finding> waitingForCover,
            Classification c) {
        if (finding.getResolution() == FindingResolution.RANK_ONLY || finding.getResolution() == null) {
            return; // F-TAREA-R005: what only ranks is not a task, nor counted
        }
        String analyzerName = finding.getAnalyzer();
        c.counting.merge(analyzerName, 1, Integer::sum);
        double taskScore = score != null ? score : 0.0;

        if (coveringAnalyzerOf(analyzerName) != null) {
            waitingForCover.add(finding);
            return;
        }
        Optional<AnalyzerPlanBinding> binding = analyzerCatalog.planBinding(analyzerName);
        String reason = unconvertedReason(binding, node.getTarget());
        if (reason != null) {
            c.unconverted(analyzerName, reason);
            return;
        }
        DiagnosisKind kind = knownKind(binding.get().getTaskKind());
        Optional<AnalyzerCorrection> correction = correctionOf(analyzerName);
        if (correction.isPresent() && correction.get().groupsByTopic() && knowledge != null) {
            String marker = finding.getIdentity() != null ? finding.getIdentity().getMarker() : null;
            String groupKey = analyzerName + "|" + marker + "|" + resolveId(knowledge);
            ScoredTask group = c.topicTasks.get(groupKey);
            if (group == null) {
                group = new ScoredTask(taskScore, AuditTarget.KNOWLEDGE, resolveId(knowledge), resolveLabel(knowledge),
                        kind);
                group.analyzer = analyzerName;
                group.hasOrigin = true;
                group.ownFinding = finding;
                group.level = levelOf(milestone);
                group.knowledgeId = resolveId(knowledge);
                group.knowledgeLabel = resolveLabel(knowledge);
                group.reachedQuizIds.add(nodeId);
                c.topicTasks.put(groupKey, group);
                nodeTasks.add(group);
            } else {
                group.score = Math.min(group.score, taskScore);
                if (!group.reachedQuizIds.contains(nodeId)) {
                    group.reachedQuizIds.add(nodeId);
                }
                group.coveredFindings.add(finding);
            }
            return;
        }
        ScoredTask task = new ScoredTask(taskScore, node.getTarget(), nodeId, nodeLabel, kind);
        task.analyzer = analyzerName;
        task.hasOrigin = true;
        task.ownFinding = finding;
        task.level = levelOf(milestone);
        task.knowledgeId = knowledge != null ? resolveId(knowledge) : null;
        task.knowledgeLabel = knowledge != null ? resolveLabel(knowledge) : null;
        task.reachedQuizIds.add(nodeId);
        nodeTasks.add(task);
    }

    private static boolean hasFindingOf(String analyzerName, List<Finding> findings) {
        for (Finding finding : findings) {
            if (finding != null && analyzerName.equals(finding.getAnalyzer())) {
                return true;
            }
        }
        return false;
    }

    private Optional<AnalyzerCorrection> correctionOf(String analyzerName) {
        if (analyzerCorrectionCatalog == null || analyzerName == null) {
            return Optional.empty();
        }
        return analyzerCorrectionCatalog.find(analyzerName);
    }

    /** The analyzer whose task covers what this one marks, from its declaration, or the known one without catalog. */
    private String coveringAnalyzerOf(String analyzerName) {
        if (analyzerName == null) {
            return null;
        }
        if (analyzerCorrectionCatalog != null) {
            return analyzerCorrectionCatalog.find(analyzerName).flatMap(AnalyzerCorrection::coveringAnalyzer)
                    .orElse(null);
        }
        return COVERED_BY_ANALYZER.get(analyzerName);
    }

    private static String coveringKindName(String coveringAnalyzer, DiagnosisKind coveringKind) {
        if (coveringKind != null) {
            return "no tiene tarea " + coveringKind.name();
        }
        return "no tiene tarea de " + coveringAnalyzer;
    }

    /** Enrich an existing vocabulary task without changing the score-driven plan (F-TAREA-R007). */
    private void attachVocabularyFindings(ScoredTask task, List<Finding> findings, AuditNode milestone,
            AuditNode knowledge) {
        if (!analyzerCatalog.find(task.analyzer).map(card -> card.getFamily() == AnalyzerFamily.VOCABULARY)
                .orElse(false)) {
            return;
        }
        Optional<AnalyzerCorrection> correction = correctionOf(task.analyzer);
        if (correction.isEmpty()) {
            return;
        }
        List<Finding> own = new ArrayList<>();
        for (Finding finding : findings) {
            if (finding != null && task.analyzer.equals(finding.getAnalyzer()) && finding.getNode() != null
                    && finding.getNode().getTarget() == task.nodeTarget
                    && task.nodeId.equals(finding.getNode().getNodeId())
                    && finding.getResolution() != null && finding.getResolution() != FindingResolution.RANK_ONLY) {
                List<ExercisePart> declared = correction.get().editScope(finding.getResolution());
                if (declared != null && !declared.isEmpty()) {
                    own.add(finding);
                }
            }
        }
        own.sort(Comparator.comparing(DefaultRefinerEngine::identityKey));
        if (!own.isEmpty()) {
            initializeOrigin(task, milestone, knowledge);
            task.ownFinding = own.get(0);
            task.coveredFindings.addAll(own.subList(1, own.size()));
        }
    }

    private void initializeOrigin(ScoredTask task, AuditNode milestone, AuditNode knowledge) {
        task.level = levelOf(milestone);
        task.knowledgeId = knowledge != null ? resolveId(knowledge) : null;
        task.knowledgeLabel = knowledge != null ? resolveLabel(knowledge) : null;
        task.reachedQuizIds.add(task.nodeId);
        task.hasOrigin = true;
    }

    private boolean isErrorsAnalyzer(String analyzerName) {
        if (analyzerName == null) {
            return false;
        }
        return analyzerCatalog.find(analyzerName).map(card -> card.getFamily() == AnalyzerFamily.ERRORS)
                .orElse(false);
    }

    /**
     * The task kind the analyzer's binding makes on this level, or null when it makes none there: no binding
     * (lemma-count, a sub-metric such as a COCA quarter, a name the catalog does not have), a level outside its task
     * targets, or a kind the plan does not know.
     */
    private DiagnosisKind taskKindAt(String analyzerName, AuditTarget target) {
        Optional<AnalyzerPlanBinding> binding = analyzerCatalog.planBinding(analyzerName);
        if (binding.isEmpty() || binding.get().getTaskTargets() == null
                || !binding.get().getTaskTargets().contains(target)) {
            return null;
        }
        return knownKind(binding.get().getTaskKind());
    }

    private void countUnconverted(AuditNode node, AnalyzerDescriptor card,
            Optional<AnalyzerPlanBinding> binding, Map<String, Integer> countsByReason) {
        AuditTarget target = node.getTarget();
        List<AuditTarget> evaluated = card.getEvaluatedTargets() != null ? card.getEvaluatedTargets() : List.of();
        Double score = node.getScores() != null ? node.getScores().get(card.getName()) : null;
        if (score != null && score < 1.0 && evaluated.contains(target)) {
            String reason = coveredReason(card.getName(), node);
            if (reason == null) {
                reason = unconvertedReason(binding, target);
            }
            if (reason != null) {
                countsByReason.merge(reason, 1, Integer::sum);
            }
        }
        if (node.getChildren() != null) {
            for (AuditNode child : node.getChildren()) {
                countUnconverted(child, card, binding, countsByReason);
            }
        }
    }

    /**
     * The reason a score below 1 is covered by the task another analyzer makes on the same node, or null when the
     * analyzer is not covered by another's task or the node has no such task.
     */
    private String coveredReason(String analyzerName, AuditNode node) {
        String coveringAnalyzer = coveringAnalyzerOf(analyzerName);
        if (coveringAnalyzer == null || node.getScores() == null) {
            return null;
        }
        DiagnosisKind coveringKind = taskKindAt(coveringAnalyzer, node.getTarget());
        Double other = node.getScores().get(coveringAnalyzer);
        if (coveringKind != null && other != null && other < 1.0) {
            String where = node.getTarget() == AuditTarget.QUIZ ? "del ejercicio" : "del nodo";
            return "cubierto por la tarea " + coveringKind.name() + " " + where;
        }
        return null;
    }

    private static String unconvertedReason(Optional<AnalyzerPlanBinding> binding, AuditTarget target) {
        if (binding.isEmpty()) {
            return REASON_NO_KIND;
        }
        String taskKind = binding.get().getTaskKind();
        if (knownKind(taskKind) == null) {
            return "el tipo de tarea " + taskKind + " no existe en el plan";
        }
        if (binding.get().getTaskTargets() == null || !binding.get().getTaskTargets().contains(target)) {
            return "su ficha no hace tareas en " + target;
        }
        return null;
    }

    private static DiagnosisKind knownKind(String taskKind) {
        if (taskKind == null) {
            return null;
        }
        for (DiagnosisKind kind : DiagnosisKind.values()) {
            if (kind.name().equals(taskKind)) {
                return kind;
            }
        }
        return null;
    }

    private static CefrLevel levelOf(AuditNode milestone) {
        if (milestone == null || milestone.getEntity() == null || milestone.getEntity().getLabel() == null) {
            return null;
        }
        try {
            return CefrLevel.valueOf(milestone.getEntity().getLabel().trim().toUpperCase());
        } catch (IllegalArgumentException notALevel) {
            return null;
        }
    }

    private static String identityKey(Finding finding) {
        return finding.getIdentity() != null && finding.getIdentity().getKey() != null
                ? finding.getIdentity().getKey() : "";
    }

    private String resolveId(AuditNode node) {
        if (node.getEntity() == null) {
            return "root";
        }
        String id = node.getEntity().getId();
        return id != null ? id : "root";
    }

    private String resolveLabel(AuditNode node) {
        if (node.getEntity() == null) {
            return "Course";
        }
        String label = node.getEntity().getLabel();
        return label != null ? label : "Course";
    }

