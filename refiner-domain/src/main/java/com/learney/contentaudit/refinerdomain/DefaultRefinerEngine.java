    /** What one walk of the report finds: the tasks in walk order and, per analyzer of errors, its counts. */
    private static final class Classification {
        final List<ScoredTask> tasks = new ArrayList<>();
        final Map<String, ScoredTask> topicTasks = new LinkedHashMap<>();
        final Map<String, Integer> counting = new LinkedHashMap<>();
        final Map<String, Set<String>> unconvertedReasons = new LinkedHashMap<>();

        void unconverted(String analyzer, String reason) {
            unconvertedReasons.computeIfAbsent(analyzer, k -> new LinkedHashSet<>()).add(reason);
        }
    }

    private static final class ScoredTask {
        double score;
        final AuditTarget nodeTarget;
        final String nodeId;
        final String nodeLabel;
        final DiagnosisKind diagnosisKind;
        String analyzer;
        boolean hasOrigin;
        Finding ownFinding;
        CefrLevel level;
        String knowledgeId;
        String knowledgeLabel;
        final List<String> reachedQuizIds = new ArrayList<>();
        final List<Finding> coveredFindings = new ArrayList<>();

        ScoredTask(double score, AuditTarget nodeTarget, String nodeId,
                   String nodeLabel, DiagnosisKind diagnosisKind) {
            this.score = score;
            this.nodeTarget = nodeTarget;
            this.nodeId = nodeId;
            this.nodeLabel = nodeLabel;
            this.diagnosisKind = diagnosisKind;
        }

        TaskOrigin origin() {
            if (!hasOrigin) {
                return null;
            }
            return new TaskOrigin(ownFinding, level, knowledgeId, knowledgeLabel, new ArrayList<>(reachedQuizIds),
                    new ArrayList<>(coveredFindings));
        }
    }

