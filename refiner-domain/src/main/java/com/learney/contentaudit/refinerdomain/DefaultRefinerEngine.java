    @Override
    public RefinementPlan plan(AuditReport report, String auditId) {
        Classification classification = classify(report);

        List<ScoredTask> rawTasks = new ArrayList<>(classification.tasks);
        // Stable: equal scores keep the order of the walk.
        rawTasks.sort(Comparator.comparingDouble(t -> t.score));

        List<RefinementTask> tasks = new ArrayList<>();
        for (int i = 0; i < rawTasks.size(); i++) {
            ScoredTask st = rawTasks.get(i);
            String taskId = String.format("task-%03d", i + 1);
            tasks.add(new RefinementTask(
                    taskId,
                    st.nodeTarget,
                    st.nodeId,
                    st.nodeLabel,
                    st.diagnosisKind,
                    i + 1,
                    RefinementTaskStatus.PENDING, st.origin()
            ));
        }

        String planId = TIMESTAMP_FORMATTER.format(Instant.now());

        return new RefinementPlan(planId, auditId != null ? auditId : "", Instant.now(), tasks);
    }

    @Override
    public Optional<RefinementTask> nextTask(RefinementPlan plan) {
        if (plan.getTasks() == null) {
            return Optional.empty();
        }
        // Only a pending task: never one of the open batch (IN_BATCH, F-TANDA-R002), nor a stale one.
        return plan.getTasks().stream()
                .filter(t -> t.getStatus() == RefinementTaskStatus.PENDING)
                .findFirst();
    }

    /**
     * F-HALL-R004 inv. 3: in the errors family the plan never drops a score below 1 in silence. Every node an errors
     * analyzer evaluated below 1 that {@link #plan} does not turn into tasks is declared here, per analyzer: it has no
     * task kind, its task kind is not a {@link DiagnosisKind} the plan knows, or its binding makes no tasks on that level
     * -- or it is covered by the task another analyzer makes on the same node, as off-level-words by the LEMMA_ABSENCE of
     * the quiz (F-NIVFR-R006, F-RONDA1-R008). The vocabulary family keeps today's plan and is not declared (F-HALL-R013).
     * It counts nodes; {@link #findingTally} counts findings.
     */
    @Override
    public List<UnconvertedScoreCount> unconvertedScores(AuditReport report) {
        List<UnconvertedScoreCount> result = new ArrayList<>();
        if (report == null || report.getRoot() == null) {
            return result;
        }
        for (AnalyzerDescriptor card : analyzerCatalog.list()) {
            if (card.getFamily() != AnalyzerFamily.ERRORS) {
                continue;
            }
            Optional<AnalyzerPlanBinding> binding = analyzerCatalog.planBinding(card.getName());
            Map<String, Integer> countsByReason = new LinkedHashMap<>();
            countUnconverted(report.getRoot(), card, binding, countsByReason);
            for (Map.Entry<String, Integer> entry : countsByReason.entrySet()) {
                result.add(new UnconvertedScoreCount(card.getName(), entry.getValue(), entry.getKey()));
            }
        }
        return result;
    }

    /**
     * F-TAREA-R001: per analyzer of errors with findings that count, in catalog order, how many findings count and how
     * they add up: own tasks of the plan, findings covered by a task of the plan, and unconverted, with the reason. The
     * findings come from the report; the tasks and the covered findings, from the plan.
     */
    @Override
    public List<PlanFindingTally> findingTally(AuditReport report, RefinementPlan plan) {
        List<PlanFindingTally> result = new ArrayList<>();
        if (report == null || report.getRoot() == null) {
            return result;
        }
        Classification classification = classify(report);
        Map<String, Integer> own = new HashMap<>();
        Map<String, Set<String>> covered = new HashMap<>();
        if (plan != null && plan.getTasks() != null) {
            for (RefinementTask task : plan.getTasks()) {
                TaskOrigin origin = task.getOrigin();
                if (origin == null) {
                    continue;
                }
                if (origin.getFinding() != null && isErrorsAnalyzer(origin.getFinding().getAnalyzer())) {
                    own.merge(origin.getFinding().getAnalyzer(), 1, Integer::sum);
                }
                if (origin.getCoveredFindings() != null) {
                    for (Finding finding : origin.getCoveredFindings()) {
                        if (finding != null && isErrorsAnalyzer(finding.getAnalyzer())) {
                            covered.computeIfAbsent(finding.getAnalyzer(), k -> new LinkedHashSet<>())
                                    .add(identityKey(finding));
                        }
                    }
                }
            }
        }
        for (AnalyzerDescriptor card : analyzerCatalog.list()) {
            String name = card.getName();
            int counting = classification.counting.getOrDefault(name, 0);
            if (card.getFamily() != AnalyzerFamily.ERRORS || counting == 0) {
                continue;
            }
            int ownTasks = own.getOrDefault(name, 0);
            int coveredCount = covered.getOrDefault(name, Set.of()).size();
            int unconverted = Math.max(0, counting - ownTasks - coveredCount);
            Set<String> reasons = classification.unconvertedReasons.getOrDefault(name, new LinkedHashSet<>());
            String reason = unconverted == 0 ? null : (reasons.isEmpty() ? null : String.join("; ", reasons));
            result.add(new PlanFindingTally(name, counting, ownTasks, coveredCount, unconverted, reason));
        }
        return result;
    }

