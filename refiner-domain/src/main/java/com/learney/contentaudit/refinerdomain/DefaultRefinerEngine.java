/**
 * Default implementation of {@link RefinerEngine}.
 *
 * <p><b>Vocabulary, as before</b> (F-TAREA-R007, F-HALL-R013): it walks the AuditNode tree and emits a
 * {@link RefinementTask} for each analyzer score below 1.0 (F-RCLA-R001) on a level where that analyzer's plan binding
 * makes tasks -- one per node and analyzer, whatever the number of words it marks.
 *
 * <p><b>Errors, one task per finding</b> (FEAT-TAREA): an analyzer of the errors family turns each of its findings that
 * counts (it does not only rank, F-TAREA-R005) into exactly one of three outcomes (F-TAREA-R001): a task of its own,
 * carrying the finding in its {@link TaskOrigin} (R002); covered by another task -- the one of the analyzer its
 * declaration names as cover, on the same exercise (R004) --, listed in that task's origin; or unconverted, with the
 * reason, in {@link #findingTally}. The findings that a declaration groups by topic (the mini theory, R003) make one task
 * per analyzer, mark and topic, on the topic, that owns the first and covers the rest. Without a catalog of corrections
 * nothing is grouped nor covered by a declaration.
 *
 * <p><b>Order</b> (R002, R008): every task keeps the score of its analyzer on its node (a topic task, the lowest of the
 * exercises it reaches) and the plan is a stable sort by it, so the tasks of the same score keep the order of the walk,
 * and within a node the order of its scores and of its findings. Two plans of the same analysis give the same tasks, the
 * same identities and the same order; the priorities are 1, 2, 3… in that order.
 */
