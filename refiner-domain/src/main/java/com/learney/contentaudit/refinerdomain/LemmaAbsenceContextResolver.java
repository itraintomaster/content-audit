    private Optional<AuditNode> findNode(AuditNode node, String nodeId, AuditTarget nodeTarget) {
        if (node == null) {
            return Optional.empty();
        }
        AuditableEntity entity = node.getEntity();
        if (node.getTarget() == nodeTarget
                && entity != null
                && nodeId != null
                && nodeId.equals(entity.getId())) {
            return Optional.of(node);
        }
        List<AuditNode> children = node.getChildren();
        if (children != null) {
            for (AuditNode child : children) {
                Optional<AuditNode> found = findNode(child, nodeId, nodeTarget);
                if (found.isPresent()) {
                    return found;
                }
            }
        }
        return Optional.empty();
    }

