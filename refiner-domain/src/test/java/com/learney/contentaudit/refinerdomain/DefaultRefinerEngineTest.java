    /**
     * Builds an AuditNode with the given target, id, label, and scores.
     * Children and parent are wired separately by the caller.
     */
    private AuditNode buildNode(AuditTarget target, String id, String label, Map<String, Double> scores) {
        AuditNode node = new AuditNode();
        node.setTarget(target);
        node.setScores(scores);
        node.setChildren(Collections.emptyList());
        // Sin entidad, el motor resuelve todo nodo al id "root" y las tareas de
        // nodos distintos se vuelven indistinguibles. Los tests que verifican
        // QUE nodo quedo tareado necesitan que el id sea real.
        node.setEntity(new AuditableEntity() {
            @Override
            public String getId() {
                return id;
            }

            @Override
            public String getLabel() {
                return label;
            }

            @Override
            public String getCode() {
                return id;
            }
        });
        return node;
    }

    /**
     * Links parent → children and sets parent back-pointers so the tree is fully wired.
     */
    private void link(AuditNode parent, List<AuditNode> children) {
        parent.setChildren(children);
        for (AuditNode child : children) {
            child.setParent(parent);
        }
    }

