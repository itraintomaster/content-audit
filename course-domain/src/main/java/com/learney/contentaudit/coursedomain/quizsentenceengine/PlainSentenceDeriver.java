    /**
     * Returns true when {@code text} is a scaffold sentence: non-blank text that ends with
     * sentence-terminal punctuation (., ?, !), possibly followed by whitespace.
     */
    private boolean isScaffoldSentence(String text) {
        if (text == null || text.isBlank()) {
            return false;
        }
        return SENTENCE_END_PATTERN.matcher(text).matches();
    }

    /**
     * Derives all plain sentences from {@code form.sentenceParts}.
     *
     * @param form the form to derive sentences from
     * @return ordered list; index 0 is the canonical variant
     * @throws QuizSentenceSerializationException if the sentenceParts violate the convention
     */
    List<String> derive(FormEntity form) {
        if (form == null || form.getSentenceParts() == null || form.getSentenceParts().isEmpty()) {
            return List.of();
        }

        List<SentencePartEntity> parts = form.getSentenceParts();

        // Collect TEXT segments (with hints stripped) and CLOZE variant lists in order
        List<String> textSegments = new ArrayList<>();    // interleaved with clozeVariants
        List<List<String>> clozeVariants = new ArrayList<>();
        // We build a "template" as alternating text/cloze indices.
        // Strategy: build a flat structure as (text | cloze-placeholder)* and then expand.

        // Validate and collect
        for (int i = 0; i < parts.size(); i++) {
            SentencePartEntity part = parts.get(i);
            if (part.getKind() == SentencePartKind.TEXT) {
                // R003 – TEXT must not have options
                if (part.getOptions() != null && !part.getOptions().isEmpty()) {
                    throw new QuizSentenceSerializationException(
                            "El TEXT de indice " + i + " trae options; los TEXT no pueden tener options",
                            String.valueOf(i));
                }
            } else if (part.getKind() == SentencePartKind.CLOZE) {
                // R004 – CLOZE must have at least one option
                if (part.getOptions() == null || part.getOptions().isEmpty()) {
                    throw new QuizSentenceSerializationException(
                            "El CLOZE de indice " + i
                                    + " no tiene options; un CLOZE requiere al menos una respuesta aceptada",
                            String.valueOf(i));
                }
                clozeVariants.add(flattenVariants(part.getOptions()));
            }
        }

        // Build the combinatorial set.
        // We iterate over all combinations of one variant per CLOZE.
        if (clozeVariants.isEmpty()) {
            // Pure-text form: one sentence, no CLOZE
            String sentence = buildSentenceFromParts(parts, new int[0]);
            return List.of(sentence);
        }

        // Compute total combinations
        int total = 1;
        for (List<String> variants : clozeVariants) {
            total *= variants.size();
        }

        List<String> result = new ArrayList<>(total);
        int[] indices = new int[clozeVariants.size()]; // all zeros → canonical combination

        for (int combo = 0; combo < total; combo++) {
            String sentence = buildSentenceFromParts(parts, indices);
            result.add(sentence);
            // Advance indices (least-significant = last CLOZE, like odometer)
            advanceIndices(indices, clozeVariants);
        }

        return result;
    }

