    /**
     * Builds one plain sentence by substituting CLOZE parts with their chosen variant and
     * stripping hints from TEXT parts.
     *
     * @param parts    the sentenceParts of the form
     * @param indices  for each CLOZE (in order of appearance), the chosen variant index
     */
    private String buildSentenceFromParts(List<SentencePartEntity> parts, int[] indices) {
        StringBuilder sb = new StringBuilder();
        int clozeIdx = 0;
        boolean firstTokenEmitted = false;

        for (SentencePartEntity part : parts) {
            String token;
            if (part.getKind() == SentencePartKind.TEXT) {
                String text = part.getText();
                if (text == null || text.isEmpty()) {
                    continue;
                }
                // Strip hints (R019)
                token = HINT_PATTERN.matcher(text).replaceAll("");
            } else if (part.getKind() == SentencePartKind.CLOZE) {
                List<String> flat = flattenVariants(part.getOptions());
                token = flat.get(indices[clozeIdx]);
                clozeIdx++;
            } else {
                continue;
            }

            // Insert canonical single space between emitted tokens; the final
            // whitespace-normalize step collapses any duplicates the raw TEXT
            // may have contributed at the boundary.
            if (firstTokenEmitted) {
                sb.append(' ');
            }
            sb.append(token);
            firstTokenEmitted = true;
        }

        // Normalize whitespace (R019): collapse runs, trim
        return whitespaceNormalizer.normalize(sb.toString());
    }
