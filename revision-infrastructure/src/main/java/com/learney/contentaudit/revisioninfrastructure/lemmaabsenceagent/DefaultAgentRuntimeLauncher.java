/**
 * In-process sentinel-agents runtime launcher.
 *
 * <p><strong>Adapter↔graph contract (launcher side):</strong>
 * <ul>
 *   <li>Agent graph directory: {@code .sentinel/agents/<agentName>/} (relative to CWD)</li>
 *   <li>The graph's entry-point node is loaded via {@link AgentLoader#loadFromDirectory(Path)}</li>
 *   <li>{@link AgentRun#run(Node, Map, ExecutionContext)} executes the graph in-process</li>
 *   <li>No gates, no scripts, no child coordinators: everything is handled declaratively
 *       inside the graph YAML/Markdown files</li>
 * </ul>
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
class DefaultAgentRuntimeLauncher implements AgentRuntimeLauncher {

    /**
     * Root directory for agent definitions relative to the project root.
     * Agent {@code <name>} is expected at {@code .sentinel/agents/<name>/}.
     */
    private static final String AGENTS_BASE_DIR = ".sentinel/agents";

    private static final DateTimeFormatter RUN_ID_FMT =
            DateTimeFormatter.ofPattern("yyyyMMdd'T'HHmmss").withZone(ZoneOffset.UTC);

    @Override
    public RunState launch(String agentName, Map<String, String> inputs, ChatModel chatModel,
            Map<String, Object> tools) {
        Path agentDir = Paths.get(AGENTS_BASE_DIR, agentName).toAbsolutePath();
        Node entryNode = AgentLoader.loadFromDirectory(agentDir);

        String runId = RUN_ID_FMT.format(Instant.now()) + "-" + UUID.randomUUID().toString().substring(0, 8);
        Path runDir = Paths.get(".sentinel", "runs", agentName, runId).toAbsolutePath();

        RunPersistence persistence = new RunPersistence(
                runDir, runId, agentName, "", null, java.util.Map.of());

        Map<String, String> enriched = new LinkedHashMap<>(inputs != null ? inputs : Collections.emptyMap());
        enriched.put("run_dir", runDir.toString());

        ExecutionContext ctx = new ExecutionContext(
                chatModel,
                tools != null ? tools : Collections.emptyMap(),
                Collections.emptyMap(),   // gates  — handled declaratively in the graph
                Collections.emptyMap(),   // scripts — handled declaratively in the graph
                runDir,                   // workDir = run-dir so graph scripts resolve artifacts by abs path
                new NodeRunners()         // default dispatcher (no custom runners)
        );

        RunState state;
        try {
            // Stream both observability channels live to the run log: framework
            // events AND the llm_request/llm_response roundtrip transcripts. The
            // roundtrips never enter RunState, so a plain AgentRun.run + a
            // post-hoc writeEvents(state) would lose every transcript — only
            // this live sink captures them. The ChatModel must carry a
            // FrameworkLlmListener (wired in DefaultLemmaAbsenceAgentGeneratorFactory).
            state = AgentRun.runRecording(
                    entryNode, enriched, ctx,
                    (event, stateAfter) -> persistence.appendFrameworkEvent(event),
                    persistence::appendEvent);
        } catch (RuntimeException e) {
            persistence.finish("failed", java.util.Map.of(
                    "halted", true,
                    "haltReason", String.valueOf(e.getMessage())));
            throw e;
        }
        persistence.writeState(state);
        boolean halted = state.runStatus().name().equals("HALTED");
        persistence.finish(halted ? "failed" : "completed", RunPersistence.outcomeOf(state));
        return state;
    }
}
