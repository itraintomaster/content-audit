    private static Map<String, String> buildInputs(QuizInstructionGenerationRequest request) {
        QuizInstructionCorrectionContext context = request.getContext();
        Map<String, String> inputs = new LinkedHashMap<>();

        if (context == null) {
            inputs.put("taskId", "");
            inputs.put("cefrLevel", "");
            inputs.put("topicLabel", "");
            inputs.put("knowledgeTitle", "");
            inputs.put("knowledgeInstructions", "");
            inputs.put("quizSentence", "");
            inputs.put("sentence", "");
            inputs.put("translation", "");
            inputs.put("sentenceMode", "");
            inputs.put("violations", "");
            inputs.put("verdictReason", "");
            inputs.put("siblingQuizzes", "");
        } else {
            inputs.put("taskId", orEmpty(context.getTaskId()));
            String cefrLevel = context.getCefrLevel() != null
                    ? context.getCefrLevel().name()
                    : orEmpty(context.getCefrLevelLabel());
            inputs.put("cefrLevel", cefrLevel);
            inputs.put("topicLabel", orEmpty(context.getTopicLabel()));
            inputs.put("knowledgeTitle", orEmpty(context.getKnowledgeTitle()));
            inputs.put("knowledgeInstructions", orEmpty(context.getKnowledgeInstructions()));
            inputs.put("quizSentence", orEmpty(context.getQuizSentence()));
            inputs.put("sentence", orEmpty(context.getSentence()));
            inputs.put("translation", orEmpty(context.getTranslation()));
            inputs.put("sentenceMode",
                    context.getSentenceMode() != null ? context.getSentenceMode().name() : "");
            inputs.put("violations", formatViolations(context.getViolations()));
            inputs.put("verdictReason", orEmpty(context.getVerdictReason()));
            inputs.put("siblingQuizzes", formatLines(context.getSiblingQuizSentences()));
        }

        // F-QICOR-R015: the graph's `assess` node needs the plan id to call
        // `content-audit assess-candidate --plan <planId> --task <taskId> ...` without the
        // original quiz travelling through the agent and back (see assess.sh).
        // QuizInstructionCorrectionContext.planId is stamped by DefaultRevisionEngine right
        // after resolving the context (mirrors the identical, already-established pattern
        // for sourceAuditId), so it is simply flattened here -- never guessed. A context
        // whose planId was never stamped (context == null, or a context resolved outside
        // that path) sends the field empty rather than a fabricated value, so assess.sh's
        // own "faltan planId/taskId" fallback (an infrastructure failure, never a fabricated
        // verdict) is what actually happens instead of a silently wrong one.
        inputs.put("planId", context != null ? orEmpty(context.getPlanId()) : "");
        inputs.put("maxAttempts", String.valueOf(request.getMaxAttempts()));

        return inputs;
    }

    private static String formatViolations(List<InstructionViolation> violations) {
        if (violations == null || violations.isEmpty()) {
            return "";
        }
        return violations.stream()
                .map(v -> "- " + orEmpty(v.getConstraint()) + " | evidencia: \""
                        + orEmpty(v.getEvidence()) + "\" | " + orEmpty(v.getExplanation()))
                .collect(Collectors.joining("\n"));
    }

    private static String formatLines(List<String> lines) {
        if (lines == null || lines.isEmpty()) {
            return "";
        }
        return lines.stream()
                .filter(s -> s != null && !s.isBlank())
                .collect(Collectors.joining("\n"));
    }

    private static String orEmpty(String value) {
        return value != null ? value : "";
    }
