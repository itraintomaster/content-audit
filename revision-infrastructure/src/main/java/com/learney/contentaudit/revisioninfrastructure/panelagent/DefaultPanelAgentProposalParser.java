        String topicInstructions = text(node, "topicInstructions");
        if (kind == PanelCandidateKind.MINI_THEORY) {
            String miniTheory = text(node, "miniTheory");
            return miniTheory == null ? null : new PanelCandidate(kind, null, miniTheory, topicInstructions, rationale);
        }
