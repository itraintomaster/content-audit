        MultipleChoiceEntity choice = choice(node.path("options"));
        if (!parts.isEmpty() || choice != null) {
            String formKind = choice != null ? "MULTIPLE_CHOICE" : "CLOZE";
            quiz.setKind(formKind);
            quiz.setForm(new FormEntity(formKind, 1.0, "", "", parts, choice, null));
        }
        return new PanelCandidate(kind, quiz, null, topicInstructions, rationale);
