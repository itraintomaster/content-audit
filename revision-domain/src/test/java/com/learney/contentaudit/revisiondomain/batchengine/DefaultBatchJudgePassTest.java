    private static BatchJudgeAccount account(List<BatchJudgeAccount> accounts, String judge) {
        for (BatchJudgeAccount account : accounts) {
            if (judge.equals(account.getJudge())) {
                return account;
            }
        }
        throw new AssertionError("no account for " + judge + " among " + judgesOf(accounts));
    }

    private static List<String> judgesOf(List<BatchJudgeAccount> accounts) {
        return accounts.stream().map(BatchJudgeAccount::getJudge).toList();
    }

    /** The keys of both sides, sorted, as {@code consulted} gives them. */
    private static List<String> both(List<String> before, List<String> after) {
        List<String> keys = new ArrayList<>(before);
        keys.addAll(after);
        Collections.sort(keys);
        return keys;
    }

    /** What the coverage reused of the ledger, over all the evaluators of the judge. */
    private static int reused(JudgeCoverageDiagnosis coverage) {
        return coverage.getEvaluators().stream().mapToInt(evaluator -> evaluator.getCoverage().getReused()).sum();
    }
