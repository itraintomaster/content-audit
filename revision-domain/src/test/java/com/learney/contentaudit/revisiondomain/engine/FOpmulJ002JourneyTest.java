    /** The plan store keeps the last plan saved, so each step and each run sees the previous one's result. */
    private static final class InMemoryPlanStore implements RefinementPlanStore {
        private final Map<String, RefinementPlan> plans = new HashMap<>();
        private RefinementPlan latest;

        private InMemoryPlanStore(RefinementPlan plan) {
            save(plan);
        }

        @Override
        public String save(RefinementPlan plan) {
            plans.put(plan.getId(), plan);
            latest = plan;
            return plan.getId();
        }

        @Override
        public Optional<RefinementPlan> load(String id) {
            return Optional.ofNullable(plans.get(id));
        }

        @Override
        public Optional<RefinementPlan> loadLatest() {
            return Optional.ofNullable(latest);
        }
    }
