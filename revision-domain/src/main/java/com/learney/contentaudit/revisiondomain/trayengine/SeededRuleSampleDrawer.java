/**
 * F-BANDEJA-R004: the sample of a rule, the same every time. Its changes still in the batch, in the order of their ids,
 * shuffled with a seed made of the id of the batch and of the rule: the same batch shows the same 20 of its 170 changes of
 * capital letters each time José opens the tray, and another batch other 20. A rule with fewer shows them all, in order.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
class SeededRuleSampleDrawer implements RuleSampleDrawer {
    @Override
    public List<BatchChange> draw(CorrectionBatch batch, String ruleId, int size) {
        List<BatchChange> ofTheRule = new ArrayList<>();
        for (BatchChange change : batch != null && batch.getChanges() != null ? batch.getChanges()
                : List.<BatchChange>of()) {
            if (change != null && change.getDroppedReason() == null && change.getOrigin() == BatchChangeOrigin.RULE
                    && Objects.equals(change.getRuleId(), ruleId)) {
                ofTheRule.add(change);
            }
        }
        ofTheRule.sort(Comparator.comparing(c -> String.valueOf(c.getChangeId())));
        if (size <= 0) {
            return new ArrayList<>();
        }
        if (ofTheRule.size() <= size) {
            return ofTheRule;
        }
        Collections.shuffle(ofTheRule, new Random(seed(batch.getId(), ruleId)));
        List<BatchChange> drawn = new ArrayList<>(ofTheRule.subList(0, size));
        drawn.sort(Comparator.comparing(c -> String.valueOf(c.getChangeId())));
        return drawn;
    }

    /** A seed that depends only on the batch and the rule, the same in every run of the JVM. */
    static long seed(String batchId, String ruleId) {
        try {
            byte[] digest = MessageDigest.getInstance("SHA-256")
                    .digest((batchId + "\u0000" + ruleId).getBytes(StandardCharsets.UTF_8));
            long seed = 0;
            for (int i = 0; i < 8; i++) {
                seed = (seed << 8) | (digest[i] & 0xff);
            }
            return seed;
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException("SHA-256 is part of every JVM", e);
        }
    }
}
