    private UnitMeasurement measurement(TopicWork work, KnowledgeEntity topic, AuditReport report) {
        CefrLevel level = work.getLevel();
        List<Finding> findings = new ArrayList<>();
        List<UnevaluatedMark> unevaluated = new ArrayList<>();
        List<RedWord> redWords = new ArrayList<>();
        List<SpokenText> spokenTexts = new ArrayList<>();
        List<LengthDeclaration> lengths = new ArrayList<>();
        Optional<AuditNode> found = knowledgeNode(report, topic.getId());
        if (found.isEmpty()) {
            return new UnitMeasurement(level, findings, unevaluated, redWords, spokenTexts, lengths);
        }
        AuditNode knowledgeNode = found.get();
        collect(knowledgeNode, findings, unevaluated);
        Set<String> taught = taught(knowledgeNode);
        SentenceMode mode = knowledgeNode.getEntity() instanceof AuditableKnowledge knowledge
                ? knowledge.getSentenceMode() : topic.getSentenceMode();
        boolean isSentence = !(knowledgeNode.getEntity() instanceof AuditableKnowledge knowledge)
                || knowledge.isIsSentence();
        Optional<TargetRange> range = level != null && sentenceLengthConfig != null
                ? sentenceLengthConfig.getTargetRange(level) : Optional.empty();

        Map<String, String> optionSentences = new LinkedHashMap<>();
        for (AuditNode quizNode : knowledgeNode.getChildren() != null ? knowledgeNode.getChildren() : List.<AuditNode>of()) {
            if (!(quizNode.getEntity() instanceof AuditableQuiz quiz)) {
                continue;
            }
            collect(quizNode, findings, unevaluated);
            String sentence = quiz.getSentences() != null && !quiz.getSentences().isEmpty()
                    ? quiz.getSentences().get(0) : quiz.getQuizSentence();
            redWords.addAll(redWords(quiz.getId(), quiz.getTokens(), level, sentence, taught));
            if (spokenTextBuilder != null) {
                spokenTexts.add(new SpokenText(quiz.getId(), quiz.getAnswerAudioKey(),
                        new ArrayList<>(spokenTextBuilder.spokenTexts(quiz, mode))));
            }
            if (isSentence && range.isPresent()) {
                // F-SMODE-R004: the length the analyzer counted -- a rewrite exercise, on its answer alone -- when it ran.
                int tokens = quizNode.getDiagnoses() instanceof DefaultQuizDiagnoses diagnoses
                        && diagnoses.getSentenceLengthDiagnosis().isPresent()
                        ? diagnoses.getSentenceLengthDiagnosis().get().getTokenCount()
                        : quiz.getTokens() != null ? quiz.getTokens().size() : 0;
                int min = range.get().getMinTokens();
                int max = range.get().getMaxTokens();
                lengths.add(new LengthDeclaration(quiz.getId(), tokens, min, max, tokens >= min && tokens <= max));
            }
            for (String option : optionSentences(quiz)) {
                optionSentences.put(quiz.getId() + "\u0000" + option, option);
            }
        }
        // F-MESA-R011: each option put in the gap of a multiple choice is a sentence of its own.
        if (!optionSentences.isEmpty() && nlpTokenizer != null) {
            Map<String, List<NlpToken>> tokens = nlpTokenizer.analyzeTokensBatch(new ArrayList<>(
                    new java.util.LinkedHashSet<>(optionSentences.values())));
            for (Map.Entry<String, String> entry : optionSentences.entrySet()) {
                String quizId = entry.getKey().substring(0, entry.getKey().indexOf('\u0000'));
                redWords.addAll(redWords(quizId, tokens != null ? tokens.get(entry.getValue()) : null, level,
                        entry.getValue(), taught));
            }
        }
        return new UnitMeasurement(level, findings, unevaluated, redWords, spokenTexts, lengths);
    }

    private static Optional<AuditNode> knowledgeNode(AuditReport report, String knowledgeId) {
        if (report == null || report.getRoot() == null) {
            return Optional.empty();
        }
        List<AuditNode> pending = new ArrayList<>(List.of(report.getRoot()));
        while (!pending.isEmpty()) {
            AuditNode node = pending.remove(0);
            if (node.getTarget() == AuditTarget.KNOWLEDGE && node.getEntity() != null
                    && (knowledgeId == null || knowledgeId.equals(node.getEntity().getId()))) {
                return Optional.of(node);
            }
            if (node.getChildren() != null) {
                pending.addAll(node.getChildren());
            }
        }
        return Optional.empty();
    }

    private static void collect(AuditNode node, List<Finding> findings, List<UnevaluatedMark> unevaluated) {
        if (node.getFindings() != null) {
            findings.addAll(node.getFindings());
        }
        String id = node.getEntity() != null ? node.getEntity().getId() : null;
        Set<String> marked = new HashSet<>();
        for (List<String> names : List.of(node.getUnevaluatedBy() != null ? node.getUnevaluatedBy() : List.<String>of(),
                node.getPartiallyEvaluatedBy() != null ? node.getPartiallyEvaluatedBy() : List.<String>of())) {
            for (String analyzer : names) {
                if (marked.add(analyzer)) {
                    unevaluated.add(new UnevaluatedMark(id, analyzer));
                }
            }
        }
    }

    /** The words the topic teaches, which are never red in it (F-SEMAF-R004). */
    private Set<String> taught(AuditNode knowledgeNode) {
        Set<String> taught = new HashSet<>();
        if (topicTeachingResolver == null) {
            return taught;
        }
        TaughtWords words = topicTeachingResolver.taughtWords(knowledgeNode);
        if (words == null) {
            return taught;
        }
        for (List<String> list : List.of(words.getTitleTerms() != null ? words.getTitleTerms() : List.<String>of(),
                words.getFrequentAnswers() != null ? words.getFrequentAnswers() : List.<String>of())) {
            for (String term : list) {
                java.util.regex.Matcher m = WORD.matcher(term != null ? term.toLowerCase(Locale.ROOT) : "");
                while (m.find()) {
                    taught.add(m.group());
                }
            }
        }
        return taught;
    }

    private List<RedWord> redWords(String quizId, List<NlpToken> tokens, CefrLevel level, String sentence,
            Set<String> taught) {
        List<RedWord> red = new ArrayList<>();
        if (lexicalEvaluator == null || tokens == null || tokens.isEmpty() || level == null) {
            return red;
        }
        SentenceLexicalFlags flags = lexicalEvaluator.evaluate(tokens, level);
        if (flags == null) {
            return red;
        }
        for (MisplacedWordFlag word : flags.getMisplacedWords() != null ? flags.getMisplacedWords()
                : List.<MisplacedWordFlag>of()) {
            if (word != null && word.getLemma() != null && !taught.contains(word.getLemma().toLowerCase(Locale.ROOT))) {
                red.add(new RedWord(quizId, word.getLemma(), word.getExpectedLevel(), false, sentence));
            }
        }
        for (OutOfCatalogFlag word : flags.getOutOfCatalogWords() != null ? flags.getOutOfCatalogWords()
                : List.<OutOfCatalogFlag>of()) {
            if (word != null && word.getLemma() != null && !taught.contains(word.getLemma().toLowerCase(Locale.ROOT))) {
                red.add(new RedWord(quizId, word.getLemma(), null, true, sentence));
            }
        }
        return red;
    }

    /** The statement with each option that is not the correct one put in the gap. */
    private static List<String> optionSentences(AuditableQuiz quiz) {
        List<String> sentences = new ArrayList<>();
        if (quiz.getMultipleChoice() == null || quiz.getMultipleChoice().getItems() == null
                || quiz.getSentenceParts() == null) {
            return sentences;
        }
        for (MultipleChoiceItemEntity item : quiz.getMultipleChoice().getItems()) {
            if (item == null || item.getLabel() == null || item.getIncidence() > 0.0) {
                continue;
            }
            StringBuilder sb = new StringBuilder();
            for (SentencePartEntity part : quiz.getSentenceParts()) {
                if (part == null) {
                    continue;
                }
                if (part.getKind() == SentencePartKind.CLOZE) {
                    sb.append(' ').append(item.getLabel());
                } else if (part.getText() != null) {
                    sb.append(' ').append(part.getText().replaceAll("\\([^)]*\\)", " "));
                }
            }
            String sentence = sb.toString().replaceAll("\\s+", " ").replaceAll("\\s+([.?!,;:])", "$1").strip();
            if (!sentence.isEmpty()) {
                sentences.add(sentence);
            }
        }
        return sentences;
    }
