/**
 * F-BANDEJA-R006: what José decided on a tie or an exercise without winner is kept with the identity of the finding and
 * the fingerprint of the exercise as the student sees it -- its instructions, its statement with its gaps and answers,
 * its options, its translation and its mini theory --, by the same fingerprinter as the ledger of evaluations
 * (F-EVCOST-R001). While that content does not change the question does not come back, in any batch or analysis; once
 * it changes, the fingerprint is another one and it may.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
class FingerprintDecisionMemory implements DecisionMemory {
    private final TrayDecisionStore decisionStore;

    private final ContentFingerprinter contentFingerprinter;

    public FingerprintDecisionMemory(TrayDecisionStore decisionStore,
            ContentFingerprinter contentFingerprinter) {
        this.decisionStore = decisionStore;
        this.contentFingerprinter = contentFingerprinter;
    }

    @Override
    public Optional<RememberedDecision> recall(Finding finding, QuizTemplateEntity quiz) {
        if (finding == null || quiz == null || decisionStore == null) {
            return Optional.empty();
        }
        return decisionStore.recall(identityOf(finding), markerOf(finding), fingerprint(quiz));
    }

    @Override
    public void remember(Finding finding, QuizTemplateEntity quiz, TrayAnswer answer,
            String batchId) {
        if (finding == null || quiz == null || decisionStore == null) {
            return;
        }
        decisionStore.remember(new RememberedDecision(identityOf(finding), markerOf(finding), fingerprint(quiz), answer,
                batchId, Instant.now()));
    }

    /** The fingerprint of what the student sees of the exercise. */
    String fingerprint(QuizTemplateEntity quiz) {
        Map<String, String> content = new LinkedHashMap<>();
        content.put("instrucciones", String.valueOf(quiz.getInstructions()));
        List<String> parts = new ArrayList<>();
        if (quiz.getForm() != null && quiz.getForm().getSentenceParts() != null) {
            for (SentencePartEntity part : quiz.getForm().getSentenceParts()) {
                if (part != null) {
                    parts.add(part.getKind() + ":" + part.getText() + ":" + part.getOptions());
                }
            }
        }
        content.put("partes", String.join(" | ", parts));
        List<String> options = new ArrayList<>();
        if (quiz.getForm() != null && quiz.getForm().getMultipleChoice() != null
                && quiz.getForm().getMultipleChoice().getItems() != null) {
            for (MultipleChoiceItemEntity item : quiz.getForm().getMultipleChoice().getItems()) {
                if (item != null) {
                    options.add(item.getLabel() + ":" + item.getIncidence());
                }
            }
        }
        content.put("opciones", String.join(" | ", options));
        content.put("traduccion", String.valueOf(quiz.getTranslation()));
        content.put("miniteoria", String.valueOf(quiz.getMiniTheory()));
        return contentFingerprinter.fingerprint(content);
    }

    private static String identityOf(Finding finding) {
        if (finding.getIdentity() != null && finding.getIdentity().getKey() != null) {
            return finding.getIdentity().getKey();
        }
        return finding.getAnalyzer() + "|" + finding.getRule() + "|"
                + (finding.getNode() != null ? finding.getNode().getNodeId() : "");
    }

    private static String markerOf(Finding finding) {
        return finding.getIdentity() != null ? finding.getIdentity().getMarker() : null;
    }
}
