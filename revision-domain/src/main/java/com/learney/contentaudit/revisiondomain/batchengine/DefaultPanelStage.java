    private TopicWork work(CorrectionBatch batch, AuditReport start, BatchBook.Place place, List<RefinementTask> tasks) {
        KnowledgeEntity knowledge = place.knowledge();
        List<ErrorTaskBrief> briefs = new ArrayList<>();
        Map<String, Integer> attemptsUsed = new LinkedHashMap<>();
        List<CandidateRejection> carried = new ArrayList<>();
        for (RefinementTask task : tasks) {
            Optional<ErrorTaskBrief> brief = briefer != null ? briefer.brief(start, task) : Optional.empty();
            brief.ifPresent(briefs::add);
            Optional<BatchTaskOutcome> outcome = BatchBook.outcome(batch, task.getId());
            if (outcome.isPresent() && outcome.get().getAttempts() > 0) {
                String key = task.getNodeTarget() == AuditTarget.QUIZ ? task.getNodeId() : knowledge.getId();
                attemptsUsed.merge(key, outcome.get().getAttempts(), Math::max);
                if (outcome.get().getDetail() != null) {
                    carried.add(new CandidateRejection(outcome.get().getAttempts(), null,
                            new ArrayList<>(List.of(outcome.get().getDetail()))));
                }
            }
        }
        TopicWordLights lights = null;
        if (wordLightsQuery != null) {
            try {
                lights = wordLightsQuery.lightsFor(start, batch.getStartAuditId(), knowledge.getId(),
                        new SuggestedLemmaQueryCriteria(Optional.empty(), Optional.empty(), Optional.empty(), false,
                                Optional.empty()));
            } catch (RuntimeException e) {
                lights = null; // the panel works without the lights of a topic the analysis cannot give
            }
        }
        ConversionOrder conversion = null;
        for (ConversionOrder order : BatchBook.list(batch.getConversionOrders())) {
            if (order != null && knowledge.getId().equals(order.getKnowledgeId())) {
                conversion = order;
            }
        }
        return new TopicWork(batch.getId(), batch.getLevel(), place.milestone().getId(), place.topic().getId(), knowledge,
                knowledge.getSentenceMode(), briefs, lights, conversion, attemptsUsed, carried);
    }

    /** One decision of the panel into the batch: its outcomes and, when accepted, its change in the ledger. */
    private CorrectionBatch accept(CorrectionBatch batch, PanelDecision decision, CourseEntity course) {
        List<PanelDecision> decisions = BatchBook.copy(batch.getPanelDecisions());
        decisions.add(decision);
        batch.setPanelDecisions(decisions);
        String changeId = null;
        if (decision.getOutcome() == PanelOutcomeKind.ACCEPTED && decision.getAccepted() != null) {
            BatchChange change = change(batch, decision, course);
            if (!BatchBook.list(change.getSteps()).isEmpty()) {
                batch = changeLedger.record(batch, change, course);
                changeId = change.getChangeId();
            }
        }
        Set<String> resolved = new LinkedHashSet<>(BatchBook.list(decision.getResolvedTaskIds()));
        for (String taskId : BatchBook.list(decision.getTaskIds())) {
            BatchTaskOutcomeKind kind = switch (decision.getOutcome()) {
                case ACCEPTED -> resolved.contains(taskId) ? BatchTaskOutcomeKind.RESOLVED_BY_PANEL
                        : BatchTaskOutcomeKind.NO_WINNER;
                case NO_LONGER_HOLDS -> BatchTaskOutcomeKind.NO_LONGER_HOLDS;
                case NO_WINNER -> BatchTaskOutcomeKind.NO_WINNER;
                case TIE -> BatchTaskOutcomeKind.TIE;
                case NOT_ATTEMPTED -> BatchTaskOutcomeKind.NOT_ATTEMPTED;
                case NO_DECLARED_SCOPE -> BatchTaskOutcomeKind.NO_DECLARED_SCOPE;
            };
            String detail = kind == BatchTaskOutcomeKind.NO_WINNER && decision.getOutcome() == PanelOutcomeKind.ACCEPTED
                    ? "el candidato aceptado del ejercicio no la resolvió" : null;
            BatchBook.setOutcome(batch, taskId, kind, resolved.contains(taskId) ? changeId : null, decision.getAttempts(),
                    detail);
        }
        return batch;
    }

    /** The accepted candidate as steps on the exercises it reaches, over the course as the batch leaves it. */
    private BatchChange change(CorrectionBatch batch, PanelDecision decision, CourseEntity course) {
        PanelCandidate candidate = decision.getAccepted();
        CourseEntity composed = changeLedger.composedCourse(batch, course);
        List<BatchChangeStep> steps = BatchBook.stepsFor(composed, candidate, decision.getQuizIds(),
                decision.getKnowledgeId());
        BatchChangeOrigin origin = candidate.getKind() == PanelCandidateKind.MULTIPLE_CHOICE_CONVERSION
                ? BatchChangeOrigin.CONVERSION : BatchChangeOrigin.PANEL;
        String target = decision.getQuizIds() != null && decision.getQuizIds().size() == 1 ? decision.getQuizIds().get(0)
                : decision.getKnowledgeId();
        String changeId = BatchBook.freeChangeId(batch,
                (origin == BatchChangeOrigin.CONVERSION ? "conversion-" : "mesa-") + target);
        return new BatchChange(changeId, origin, null, decision.getKnowledgeId(),
                new ArrayList<>(BatchBook.list(decision.getResolvedTaskIds())), steps, decision.getAcceptedVerdict(), false,
                Instant.now(), null);
    }

    /** Whether José's order on a topic already got its outcomes in this batch. */
    private static boolean conversionDone(CorrectionBatch batch, String knowledgeId) {
        return BatchBook.list(batch.getPanelDecisions()).stream().anyMatch(d -> d != null
                && knowledgeId.equals(d.getKnowledgeId()) && d.getOutcome() != PanelOutcomeKind.NOT_ATTEMPTED
                && (d.getAccepted() != null && d.getAccepted().getKind() == PanelCandidateKind.MULTIPLE_CHOICE_CONVERSION
                        || d.getBestFailing() != null
                        && d.getBestFailing().getKind() == PanelCandidateKind.MULTIPLE_CHOICE_CONVERSION));
    }

    private static String topicOf(RefinementTask task, CourseEntity course) {
        String knowledge = BatchBook.knowledgeOf(task);
        if (knowledge != null) {
            return knowledge;
        }
        for (String quizId : BatchBook.quizzesOf(task)) {
            Optional<BatchBook.Place> place = BatchBook.place(course, quizId);
            if (place.isPresent()) {
                return place.get().knowledge().getId();
            }
        }
        return null;
    }
