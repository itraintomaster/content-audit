/**
 * F-QICOR-R004 criterio 2: the candidate must not introduce a misplaced or
 * out-of-catalog word the original did not already have. Preexisting flags
 * are NOT a reason to fail -- only NEW ones are (the rule's "los flags
 * preexistentes no bloquean" clause) -- so both sentences are measured with
 * the same {@link SentenceLexicalEvaluator} the audit uses (FEAT-CLEX) and the
 * candidate's flags are checked against the original's, not against zero.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
class LevelVocabularyCriterion implements CandidateCriterionEvaluator {
    private final SentenceLexicalEvaluator lexicalEvaluator;

    private final NlpTokenizer tokenizer;

    public LevelVocabularyCriterion(SentenceLexicalEvaluator lexicalEvaluator,
            NlpTokenizer tokenizer) {
        this.lexicalEvaluator = lexicalEvaluator;
        this.tokenizer = tokenizer;
    }

    @Override
    public CorrectionCriterion criterion() {
        return CorrectionCriterion.LEVEL_VOCABULARY;
    }

    @Override
    public CriterionVerdict evaluate(CandidateAssessmentInput input) {
        CefrLevel level = input.getCefrLevel();
        if (level == null) {
            return new CriterionVerdict(criterion(), CriterionOutcome.NOT_EVALUABLE,
                    "No se pudo evaluar el vocabulario: nivel CEFR no disponible");
        }

        CourseElementSnapshot originalSnapshot = input.getOriginal();
        CourseElementSnapshot candidateSnapshot = input.getCandidate();
        QuizTemplateEntity originalQuiz = originalSnapshot != null ? originalSnapshot.getQuiz() : null;
        QuizTemplateEntity candidateQuiz = candidateSnapshot != null ? candidateSnapshot.getQuiz() : null;
        if (originalQuiz == null || candidateQuiz == null) {
            return new CriterionVerdict(criterion(), CriterionOutcome.NOT_EVALUABLE,
                    "No se pudo comparar: falta el ejercicio original o el candidato");
        }

        List<NlpToken> originalTokens = tokenizer.analyzeTokens(canonicalSentence(originalQuiz));
        List<NlpToken> candidateTokens = tokenizer.analyzeTokens(canonicalSentence(candidateQuiz));
        SentenceLexicalFlags originalFlags = lexicalEvaluator.evaluate(originalTokens, level);
        SentenceLexicalFlags candidateFlags = lexicalEvaluator.evaluate(candidateTokens, level);

        Set<String> originalMisplacedKeys = new HashSet<>();
        for (MisplacedWordFlag flag : originalFlags.getMisplacedWords()) {
            originalMisplacedKeys.add(key(flag.getLemma(), flag.getPos()));
        }
        Set<String> originalOutOfCatalogKeys = new HashSet<>();
        for (OutOfCatalogFlag flag : originalFlags.getOutOfCatalogWords()) {
            originalOutOfCatalogKeys.add(key(flag.getLemma(), flag.getPos()));
        }

        for (MisplacedWordFlag flag : candidateFlags.getMisplacedWords()) {
            if (!originalMisplacedKeys.contains(key(flag.getLemma(), flag.getPos()))) {
                return new CriterionVerdict(criterion(), CriterionOutcome.FAILED,
                        "El candidato introduce la palabra '" + flag.getLemma()
                                + "' mal ubicada para el nivel " + level
                                + " (esperada en " + flag.getExpectedLevel() + ")");
            }
        }
        for (OutOfCatalogFlag flag : candidateFlags.getOutOfCatalogWords()) {
            if (!originalOutOfCatalogKeys.contains(key(flag.getLemma(), flag.getPos()))) {
                return new CriterionVerdict(criterion(), CriterionOutcome.FAILED,
                        "El candidato introduce la palabra fuera de catalogo '"
                                + flag.getLemma() + "'");
            }
        }

        return new CriterionVerdict(criterion(), CriterionOutcome.PASSED,
                "El candidato no introduce vocabulario nuevo mal ubicado ni fuera de catalogo");
    }

    private String canonicalSentence(QuizTemplateEntity quiz) {
        List<String> sentences = quiz.getSentences();
        return (sentences != null && !sentences.isEmpty()) ? sentences.get(0) : "";
    }

    private String key(String lemma, String pos) {
        return (lemma != null ? lemma : "") + "|" + (pos != null ? pos : "");
    }
}
