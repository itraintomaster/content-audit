    @Override
    public CorrectionBatch apply(CorrectionBatch batch, AuditReport start, CourseEntity course) {
        Map<String, RefinementTask> tasks = tasksOf(batch);
        // The pending tasks by rule of each exercise, in the order of the batch.
        Map<String, List<RefinementTask>> byExercise = new LinkedHashMap<>();
        for (String taskId : BatchBook.list(batch.getTaskIds())) {
            RefinementTask task = tasks.get(taskId);
            if (ContentCorrectionTasks.audioOnly(task)) continue;
            task = ContentCorrectionTasks.content(task);
            Optional<Finding> finding = BatchBook.findingOf(task);
            if (task == null || finding.isEmpty() || task.getNodeTarget() != AuditTarget.QUIZ
                    || finding.get().getResolution() != FindingResolution.RULE
                    || BatchBook.kind(batch, taskId) != BatchTaskOutcomeKind.PENDING
                    || BatchBook.outcome(batch, taskId).isPresent()) {
                continue;
            }
            byExercise.computeIfAbsent(task.getNodeId(), id -> new ArrayList<>()).add(task);
        }
        Set<String> withFix = ruleFixes != null
                ? ruleFixes.stream().map(RuleFix::analyzerName).collect(Collectors.toSet()) : Set.of();
        for (Map.Entry<String, List<RefinementTask>> entry : byExercise.entrySet()) {
            String quizId = entry.getKey();
            for (RefinementTask task : entry.getValue()) {
                if (!withFix.contains(BatchBook.findingOf(task).get().getAnalyzer())) {
                    BatchBook.setOutcome(batch, task.getId(), BatchTaskOutcomeKind.PENDING, null, null,
                            "a la mesa: su analizador no tiene un arreglo por regla");
                }
            }
            for (RuleFix fix : ruleFixes != null ? ruleFixes : List.<RuleFix>of()) {
                List<RefinementTask> mine = new ArrayList<>();
                for (RefinementTask task : entry.getValue()) {
                    if (fix.analyzerName().equals(BatchBook.findingOf(task).get().getAnalyzer())) {
                        mine.add(task);
                    }
                }
                if (!mine.isEmpty()) {
                    batch = fix(batch, start, course, quizId, fix, mine);
                    if (batchStore != null) {
                        batchStore.save(batch);
                    }
                }
            }
        }
        return batch;
    }

