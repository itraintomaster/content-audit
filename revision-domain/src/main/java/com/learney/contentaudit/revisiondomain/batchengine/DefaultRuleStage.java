    private CorrectionBatch fix(CorrectionBatch batch, AuditReport start, CourseEntity course, String quizId, RuleFix fix,
            List<RefinementTask> tasks) {
        CourseEntity current = changeLedger.composedCourse(batch, course);
        Optional<BatchBook.Place> place = BatchBook.place(current, quizId);
        if (place.isEmpty() || place.get().quiz() == null) {
            for (RefinementTask task : tasks) {
                BatchBook.setOutcome(batch, task.getId(), BatchTaskOutcomeKind.PENDING, null, null,
                        "a la mesa: el ejercicio no está en el curso");
            }
            return batch;
        }
        BatchBook.Place where = place.get();
        QuizTemplateEntity before = BatchBook.copy(where.quiz());
        AuditableQuiz analyzed = BatchBook.node(start, quizId).map(AuditNode::getEntity)
                .filter(AuditableQuiz.class::isInstance).map(AuditableQuiz.class::cast).orElse(null);
        Map<String, RefinementTask> byIdentity = new LinkedHashMap<>();
        List<Finding> findings = new ArrayList<>();
        for (RefinementTask task : tasks) {
            Finding finding = BatchBook.findingOf(task).get();
            findings.add(finding);
            byIdentity.put(BatchBook.identity(finding), task);
        }
        RuleFixResult result;
        try {
            result = fix.fix(new RuleFixRequest(BatchBook.copy(before), analyzed, where.knowledge().getSentenceMode(),
                    findings));
        } catch (RuntimeException e) {
            for (RefinementTask task : tasks) {
                BatchBook.setOutcome(batch, task.getId(), BatchTaskOutcomeKind.PENDING, null, null,
                        "a la mesa: la regla de " + fix.analyzerName() + " falló: " + e.getMessage());
            }
            return batch;
        }
        String detail = result.getDetail() != null ? result.getDetail() : "";
        List<RefinementTask> fixed = new ArrayList<>();
        for (FindingIdentity identity : BatchBook.list(result.getFixed())) {
            RefinementTask task = identity != null ? byIdentity.get(identity.getKey()) : null;
            if (task != null && !fixed.contains(task)) {
                fixed.add(task);
            }
        }
        for (RefinementTask task : tasks) {
            if (!fixed.contains(task)) {
                BatchBook.setOutcome(batch, task.getId(), BatchTaskOutcomeKind.PENDING, null, null,
                        "a la mesa, declinada por la regla: " + detail);
            }
        }
        List<AudioRerecordRequest> rerecords = new ArrayList<>();
        for (RuleFixRerecording rerecording : BatchBook.list(result.getRerecordings())) {
            rerecords.add(new AudioRerecordRequest(quizId, rerecording.getAudioKey(),
                    new ArrayList<>(List.of(rerecording.getText()))));
        }
        if (fixed.isEmpty()) {
            return batch;
        }
        QuizTemplateEntity after = result.getQuiz() != null ? BatchBook.copy(result.getQuiz()) : BatchBook.copy(before);
        List<ExercisePart> parts = BatchBook.changedParts(before, after);
        if (parts.isEmpty() && rerecords.isEmpty()) {
            for (RefinementTask task : fixed) {
                BatchBook.setOutcome(batch, task.getId(), BatchTaskOutcomeKind.PENDING, null, null,
                        "a la mesa: la regla no cambió nada");
            }
            return batch;
        }

        // The change gate, measured without a query.
        KnowledgeEntity topicBefore = where.knowledge();
        KnowledgeEntity topicAfter = withQuiz(topicBefore, after);
        TopicWork work = new TopicWork(batch.getId(), batch.getLevel(), where.milestone().getId(), where.topic().getId(),
                topicBefore, topicBefore.getSentenceMode(), new ArrayList<>(), null, null, new HashMap<>(),
                new ArrayList<>());
        BatchBook.NoQueries noQueries = new BatchBook.NoQueries(NO_QUERIES);
        UnitMeasurement measuredBefore = topicMeter.measure(work, topicBefore, batch.getAnalyzers(), noQueries);
        UnitMeasurement measuredAfter = topicMeter.measure(work, topicAfter, batch.getAnalyzers(), noQueries);
        ChangeGateVerdict verdict = changeGate.check(new ChangeProbe(new ArrayList<>(List.of(quizId)), false,
                measuredBefore, measuredAfter, rerecords));
        if (!verdict.isPasses()) {
            for (RefinementTask task : fixed) {
                BatchBook.setOutcome(batch, task.getId(), BatchTaskOutcomeKind.PENDING, null, null,
                        "a la mesa: la regla no pasó la compuerta: " + String.join("; ", BatchBook.list(verdict.getReasons())));
            }
            return batch;
        }
        String changeId = "regla-" + fix.analyzerName() + "-" + quizId;
        BatchChange change = new BatchChange(changeId, BatchChangeOrigin.RULE, fix.analyzerName(),
                topicBefore.getId(), fixed.stream().map(RefinementTask::getId).collect(Collectors.toList()),
                new ArrayList<>(List.of(new BatchChangeStep(quizId, new ArrayList<>(parts),
                        new CourseElementSnapshot(AuditTarget.QUIZ, quizId, after, null)))),
                verdict, false, Instant.now(), null);
        batch = changeLedger.record(batch, change, course);
        boolean onlyRerecords = parts.isEmpty();
        for (RefinementTask task : fixed) {
            BatchBook.setOutcome(batch, task.getId(), onlyRerecords ? BatchTaskOutcomeKind.PENDING_RERECORDING
                    : BatchTaskOutcomeKind.RESOLVED_BY_RULE, changeId, 0, detail);
        }
        return batch;
    }

    private Map<String, RefinementTask> tasksOf(CorrectionBatch batch) {
        if (plans == null || batch.getPlanId() == null) {
            return Map.of();
        }
        Optional<RefinementPlan> plan = plans.load(batch.getPlanId());
        return plan.map(BatchBook::tasksById).orElse(Map.of());
    }

    /** The topic with the exercise replaced, a new list so the topic it came from does not move. */
    static KnowledgeEntity withQuiz(KnowledgeEntity topic, QuizTemplateEntity quiz) {
        List<QuizTemplateEntity> quizzes = new ArrayList<>();
        for (QuizTemplateEntity each : BatchBook.list(topic.getQuizTemplates())) {
            quizzes.add(each != null && each.getId() != null && each.getId().equals(quiz.getId()) ? quiz : each);
        }
        return new KnowledgeEntity(topic.getId(), topic.getCode(), topic.getKind(), topic.getLabel(), topic.getOldId(),
                topic.getParentId(), topic.isIsRule(), topic.getInstructions(), topic.getOrder(), topic.getSlug(), quizzes,
                topic.getSentenceMode());
    }
