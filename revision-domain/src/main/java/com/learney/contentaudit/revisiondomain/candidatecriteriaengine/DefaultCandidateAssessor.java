/**
 * F-QICOR-R004/R013/R014/R015: submits a candidate to the WHOLE registered
 * catalog -- no early return on the first non-PASSED verdict, unlike the
 * pre-F-QICOR-R012 design, because without every criterion's verdict there is
 * nothing to count or rank (R013 detail: "sin corte al primer no-PASSED no
 * habria como contar cuantos cumple"). Three conditions decide {@code
 * eligible} -- the gate for competing at all (F-QICOR-R016): {@link
 * CorrectionCriterion#INSTRUCTION_COMPLIANCE} (F-QICOR-R005, the first
 * absolute criterion), {@link CorrectionCriterion#REAL_WORLD_SENSE}
 * (F-QICOR-R016, the second absolute criterion), and whether the candidate is
 * a real change over the original (F-QICOR-R001/R010). {@link
 * CorrectionCriterion#LENGTH_IN_RANGE} never adds to {@code satisfiedCriteria}
 * and never appears in {@code unmetCriteria} (F-QICOR-R011); its structured
 * measurement travels on its own field instead. Neither {@code
 * INSTRUCTION_COMPLIANCE} nor {@code REAL_WORLD_SENSE} adds to {@code
 * satisfiedCriteria} either -- they are gates, not members of the "no
 * empeorar" catalog (F-QICOR-R004) nor of {@link CandidateRanking#precedence()}
 * (F-QICOR-R013: every candidate that competes satisfies both absolutes by
 * construction, so counting either would add the same unit to every
 * competitor and never break a tie) -- but each DOES appear in {@code
 * unmetCriteria} when it fails, since {@link
 * com.learney.contentaudit.revisiondomain.NoAcceptableCandidateException} and
 * the R006 "correccion no lograda" desenlace need to be able to name it as
 * the reason nothing was entregable. A {@code NOT_EVALUABLE} outcome on
 * either absolute counts exactly like {@code FAILED} for eligibility -- the
 * prudent reading is the same in both cases (R013): "could not verify" is
 * never treated as "passed by omission".
 *
 * <p>Performance note (does not change any of the above): the catalog is
 * still consulted whole and the returned verdicts are still exactly one per
 * active criterion, in catalog order. What changes is WHEN each evaluator
 * runs. The three judgment criteria backed by an LLM call over the network
 * -- {@link CorrectionCriterion#FAITHFUL_TRANSLATION}, {@link
 * CorrectionCriterion#SOLVABLE_SAME_KIND} and {@link
 * CorrectionCriterion#REAL_WORLD_SENSE}, each a ~15s round trip -- are
 * dispatched together instead of back-to-back, which is what used to put a
 * batch of {@code assess-candidate} calls on the edge of the framework's
 * per-node timeout. {@link CorrectionCriterion#INSTRUCTION_COMPLIANCE} is
 * judge-backed too but its evaluator appends to the evaluation ledger (an
 * append-only {@code .jsonl}); it is deliberately left serial, evaluated
 * exactly once like before, because this class has no way to verify a
 * concurrent write there is safe. Every other criterion is deterministic and
 * cheap and stays serial as well -- concurrency would not measurably help
 * there. See {@link #evaluateCatalog} for the mechanics.
 */
