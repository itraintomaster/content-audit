package com.learney.contentaudit.revisiondomain.blindsampleengine;

import com.learney.contentaudit.revisiondomain.blindsample.PairAnswer;
import com.learney.contentaudit.revisiondomain.blindsample.ProportionEstimate;
import java.util.List;
import java.util.Objects;
import javax.annotation.processing.Generated;

/**
 * F-CIEGA-R004, R005 and R006: the statistics of a blind sample, pure and without state.
 *
 * <ul>
 *   <li>{@code lower95}/{@code upper95}: the Wilson score interval at 95 % (z = 1,959964) -- 95
 *       of 100 gives [88,8; 97,8], 1 of 100 [0,2; 5,4] and 4 of 100 [1,6; 9,8]. Its margin is
 *       half its width: ±4,3 points at 25,7 % with 400.</li>
 *   <li>{@code upperOneSided95}: the exact one-sided Clopper-Pearson upper bound at 95 %, the
 *       share p at which seeing {@code count} or fewer has a probability of 5 % -- 0 of 100 gives
 *       3,0 %, 2 of 300 2,1 % and 2 of 400 1,6 %.</li>
 *   <li>Cohen's kappa over the four answers.</li>
 * </ul>
 *
 * With nothing counted ({@code total} 0) the estimate says nothing: share 0, interval [0; 1] and
 * bound 1.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
public class DefaultSampleStatistics implements SampleStatistics {

    /** The 97,5 % quantile of the standard normal: a two-sided interval at 95 %. */
    static final double Z_95 = 1.959964;

    /** One-sided: the bound leaves 5 % above it. */
    private static final double ALPHA_ONE_SIDED = 0.05;

    /** Bisection steps for the exact bound: 2^-80 is far below any digit that is published. */
    private static final int BISECTION_STEPS = 80;

    @Override
    public ProportionEstimate proportion(int count, int total) {
        if (total < 0 || count < 0 || count > total) {
            throw new IllegalArgumentException(
                    "A proportion needs 0 <= count <= total, got " + count + " of " + total);
        }
        if (total == 0) {
            return new ProportionEstimate(0, 0, 0.0, 0.0, 1.0, 1.0);
        }
        double share = (double) count / total;
        double z2 = Z_95 * Z_95;
        double denominator = 1.0 + z2 / total;
        double center = (share + z2 / (2.0 * total)) / denominator;
        double half = Z_95 * Math.sqrt(share * (1.0 - share) / total + z2 / (4.0 * total * total))
                / denominator;
        double lower = count == 0 ? 0.0 : Math.max(0.0, center - half);
        double upper = count == total ? 1.0 : Math.min(1.0, center + half);
        return new ProportionEstimate(count, total, share, lower, upper, upperOneSided(count, total));
    }

    @Override
    public double kappa(List<PairAnswer> responsible, List<PairAnswer> other) {
        Objects.requireNonNull(responsible, "responsible");
        Objects.requireNonNull(other, "other");
        if (responsible.size() != other.size()) {
            throw new IllegalArgumentException("Kappa needs the answers of both reviewers to the same pairs: "
                    + responsible.size() + " and " + other.size());
        }
        int n = responsible.size();
        if (n == 0) {
            return 0.0;
        }
        int categories = PairAnswer.values().length;
        long[] byResponsible = new long[categories];
        long[] byOther = new long[categories];
        int agreeing = 0;
        for (int i = 0; i < n; i++) {
            PairAnswer a = Objects.requireNonNull(responsible.get(i), "answer of the responsible");
            PairAnswer b = Objects.requireNonNull(other.get(i), "answer of the other reviewer");
            if (a == b) {
                agreeing++;
            }
            byResponsible[a.ordinal()]++;
            byOther[b.ordinal()]++;
        }
        long chanceProduct = 0;
        for (int c = 0; c < categories; c++) {
            chanceProduct += byResponsible[c] * byOther[c];
        }
        long pairsSquared = (long) n * n;
        if (chanceProduct == pairsSquared) {
            // Both gave one and the same answer to every pair: chance alone explains it and kappa
            // is 0/0. They agree on everything, so it reads as full agreement.
            return 1.0;
        }
        double observed = (double) agreeing / n;
        double expected = (double) chanceProduct / pairsSquared;
        return (observed - expected) / (1.0 - expected);
    }

    /**
     * F-CIEGA-R006: the margin of a share at 95 %, the half-width of the normal approximation -- the «±4 puntos»
     * of the proposal: ±4,3 points at 25,7 % and ±2,1 at 5 % with 400 exercises. The interval it publishes is
     * Wilson's; the margin is what a blind share and the analyzers' are compared with.
     */
    static double margin(ProportionEstimate estimate) {
        if (estimate == null || estimate.getTotal() <= 0) {
            return 1.0;
        }
        double share = estimate.getShare();
        return Z_95 * Math.sqrt(share * (1.0 - share) / estimate.getTotal());
    }

    // -------------------------------------------------------------------------
    // The exact one-sided bound (Clopper-Pearson)
    // -------------------------------------------------------------------------

    private static double upperOneSided(int count, int total) {
        if (count == total) {
            return 1.0;
        }
        if (count == 0) {
            // P(X = 0) = (1 - p)^n = alpha
            return -Math.expm1(Math.log(ALPHA_ONE_SIDED) / total);
        }
        double low = (double) count / total;
        double high = 1.0;
        for (int step = 0; step < BISECTION_STEPS; step++) {
            double mid = (low + high) / 2.0;
            if (binomialCdf(count, total, mid) > ALPHA_ONE_SIDED) {
                low = mid;
            } else {
                high = mid;
            }
        }
        return high;
    }

    /** P(X <= k) for X ~ Binomial(n, p), summed in logarithms so a long sample does not underflow. */
    private static double binomialCdf(int k, int n, double p) {
        if (p <= 0.0) {
            return 1.0;
        }
        if (p >= 1.0) {
            return k >= n ? 1.0 : 0.0;
        }
        double logP = Math.log(p);
        double logQ = Math.log1p(-p);
        double[] logTerms = new double[k + 1];
        double logChoose = 0.0;
        double max = Double.NEGATIVE_INFINITY;
        for (int i = 0; i <= k; i++) {
            if (i > 0) {
                logChoose += Math.log(n - i + 1) - Math.log(i);
            }
            logTerms[i] = logChoose + i * logP + (n - i) * logQ;
            max = Math.max(max, logTerms[i]);
        }
        double sum = 0.0;
        for (double logTerm : logTerms) {
            sum += Math.exp(logTerm - max);
        }
        return Math.min(1.0, Math.exp(max + Math.log(sum)));
    }
}
