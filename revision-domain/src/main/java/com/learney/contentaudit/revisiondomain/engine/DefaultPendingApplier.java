/**
 * F-PROYU-R002, written once: a proposal enters if and only if its node exists and its
 * {@code elementBefore} matches that node in the course it is applied on; they are applied in order of
 * creation (and of id, when two share the instant), and the one that does not enter is declared not
 * applicable with its cause. A proposal is written as {@code approve} writes it (F-REVAPR-R011): the
 * node of its {@code elementBefore} replaced by its {@code elementAfter} and, for a knowledge, the
 * titles of its quizzes aligned to it (F-RPRES-R004). The course it receives is never modified.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
class DefaultPendingApplier implements PendingApplier {
    /** Creation order, and the id when two proposals share the instant. */
    static final Comparator<RevisionProposal> CREATION_ORDER = Comparator
            .comparing(RevisionProposal::getCreatedAt, Comparator.nullsLast(Comparator.<Instant>naturalOrder()))
            .thenComparing(RevisionProposal::getProposalId, Comparator.nullsLast(Comparator.<String>naturalOrder()));

    private final CourseElementLocator courseElementLocator;

    public DefaultPendingApplier(CourseElementLocator courseElementLocator) {
        this.courseElementLocator = courseElementLocator;
    }

    @Override
    public AppliedProposals apply(CourseEntity course, List<RevisionProposal> proposals) {
        List<RevisionProposal> ordered = new ArrayList<>(proposals != null ? proposals : List.of());
        ordered.removeIf(p -> p == null);
        ordered.sort(CREATION_ORDER);

        CourseEntity current = course;
        List<RevisionProposal> applied = new ArrayList<>();
        List<NonApplicablePending> nonApplicable = new ArrayList<>();
        for (RevisionProposal proposal : ordered) {
            String nodeId = proposal.getNodeId();
            AuditTarget target = proposal.getNodeTarget();
            Optional<CourseElementSnapshot> node;
            try {
                node = courseElementLocator.snapshot(current, target, nodeId);
            } catch (RuntimeException e) {
                nonApplicable.add(new NonApplicablePending(proposal.getProposalId(), NonApplicablePendingReason.OTHER,
                        "El nodo '" + nodeId + "' no se pudo leer en el curso: " + e.getMessage()));
                continue;
            }
            if (node.isEmpty()) {
                nonApplicable.add(new NonApplicablePending(proposal.getProposalId(),
                        NonApplicablePendingReason.NODE_ABSENT,
                        "El nodo '" + nodeId + "' (" + target + ") ya no está en el curso"));
                continue;
            }
            CourseElementSnapshot before = proposal.getElementBefore();
            if (before != null && !before.equals(node.get())) {
                nonApplicable.add(new NonApplicablePending(proposal.getProposalId(),
                        NonApplicablePendingReason.ELEMENT_BEFORE_MISMATCH,
                        "El elementBefore de la propuesta no coincide con el nodo '" + nodeId
                                + "' en el curso: otra propuesta anterior ya lo cambió"));
                continue;
            }
            CourseElementSnapshot after = proposal.getElementAfter();
            if (after == null) {
                nonApplicable.add(new NonApplicablePending(proposal.getProposalId(), NonApplicablePendingReason.OTHER,
                        "La propuesta no trae elementAfter para el nodo '" + nodeId + "'"));
                continue;
            }
            try {
                CourseEntity replaced = courseElementLocator.replace(current, after);
                if (after.getNodeTarget() == AuditTarget.KNOWLEDGE) {
                    replaced = courseElementLocator.alignQuizTitles(replaced, after.getNodeId());
                }
                current = replaced;
            } catch (RuntimeException e) {
                nonApplicable.add(new NonApplicablePending(proposal.getProposalId(), NonApplicablePendingReason.OTHER,
                        "No se pudo escribir la propuesta en el nodo '" + nodeId + "': " + e.getMessage()));
                continue;
            }
            applied.add(proposal);
        }
        return new AppliedProposals(current, applied, nonApplicable);
    }
}
