    private BlindSampleResult result(BlindSample sample) {
        BlindSampleGoal goal = sample.getGoal() != null ? sample.getGoal() : goalBook.effective().getBlindSample();
        String responsible = goal != null ? goal.getResponsible() : null;
        SampleCounts.Tally tally = SampleCounts.tally(sample, responsible);
        List<String> unmet = SampleCounts.unmetParts(tally, goal, statistics);
        return new BlindSampleResult(sample.getSampleId(), sample.getScopeId(), responsible, tally.answered(),
                statistics.proportion(tally.betterOrEqual(), tally.answered()),
                statistics.proportion(tally.worse(), tally.answered()),
                statistics.proportion(tally.bothWrong(), tally.answered()), tally.answered() > 0 && unmet.isEmpty(),
                unmet, agreement(sample, responsible), cumulative(sample, goal),
                sample.getPairs() != null ? new ArrayList<>(sample.getPairs()) : new ArrayList<>());
    }

    /**
     * R005: the other reviewer with the most pairs in common with the responsible -- the tester who answers the
     * first 30 --, in how many they gave the same answer, and Cohen's kappa over those pairs, in pair order.
     */
    private ReviewerAgreement agreement(BlindSample sample, String responsible) {
        if (responsible == null || sample.getAnswers() == null) {
            return null;
        }
        Map<Integer, PairAnswer> mine = SampleCounts.answersOf(sample, responsible);
        Set<String> others = new java.util.LinkedHashSet<>();
        for (PairAnswerRecord record : sample.getAnswers()) {
            if (record != null && record.getReviewer() != null && !responsible.equals(record.getReviewer())) {
                others.add(record.getReviewer());
            }
        }
        String best = null;
        int bestCommon = 0;
        for (String other : others) {
            int common = 0;
            for (Integer index : SampleCounts.answersOf(sample, other).keySet()) {
                if (mine.containsKey(index)) {
                    common++;
                }
            }
            if (common > bestCommon) {
                best = other;
                bestCommon = common;
            }
        }
        if (best == null) {
            return null;
        }
        Map<Integer, PairAnswer> theirs = SampleCounts.answersOf(sample, best);
        List<PairAnswer> a = new ArrayList<>();
        List<PairAnswer> b = new ArrayList<>();
        int agreeing = 0;
        for (Map.Entry<Integer, PairAnswer> answer : mine.entrySet()) {
            PairAnswer other = theirs.get(answer.getKey());
            if (other == null) {
                continue;
            }
            a.add(answer.getValue());
            b.add(other);
            if (answer.getValue() == other) {
                agreeing++;
            }
        }
        return new ReviewerAgreement(responsible, best, a.size(), agreeing, statistics.kappa(a, b));
    }

    /**
     * R004: the samples closed since the baseline -- with the same baseline as this one --, each with the answers
     * of its responsible: how many pairs and how many worse the course carries, the one-sided bound of the worse
     * and whether it is already below the goal of the course. A progress goal: it does not decide.
     */
    private CumulativeSample cumulative(BlindSample sample, BlindSampleGoal goal) {
        Map<String, BlindSample> closed = new LinkedHashMap<>();
        List<BlindSample> all = store.listPairs();
        for (BlindSample other : all != null ? all : List.<BlindSample>of()) {
            if (other != null && other.getClosedAt() != null
                    && Objects.equals(other.getBaselineAuditId(), sample.getBaselineAuditId())) {
                closed.put(other.getSampleId(), other);
            }
        }
        closed.put(sample.getSampleId(), sample);
        int pairs = 0;
        int worse = 0;
        for (BlindSample each : closed.values()) {
            String responsible = each.getGoal() != null ? each.getGoal().getResponsible()
                    : goal != null ? goal.getResponsible() : null;
            SampleCounts.Tally tally = SampleCounts.tally(each, responsible);
            pairs += tally.answered();
            worse += tally.worse();
        }
        double bound = statistics.proportion(worse, pairs).getUpperOneSided95();
        boolean below = goal != null && pairs > 0 && bound < goal.getCumulativeMaxWorseShare();
        return new CumulativeSample(closed.size(), pairs, worse, bound, below);
    }
