    @Override
    public BlindSample draw(Path coursePath, ProjectionScope scope, Long seed) {
        CourseProjection projection = courseProjector.project(coursePath, scope);
        if (projection.getAvailability() != ConsolidatedViewAvailability.AVAILABLE
                || projection.getApproved() == null || projection.getProjected() == null) {
            String detail = projection.getUnavailability() != null && projection.getUnavailability().getDetail() != null
                    ? projection.getUnavailability().getDetail() : "la proyección no está disponible";
            throw new IllegalStateException("No se puede sortear la muestra ciega: " + detail);
        }
        Set<String> returning = new HashSet<>();
        BatchComparison comparison = batchComparator.compare(coursePath, scope);
        if (comparison != null && comparison.getChanges() != null) {
            for (ChangeOutcome outcome : comparison.getChanges()) {
                if (outcome != null && outcome.isReturns()) {
                    returning.add(outcome.getProposalId());
                }
            }
        }
        Map<String, AuditNode> before = StudentSides.quizzes(projection.getApproved());
        Map<String, AuditNode> after = StudentSides.quizzes(projection.getProjected());
        List<ProjectedChange> candidates = new ArrayList<>();
        for (ProjectedChange change : projection.getChanges() != null ? projection.getChanges()
                : List.<ProjectedChange>of()) {
            if (change != null && change.isPending() && change.getNodeTarget() == AuditTarget.QUIZ
                    && !returning.contains(change.getProposalId()) && before.containsKey(change.getNodeId())
                    && after.containsKey(change.getNodeId())) {
                candidates.add(change);
            }
        }

        long drawSeed = seed != null ? seed : new SecureRandom().nextLong();
        Random random = new Random(drawSeed);
        Collections.shuffle(candidates, random);
        BlindSampleGoal goal = goalBook.effective().getBlindSample();
        int size = goal != null ? Math.min(goal.getSize(), candidates.size()) : candidates.size();
        List<BlindPair> pairs = new ArrayList<>();
        for (int i = 0; i < size; i++) {
            ProjectedChange change = candidates.get(i);
            StudentSide was = StudentSides.side(before.get(change.getNodeId()), studentViewRenderer);
            StudentSide is = StudentSides.side(after.get(change.getNodeId()), studentViewRenderer);
            BlindSide afterSide = random.nextBoolean() ? BlindSide.A : BlindSide.B;
            pairs.add(new BlindPair(i + 1, change.getProposalId(), change.getNodeId(),
                    afterSide == BlindSide.A ? is : was, afterSide == BlindSide.A ? was : is, afterSide));
        }

        Instant now = Instant.now();
        String id = StudentSides.newId(ID_PREFIX, now, taken -> store.loadPairs(taken).isPresent());
        String baselineAuditId = baselineStore.read().map(Baseline::getAuditId).orElse(null);
        BlindSample sample = new BlindSample(id, projection.getScopeId(), baselineAuditId,
                projection.getActiveAuditId(), projection.getActivePlanId(), drawSeed, now, goal, pairs,
                new ArrayList<>(), null);
        store.savePairs(sample);
        return sample;
    }

    @Override
    public List<BlindPairView> pairs(String sampleId) {
        BlindSample sample = load(sampleId);
        List<BlindPairView> views = new ArrayList<>();
        for (BlindPair pair : sample.getPairs() != null ? sample.getPairs() : List.<BlindPair>of()) {
            views.add(new BlindPairView(pair.getIndex(), pair.getSideA(), pair.getSideB()));
        }
        return views;
    }

    @Override
    public void answer(String sampleId, int pairIndex, PairAnswer answer, String reviewer) {
        BlindSample sample = load(sampleId);
        if (sample.getClosedAt() != null) {
            throw new SampleClosedException(sampleId);
        }
        if (SampleCounts.pair(sample, pairIndex) == null) {
            int count = sample.getPairs() != null ? sample.getPairs().size() : 0;
            throw new IllegalArgumentException("Sample '" + sampleId + "' has no pair " + pairIndex + ": its pairs go from 1 to "
                    + count + ".");
        }
        if (answer == null) {
            throw new IllegalArgumentException("An answer is one of A_BETTER, B_BETTER, EQUAL or BOTH_WRONG.");
        }
        if (reviewer == null || reviewer.isBlank()) {
            throw new IllegalArgumentException("An answer needs who gives it.");
        }
        List<PairAnswerRecord> answers = sample.getAnswers() != null ? new ArrayList<>(sample.getAnswers())
                : new ArrayList<>();
        answers.add(new PairAnswerRecord(pairIndex, answer, reviewer.trim(), Instant.now()));
        sample.setAnswers(answers);
        store.savePairs(sample);
    }

    @Override
    public BlindSampleResult close(String sampleId) {
        BlindSample sample = load(sampleId);
        if (sample.getClosedAt() == null) {
            sample.setClosedAt(Instant.now());
            store.savePairs(sample);
        }
        return result(sample);
    }

    @Override
    public Optional<BlindSampleResult> result(String sampleId) {
        BlindSample sample = load(sampleId);
        return sample.getClosedAt() == null ? Optional.empty() : Optional.of(result(sample));
    }

    private BlindSample load(String sampleId) {
        return store.loadPairs(sampleId)
                .orElseThrow(() -> new IllegalArgumentException("There is no blind sample '" + sampleId + "'."));
    }

