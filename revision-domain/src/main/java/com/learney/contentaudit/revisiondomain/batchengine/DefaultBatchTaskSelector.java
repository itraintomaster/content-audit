    private boolean concernsAudio(Finding finding) {
        if (finding == null || correctionCatalog == null) {
            return false;
        }
        return correctionCatalog.find(finding.getAnalyzer()).map(c -> c.concernsAudio(finding)).orElse(false);
    }

    /** The nodes under the milestone of the level, the milestone included. */
    private static List<AuditNode> levelNodes(AuditReport start, CefrLevel level) {
        List<AuditNode> nodes = new ArrayList<>();
        for (AuditNode node : BatchBook.nodes(start)) {
            if (node.getTarget() == AuditTarget.MILESTONE && node.getEntity() != null && level != null
                    && level.name().equalsIgnoreCase(node.getEntity().getLabel())) {
                List<AuditNode> pending = new ArrayList<>(List.of(node));
                while (!pending.isEmpty()) {
                    AuditNode current = pending.remove(0);
                    nodes.add(current);
                    if (current.getChildren() != null) {
                        pending.addAll(current.getChildren());
                    }
                }
            }
        }
        return nodes;
    }

    /** F-TAREA-R005: the findings of a tie rule of their analyzer, for the tray. */
    private List<Finding> ties(List<AuditNode> nodes) {
        List<Finding> ties = new ArrayList<>();
        for (AuditNode node : nodes) {
            for (Finding finding : BatchBook.list(node.getFindings())) {
                Optional<AnalyzerCorrection> correction = correctionCatalog != null && finding != null
                        ? correctionCatalog.find(finding.getAnalyzer()) : Optional.empty();
                if (correction.isPresent() && BatchBook.list(correction.get().tieRules()).contains(finding.getRule())) {
                    ties.add(finding);
                }
            }
        }
        return ties;
    }

    /** F-NOEMP-R010: per analyzer, how many exercises of the level it left unevaluated. */
    private static List<NotComparedCount> unevaluated(List<AuditNode> nodes) {
        Map<String, Integer> byAnalyzer = new LinkedHashMap<>();
        for (AuditNode node : nodes) {
            if (node.getTarget() != AuditTarget.QUIZ) {
                continue;
            }
            Set<String> analyzers = new HashSet<>(BatchBook.list(node.getUnevaluatedBy()));
            analyzers.addAll(BatchBook.list(node.getPartiallyEvaluatedBy()));
            for (String analyzer : analyzers) {
                byAnalyzer.merge(analyzer, 1, Integer::sum);
            }
        }
        List<NotComparedCount> counts = new ArrayList<>();
        byAnalyzer.entrySet().stream().sorted(Map.Entry.comparingByKey())
                .forEach(e -> counts.add(new NotComparedCount(e.getKey(), e.getValue())));
        return counts;
    }

    /** José's orders: each topic of the level named by its id or its name passes to multiple choice. */
    private static List<ConversionOrder> conversions(List<AuditNode> nodes, List<String> topics) {
        List<ConversionOrder> orders = new ArrayList<>();
        for (String topic : BatchBook.list(topics)) {
            if (topic == null || topic.isBlank()) {
                continue;
            }
            for (AuditNode node : nodes) {
                if (node.getTarget() != AuditTarget.KNOWLEDGE || node.getEntity() == null) {
                    continue;
                }
                String id = node.getEntity().getId();
                String label = node.getEntity().getLabel();
                boolean named = topic.equals(id) || label != null
                        && label.strip().toLowerCase(Locale.ROOT).equals(topic.strip().toLowerCase(Locale.ROOT));
                if (named && orders.stream().noneMatch(o -> o.getKnowledgeId().equals(id))) {
                    orders.add(new ConversionOrder(id, FormKind.MULTIPLE_CHOICE, CONVERSION_OPTIONS));
                }
            }
        }
        return orders;
    }
