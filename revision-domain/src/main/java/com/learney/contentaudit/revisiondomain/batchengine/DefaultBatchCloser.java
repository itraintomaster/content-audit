    /** The changes of the exercise of a returned proposal leave the batch, each task spending an attempt. */
    private List<String> giveBack(CorrectionBatch batch, ReturnedChange back, CourseEntity startCourse) {
        String quizId = null;
        for (BatchProposalRef ref : BatchBook.list(batch.getQuizProposals())) {
            if (ref != null && Objects.equals(ref.getProposalId(), back.getProposalId())) {
                quizId = ref.getQuizId();
            }
        }
        List<String> dropped = new ArrayList<>();
        if (quizId == null) {
            return dropped;
        }
        int maxAttempts = batch.getSettings() != null && batch.getSettings().getMaxAttempts() > 0
                ? batch.getSettings().getMaxAttempts() : DEFAULT_MAX_ATTEMPTS;
        String reason = back.getReason() != null ? back.getReason() : String.valueOf(back.getCause());
        for (BatchChange change : BatchBook.copy(batch.getChanges())) {
            if (change == null || change.getDroppedReason() != null || !touches(change, quizId)) {
                continue;
            }
            Map<String, Integer> attempts = new LinkedHashMap<>();
            for (String taskId : BatchBook.list(change.getTaskIds())) {
                attempts.put(taskId, BatchBook.outcome(batch, taskId).map(BatchTaskOutcome::getAttempts).orElse(0));
            }
            changeLedger.drop(batch, change.getChangeId(), "la compuerta de la tanda lo devolvió: " + reason, startCourse);
            dropped.add(change.getChangeId());
            for (Map.Entry<String, Integer> entry : attempts.entrySet()) {
                int spent = entry.getValue() + 1; // returning spends one attempt more
                if (spent >= maxAttempts) {
                    BatchBook.setOutcome(batch, entry.getKey(), BatchTaskOutcomeKind.RETURNED_WITHOUT_ATTEMPTS, null,
                            spent, reason);
                } else {
                    BatchBook.setOutcome(batch, entry.getKey(), BatchTaskOutcomeKind.PENDING, null, spent, reason);
                }
            }
        }
        return dropped;
    }

    private static boolean touches(BatchChange change, String nodeId) {
        for (BatchChangeStep step : BatchBook.list(change.getSteps())) {
            if (step != null && Objects.equals(step.getQuizId(), nodeId)) {
                return true;
            }
        }
        return false;
    }

    /**
     * R006 inv. 2 and 3: a task stays resolved when its finding and the ones it covers no longer appear in the
     * recalculated course -- what F counts as fixed --; a task of the audio whose audio the batch asked to record again
     * waits for the recording; any other task a change took and that the recalculation still marks goes back to pending.
     */
    private void settle(CorrectionBatch batch, BatchComparison comparison, Map<String, RefinementTask> tasks) {
        Set<String> fixed = new HashSet<>();
        for (ChangeOutcome change : comparison != null ? BatchBook.list(comparison.getChanges())
                : List.<ChangeOutcome>of()) {
            for (Finding finding : BatchBook.list(change.getFixedFindings())) {
                fixed.add(BatchBook.identity(finding));
            }
        }
        Set<String> rerecorded = new LinkedHashSet<>();
        for (BatchChange change : BatchBook.list(batch.getChanges())) {
            if (change != null && change.getDroppedReason() == null && change.getGateVerdict() != null) {
                for (AudioRerecordRequest request : BatchBook.list(change.getGateVerdict().getRerecords())) {
                    rerecorded.add(request.getQuizId());
                }
            }
        }
        for (String taskId : BatchBook.list(batch.getTaskIds())) {
            BatchTaskOutcomeKind kind = BatchBook.kind(batch, taskId);
            if (kind != BatchTaskOutcomeKind.RESOLVED_BY_RULE && kind != BatchTaskOutcomeKind.RESOLVED_BY_PANEL
                    && kind != BatchTaskOutcomeKind.PENDING_RERECORDING) {
                continue;
            }
            RefinementTask task = tasks.get(taskId);
            Optional<Finding> finding = BatchBook.findingOf(task);
            if (task == null || finding.isEmpty()) {
                continue;
            }
            boolean gone = fixed.contains(BatchBook.identity(finding.get()));
            for (Finding covered : BatchBook.list(task.getOrigin().getCoveredFindings())) {
                gone &= fixed.contains(BatchBook.identity(covered));
            }
            BatchTaskOutcome outcome = BatchBook.outcome(batch, taskId).orElse(null);
            String changeId = outcome != null ? outcome.getChangeId() : null;
            int attempts = outcome != null ? outcome.getAttempts() : 0;
            boolean audio = concernsAudio(finding.get())
                    && BatchBook.quizzesOf(task).stream().anyMatch(rerecorded::contains);
            if (audio && !gone) {
                BatchBook.setOutcome(batch, taskId, BatchTaskOutcomeKind.PENDING_RERECORDING, changeId, attempts,
                        "su hallazgo sigue hasta que se grabe el audio pedido");
            } else if (!gone) {
                BatchBook.setOutcome(batch, taskId, BatchTaskOutcomeKind.PENDING, changeId, attempts,
                        "el curso recalculado todavía la marca");
            }
        }
    }

    private boolean concernsAudio(Finding finding) {
        return corrections != null && corrections.find(finding.getAnalyzer()).map(c -> c.concernsAudio(finding))
                .orElse(false);
    }

    /**
     * F-NOEMP-R007: the nodes the composed course changed that the batch may not touch -- every exercise of its tasks,
     * of the topics of its tasks of the whole topic and of its conversions, and those topics.
     */
    private List<String> changedOutside(CorrectionBatch batch, CourseEntity startCourse, Map<String, RefinementTask> tasks) {
        CourseEntity composed = changeLedger.composedCourse(batch, startCourse);
        Set<String> allowed = new HashSet<>();
        Set<String> topics = new HashSet<>();
        for (String taskId : BatchBook.list(batch.getTaskIds())) {
            RefinementTask task = tasks.get(taskId);
            if (task == null) {
                continue;
            }
            allowed.addAll(BatchBook.quizzesOf(task));
            if (task.getNodeTarget() != com.learney.contentaudit.auditdomain.AuditTarget.QUIZ) {
                topics.add(BatchBook.knowledgeOf(task));
            }
        }
        for (var order : BatchBook.list(batch.getConversionOrders())) {
            if (order != null) {
                topics.add(order.getKnowledgeId());
            }
        }
        List<String> outside = new ArrayList<>();
        Map<String, Object> before = contents(startCourse, topics);
        Map<String, Object> after = contents(composed, topics);
        allowed.addAll(topics);
        for (Map.Entry<String, Object> entry : after.entrySet()) {
            if (!Objects.equals(before.get(entry.getKey()), entry.getValue()) && !allowed.contains(entry.getKey())) {
                outside.add(entry.getKey());
            }
        }
        return outside;
    }

    /** What each node of the course holds, to tell what changed; the exercises of the given topics are allowed too. */
    private static Map<String, Object> contents(CourseEntity course, Set<String> topics) {
        Map<String, Object> contents = new LinkedHashMap<>();
        if (course == null || course.getRoot() == null) {
            return contents;
        }
        for (MilestoneEntity milestone : BatchBook.list(course.getRoot().getMilestones())) {
            for (TopicEntity topic : BatchBook.list(milestone.getTopics())) {
                for (KnowledgeEntity knowledge : BatchBook.list(topic.getKnowledges())) {
                    contents.put(knowledge.getId(), List.of(String.valueOf(knowledge.getInstructions()),
                            String.valueOf(knowledge.getLabel())));
                    for (QuizTemplateEntity quiz : BatchBook.list(knowledge.getQuizTemplates())) {
                        if (quiz != null) {
                            contents.put(quiz.getId(), quiz);
                            if (topics.contains(knowledge.getId())) {
                                topics.add(quiz.getId());
                            }
                        }
                    }
                }
            }
        }
        return contents;
    }
