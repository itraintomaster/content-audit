    static List<String> changedOutside(CorrectionBatch batch, CourseEntity startCourse, CourseEntity composed,
            Map<String, RefinementTask> tasks, BatchStore batches) {
        Set<String> allowed = new HashSet<>();
        Set<String> topics = new HashSet<>();
        for (String taskId : BatchBook.list(batch.getTaskIds())) {
            RefinementTask task = tasks.get(taskId);
            if (task == null) {
                continue;
            }
            allowed.addAll(BatchBook.quizzesOf(task));
            if (task.getNodeTarget() != com.learney.contentaudit.auditdomain.AuditTarget.QUIZ) {
                topics.add(BatchBook.knowledgeOf(task));
            }
        }
        for (var order : BatchBook.list(batch.getConversionOrders())) {
            if (order != null) {
                topics.add(order.getKnowledgeId());
            }
        }
        List<String> outside = new ArrayList<>();
        Map<String, Object> before = contents(startCourse, topics);
        Map<String, Object> after = contents(composed, topics);
        // A new plan omits resolved predecessor tasks, but their exact steps remain authorized. A human may withdraw
        // some of those steps: compare against that surviving subset, not just the predecessor's final snapshot.
        // Every newly changed node still needs a task or conversion in this correction.
        Map<String, Object> inherited = inheritedContents(batch, startCourse, batches);
        allowed.addAll(topics);
        for (Map.Entry<String, Object> entry : after.entrySet()) {
            if (!Objects.equals(before.get(entry.getKey()), entry.getValue()) && !allowed.contains(entry.getKey())
                    && !Objects.equals(inherited.get(entry.getKey()), entry.getValue())) {
                outside.add(entry.getKey());
            }
        }
        return outside;
    }

    private static Map<String, Object> inheritedContents(CorrectionBatch batch, CourseEntity base, BatchStore batches) {
        if (batch.getEvolution() == null) return Map.of();
        CorrectionBatch parent = batches == null ? null : batches.load(batch.getEvolution().parentBatchId()).orElse(null);
        if (parent == null) return contents(batch.getEvolution().sourceCourse(), new HashSet<>());
        Map<String, BatchChange> original = new LinkedHashMap<>();
        for (BatchChange change : BatchBook.list(parent.getChanges()))
            if (change != null && change.getDroppedReason() == null) original.put(change.getChangeId(), change);
        List<BatchChange> surviving = BatchBook.list(batch.getChanges()).stream()
                .filter(c -> c != null && c.getDroppedReason() == null && original.containsKey(c.getChangeId())
                        && Objects.equals(original.get(c.getChangeId()).getSteps(), c.getSteps())).toList();
        CorrectionBatch trusted = new CorrectionBatch(); trusted.setChanges(surviving);
        CourseEntity inherited = new DefaultBatchChangeLedger(null,
                new com.learney.contentaudit.revisiondomain.engine.DefaultCourseElementLocator()).composedCourse(trusted, base);
        return contents(inherited, new HashSet<>());
    }

    /** What each node of the course holds, to tell what changed; the exercises of the given topics are allowed too. */
    private static Map<String, Object> contents(CourseEntity course, Set<String> topics) {
        Map<String, Object> contents = new LinkedHashMap<>();
        if (course == null || course.getRoot() == null) {
            return contents;
        }
        for (MilestoneEntity milestone : BatchBook.list(course.getRoot().getMilestones())) {
            for (TopicEntity topic : BatchBook.list(milestone.getTopics())) {
                for (KnowledgeEntity knowledge : BatchBook.list(topic.getKnowledges())) {
                    contents.put(knowledge.getId(), List.of(String.valueOf(knowledge.getInstructions()),
                            String.valueOf(knowledge.getLabel())));
                    for (QuizTemplateEntity quiz : BatchBook.list(knowledge.getQuizTemplates())) {
                        if (quiz != null) {
                            contents.put(quiz.getId(), quiz);
                            if (topics.contains(knowledge.getId())) {
                                topics.add(quiz.getId());
                            }
                        }
                    }
                }
            }
        }
        return contents;
    }
