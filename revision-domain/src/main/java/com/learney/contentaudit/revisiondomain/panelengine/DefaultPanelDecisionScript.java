    private static TaskProgress progress(List<ErrorTaskBrief> briefs, UnitMeasurement from, UnitMeasurement to,
            List<String> restoredContracts) {
        Map<String, Finding> before = present(from);
        Map<String, Finding> after = present(to);
        Set<UnevaluatedMark> unevaluated = new HashSet<>(to.getUnevaluated() != null ? to.getUnevaluated() : List.of());
        List<String> resolved = new ArrayList<>();
        List<String> improved = new ArrayList<>();
        Map<String, String> improvements = new LinkedHashMap<>();
        Map<String, String> open = new LinkedHashMap<>();
        for (ErrorTaskBrief brief : briefs) {
            if (brief == null || brief.getTask() == null) {
                continue;
            }
            String taskId = brief.getTask().getId();
            if (brief instanceof com.learney.contentaudit.revisiondomain.panel.DidacticRepairBrief
                    && restoredContracts != null && restoredContracts.contains(taskId)) {
                resolved.add(taskId);
                continue;
            }
            if (brief.getFinding() == null) {
                continue;
            }
            List<Finding> own = findingsOf(brief);
            boolean stays = false;
            boolean pending = false;
            for (Finding finding : own) {
                pending |= unevaluated.contains(mark(finding));
                stays |= after.containsKey(identity(finding)) || unevaluated.contains(mark(finding));
            }
            if (!stays) {
                resolved.add(taskId);
                continue;
            }
            open.put(taskId, measure(brief, after, to));
            if (pending) {
                continue; // a judge that did not look gives no evidence of a repair
            }
            boolean lighter = false;
            boolean heavier = false;
            for (Finding finding : own) {
                Finding was = before.get(identity(finding));
                Finding is = after.get(identity(finding));
                if (was != null && is == null) {
                    lighter = true;
                } else if (was == null && is != null) {
                    heavier = true;
                } else if (was != null) {
                    int change = Integer.compare(severityRank(was.getSeverity()), severityRank(is.getSeverity()));
                    lighter |= change < 0;
                    heavier |= change > 0;
                }
            }
            Optional<LengthDeclaration> lengthBefore = lengthOf(brief, from);
            Optional<LengthDeclaration> lengthAfter = lengthOf(brief, to);
            if (lengthBefore.isPresent() && lengthAfter.isPresent()) {
                int change = Integer.compare(distance(lengthAfter.get()), distance(lengthBefore.get()));
                lighter |= change < 0;
                heavier |= change > 0;
            }
            if (lighter && !heavier) {
                improved.add(taskId);
                improvements.put(taskId, lengthBefore.isPresent() && lengthAfter.isPresent()
                        ? "largo " + lengthBefore.get().getTokens() + " → " + lengthAfter.get().getTokens() + " (meta "
                                + lengthAfter.get().getTargetMin() + " a " + lengthAfter.get().getTargetMax() + ")"
                        : count(own, before) + " → " + count(own, after));
            }
        }
        return new TaskProgress(resolved, improved, improvements, open);
    }

    /** How a task still open measures: its length with the range, or its findings with their severity. */
    private static String measure(ErrorTaskBrief brief, Map<String, Finding> present, UnitMeasurement measurement) {
        Optional<LengthDeclaration> length = lengthOf(brief, measurement);
        if (length.isPresent()) {
            LengthDeclaration l = length.get();
            return "largo " + l.getTokens() + " (meta " + l.getTargetMin() + " a " + l.getTargetMax() + ")";
        }
        List<String> parts = new ArrayList<>();
        for (Finding finding : findingsOf(brief)) {
            Finding is = present.get(identity(finding));
            if (is == null) {
                continue;
            }
            String observation = is.getEvidence() != null && is.getEvidence().getObservation() != null
                    ? is.getEvidence().getObservation().strip() : "";
            if (observation.length() > OBSERVATION_CHARS) {
                observation = observation.substring(0, OBSERVATION_CHARS - 1) + "…";
            }
            parts.add(is.getAnalyzer() + " " + spanish(is.getSeverity()) + (observation.isEmpty() ? "" : ": "
                    + observation));
        }
        return parts.isEmpty() ? brief.getFinding().getAnalyzer() + " sin evaluar" : String.join("; ", parts);
    }

    /** «1 marca media», «2 marcas, la más grave alta», «ninguna marca». */
    private static String count(List<Finding> own, Map<String, Finding> present) {
        int n = 0;
        FindingSeverity worst = null;
        for (Finding finding : own) {
            Finding is = present.get(identity(finding));
            if (is != null) {
                n++;
                if (worst == null || severityRank(is.getSeverity()) < severityRank(worst)) {
                    worst = is.getSeverity();
                }
            }
        }
        if (n == 0) {
            return "ninguna marca";
        }
        return n == 1 ? "1 marca " + spanish(worst) : n + " marcas, la más grave " + spanish(worst);
    }

