    /** «resuelve t1; mejora t2 (largo 18 → 10 (meta 3 a 8))». */
    private static String done(TaskProgress progress) {
        List<String> parts = new ArrayList<>();
        if (!progress.resolved().isEmpty()) {
            parts.add("resuelve " + String.join(", ", progress.resolved()));
        }
        if (!progress.improved().isEmpty()) {
            List<String> improved = new ArrayList<>();
            for (String taskId : progress.improved()) {
                improved.add(taskId + " (" + progress.improvements().get(taskId) + ")");
            }
            parts.add("mejora " + String.join(", ", improved));
        }
        return String.join("; ", parts);
    }

    /** F-MESA-R007 inv. 2: how each task still open measures in the candidate. */
    private static String still(TaskProgress progress) {
        if (progress.open().isEmpty()) {
            return "";
        }
        List<String> open = new ArrayList<>();
        for (Map.Entry<String, String> entry : progress.open().entrySet()) {
            open.add(entry.getKey() + ": " + entry.getValue());
        }
        return " — sigue abierta " + String.join("; ", open);
    }

