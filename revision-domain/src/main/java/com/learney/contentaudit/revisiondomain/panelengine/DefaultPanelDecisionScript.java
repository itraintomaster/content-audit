    /** F-MESA-R008: the findings of a tie rule its analyzer declares, on the exercises of the tasks. */
    private List<Finding> ties(UnitMeasurement measurement, Set<String> exercises) {
        List<Finding> ties = new ArrayList<>();
        for (Finding finding : measurement.getFindings() != null ? measurement.getFindings() : List.<Finding>of()) {
            if (finding == null || finding.getNode() == null) {
                continue;
            }
            if (!exercises.isEmpty() && !exercises.contains(finding.getNode().getNodeId())) {
                continue;
            }
            Optional<AnalyzerCorrection> correction = correctionCatalog != null
                    ? correctionCatalog.find(finding.getAnalyzer()) : Optional.empty();
            if (correction.isPresent() && correction.get().tieRules() != null
                    && correction.get().tieRules().contains(finding.getRule())) {
                ties.add(finding);
            }
        }
        return ties;
    }

    /**
     * The order among accepted candidates: more tasks resolved; fewer findings by severity, from blocking down; not
     * changing what is heard; lengths closer to the range.
     */
    private static int[] rank(ScoredCandidate candidate, TaskProgress progress) {
        int[] bySeverity = new int[FindingSeverity.values().length];
        for (Finding finding : candidate.getMeasurement().getFindings() != null
                ? candidate.getMeasurement().getFindings() : List.<Finding>of()) {
            if (finding != null && finding.getSeverity() != null) {
                bySeverity[severityRank(finding.getSeverity())]++;
            }
        }
        ChangeGateVerdict gate = candidate.getGate();
        int heardChanges = gate.getRerecords() != null && !gate.getRerecords().isEmpty() ? 1 : 0;
        int outOfRange = 0;
        for (LengthDeclaration length : gate.getLengths() != null ? gate.getLengths() : List.<LengthDeclaration>of()) {
            if (length != null) {
                outOfRange += distance(length);
            }
        }
        int[] key = new int[bySeverity.length + 3];
        key[0] = -progress.resolved().size();
        System.arraycopy(bySeverity, 0, key, 1, bySeverity.length);
        key[bySeverity.length + 1] = heardChanges;
        key[bySeverity.length + 2] = outOfRange;
        return key;
    }

    /** How far a length is from its range: 0 inside it. */
    static int distance(LengthDeclaration length) {
        if (length.getTokens() < length.getTargetMin()) {
            return length.getTargetMin() - length.getTokens();
        }
        return Math.max(0, length.getTokens() - length.getTargetMax());
    }

    /** The length of the exercise of a length task, as a measurement declares it. */
    private static Optional<LengthDeclaration> lengthOf(ErrorTaskBrief brief, UnitMeasurement measurement) {
        if (!SENTENCE_LENGTH.equals(brief.getFinding().getAnalyzer()) || brief.getTask().getNodeId() == null) {
            return Optional.empty();
        }
        for (LengthDeclaration length : measurement.getLengths() != null ? measurement.getLengths()
                : List.<LengthDeclaration>of()) {
            if (length != null && brief.getTask().getNodeId().equals(length.getQuizId())) {
                return Optional.of(length);
            }
        }
        return Optional.empty();
    }

    /** Blocking first: the rank of a severity in the comparison of findings. */
    private static int severityRank(FindingSeverity severity) {
        if (severity == null) {
            return FindingSeverity.values().length;
        }
        return switch (severity) {
            case BLOCKING -> 0;
            case HIGH -> 1;
            case MEDIUM -> 2;
            case LOW -> 3;
        };
    }

    private static String spanish(FindingSeverity severity) {
        if (severity == null) {
            return "sin gravedad";
        }
        return switch (severity) {
            case BLOCKING -> "bloqueante";
            case HIGH -> "alta";
            case MEDIUM -> "media";
            case LOW -> "baja";
        };
    }

    private static int compare(int[] a, int[] b) {
        for (int i = 0; i < a.length; i++) {
            if (a[i] != b[i]) {
                return Integer.compare(a[i], b[i]);
            }
        }
        return 0;
    }

    private static List<Finding> findingsOf(ErrorTaskBrief brief) {
        List<Finding> own = new ArrayList<>();
        own.add(brief.getFinding());
        for (Finding covered : brief.getCoveredFindings() != null ? brief.getCoveredFindings() : List.<Finding>of()) {
            if (covered != null) {
                own.add(covered);
            }
        }
        return own;
    }

    private static Map<String, Finding> present(UnitMeasurement measurement) {
        Map<String, Finding> present = new HashMap<>();
        for (Finding finding : measurement.getFindings() != null ? measurement.getFindings() : List.<Finding>of()) {
            if (finding != null) {
                present.put(identity(finding), finding);
            }
        }
        return present;
    }

    /** A missing finding gives no evidence of a repair when its judge still has this node pending. */
    private static UnevaluatedMark mark(Finding finding) {
        return new UnevaluatedMark(finding.getNode() != null ? finding.getNode().getNodeId() : null,
                finding.getAnalyzer());
    }

    private static Set<String> exercisesOf(List<ErrorTaskBrief> briefs) {
        Set<String> exercises = new LinkedHashSet<>();
        for (ErrorTaskBrief brief : briefs) {
            if (brief != null && brief.getTask() != null && brief.getTask().getNodeId() != null) {
                exercises.add(brief.getTask().getNodeId());
            }
        }
        return exercises;
    }

    static String identity(Finding finding) {
        if (finding.getIdentity() != null && finding.getIdentity().getKey() != null) {
            return finding.getIdentity().getKey();
        }
        return finding.getAnalyzer() + "|" + finding.getRule() + "|"
                + (finding.getNode() != null ? finding.getNode().getNodeId() : "");
    }
