    private static LevelImpact levelImpact(AuditTarget level, String nodeId, AuditNode before, AuditNode after) {
        // F-HALL-R010: the aggregate is the vocabulary score the engine published on each report.
        Double beforeVocabulary = vocabulary(before);
        Double afterVocabulary = vocabulary(after);
        ScoreDelta aggregate = beforeVocabulary != null && afterVocabulary != null
                ? new ScoreDelta(beforeVocabulary, afterVocabulary, afterVocabulary - beforeVocabulary)
                : null;
        Map<String, Double> beforeScores = before.getScores() != null ? before.getScores() : Map.of();
        Map<String, Double> afterScores = after.getScores() != null ? after.getScores() : Map.of();
        List<DimensionDelta> dimensions = new ArrayList<>();
        for (Map.Entry<String, Double> entry : beforeScores.entrySet()) {
            Double afterValue = afterScores.get(entry.getKey());
            if (entry.getValue() != null && afterValue != null) {
                dimensions.add(new DimensionDelta(entry.getKey(),
                        new ScoreDelta(entry.getValue(), afterValue, afterValue - entry.getValue())));
            }
        }
        return new LevelImpact(level, nodeId, aggregate, dimensions);
    }

    private static Double vocabulary(AuditNode node) {
        return node.getNumbers() != null ? node.getNumbers().getVocabularyScore() : null;
    }

