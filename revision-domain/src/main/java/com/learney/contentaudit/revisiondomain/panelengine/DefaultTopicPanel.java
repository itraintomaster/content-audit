    /** The exercise a candidate leaves, as the student reads it: «No cameras. You ___ use cameras.» (can't). */
    private String shown(KnowledgeEntity topic, String quizId, PanelCandidate candidate, List<ErrorTaskBrief> tasks) {
        if (quizStudentViewRenderer == null || candidate == null || quizId == null) {
            return null;
        }
        try {
            Optional<QuizTemplateEntity> quiz = TopicState.quiz(TopicState.apply(topic, quizId, candidate, tasks), quizId);
            if (quiz.isEmpty()) {
                return null;
            }
            QuizStudentView view = quizStudentViewRenderer.render(TopicState.auditable(quiz.get()));
            if (view == null || view.getStatement() == null) {
                return null;
            }
            List<String> answers = new ArrayList<>();
            for (var gap : view.getGaps() != null ? view.getGaps() : List.<com.learney.contentaudit.auditdomain.studentview.StudentGapView>of()) {
                if (gap != null && gap.getFirstAnswer() != null) {
                    answers.add(gap.getFirstAnswer());
                }
            }
            return "«" + view.getStatement() + "»" + (answers.isEmpty() ? "" : " (" + String.join(" / ", answers) + ")");
        } catch (RuntimeException e) {
            return null; // what was proposed is context for the next attempt, never a reason to stop
        }
    }

    /** Screens, measures and gates one candidate against the exercise as it was measured before. */
    private ScoredCandidate score(TopicWork now, KnowledgeEntity current, String quizId, PanelCandidate candidate,
            List<ErrorTaskBrief> tasks, UnitMeasurement before, List<String> analyzers, QueryAllowance allowance) {
        List<String> violations = screen.screen(now, quizId, candidate);
        if (violations != null && !violations.isEmpty()) {
            return new ScoredCandidate(candidate, null, null, new ArrayList<>(violations));
        }
        KnowledgeEntity changed = TopicState.apply(current, quizId, candidate, tasks);
        UnitMeasurement after = meter.measure(with(now, changed), changed, analyzers, allowance);
        boolean topicLevel = quizId == null || candidate.getTopicInstructions() != null;
        ChangeGateVerdict verdict = changeGate.check(new ChangeProbe(quizIdsOf(quizId, candidate, tasks), topicLevel,
                before, after, new ArrayList<>()));
        ScoredCandidate scored = new ScoredCandidate(candidate, after, verdict, new ArrayList<>());
        scored.setRestoredContractTaskIds(tasks.stream()
                .filter(t -> t instanceof com.learney.contentaudit.revisiondomain.panel.DidacticRepairBrief)
                .map(t -> (com.learney.contentaudit.revisiondomain.panel.DidacticRepairBrief) t)
                .filter(t -> DidacticContracts.violations(t.getReference(), TopicState.quiz(changed, quizId).orElse(null),
                        changed.getInstructions(), now.getSentenceMode()).isEmpty())
                .map(t -> t.getTask().getId()).toList());
        return scored;
    }

