    /** The analyzers of the settings that read something these tasks may change, and the ones that marked them. */
    private static List<String> analyzersFor(List<ErrorTaskBrief> tasks, PanelRunSettings settings,
            Set<ExercisePart> scope) {
        List<String> all = settings != null && settings.getAnalyzers() != null ? settings.getAnalyzers() : List.of();
        if (all.isEmpty()) {
            return List.of();
        }
        Set<String> marked = new HashSet<>();
        for (ErrorTaskBrief brief : tasks) {
            if (brief.getFinding() != null) {
                marked.add(brief.getFinding().getAnalyzer());
            }
            for (Finding covered : brief.getCoveredFindings() != null ? brief.getCoveredFindings() : List.<Finding>of()) {
                marked.add(covered.getAnalyzer());
            }
        }
        List<String> chosen = new ArrayList<>();
        for (String analyzer : all) {
            if (marked.contains(analyzer) || AnalyzerReads.readsAny(analyzer, scope)) {
                chosen.add(analyzer);
            }
        }
        return chosen;
    }

    private static Set<ExercisePart> scopeOf(List<ErrorTaskBrief> tasks) {
        Set<ExercisePart> scope = EnumSet.noneOf(ExercisePart.class);
        for (ErrorTaskBrief brief : tasks) {
            if (brief.getEditScope() != null) {
                scope.addAll(brief.getEditScope());
            }
        }
        if (scope.contains(ExercisePart.STATEMENT) || scope.contains(ExercisePart.ANSWERS)
                || scope.contains(ExercisePart.OPTIONS)) {
            // What the student reads and hears moves with them, and with it the sentence that is stored.
            scope.add(ExercisePart.STORED_SENTENCE);
            scope.add(ExercisePart.AUDIO);
        }
        return scope;
    }

    private boolean twoFixes(List<ErrorTaskBrief> tasks) {
        if (corrections == null) {
            return false;
        }
        for (ErrorTaskBrief brief : tasks) {
            if (brief.getFinding() == null) {
                continue;
            }
            Optional<AnalyzerCorrection> correction = corrections.find(brief.getFinding().getAnalyzer());
            if (correction.isPresent() && correction.get().offersTwoFixes()) {
                return true;
            }
        }
        return false;
    }

