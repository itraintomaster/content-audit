    private static TopicWork with(TopicWork work, KnowledgeEntity topic) {
        TopicWork current = new TopicWork(work.getBatchId(), work.getLevel(), work.getMilestoneId(), work.getTopicId(), topic,
                work.getSentenceMode(), work.getBriefs(), work.getWordLights(), work.getConversion(),
                work.getAttemptsUsed(), work.getCarriedRejections());
        current.setNewEvaluationSubjectIds(work.getNewEvaluationSubjectIds());
        current.setDidacticReferences(work.getDidacticReferences());
        return current;
    }

    private static boolean holds(ErrorTaskBrief brief, Set<String> present, Set<UnevaluatedMark> pending) {
        if (brief.getFinding() != null && (present.contains(DefaultPanelDecisionScript.identity(brief.getFinding()))
                || pending(brief.getFinding(), pending))) {
            return true;
        }
        for (Finding covered : brief.getCoveredFindings() != null ? brief.getCoveredFindings() : List.<Finding>of()) {
            if (present.contains(DefaultPanelDecisionScript.identity(covered)) || pending(covered, pending)) {
                return true;
            }
        }
        return false;
    }

    /** Absence of a finding is not evidence that it disappeared when its judge has not evaluated this node. */
    private static boolean pending(Finding finding, Set<UnevaluatedMark> pending) {
        return finding != null && finding.getNode() != null
                && pending.contains(new UnevaluatedMark(finding.getNode().getNodeId(), finding.getAnalyzer()));
    }

    private static Set<String> identities(List<Finding> findings) {
        Set<String> identities = new HashSet<>();
        for (Finding finding : findings != null ? findings : List.<Finding>of()) {
            if (finding != null) {
                identities.add(DefaultPanelDecisionScript.identity(finding));
            }
        }
        return identities;
    }

    /** The lines of the script about the i-th candidate, or all of them when it names none. */
    private static List<String> reasonsOf(ScriptDecision decision, int i) {
        List<String> mine = new ArrayList<>();
        String prefix = "candidato " + (i + 1);
        for (String reason : decision.getReasons() != null ? decision.getReasons() : List.<String>of()) {
            if (reason.startsWith(prefix + " ") || reason.startsWith(prefix + ":")) {
                mine.add(reason.substring(reason.indexOf(':') + 1).strip());
            }
        }
        if (mine.isEmpty() && decision.getReasons() != null) {
            mine.addAll(decision.getReasons());
        }
        return mine;
    }

    /** How badly a rejected candidate failed: the screen worst, then what the gate found new. */
    private static int failure(ScoredCandidate candidate) {
        if (candidate.getScreenViolations() != null && !candidate.getScreenViolations().isEmpty()) {
            return 1000 + candidate.getScreenViolations().size();
        }
        if (candidate.getGate() == null) {
            return 900;
        }
        ChangeGateVerdict gate = candidate.getGate();
        return (gate.getNewErrors() != null ? gate.getNewErrors().size() : 0)
                + (gate.getNewRedWords() != null ? gate.getNewRedWords().size() : 0) + (gate.isPasses() ? 0 : 1);
    }

    private static ScoredCandidate tiedCandidate(List<ScoredCandidate> scored, ScriptDecision decision) {
        Set<String> tied = identities(decision.getTieFindings());
        for (ScoredCandidate one : scored) {
            if (one.getMeasurement() != null && !java.util.Collections.disjoint(identities(one.getMeasurement()
                    .getFindings()), tied)) {
                return one;
            }
        }
        return scored.isEmpty() ? null : scored.get(0);
    }

    private static List<String> taskIds(List<ErrorTaskBrief> tasks) {
        List<String> ids = new ArrayList<>();
        for (ErrorTaskBrief brief : tasks) {
            if (brief.getTask() != null && brief.getTask().getId() != null) {
                ids.add(brief.getTask().getId());
            }
        }
        return ids;
    }

    private static List<String> quizIdsOf(ErrorTaskBrief brief) {
        if (brief.getTask().getNodeTarget() == AuditTarget.QUIZ) {
            return new ArrayList<>(List.of(brief.getTask().getNodeId()));
        }
        return reachOf(List.of(brief));
    }

    private static List<String> reachOf(List<ErrorTaskBrief> tasks) {
        Set<String> reach = new LinkedHashSet<>();
        for (ErrorTaskBrief brief : tasks) {
            if (brief.getTask() != null && brief.getTask().getOrigin() != null
                    && brief.getTask().getOrigin().getReachedQuizIds() != null) {
                reach.addAll(brief.getTask().getOrigin().getReachedQuizIds());
            }
        }
        return new ArrayList<>(reach);
    }

    private static List<String> quizIdsOf(String quizId, PanelCandidate candidate, List<ErrorTaskBrief> tasks) {
        if (quizId != null) {
            return new ArrayList<>(List.of(quizId));
        }
        return reachOf(tasks);
    }

    private static PanelDecision decision(String knowledgeId, List<String> quizIds, List<ErrorTaskBrief> tasks,
            PanelOutcomeKind outcome, int attempts, List<CandidateRejection> rejections, int spent) {
        return new PanelDecision(knowledgeId, new ArrayList<>(quizIds), taskIds(tasks), outcome, null, null,
                new ArrayList<>(), attempts, new ArrayList<>(rejections), null, null, new ArrayList<>(), spent);
    }
