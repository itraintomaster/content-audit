    public CorrectionBatch drop(CorrectionBatch batch, String changeId, String reason,
            CourseEntity startCourse) {
        startCourse = BatchCourses.start(batch, startCourse, batches);
        List<BatchChange> changes = BatchBook.list(batch.getChanges());
        int at = -1;
        for (int i = 0; i < changes.size(); i++) {
            if (changes.get(i) != null && Objects.equals(changes.get(i).getChangeId(), changeId)) {
                at = i;
            }
        }
        if (at < 0 || changes.get(at).getDroppedReason() != null) {
            throw new IllegalArgumentException("La tanda " + batch.getId() + " no tiene un cambio " + changeId
                    + " que se pueda sacar.");
        }
        BatchChange dropped = changes.get(at);
        String why = reason != null && !reason.isBlank() ? reason : "lo sacó José";
        dropped.setDroppedReason(why);
        Set<String> touched = new LinkedHashSet<>(nodesOf(dropped));
        // Later changes of the same exercise that touched the same fields go with it, named.
        List<BatchChange> chained = new ArrayList<>();
        for (int i = at + 1; i < changes.size(); i++) {
            BatchChange later = changes.get(i);
            if (later == null || later.getDroppedReason() != null) {
                continue;
            }
            if (overlaps(dropped, later) || chained.stream().anyMatch(c -> overlaps(c, later))) {
                later.setDroppedReason(CHAINED_PREFIX + dropped.getChangeId() + ": tocó lo mismo en el mismo ejercicio");
                chained.add(later);
                touched.addAll(nodesOf(later));
            }
        }
        for (String nodeId : touched) {
            recompose(batch, nodeId, startCourse);
        }
        List<BatchChange> out = new ArrayList<>(List.of(dropped));
        out.addAll(chained);
        for (BatchChange change : out) {
            for (String taskId : BatchBook.list(change.getTaskIds())) {
                BatchBook.setOutcome(batch, taskId, BatchTaskOutcomeKind.PENDING, null, null,
                        "volvió a pendiente: " + change.getDroppedReason());
            }
        }
        return batch;
    }

