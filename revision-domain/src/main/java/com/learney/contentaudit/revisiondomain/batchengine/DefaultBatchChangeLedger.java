    /** The node as the steps of the batch leave it, over the node as the batch opened. */
    private Optional<CourseElementSnapshot> composed(CorrectionBatch batch, String nodeId, CourseEntity startCourse) {
        List<BatchChangeStep> steps = BatchBook.stepsOn(batch, nodeId);
        if (steps.isEmpty()) {
            return Optional.empty();
        }
        Optional<CourseElementSnapshot> before = before(startCourse, nodeId, steps);
        if (before.isEmpty()) {
            return Optional.empty();
        }
        CourseElementSnapshot composed = before.get();
        for (BatchChangeStep step : steps) {
            composed = BatchBook.apply(composed, step);
        }
        return Optional.of(composed);
    }

    private Optional<CourseElementSnapshot> before(CourseEntity startCourse, String nodeId, List<BatchChangeStep> steps) {
        AuditTarget target = steps.stream().anyMatch(s -> s.getAfter() != null
                && s.getAfter().getNodeTarget() == AuditTarget.KNOWLEDGE) ? AuditTarget.KNOWLEDGE : AuditTarget.QUIZ;
        return elementLocator.snapshot(startCourse, target, nodeId);
    }

    /** The pending proposal of a node replaced by the composition of its steps, or rejected when none is left. */
    private void recompose(CorrectionBatch batch, String nodeId, CourseEntity startCourse) {
        List<BatchProposalRef> refs = BatchBook.copy(batch.getQuizProposals());
        String proposalId = proposalIdOf(batch, nodeId);
        Optional<CourseElementSnapshot> after = composed(batch, nodeId, startCourse);
        refs.removeIf(ref -> ref != null && Objects.equals(ref.getQuizId(), nodeId));
        List<BatchChangeStep> steps = BatchBook.stepsOn(batch, nodeId);
        Optional<CourseElementSnapshot> before = steps.isEmpty()
                ? elementLocator.snapshot(startCourse, AuditTarget.QUIZ, nodeId)
                        .or(() -> elementLocator.snapshot(startCourse, AuditTarget.KNOWLEDGE, nodeId))
                : before(startCourse, nodeId, steps);
        if (after.isEmpty()) {
            Optional<RevisionArtifact> previous = artifactStore != null
                    ? artifactStore.load(batch.getPlanId(), proposalId) : Optional.empty();
            if (previous.isPresent() && previous.get().getVerdict() == RevisionVerdict.PENDING_APPROVAL) {
                RevisionArtifact rejected = previous.get();
                rejected.setVerdict(RevisionVerdict.REJECTED);
                rejected.setOutcome(RevisionOutcomeKind.REJECTED);
                rejected.setDecidedAt(Instant.now());
                rejected.setRejectionReason("Se sacaron de la tanda " + batch.getId() + " todos sus cambios.");
                artifactStore.save(rejected);
            }
            batch.setQuizProposals(refs);
            return;
        }
        List<String> taskIds = new ArrayList<>();
        List<String> origins = new ArrayList<>();
        for (BatchChange change : BatchBook.list(batch.getChanges())) {
            if (change != null && change.getDroppedReason() == null && nodesOf(change).contains(nodeId)) {
                taskIds.addAll(BatchBook.list(change.getTaskIds()));
                origins.add(change.getChangeId());
            }
        }
        RevisionProposal proposal = new RevisionProposal(proposalId, taskIds.isEmpty() ? null : taskIds.get(0),
                batch.getPlanId(), batch.getStartAuditId(), null, after.get().getNodeTarget(), nodeId,
                before.orElse(null), after.get(), "Tanda " + batch.getId() + ": " + String.join(", ", origins),
                REVISER_KIND, Instant.now(), null, new ArrayList<>(), null);
        if (artifactStore != null) {
            artifactStore.save(new RevisionArtifact(proposal, RevisionVerdict.PENDING_APPROVAL, null,
                    RevisionOutcomeKind.PENDING_APPROVAL_PERSISTED, null, null, null, null));
        }
        refs.add(new BatchProposalRef(nodeId, proposalId));
        batch.setQuizProposals(refs);
    }

    static String proposalIdOf(CorrectionBatch batch, String nodeId) {
        return batch.getId() + "-" + nodeId;
    }

    private static List<String> nodesOf(BatchChange change) {
        List<String> nodes = new ArrayList<>();
        for (BatchChangeStep step : BatchBook.list(change.getSteps())) {
            if (step != null && step.getQuizId() != null && !nodes.contains(step.getQuizId())) {
                nodes.add(step.getQuizId());
            }
        }
        return nodes;
    }

    /** Two changes overlap when they touched a same field of a same node. */
    private static boolean overlaps(BatchChange first, BatchChange second) {
        for (BatchChangeStep a : BatchBook.list(first.getSteps())) {
            for (BatchChangeStep b : BatchBook.list(second.getSteps())) {
                if (a != null && b != null && Objects.equals(a.getQuizId(), b.getQuizId())) {
                    Set<BatchBook.Field> fields = BatchBook.fields(a.getParts());
                    fields.retainAll(BatchBook.fields(b.getParts()));
                    if (!fields.isEmpty()) {
                        return true;
                    }
                }
            }
        }
        return false;
    }

    private static String nextChangeId(CorrectionBatch batch, BatchChange change) {
        String prefix = change.getOrigin() != null ? change.getOrigin().name().toLowerCase() : "cambio";
        return prefix + "-" + (BatchBook.list(batch.getChanges()).size() + 1);
    }
