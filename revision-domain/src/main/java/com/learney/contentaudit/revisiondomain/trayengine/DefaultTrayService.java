    private void noWinner(CorrectionBatch batch, CourseEntity course, TrayItem item, TrayResponse response, String who) {
        TrayBook.NoWinner noWinner = TrayBook.noWinners(batch).stream()
                .filter(n -> n.quizId().equals(item.getQuizId())).findFirst()
                .orElseThrow(() -> new IllegalArgumentException("El ejercicio " + item.getQuizId()
                        + " ya no espera a José."));
        QuizTemplateEntity original = TrayBook.place(course, item.getQuizId()).map(TrayBook.Place::quiz).orElse(null);
        Finding question = TrayBook.noWinnerQuestion(noWinner.quizId(), noWinner.taskIds());
        String note = response.getNote();
        switch (response.getAnswer()) {
            case KEEP_ORIGINAL -> {
                batchService.adjust(adjustment(BatchAdjustmentKind.KEEP_ORIGINAL, item.getQuizId(), noWinner.taskIds(),
                        null, null, null, null, note != null ? note : "José deja el original", who));
                memory.remember(question, original, TrayAnswer.KEEP_ORIGINAL, batch.getId());
            }
            case APPROVE_CANDIDATE -> {
                batchService.adjust(adjustment(BatchAdjustmentKind.ACCEPT_AS_EXCEPTION, item.getQuizId(),
                        noWinner.taskIds(), null, null, bestOf(noWinner, original), null,
                        note != null ? note : "José aprueba el candidato aunque no pasó", who));
                memory.remember(question, original, TrayAnswer.APPROVE_CANDIDATE, batch.getId());
            }
            case WRITE_FIX -> {
                if (response.getFix() == null) {
                    throw new IllegalArgumentException("«escribir el arreglo» necesita el arreglo de José.");
                }
                batchService.adjust(adjustment(BatchAdjustmentKind.RETURN_TO_PANEL, item.getQuizId(), noWinner.taskIds(),
                        null, null, response.getFix(), null, note != null ? note : "arreglo de José", who));
            }
            default -> throw new UnexpectedTrayAnswerException(String.valueOf(response.getAnswer()), item.getItemId(),
                    "KEEP_ORIGINAL, APPROVE_CANDIDATE, WRITE_FIX");
        }
    }

    /** The candidate that failed least: the panel's, or the change the gate of the batch returned. */
    private static PanelCandidate bestOf(TrayBook.NoWinner noWinner, QuizTemplateEntity original) {
        if (noWinner.decision() != null && noWinner.decision().getBestFailing() != null) {
            return noWinner.decision().getBestFailing();
        }
        BatchChange returned = noWinner.returned();
        for (BatchChangeStep step : returned != null ? TrayBook.list(returned.getSteps()) : List.<BatchChangeStep>of()) {
            if (step != null && Objects.equals(step.getQuizId(), noWinner.quizId()) && step.getAfter() != null
                    && step.getAfter().getQuiz() != null) {
                return new PanelCandidate(PanelCandidateKind.WHOLE_EXERCISE, step.getAfter().getQuiz(), null, null,
                        "el cambio que devolvió la compuerta de la tanda");
            }
        }
        throw new IllegalArgumentException("El ejercicio " + noWinner.quizId() + " no tiene un candidato que aprobar.");
    }

