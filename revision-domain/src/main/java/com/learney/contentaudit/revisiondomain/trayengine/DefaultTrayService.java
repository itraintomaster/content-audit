    private void tieOnCourse(CorrectionBatch batch, CourseEntity course, TrayItem item, TrayAnswer answer, String note,
            String who) {
        Finding tie = TrayBook.list(item.getFindings()).get(0);
        QuizTemplateEntity quiz = TrayBook.place(course, item.getQuizId()).map(TrayBook.Place::quiz).orElse(null);
        if (answer == TrayAnswer.IS_ERROR) {
            batchService.adjust(adjustment(BatchAdjustmentKind.TASK_FROM_TIE, item.getQuizId(), List.of(), null, null,
                    null, tie, note != null ? note : "es un error", who));
        }
        memory.remember(tie, quiz, answer, batch.getId());
    }

    private void tieOnCandidate(CorrectionBatch batch, CourseEntity course, TrayItem item, TrayAnswer answer, String note,
            String who) {
        PanelDecision decision = TrayBook.candidateTies(batch).get(item.getQuizId());
        if (decision == null) {
            throw new IllegalArgumentException("El desempate de " + item.getQuizId() + " ya no espera a José.");
        }
        Finding tie = TrayBook.list(decision.getTieFindings()).isEmpty() ? null : decision.getTieFindings().get(0);
        QuizTemplateEntity original = TrayBook.place(course, item.getQuizId()).map(TrayBook.Place::quiz).orElse(null);
        QuizTemplateEntity candidate = DefaultTrayAssembler.candidateQuiz(decision.getBestFailing(), original);
        if (answer == TrayAnswer.PASSES) {
            batchService.adjust(adjustment(BatchAdjustmentKind.ACCEPT_CANDIDATE, item.getQuizId(), decision.getTaskIds(),
                    null, null, decision.getBestFailing(), tie, note != null ? note : "José: pasa", who));
        } else {
            batchService.adjust(adjustment(BatchAdjustmentKind.RETURN_TO_PANEL, item.getQuizId(), decision.getTaskIds(),
                    null, null, null, tie, note != null ? note : "José: el candidato no pasa", who));
        }
        if (tie != null) {
            memory.remember(tie, candidate, answer, batch.getId());
        }
    }

