    @Override
    public Tray answer(TrayResponse response) {
        if (response == null || response.getItemId() == null) {
            throw new IllegalArgumentException("Una respuesta de la bandeja necesita la cosa que contesta.");
        }
        CorrectionBatch batch = open();
        CourseEntity course = courseRepository.load(coursePath);
        Tray tray = assembler.assemble(batch, pairs(batch), blindClosed(batch), course);
        TrayItem item = TrayBook.list(tray.getItems()).stream()
                .filter(i -> response.getItemId().equals(i.getItemId())).findFirst()
                .orElseThrow(() -> new IllegalArgumentException("La bandeja de la tanda " + batch.getId()
                        + " no tiene «" + response.getItemId() + "»."));
        TrayAnswer answer = response.getAnswer();
        if (answer == null || !TrayBook.list(item.getAnswers()).contains(answer)) {
            throw new UnexpectedTrayAnswerException(String.valueOf(answer), item.getItemId(),
                    TrayBook.list(item.getAnswers()).isEmpty() ? "no se contesta"
                            : TrayBook.list(item.getAnswers()).stream().map(Enum::name)
                                    .collect(Collectors.joining(", ")));
        }
        String who = response.getDecidedBy() != null && !response.getDecidedBy().isBlank() ? response.getDecidedBy()
                : JOSE;
        switch (item.getKind()) {
            case BLIND_SAMPLE -> blindPair(item, response, who);
            case TIE_ON_COURSE -> tieOnCourse(batch, course, item, answer, response.getNote(), who);
            case TIE_ON_CANDIDATE -> tieOnCandidate(batch, course, item, answer, response.getNote(), who);
            case NO_WINNER -> noWinner(batch, course, item, response, who);
            case RULE_SAMPLE -> ruleSample(batch, item, response, who);
            case PENDING_RERECORDING -> {
                // never answered: recording is José's work outside content-audit
            }
        }
        return view();
    }

    @Override
    public BatchPublication publish(String approvedBy, String note) {
        CorrectionBatch batch = open();
        if (!blindClosed(batch)) {
            // F-CJUEZ-R004 inv. 3: the last closing already says which judges without approval keep the batch from
            // publishing -- compared again it would say it too, but closing a batch of A1 takes minutes --; the refusal
            // copies them, so José does not answer the sample first to find out.
            String judges = judgesWithoutApproval(batch);
            throw new BatchNotPublishableException(batch.getId(), judges != null
                    ? "el veredicto de su último cierre dice «" + judges + "»: no pasa mientras sigan así, aunque se"
                            + " responda la muestra ciega (que además falta: respondela desde la bandeja, par por par)"
                    : "el veredicto de la tanda es «falta la muestra ciega»: respondela desde la bandeja, par por par");
        }
        // R004 and R007: a rule whose sample José did not approve stays out.
        List<String> excluded = TrayBook.rulesToSample(batch);
        // R008: the verdict with every decision of José in; publishing closes with no request (no judges paid here).
        BatchClosing closing = batchService.close(new BatchCloseRequest(new LinkedHashMap<>(), null));
        // F-PUBPROD-R005: «no se puede decidir» no es «pasa», y un piso sin decidir tampoco: la negativa lo dice antes
        // que la compuerta, aunque pase, con las palabras de siempre (VerdictWording) y con lo que dice el veredicto
        // (por ejemplo, los jueces sin aprobar de F-CJUEZ-R004).
        BatchVerdict verdict = closing != null && closing.getComparison() != null
                ? closing.getComparison().getVerdict() : null;
        String refusedVerdict = "el veredicto de F es " + VerdictWording.quoted(verdict) + ", no «pasa»"
                + (verdict != null && verdict.getDetail() != null ? ": " + verdict.getDetail() : "");
        if (verdict != null && (verdict.getKind() == VerdictKind.UNDECIDABLE
                || VerdictWording.undecidedFloors(verdict) > 0)) {
            throw new BatchNotPublishableException(batch.getId(), refusedVerdict);
        }
        if (closing == null || closing.getGate() == null || !closing.getGate().isPasses()) {
            throw new BatchNotPublishableException(batch.getId(), "la compuerta de «no empeorar» no pasa"
                    + (closing != null && closing.getGate() != null ? ": " + String.join("; ",
                    TrayBook.list(closing.getGate().getReasons())) : ""));
        }
        if (!VerdictWording.publishable(verdict)) {
            throw new BatchNotPublishableException(batch.getId(), refusedVerdict);
        }
        return batchService.publish(new BatchPublishRequest(approvedBy != null ? approvedBy : JOSE, note, excluded));
    }

