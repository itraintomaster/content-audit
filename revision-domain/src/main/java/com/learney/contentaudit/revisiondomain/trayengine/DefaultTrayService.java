    /**
     * F-CJUEZ-R004: the judges without approval that the verdict of the last closing names, as the comparison ends its
     * detail with them -- «juez sin aprobar: A, B» --, copied as it says them; null when the batch was never closed or its
     * last verdict names none.
     */
    private static String judgesWithoutApproval(CorrectionBatch batch) {
        List<BatchClosing> closings = TrayBook.list(batch.getClosings());
        BatchClosing last = closings.isEmpty() ? null : closings.get(closings.size() - 1);
        BatchVerdict verdict = last != null && last.getComparison() != null ? last.getComparison().getVerdict() : null;
        String detail = verdict != null ? verdict.getDetail() : null;
        int at = detail != null ? detail.lastIndexOf(JUDGES_WITHOUT_APPROVAL) : -1;
        return at >= 0 ? detail.substring(at) : null;
    }

    private CorrectionBatch open() {
        Optional<CorrectionBatch> open = batchStore != null ? batchStore.open() : batchService.current();
        return open.orElseThrow(() -> new NoOpenBatchException(
                "No hay una tanda abierta: la bandeja es la de la tanda abierta."));
    }

    private List<BlindPairView> pairs(CorrectionBatch batch) {
        String sampleId = batch.getBlindSampleId();
        if (sampleId == null || blindSampleService == null || blindClosed(batch)) {
            return new ArrayList<>();
        }
        return new ArrayList<>(TrayBook.list(blindSampleService.pairs(sampleId)));
    }

    private boolean blindClosed(CorrectionBatch batch) {
        String sampleId = batch.getBlindSampleId();
        return sampleId != null && blindSampleService != null && blindSampleService.result(sampleId).isPresent();
    }

    private static BatchAdjustment adjustment(BatchAdjustmentKind kind, String quizId, List<String> taskIds,
            String changeId, String ruleId, PanelCandidate candidate, Finding finding, String reason, String who) {
        return new BatchAdjustment(kind, quizId, new ArrayList<>(TrayBook.list(taskIds)), changeId, ruleId, candidate,
                finding, reason, who, Instant.now());
    }
