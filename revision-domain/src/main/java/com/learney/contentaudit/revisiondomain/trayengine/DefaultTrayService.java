    private void blindPair(TrayItem item, TrayResponse response, String who) {
        if (response.getPairIndex() == null || response.getPairAnswer() == null) {
            throw new IllegalArgumentException("Un par de la muestra ciega se contesta con su número y A_BETTER, B_BETTER,"
                    + " EQUAL o BOTH_WRONG.");
        }
        String sampleId = item.getBlindSampleId();
        blindSampleService.answer(sampleId, response.getPairIndex(), response.getPairAnswer(), who);
        int last = TrayBook.list(item.getBlindPairs()).stream().mapToInt(BlindPairView::getIndex).max().orElse(0);
        if (response.getPairIndex() >= last) {
            blindSampleService.close(sampleId); // the last pair closes it, and only then the rest of the tray shows
        }
    }

