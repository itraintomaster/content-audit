    private void ruleSample(CorrectionBatch batch, TrayItem item, TrayResponse response, String who) {
        String ruleId = item.getRuleId();
        switch (response.getAnswer()) {
            case RULE_OK -> batchService.adjust(adjustment(BatchAdjustmentKind.APPROVE_RULE_SAMPLE, null, List.of(), null,
                    ruleId, null, null, response.getNote() != null ? response.getNote() : "la muestra está bien", who));
            case DROP_CHANGE -> {
                String changeId = response.getChangeId();
                boolean ofTheRule = TrayBook.list(batch.getChanges()).stream().anyMatch(c -> c != null
                        && Objects.equals(c.getChangeId(), changeId) && Objects.equals(c.getRuleId(), ruleId)
                        && c.getDroppedReason() == null);
                if (!ofTheRule) {
                    throw new IllegalArgumentException("Para sacar un cambio de la regla " + ruleId + " hace falta uno"
                            + " de sus cambios, no «" + changeId + "».");
                }
                batchService.adjust(adjustment(BatchAdjustmentKind.DROP_CHANGE, null, List.of(), changeId, ruleId, null,
                        null, response.getNote() != null ? response.getNote() : "José lo sacó mirando la muestra", who));
            }
            case DROP_RULE -> batchService.adjust(adjustment(BatchAdjustmentKind.DROP_RULE, null, List.of(), null, ruleId,
                    null, null, response.getNote(), who));
            default -> throw new UnexpectedTrayAnswerException(String.valueOf(response.getAnswer()), item.getItemId(),
                    "RULE_OK, DROP_CHANGE, DROP_RULE");
        }
    }

