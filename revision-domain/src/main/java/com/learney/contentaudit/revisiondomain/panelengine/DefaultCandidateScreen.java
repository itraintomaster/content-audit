    private static boolean isConversion(TopicWork work, QuizTemplateEntity original, PanelCandidate candidate) {
        if (candidate.getKind() == PanelCandidateKind.MULTIPLE_CHOICE_CONVERSION) {
            return true;
        }
        ConversionOrder order = work.getConversion();
        return order != null && order.getTargetKind() == FormKind.MULTIPLE_CHOICE
                && !TopicState.isMultipleChoice(original) && TopicState.isMultipleChoice(candidate.getQuiz());
    }

    private static List<String> conversion(TopicWork work, QuizTemplateEntity original, PanelCandidate candidate,
            QuizTemplateEntity proposed) {
        List<String> violations = new ArrayList<>();
        ConversionOrder order = work.getConversion();
        int optionCount = order != null && order.getOptionCount() > 0 ? order.getOptionCount() : DEFAULT_OPTION_COUNT;
        if (!TopicState.isMultipleChoice(proposed)) {
            violations.add("no pasó a opción múltiple");
            return violations;
        }
        List<MultipleChoiceItemEntity> items = items(proposed);
        List<MultipleChoiceItemEntity> correct = items.stream().filter(i -> i != null && i.getIncidence() > 0.0).toList();
        if (correct.size() != 1) {
            violations.add("tiene " + correct.size() + " opciones correctas y debe tener una sola");
        }
        if (items.size() != optionCount) {
            violations.add("tiene " + items.size() + " opciones y el encargo pide " + optionCount);
        }
        // 1. The correct option is the first accepted answer of today: what is heard does not change.
        String first = TopicState.firstAnswer(original);
        String right = correct.size() == 1 ? correct.get(0).getLabel() : null;
        if (right != null && !compact(right).equals(compact(first))) {
            violations.add("la opción correcta «" + right + "» no es la primera respuesta aceptada de hoy, «" + first
                    + "»: cambiaría lo que se escucha");
        }
        // 2. The others are contractions different from the correct one, none of them the correct one in another form.
        Set<String> seen = new LinkedHashSet<>();
        for (MultipleChoiceItemEntity item : items) {
            if (item == null || item.getLabel() == null || item.getIncidence() > 0.0) {
                continue;
            }
            String label = item.getLabel();
            if (right != null && longForm(label).equals(longForm(right))) {
                violations.add("«" + label + "» es la correcta «" + right + "» en otra forma");
            } else if (!label.contains("'") && !label.contains("’")) {
                violations.add("«" + label + "» no es una contracción");
            }
            if (!seen.add(longForm(label))) {
                violations.add("«" + label + "» repite otra opción");
            }
        }
        // 3. The translation and the mini theory stay; the instructions ask to choose, without asking for a form.
        if (!Objects.equals(original.getTranslation(), proposed.getTranslation())) {
            violations.add("cambia la traducción");
        }
        if (!Objects.equals(original.getMiniTheory(), proposed.getMiniTheory())) {
            violations.add("cambia la miniteoría");
        }
        // F-CONVERSION-R003: conversion must retain every stored variant, including its order.
        if (!Objects.equals(original.getSentences(), proposed.getSentences())) {
            violations.add("cambia las oraciones guardadas; la conversión debe conservar todas sus variantes y su orden");
        }
        if (proposed.getInstructions() != null && ASKS_FOR_A_FORM.matcher(proposed.getInstructions()).find()) {
            violations.add("la consigna del ejercicio sigue pidiendo una forma");
        }
        if (candidate.getTopicInstructions() != null && ASKS_FOR_A_FORM.matcher(candidate.getTopicInstructions()).find()) {
            violations.add("la consigna del tema sigue pidiendo una forma");
        }
        return violations;
    }

