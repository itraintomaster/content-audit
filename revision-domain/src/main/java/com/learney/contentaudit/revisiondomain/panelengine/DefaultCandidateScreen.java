    /** The parts the tasks of the exercise may change, by the declaration of the analyzer of each one. */
    private Set<ExercisePart> allowedParts(TopicWork work, String quizId) {
        Set<ExercisePart> allowed = EnumSet.noneOf(ExercisePart.class);
        for (ErrorTaskBrief brief : work.getBriefs() != null ? work.getBriefs() : List.<ErrorTaskBrief>of()) {
            if (brief == null || brief.getTask() == null || brief.getTask().getNodeTarget() != AuditTarget.QUIZ
                    || !Objects.equals(brief.getTask().getNodeId(), quizId)) {
                continue;
            }
            List<ExercisePart> scope = brief.getEditScope();
            if ((scope == null || scope.isEmpty()) && brief.getFinding() != null && correctionCatalog != null) {
                scope = correctionCatalog.find(brief.getFinding().getAnalyzer())
                        .map(c -> c.editScope(brief.getFinding().getResolution())).orElse(List.of());
            }
            if (scope != null) {
                allowed.addAll(scope);
            }
        }
        if (allowed.contains(ExercisePart.STATEMENT) || allowed.contains(ExercisePart.ANSWERS)) {
            // The translation follows the English: a new sentence brings its own.
            allowed.add(ExercisePart.TRANSLATION);
        }
        if (allowed.contains(ExercisePart.STATEMENT) || allowed.contains(ExercisePart.ANSWERS)
                || allowed.contains(ExercisePart.OPTIONS)) {
            // F-NOEMP-R004: spoken text follows the exercise. The later change gate turns the changed text into an
            // AudioRerecordRequest; rejecting AUDIO here would prevent that required declaration from being created.
            allowed.add(ExercisePart.AUDIO);
        }
        return allowed;
    }

    private static List<MultipleChoiceItemEntity> items(QuizTemplateEntity quiz) {
        return quiz.getForm() != null && quiz.getForm().getMultipleChoice() != null
                && quiz.getForm().getMultipleChoice().getItems() != null
                ? quiz.getForm().getMultipleChoice().getItems() : List.of();
    }

    private static String name(ExercisePart part) {
        return switch (part) {
            case STATEMENT -> "el enunciado";
            case HINT -> "la pista";
            case ANSWERS -> "las respuestas";
            case OPTIONS -> "las opciones";
            case FORM_KIND -> "el tipo de ejercicio";
            case TRANSLATION -> "la traducción";
            case MINI_THEORY -> "la miniteoría";
            case INSTRUCTIONS -> "la consigna";
            case TOPIC_INSTRUCTIONS -> "la consigna del tema";
            case STORED_SENTENCE -> "la oración guardada";
            case AUDIO -> "lo que se escucha";
            case WHOLE_EXERCISE -> "el ejercicio entero";
        };
    }

    private static String compact(String text) {
        return text == null ? "" : text.toLowerCase(Locale.ROOT).replace('’', '\'').replaceAll("\\s+", " ").strip();
    }

    /** The answer read in its long form: «isn't» and «'s not» are both «is not». */
    static String longForm(String text) {
        String t = " " + compact(text) + " ";
        t = t.replace("won't", "will not").replace("can't", "can not").replace("shan't", "shall not")
                .replace("n't", " not").replace("'re", " are").replace("'m", " am").replace("'s", " is")
                .replace("'ve", " have").replace("'ll", " will").replace("'d", " would");
        return t.replaceAll("\\s+", " ").strip();
    }
