/**
 * The one place that maps a course and measures it (F-PROYU-R001, R003): with the analyzers whose
 * measures the starting analysis keeps at its root, in that order -- the catalog's, as the engine wrote
 * them --, so every photo measures what the analysis it starts from measured. The budget of an analyzer
 * the request names travels as its policy; every other analyzer goes without one and its provider
 * completes it by whom it consults, as in {@code analyze}: a local model without a cap, claude -p with
 * budget 0 (F-RONDA2-R002). A starting analysis that keeps no measures -- saved before the contract --
 * falls back to the base run, and the report says so in its root.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
class DefaultProjectionMeasurer implements ProjectionMeasurer {
    /** Key of the root's metadata that declares with which analyzers the photo was measured. */
    static final String MEASURE_KEY = "projectionMeasure";

    /** The photo ran the analyzers of the starting analysis. */
    static final String STARTING_ANALYSIS = "STARTING_ANALYSIS";

    /** The starting analysis kept no measures: the photo is the base run. */
    static final String BASE_RUN = "BASE_RUN";

    private final CourseMapper courseMapper;

    private final AuditEngine auditEngine;

    public DefaultProjectionMeasurer(CourseMapper courseMapper, AuditEngine auditEngine) {
        this.courseMapper = courseMapper;
        this.auditEngine = auditEngine;
    }

    @Override
    public AuditReport measure(CourseEntity course, AuditReport startingAnalysis,
            Map<String, Integer> analyzerBudgets) {
        AuditableCourse auditable = courseMapper.map(course);
        List<String> analyzers = measuredAnalyzers(startingAnalysis);
        AuditReport report;
        String measure;
        if (analyzers.isEmpty()) {
            report = auditEngine.runAudit(auditable);
            measure = BASE_RUN;
        } else {
            Map<String, EvaluationRunPolicy> policies = new LinkedHashMap<>();
            if (analyzerBudgets != null) {
                for (String analyzer : analyzers) {
                    Integer budget = analyzerBudgets.get(analyzer);
                    if (budget != null) {
                        policies.put(analyzer, new EvaluationRunPolicy(budget, false, null, null, null, null));
                    }
                }
            }
            report = auditEngine.runAudit(auditable, new AnalyzerRunSelection(analyzers, policies));
            measure = STARTING_ANALYSIS;
        }
        declare(report, measure);
        return report;
    }

    /** The analyzers of the starting analysis, from the measures at its root, in their order. */
    static List<String> measuredAnalyzers(AuditReport startingAnalysis) {
        List<String> names = new ArrayList<>();
        if (startingAnalysis == null || startingAnalysis.getRoot() == null
                || startingAnalysis.getRoot().getMeasures() == null) {
            return names;
        }
        for (AnalyzerMeasure measure : startingAnalysis.getRoot().getMeasures()) {
            if (measure != null && measure.getAnalyzer() != null && !names.contains(measure.getAnalyzer())) {
                names.add(measure.getAnalyzer());
            }
        }
        return names;
    }

    private static void declare(AuditReport report, String measure) {
        if (report == null || report.getRoot() == null) {
            return;
        }
        AuditNode root = report.getRoot();
        Map<String, Object> metadata = root.getMetadata() != null
                ? new LinkedHashMap<>(root.getMetadata()) : new LinkedHashMap<>();
        metadata.put(MEASURE_KEY, measure);
        root.setMetadata(metadata);
    }
}
