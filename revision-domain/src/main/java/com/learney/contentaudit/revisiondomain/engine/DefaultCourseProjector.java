    private CourseProjection project(Path coursePath, ProjectionScope scope, AuditReport measuredApproved,
            AuditReport measuredProjected) {
        // The active pair: the projection starts from it (F-PROYU-R006).
        Optional<ActiveAnalysisSelection> selection = activeAnalysisSelectionStore.read();
        if (selection.isEmpty() || selection.get().getAuditId() == null || selection.get().getPlanId() == null) {
            return unavailable(null, null, scope, ConsolidatedViewUnavailabilityReason.NO_ACTIVE_ANALYSIS,
                    "No hay un par activo: set-active --audit <id> --plan <id>");
        }
        String auditId = selection.get().getAuditId();
        String planId = selection.get().getPlanId();
        Optional<RefinementPlan> plan = refinementPlanStore.load(planId);
        if (plan.isEmpty()) {
            return unavailable(auditId, planId, scope, ConsolidatedViewUnavailabilityReason.ACTIVE_PLAN_UNAVAILABLE,
                    "El plan activo '" + planId + "' no está");
        }
        Optional<AuditReport> active = auditReportStore.load(auditId);
        if (active.isEmpty()) {
            return unavailable(auditId, planId, scope, ConsolidatedViewUnavailabilityReason.NO_ACTIVE_ANALYSIS,
                    "El análisis activo '" + auditId + "' no está");
        }
        AuditReport original = active.get();

        // The proposals of the active plan: the approved ones and the pending ones of the scope.
        List<RevisionProposal> approved = new ArrayList<>();
        Map<String, RevisionProposal> pendingById = new LinkedHashMap<>();
        for (RevisionArtifact artifact : revisionArtifactStore.listByPlan(planId)) {
            if (artifact == null || artifact.getProposal() == null) {
                continue;
            }
            if (artifact.getVerdict() == RevisionVerdict.APPROVED) {
                approved.add(artifact.getProposal());
            } else if (artifact.getVerdict() == RevisionVerdict.PENDING_APPROVAL) {
                pendingById.putIfAbsent(artifact.getProposal().getProposalId(), artifact.getProposal());
            }
        }
        List<NonApplicablePending> nonApplicable = new ArrayList<>();
        List<RevisionProposal> pending = new ArrayList<>();
        if (scope == null || scope.getProposalIds() == null) {
            pending.addAll(pendingById.values());
        } else {
            Set<String> named = new LinkedHashSet<>(scope.getProposalIds());
            for (String id : named) {
                RevisionProposal proposal = pendingById.get(id);
                if (proposal != null) {
                    pending.add(proposal);
                } else {
                    nonApplicable.add(new NonApplicablePending(id, NonApplicablePendingReason.OTHER,
                            "'" + id + "' no es una propuesta pendiente del plan activo '" + planId + "'"));
                }
            }
        }

        CourseEntity course;
        try {
            course = courseRepository.load(coursePath);
        } catch (RuntimeException e) {
            return unavailable(auditId, planId, scope, ConsolidatedViewUnavailabilityReason.REAGGREGATION_FAILED,
                    "No se pudo leer el curso: " + e.getMessage());
        }

        // The approved ones are already written in the course (approve writes it), so one whose node
        // no longer matches its elementBefore is not declared; but one whose node is gone, or that
        // cannot be written, makes the projection inconsistent (F-CDIFF-R013). The pending ones of
        // the scope go on top of them.
        AppliedProposals withApproved = pendingApplier.apply(course, approved);
        for (NonApplicablePending failed : withApproved.getNonApplicable()) {
            if (failed.getReason() != NonApplicablePendingReason.ELEMENT_BEFORE_MISMATCH) {
                return unavailable(auditId, planId, scope, ConsolidatedViewUnavailabilityReason.INCONSISTENT_PROPOSAL,
                        "La propuesta aprobada '" + failed.getProposalId() + "' no se puede escribir en el curso: "
                                + failed.getDetail());
            }
        }
        AppliedProposals withPending = pendingApplier.apply(withApproved.getCourse(), pending);
        nonApplicable.addAll(withPending.getNonApplicable());

        Map<String, Integer> budgets = scope != null && scope.getAnalyzerBudgets() != null
                ? scope.getAnalyzerBudgets() : Map.of();
        AuditReport approvedPhoto;
        AuditReport projectedPhoto;
        try {
            approvedPhoto = measuredApproved != null ? measuredApproved : projectionMeasurer.measure(withApproved.getCourse(), original, budgets);
            projectedPhoto = measuredProjected != null ? measuredProjected : withPending.getApplied().isEmpty()
                    ? approvedPhoto
                    : projectionMeasurer.measure(withPending.getCourse(), original, budgets);
        } catch (RuntimeException e) {
            return unavailable(auditId, planId, scope, ConsolidatedViewUnavailabilityReason.REAGGREGATION_FAILED,
                    "No se pudo medir la proyección: " + e.getMessage());
        }

        List<ProjectedChange> changes = new ArrayList<>();
        List<RevisionProposal> orderedApproved = new ArrayList<>(approved);
        orderedApproved.sort(DefaultPendingApplier.CREATION_ORDER);
        for (RevisionProposal proposal : orderedApproved) {
            changes.add(new ProjectedChange(proposal.getProposalId(), proposal.getNodeTarget(), proposal.getNodeId(),
                    false));
        }
        for (RevisionProposal proposal : withPending.getApplied()) {
            changes.add(new ProjectedChange(proposal.getProposalId(), proposal.getNodeTarget(), proposal.getNodeId(),
                    true));
        }

        return new CourseProjection(auditId, planId, scopeId(scope, planId), ConsolidatedViewAvailability.AVAILABLE,
                null, original, approvedPhoto, projectedPhoto, changes, nonApplicable);
    }

    /** The id of the batch when there is one; without a batch, the active plan's. */
    private static String scopeId(ProjectionScope scope, String planId) {
        return scope != null && scope.getScopeId() != null && !scope.getScopeId().isBlank()
                ? scope.getScopeId() : planId;
    }

    private static CourseProjection unavailable(String auditId, String planId, ProjectionScope scope,
            ConsolidatedViewUnavailabilityReason reason, String detail) {
        return new CourseProjection(auditId, planId, scopeId(scope, planId), ConsolidatedViewAvailability.UNAVAILABLE,
                new ConsolidatedViewUnavailability(reason, detail), null, null, null, List.of(), List.of());
    }
