    private List<TrayItem> courseTies(CorrectionBatch batch, CourseEntity course) {
        List<TrayItem> items = new ArrayList<>();
        Map<String, Integer> perQuiz = new LinkedHashMap<>();
        for (Finding tie : TrayBook.list(batch.getCourseTies())) {
            String quizId = tie != null && tie.getNode() != null ? tie.getNode().getNodeId() : null;
            Optional<TrayBook.Place> place = TrayBook.place(course, quizId);
            if (place.isEmpty() || recalled(tie, place.get().quiz())) {
                continue;
            }
            int n = perQuiz.merge(quizId, 1, Integer::sum);
            items.add(new TrayItem(TrayBook.TIE_ON_COURSE + quizId + (n > 1 ? "-" + n : ""), TrayItemKind.TIE_ON_COURSE,
                    tie.getSeverity(), place.get().knowledge().getId(), quizId,
                    "Los dos jueces de " + tie.getAnalyzer() + " no coinciden sobre este ejercicio: ¿es un error?",
                    new ArrayList<>(List.of(TrayAnswer.IS_ERROR, TrayAnswer.NOT_ERROR)), view(place.get().quiz()), null,
                    new ArrayList<>(List.of(tie)), observation(tie), null, new ArrayList<>(), null, new ArrayList<>(),
                    null));
        }
        return items;
    }

    private List<TrayItem> candidateTies(CorrectionBatch batch, CourseEntity course) {
        List<TrayItem> items = new ArrayList<>();
        for (Map.Entry<String, PanelDecision> entry : TrayBook.candidateTies(batch).entrySet()) {
            String quizId = entry.getKey();
            PanelDecision decision = entry.getValue();
            Optional<TrayBook.Place> place = TrayBook.place(course, quizId);
            QuizTemplateEntity candidate = candidateQuiz(decision.getBestFailing(),
                    place.map(TrayBook.Place::quiz).orElse(null));
            List<Finding> ties = new ArrayList<>(TrayBook.list(decision.getTieFindings()));
            if (!ties.isEmpty() && candidate != null && recalled(ties.get(0), candidate)) {
                continue;
            }
            String analyzer = ties.isEmpty() ? "traducción y sentido" : ties.get(0).getAnalyzer();
            items.add(new TrayItem(TrayBook.TIE_ON_CANDIDATE + quizId, TrayItemKind.TIE_ON_CANDIDATE,
                    TrayBook.mostSevere(ties), decision.getKnowledgeId(), quizId,
                    "Los dos jueces de " + analyzer + " no coinciden sobre el candidato de la mesa: ¿pasa?",
                    new ArrayList<>(List.of(TrayAnswer.PASSES, TrayAnswer.DOES_NOT_PASS)),
                    place.map(p -> view(p.quiz())).orElse(null), candidate != null ? view(candidate) : null, ties,
                    attempts(decision), null, new ArrayList<>(), null, new ArrayList<>(), null));
        }
        return items;
    }

