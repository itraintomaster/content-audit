    private List<TrayItem> rerecordings(CorrectionBatch batch, CourseEntity course) {
        Map<String, AudioRerecordRequest> latest = new LinkedHashMap<>();
        for (AudioRerecordRequest request : TrayBook.list(batch.getPendingRerecords())) {
            put(latest, request);
        }
        for (BatchChange change : TrayBook.list(batch.getChanges())) {
            if (change == null || change.getDroppedReason() != null || change.getGateVerdict() == null) {
                continue;
            }
            for (AudioRerecordRequest request : TrayBook.list(change.getGateVerdict().getRerecords())) {
                put(latest, request);
            }
        }
        List<TrayItem> items = new ArrayList<>();
        for (Map.Entry<String, AudioRerecordRequest> entry : latest.entrySet()) {
            AudioRerecordRequest request = entry.getValue();
            Optional<TrayBook.Place> place = TrayBook.place(course, request.getQuizId());
            QuizTemplateEntity shown = TrayBook.changed(batch, request.getQuizId())
                    .orElse(place.map(TrayBook.Place::quiz).orElse(null));
            items.add(new TrayItem(TrayBook.RERECORD + entry.getKey(), TrayItemKind.PENDING_RERECORDING, null,
                    place.map(p -> p.knowledge().getId()).orElse(null), request.getQuizId(), null, new ArrayList<>(),
                    shown != null ? view(shown) : null, null, new ArrayList<>(), new ArrayList<>(), null,
                    new ArrayList<>(), null, new ArrayList<>(), request));
        }
        return items;
    }

    /** Each audio once, with the latest text asked. */
    private static void put(Map<String, AudioRerecordRequest> latest, AudioRerecordRequest request) {
        if (request == null) {
            return;
        }
        String key = request.getAudioKey() != null && !request.getAudioKey().isBlank() ? request.getAudioKey()
                : request.getQuizId();
        latest.remove(key);
        latest.put(key, request);
    }

