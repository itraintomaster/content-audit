    private List<TrayItem> noWinners(CorrectionBatch batch, CourseEntity course) {
        List<TrayItem> items = new ArrayList<>();
        for (TrayBook.NoWinner noWinner : TrayBook.noWinners(batch)) {
            Optional<TrayBook.Place> place = TrayBook.place(course, noWinner.quizId());
            if (place.isEmpty() || recalled(TrayBook.noWinnerQuestion(noWinner.quizId(), noWinner.taskIds()),
                    place.get().quiz())) {
                continue;
            }
            QuizTemplateEntity original = place.get().quiz();
            QuizTemplateEntity candidate = null;
            List<Finding> failed = new ArrayList<>();
            List<String> reasons = new ArrayList<>();
            int tried = 0;
            PanelDecision decision = noWinner.decision();
            if (decision != null) {
                candidate = candidateQuiz(decision.getBestFailing(), original);
                ChangeGateVerdict verdict = decision.getBestFailingVerdict();
                if (verdict != null) {
                    failed.addAll(TrayBook.list(verdict.getNewErrors()));
                    for (String reason : TrayBook.list(verdict.getReasons())) {
                        reasons.add("no pasó: " + reason);
                    }
                }
                reasons.addAll(attempts(decision));
                tried = decision.getAttempts();
            }
            if (noWinner.returned() != null) {
                BatchChange returned = noWinner.returned();
                for (BatchChangeStep step : TrayBook.list(returned.getSteps())) {
                    if (step != null && noWinner.quizId().equals(step.getQuizId()) && step.getAfter() != null
                            && step.getAfter().getQuiz() != null) {
                        candidate = step.getAfter().getQuiz();
                    }
                }
                reasons.add("la compuerta de la tanda lo devolvió: " + returned.getDroppedReason());
            }
            for (String taskId : noWinner.taskIds()) {
                tried = Math.max(tried, TrayBook.outcome(batch, taskId).map(BatchTaskOutcome::getAttempts).orElse(0));
            }
            List<TrayAnswer> answers = new ArrayList<>(List.of(TrayAnswer.KEEP_ORIGINAL));
            if (candidate != null) {
                answers.add(TrayAnswer.APPROVE_CANDIDATE);
            }
            answers.add(TrayAnswer.WRITE_FIX);
            items.add(new TrayItem(TrayBook.NO_WINNER + noWinner.quizId(), TrayItemKind.NO_WINNER,
                    TrayBook.mostSevere(failed), place.get().knowledge().getId(), noWinner.quizId(),
                    "Nadie arregló este ejercicio" + (tried > 0 ? " en " + tried + (tried == 1 ? " intento" : " intentos")
                            : "") + ": ¿dejás el original, aprobás el candidato o escribís el arreglo?",
                    answers, view(original), candidate != null ? view(candidate) : null, failed, reasons, null,
                    new ArrayList<>(), null, new ArrayList<>(), null));
        }
        return items;
    }

    /** The reasons of each attempt, as the panel gave them back. */
    private static List<String> attempts(PanelDecision decision) {
        List<String> reasons = new ArrayList<>();
        for (CandidateRejection rejection : TrayBook.list(decision.getRejections())) {
            if (rejection != null) {
                reasons.add("intento " + rejection.getAttempt() + ": " + String.join("; ",
                        TrayBook.list(rejection.getReasons())));
            }
        }
        return reasons;
    }

