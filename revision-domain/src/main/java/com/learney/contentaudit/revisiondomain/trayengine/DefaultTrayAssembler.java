    private boolean recalled(Finding finding, QuizTemplateEntity quiz) {
        return memory != null && memory.recall(finding, quiz).isPresent();
    }

    /** The exercise a candidate proposes: its own, or the original with the mini theory it writes. */
    static QuizTemplateEntity candidateQuiz(PanelCandidate candidate, QuizTemplateEntity original) {
        if (candidate == null) {
            return null;
        }
        if (candidate.getQuiz() != null) {
            return candidate.getQuiz();
        }
        if (original != null && candidate.getMiniTheoryText() != null) {
            QuizTemplateEntity copy = QuizTemplateEntities.copyOf(original);
            copy.setMiniTheory(candidate.getMiniTheoryText());
            return copy;
        }
        return original;
    }

    private QuizStudentView view(QuizTemplateEntity quiz) {
        if (quiz == null || quizStudentViewRenderer == null) {
            return null;
        }
        return quizStudentViewRenderer.render(new AuditableQuiz(new ArrayList<>(), quiz.getId(), quiz.getTitle(),
                quiz.getCode(), quiz.getTranslation(), quiz.getSentences(), null, quiz.getInstructions(),
                quiz.getForm() != null ? quiz.getForm().getSentenceParts() : null,
                quiz.getForm() != null ? quiz.getForm().getMultipleChoice() : null, quiz.getMiniTheory(),
                quiz.getAnswerAudioUrl()));
    }

    private static List<String> observation(Finding finding) {
        List<String> reasons = new ArrayList<>();
        if (finding.getEvidence() != null && finding.getEvidence().getObservation() != null) {
            reasons.add(finding.getEvidence().getObservation());
        }
        return reasons;
    }
