    private List<TrayItem> ruleSamples(CorrectionBatch batch, CourseEntity course) {
        List<TrayItem> items = new ArrayList<>();
        for (String ruleId : TrayBook.rulesToSample(batch)) {
            List<TraySamplePair> pairs = new ArrayList<>();
            for (BatchChange change : ruleSampleDrawer.draw(batch, ruleId, RULE_SAMPLE_SIZE)) {
                for (BatchChangeStep step : TrayBook.list(change.getSteps())) {
                    if (step == null || step.getAfter() == null || step.getAfter().getQuiz() == null) {
                        continue;
                    }
                    QuizStudentView before = TrayBook.place(course, step.getQuizId()).map(p -> view(p.quiz()))
                            .orElse(null);
                    pairs.add(new TraySamplePair(change.getChangeId(), step.getQuizId(), before,
                            view(step.getAfter().getQuiz())));
                }
            }
            int total = TrayBook.changesOf(batch, ruleId);
            items.add(new TrayItem(TrayBook.RULE_SAMPLE + ruleId, TrayItemKind.RULE_SAMPLE, null, null, null,
                    "La regla " + ruleId + " cambió " + total + (total == 1 ? " ejercicio" : " ejercicios") + "; mirá "
                            + (pairs.size() >= total ? "todos" : "estos " + pairs.size())
                            + ": ¿está bien? Podés sacar un cambio o la regla entera.",
                    new ArrayList<>(List.of(TrayAnswer.RULE_OK, TrayAnswer.DROP_CHANGE, TrayAnswer.DROP_RULE)), null, null,
                    new ArrayList<>(), new ArrayList<>(), ruleId, pairs, null, new ArrayList<>(), null));
        }
        return items;
    }

