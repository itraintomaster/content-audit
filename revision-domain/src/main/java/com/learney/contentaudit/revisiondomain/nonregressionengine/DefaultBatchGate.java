    /** A floor that the row breaks, with how much is missing to bring it back, or null. */
    private static Breach breachOf(ComparisonRow row) {
        RowValue projected = row.getProjected();
        if (projected == null || projected.getValue() == null) {
            return null;
        }
        String where = describe(row);
        if (row.getUnit() == GoalUnit.EXERCISES) {
            RowValue start = row.getApproved() != null ? row.getApproved() : row.getBaseline();
            if (start == null || start.getValue() == null) {
                return null;
            }
            double deficit = projected.getValue() - start.getValue();
            if (deficit > EPSILON) {
                String rule = row.getFamily() == AnalyzerFamily.VOCABULARY ? "F-NOEMP-R005 (inv. 3)" : "F-NOEMP-R005 (inv. 2)";
                return new Breach(deficit, rule + ": ejercicios con " + where + ": " + GateRules.number(start.getValue())
                        + " → " + GateRules.number(projected.getValue()) + " contra el inicio de la tanda (tolerancia 0)");
            }
            return null;
        }
        if (row.getFamily() == AnalyzerFamily.VOCABULARY) {
            RowValue base = row.getBaseline();
            if (base == null || base.getValue() == null) {
                return null;
            }
            double floor = base.getValue() - GateRules.VOCABULARY_TOLERANCE * scaleOf(base.getValue(), projected.getValue());
            double deficit = floor - projected.getValue();
            if (deficit > EPSILON) {
                return new Breach(deficit, "F-NOEMP-R006: " + where + ": " + GateRules.number(base.getValue()) + " → "
                        + GateRules.number(projected.getValue()) + " contra la línea base (tolerancia "
                        + GateRules.number(GateRules.VOCABULARY_TOLERANCE) + " puntos, acumulada)");
            }
        }
        return null;
    }

    /**
     * Scores travel either as points (73.92) or as fractions (0.7392). The tolerance is half a point of the percentage:
     * on a fraction it is 0.005.
     */
    private static double scaleOf(double base, double projected) {
        return Math.max(Math.abs(base), Math.abs(projected)) <= 1.0 + EPSILON ? 0.01 : 1.0;
    }

    /** R008: the changes the comparison ranks as worsening the row most, until the sum of their effects covers it. */
    private static List<String> culprits(BatchComparison comparison, ComparisonRow row, double deficit,
            Set<String> exceptions, Set<String> alreadyReturned) {
        List<ChangeAttribution> attributions = new ArrayList<>();
        for (FloorBreach breach : list(comparison.getBreaches())) {
            ComparisonRow broken = breach.getRow();
            if (broken != null && sameRow(broken, row)) {
                attributions.addAll(list(breach.getAttributions()));
            }
        }
        boolean points = row.getUnit() != GoalUnit.EXERCISES;
        attributions.sort(Comparator.comparingDouble((ChangeAttribution a) -> -worsening(a, points))
                .thenComparing(a -> String.valueOf(a.getProposalId())));
        List<String> culprits = new ArrayList<>();
        double covered = 0.0;
        for (ChangeAttribution attribution : attributions) {
            if (covered >= deficit - EPSILON) {
                break;
            }
            double effect = worsening(attribution, points);
            if (effect <= 0 || exceptions.contains(attribution.getProposalId())) {
                continue;
            }
            if (!culprits.contains(attribution.getProposalId())) {
                culprits.add(attribution.getProposalId());
            }
            covered += effect;
        }
        return culprits;
    }

    /** How much a change worsens its row on its own: lower points, or more exercises. */
    private static double worsening(ChangeAttribution attribution, boolean points) {
        return points ? -attribution.getEffect() : attribution.getEffect();
    }

    private static boolean sameRow(ComparisonRow a, ComparisonRow b) {
        return Objects.equals(a.getSubject(), b.getSubject()) && Objects.equals(a.getNodeId(), b.getNodeId())
                && Objects.equals(a.getNodeTarget(), b.getNodeTarget());
    }

    private static String describe(ComparisonRow row) {
        String node = row.getLabel() != null ? row.getLabel() : row.getNodeId();
        return row.getSubject() + " en " + node;
    }

