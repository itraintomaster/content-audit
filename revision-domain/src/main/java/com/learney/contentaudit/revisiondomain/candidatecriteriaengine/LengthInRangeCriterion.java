/**
 * F-QICOR-R004 criterio 1: the candidate's length falls within the same
 * per-CEFR target range the audit applies, measured with the exact same
 * {@link NlpTokenizer#countTokens(String)} over the same canonical sentence
 * (index 0 of {@code sentences}) that {@code CourseToAuditableMapper} tokenizes
 * -- never an approximation, so a candidate that passes here is never
 * re-flagged by the next audit for the same reason.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
class LengthInRangeCriterion implements CandidateCriterionEvaluator {
    private final NlpTokenizer tokenizer;

    private final SentenceLengthConfig sentenceLengthConfig;

    public LengthInRangeCriterion(NlpTokenizer tokenizer,
            SentenceLengthConfig sentenceLengthConfig) {
        this.tokenizer = tokenizer;
        this.sentenceLengthConfig = sentenceLengthConfig;
    }

    @Override
    public CorrectionCriterion criterion() {
        return CorrectionCriterion.LENGTH_IN_RANGE;
    }

    @Override
    public CriterionVerdict evaluate(CandidateAssessmentInput input) {
        CefrLevel level = input.getCefrLevel();
        if (level == null) {
            return new CriterionVerdict(criterion(), CriterionOutcome.NOT_EVALUABLE,
                    "No se pudo medir la longitud: nivel CEFR no disponible");
        }

        Optional<TargetRange> rangeOpt = sentenceLengthConfig.getTargetRange(level);
        if (rangeOpt.isEmpty()) {
            return new CriterionVerdict(criterion(), CriterionOutcome.NOT_EVALUABLE,
                    "No hay rango de longitud configurado para el nivel " + level);
        }

        CourseElementSnapshot candidateSnapshot = input.getCandidate();
        QuizTemplateEntity candidateQuiz = candidateSnapshot != null ? candidateSnapshot.getQuiz() : null;
        String canonicalSentence = canonicalSentence(candidateQuiz);
        int tokens = tokenizer.countTokens(canonicalSentence);

        TargetRange range = rangeOpt.get();
        if (tokens < range.getMinTokens() || tokens > range.getMaxTokens()) {
            return new CriterionVerdict(criterion(), CriterionOutcome.FAILED,
                    "La oracion candidata tiene " + tokens + " tokens; el rango del nivel "
                            + level + " es " + range.getMinTokens() + "-" + range.getMaxTokens());
        }

        return new CriterionVerdict(criterion(), CriterionOutcome.PASSED,
                "La oracion candidata tiene " + tokens + " tokens, dentro del rango "
                        + range.getMinTokens() + "-" + range.getMaxTokens());
    }

    private String canonicalSentence(QuizTemplateEntity quiz) {
        if (quiz == null) {
            return "";
        }
        List<String> sentences = quiz.getSentences();
        return (sentences != null && !sentences.isEmpty()) ? sentences.get(0) : "";
    }
}
