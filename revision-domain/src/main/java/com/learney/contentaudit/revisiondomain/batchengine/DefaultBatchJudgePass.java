    /** The account of every judge that reads what the batch changes; paid within {@code request}, or a trial if null. */
    private List<BatchJudgeAccount> accounts(CorrectionBatch batch, CourseEntity startCourse,
            CourseEntity composedCourse, BatchCloseRequest request) {
        List<AnalyzerDescriptor> cards = judgeCards(batch);
        BatchChanges changes = BatchChanges.of(batch, startCourse);
        List<BatchJudgeAccount> accounts = new ArrayList<>();
        if (cards.isEmpty() || changes.isEmpty()) {
            return accounts;
        }
        int atOnce = queriesAtOnce(batch);
        List<String> names = new ArrayList<>();
        for (AnalyzerDescriptor card : cards) {
            names.add(card.getName());
        }
        Trial trial = new Trial(ChangedCourseCuts.of(startCourse, composedCourse, changes), names, atOnce);
        List<JudgeLine> lines = new ArrayList<>();
        for (AnalyzerDescriptor card : cards) {
            JudgeLine line = JudgeLine.read(card, trial, freshnessCatalog);
            if (line.units > 0) {
                lines.add(line);
            }
        }
        if (request != null) {
            Integer left = request.getQueryCap() != null ? Math.max(0, request.getQueryCap()) : null;
            for (JudgeLine line : lines) {
                left = grant(line, request, left, trial);
            }
        }
        for (JudgeLine line : lines) {
            accounts.add(line.account());
        }
        return accounts;
    }

    /**
     * The budget a judge has when its turn comes -- its own, what is left of the cap, or the smaller of the two -- and the
     * payment within it; what is left of the cap afterwards. A local judge has none and spends none; one without an
     * approved exam is given its own budget, since it was named, and consults nothing with it.
     */
    private Integer grant(JudgeLine line, BatchCloseRequest request, Integer capLeft, Trial trial) {
        if (line.local) {
            return capLeft;
        }
        Integer own = request.getJudgeBudgets() != null ? request.getJudgeBudgets().get(line.name) : null;
        if (own != null) {
            own = Math.max(0, own);
        }
        if (!line.approved) {
            line.budget = own;
            return capLeft;
        }
        Integer allowance = own != null && capLeft != null ? Integer.valueOf(Math.min(own, capLeft))
                : own != null ? own : capLeft;
        line.budget = allowance;
        if (allowance == null || allowance <= 0) {
            return capLeft;
        }
        pay(line, trial, allowance);
        return capLeft != null ? Math.max(0, capLeft - line.spent) : null;
    }

    /**
     * Pays a judge what it misses on each side that it misses something, the before side first, running it alone with what
     * is left of its budget; what it spends comes off. After a failure of its service it starts nothing more -- not even on
     * the other side --, and its account says why.
     */
    private void pay(JudgeLine line, Trial trial, int allowance) {
        int left = allowance;
        for (Side side : Side.values()) {
            AuditableCourse course = trial.course(Part.of(line.unit, side));
            if (left <= 0 || line.unavailableReason != null) {
                return;
            }
            if (course == null || line.missing.get(side) == 0) {
                continue;
            }
            AuditReport paid = trial.run(course, List.of(line.name), Map.of(line.name, left));
            JudgeCoverageDiagnosis coverage = coverageOf(paid, line.name);
            if (coverage == null) {
                continue;
            }
            int spent = spent(coverage);
            line.spent += spent;
            left -= spent;
            line.missing.put(side, pending(coverage));
            line.unavailableReason = coverage.getUnavailableReason();
        }
    }

