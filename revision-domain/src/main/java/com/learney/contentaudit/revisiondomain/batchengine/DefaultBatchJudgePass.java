    /**
     * The cuts of the course, mapped once, and what every judge of the batch published running over each of them with a
     * budget of 0 -- nothing is asked of any judge. It also runs the judges that get paid, one at a time.
     */
    private final class Trial {
        private final Map<Part, AuditableCourse> courses = new EnumMap<>(Part.class);

        private final Map<Part, AuditReport> reports = new EnumMap<>(Part.class);

        private final int atOnce;

        Trial(ChangedCourseCuts cuts, List<String> judges, int atOnce) {
            this.atOnce = atOnce;
            Map<Part, CourseEntity> entities = new EnumMap<>(Part.class);
            entities.put(Part.EXERCISES_BEFORE, cuts.exercisesBefore());
            entities.put(Part.EXERCISES_AFTER, cuts.exercisesAfter());
            entities.put(Part.TOPICS_BEFORE, cuts.topicsBefore());
            entities.put(Part.TOPICS_AFTER, cuts.topicsAfter());
            for (Part part : Part.values()) {
                if (entities.get(part) != null) {
                    AuditableCourse course = courseMapper.map(entities.get(part));
                    courses.put(part, course);
                    reports.put(part, run(course, judges, Map.of()));
                }
            }
        }

        AuditableCourse course(Part part) {
            return courses.get(part);
        }

        AuditReport report(Part part) {
            return reports.get(part);
        }

        /** One run of the engine: the judges given, each with its own budget -- 0 unless it is named in {@code budgets}. */
        AuditReport run(AuditableCourse course, List<String> judges, Map<String, Integer> budgets) {
            Map<String, EvaluationRunPolicy> policies = new LinkedHashMap<>();
            for (String judge : judges) {
                policies.put(judge, new EvaluationRunPolicy(budgets.getOrDefault(judge, 0), false, null, null, null,
                        atOnce));
            }
            return auditEngine.runAudit(course, new AnalyzerRunSelection(new ArrayList<>(judges), policies));
        }
    }

