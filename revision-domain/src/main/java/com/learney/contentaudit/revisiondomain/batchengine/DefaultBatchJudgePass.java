    /** The consultations the judge still needs to decide what it reached: pending and failed. */
    private static int pending(JudgeCoverageDiagnosis coverage) {
        if (coverage.getCost() != null) {
            return coverage.getCost().getPendingConsultations();
        }
        return sum(coverage, each -> each.getPending() + each.getFailed());
    }

    private static int sum(JudgeCoverageDiagnosis coverage, Function<EvaluationCoverage, Integer> of) {
        int total = 0;
        for (EvaluatorCoverage evaluator : BatchBook.list(coverage.getEvaluators())) {
            if (evaluator != null && evaluator.getCoverage() != null) {
                total += of.apply(evaluator.getCoverage());
            }
        }
        return total;
    }

