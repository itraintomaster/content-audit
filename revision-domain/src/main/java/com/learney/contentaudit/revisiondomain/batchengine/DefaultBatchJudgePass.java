    /** What the pass knows of a judge while it works, until it becomes its account. */
    private static final class JudgeLine {
        final String name;

        final String displayName;

        AuditTarget unit = AuditTarget.QUIZ;

        boolean approved = true;

        JudgeExamStatus examStatus;

        String reason;

        boolean local;

        /** The exercises or topics it judges, before and after. */
        int units;

        int reused;

        int spent;

        Integer budget;

        String unavailableReason;

        /** F-ALDIA-R005: the marks of what it reuses on both sides, when today's judge is known. */
        JudgeFreshnessTally freshness;

        /** What it misses on each side: pending and failed consultations. */
        final Map<Side, Integer> missing = new EnumMap<>(Side.class);

        private JudgeLine(AnalyzerDescriptor card) {
            this.name = card.getName();
            this.displayName = card.getDisplayName() != null && !card.getDisplayName().isBlank()
                    ? card.getDisplayName() : card.getName();
            missing.put(Side.BEFORE, 0);
            missing.put(Side.AFTER, 0);
        }

        /**
         * What the trial says of the judge. A judge of the catalog says what it reached and the standing of its exam in
         * its coverage; a local tool without coverage, as grammar, leaves the run of its tool -- with the exam of its
         * version -- and a mark on each exercise it read. It is local if the run of its tool says it went by it, not by its
         * claude -p alternative.
         */
        static JudgeLine read(AnalyzerDescriptor card, Trial trial, JudgeFreshnessCatalog catalog) {
            JudgeLine line = new JudgeLine(card);
            JudgeCoverageDiagnosis coverage = null;
            LocalToolRunDiagnosis tool = null;
            for (Part part : Part.values()) {
                AuditReport report = trial.report(part);
                if (report != null) {
                    coverage = coverage != null ? coverage : coverageOf(report, line.name);
                    tool = tool != null ? tool : toolRunOf(report, line.name);
                }
            }
            line.local = tool != null && !tool.isAlternative();
            if (coverage != null) {
                line.unit = coverage.getUnit() != null ? coverage.getUnit() : AuditTarget.QUIZ;
                line.standing(coverage.getStanding());
                AuditTarget unit = line.unit;
                if (catalog != null) {
                    catalog.reference(line.name).ifPresent(reference ->
                            line.freshness = new JudgeFreshnessTally(reference, line.displayName, unit));
                }
            } else if (tool != null) {
                line.examStatus = tool.getExamState();
                line.approved = line.examStatus == null || line.examStatus == JudgeExamStatus.APPROVED
                        || line.examStatus == JudgeExamStatus.PROMOTED;
                line.reason = tool.isPublished() ? null : tool.getReason();
            }
            for (Side side : Side.values()) {
                AuditReport report = trial.report(Part.of(line.unit, side));
                if (report != null) {
                    line.count(side, report, coverage != null);
                }
            }
            return line;
        }

        /** The exam of its version: approved when it consults on the course, with the reason when it does not. */
        private void standing(JudgeExamStanding standing) {
            if (standing != null) {
                approved = standing.isConsultsOnCourse();
                examStatus = standing.getStatus();
                reason = approved ? null : standing.getReason();
            }
        }

        /** What it reached on a side of its cut, what the ledger had and what it misses. */
        private void count(Side side, AuditReport report, boolean covered) {
            if (!covered) {
                units += marked(report, name);
                return;
            }
            JudgeCoverageDiagnosis seen = coverageOf(report, name);
            if (seen != null) {
                units += seen.getReached();
                reused += DefaultBatchJudgePass.reused(seen);
                missing.put(side, DefaultBatchJudgePass.pending(seen));
                if (freshness != null) {
                    // The trial pays nothing: every verdict it counts by version is one the ledger had.
                    int marked = 0;
                    for (JudgeVersionStanding version : BatchBook.list(seen.getVersions())) {
                        if (version != null) {
                            freshness.add(version.getJudgeVersion(), version.getRuntimeIdentity(), version.getVerdictCount());
                            marked += Math.max(0, version.getVerdictCount());
                        }
                    }
                    freshness.notMeasured(seen.getReached() - marked);
                }
            }
        }

        BatchJudgeAccount account() {
            BatchJudgeAccount account = new BatchJudgeAccount(name, displayName, unit, approved, examStatus, reason, units,
                    budget, spent, reused, missing.get(Side.BEFORE) + missing.get(Side.AFTER), 0, 0, unavailableReason, local);
            account.setFreshness(freshness != null ? freshness.count() : null);
            return account;
        }
    }
