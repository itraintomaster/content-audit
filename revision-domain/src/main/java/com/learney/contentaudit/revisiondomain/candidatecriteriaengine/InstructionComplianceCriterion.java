/**
 * F-QICOR-R005: the corrected candidate is submitted to the exact same
 * quiz-instruction validation that detected the original's non-compliance --
 * same {@link QuizInstructionSubjectViewFactory} mapping, same {@link
 * QuizInstructionComplianceChecker} -- so a candidate that passes here is
 * never re-flagged by the next audit. This is the last criterion in the
 * catalog (the most expensive one, a judge query) and only runs once every
 * cheaper criterion already passed.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
class InstructionComplianceCriterion implements CandidateCriterionEvaluator {
    private final QuizInstructionComplianceChecker complianceChecker;

    private final QuizInstructionSubjectViewFactory subjectViewFactory;

    public InstructionComplianceCriterion(QuizInstructionComplianceChecker complianceChecker,
            QuizInstructionSubjectViewFactory subjectViewFactory) {
        this.complianceChecker = complianceChecker;
        this.subjectViewFactory = subjectViewFactory;
    }

    @Override
    public CorrectionCriterion criterion() {
        return CorrectionCriterion.INSTRUCTION_COMPLIANCE;
    }

    @Override
    public CriterionVerdict evaluate(CandidateAssessmentInput input) {
        CourseElementSnapshot candidateSnapshot = input.getCandidate();
        QuizTemplateEntity candidateQuiz = candidateSnapshot != null ? candidateSnapshot.getQuiz() : null;
        if (candidateQuiz == null) {
            return new CriterionVerdict(criterion(), CriterionOutcome.NOT_EVALUABLE,
                    "No se pudo verificar el cumplimiento de consigna: falta el candidato");
        }

        QuizInstructionSubjectView view = subjectViewFactory.fromQuiz(
                candidateQuiz,
                input.getCefrLevelLabel(),
                input.getTopicLabel(),
                input.getKnowledgeTitle(),
                input.getKnowledgeInstructions());

        QuizInstructionComplianceResult result = complianceChecker.check(view);

        if (result.getStatus() == QuizInstructionComplianceStatus.EVALUATED) {
            QuizInstructionVerdict verdict = result.getVerdict();
            if (verdict != null && verdict.isFollowsInstructions()) {
                return new CriterionVerdict(criterion(), CriterionOutcome.PASSED,
                        "El candidato cumple la consigna segun la validacion vigente");
            }
            String reason = verdict != null ? verdict.getReason() : "sin motivo declarado";
            return new CriterionVerdict(criterion(), CriterionOutcome.FAILED,
                    "El candidato sigue incumpliendo la consigna: " + reason);
        }

        return new CriterionVerdict(criterion(), CriterionOutcome.NOT_EVALUABLE,
                result.getReason() != null
                        ? result.getReason()
                        : "No se pudo verificar el cumplimiento de consigna");
    }
}
