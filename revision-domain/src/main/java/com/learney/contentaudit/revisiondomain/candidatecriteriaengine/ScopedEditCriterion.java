    // F-QICOR-R010: strips empty parts before any comparison happens. Returns a fresh list
    // (never the input, which may be null) so callers can safely index and size() it like
    // any other part list.
    private List<SentencePartEntity> withoutEmptyTextParts(List<SentencePartEntity> parts) {
        if (parts == null) {
            return List.of();
        }
        List<SentencePartEntity> filtered = new ArrayList<>(parts.size());
        for (SentencePartEntity part : parts) {
            if (!isEmptyTextPart(part)) {
                filtered.add(part);
            }
        }
        return filtered;
    }

    // F-QICOR-R010: only a TEXT part ("fixed text") with zero characters is "empty" in the
    // rule's sense. A CLOZE part's own text field is conventionally blank too — its content
    // lives in its accepted options, not in `text` — but that is a structural convention for
    // representing a gap, not "no content at all", so CLOZE parts are never filtered here
    // regardless of their text field.
    private boolean isEmptyTextPart(SentencePartEntity part) {
        return part != null && part.getKind() == SentencePartKind.TEXT
                && (part.getText() == null || part.getText().isBlank());
    }

    private boolean isChangeSignalled(String before, String after, List<String> signalledFragments) {
        for (String fragment : signalledFragments) {
            if (fragment == null || fragment.isBlank()) {
                continue;
            }
            if (containsOrIsContained(before, fragment) || containsOrIsContained(after, fragment)) {
                return true;
            }
        }
        return false;
    }

    private boolean optionsSignalled(List<String> before, List<String> after,
            List<String> signalledFragments) {
        if (before != null) {
            for (String option : before) {
                if (isChangeSignalled(option, null, signalledFragments)) {
                    return true;
                }
            }
        }
        if (after != null) {
            for (String option : after) {
                if (isChangeSignalled(null, option, signalledFragments)) {
                    return true;
                }
            }
        }
        return false;
    }

    private boolean containsOrIsContained(String text, String fragment) {
        // Guard against blank: an empty CLOZE part text (the common representation of
        // "no literal text here, just an accepted-options gap") would otherwise be
        // trivially "contained" in every non-empty fragment, falsely marking every gap
        // as signalled regardless of what the violation actually pointed at.
        if (text == null || text.isBlank()) {
            return false;
        }
        return text.contains(fragment) || fragment.contains(text);
    }
