/**
 * Names the changes that break a floor of a level or of the course (F-METAS-R004): a number of a level is no
 * exercise's, so each change of the batch is left out once -- its node goes back to its version at the batch
 * start -- and the variant is measured with the analyzers of the projection. The course of each variant is built
 * from the exercises both photos already mapped, so nothing is read or tokenized again: one engine run per change,
 * for every broken floor at once. Its effect is the number of the whole projection minus the number without it,
 * in the unit of the row; the one that worsens it most goes first, so the gate of E can return from the first on.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
public class LeaveOneOutChangeAttributor implements ChangeAttributor {
    private static final double EPSILON = 1e-9;

    private final AuditEngine auditEngine;

    public LeaveOneOutChangeAttributor(AuditEngine auditEngine) {
        this.auditEngine = auditEngine;
    }

    @Override
    public List<FloorBreach> attribute(CourseProjection projection, List<FloorBreach> breaches) {
        List<FloorBreach> result = new ArrayList<>();
        if (breaches == null || breaches.isEmpty()) {
            return result;
        }
        List<List<ChangeAttribution>> attributions = new ArrayList<>();
        for (int i = 0; i < breaches.size(); i++) {
            attributions.add(new ArrayList<>());
        }
        if (projection != null && projection.getProjected() != null && projection.getApproved() != null) {
            AuditReport projected = projection.getProjected();
            Map<String, AuditNode> projectedIndex = ReportTree.index(projected);
            Map<String, AuditNode> startIndex = ReportTree.index(projection.getApproved());
            List<String> analyzers = ReportTree.measuredAnalyzers(projected);
            for (ProjectedChange change : DefaultBatchComparator.pendingChanges(projection)) {
                AuditNode before = startIndex.get(ReportTree.key(change.getNodeTarget(), change.getNodeId()));
                if (before == null) {
                    continue;
                }
                AuditableCourse variant = ReportTree.course(projected, Map.of(change.getNodeId(), before));
                if (variant == null) {
                    continue;
                }
                AuditReport without;
                try {
                    without = analyzers.isEmpty()
                            ? auditEngine.runAudit(variant)
                            : auditEngine.runAudit(variant, new AnalyzerRunSelection(analyzers, Map.of()));
                } catch (RuntimeException e) {
                    continue;
                }
                if (without == null) {
                    continue;
                }
                Map<String, AuditNode> withoutIndex = ReportTree.index(without);
                for (int i = 0; i < breaches.size(); i++) {
                    ChangeAttribution attribution = effect(change, breaches.get(i), projectedIndex, withoutIndex);
                    if (attribution != null) {
                        attributions.get(i).add(attribution);
                    }
                }
            }
        }
        for (int i = 0; i < breaches.size(); i++) {
            FloorBreach breach = breaches.get(i);
            List<ChangeAttribution> ordered = attributions.get(i);
            GoalUnit unit = breach.getRow() != null ? breach.getRow().getUnit() : null;
            Comparator<ChangeAttribution> worstFirst = unit == GoalUnit.POINTS
                    ? Comparator.comparingDouble(ChangeAttribution::getEffect)
                    : Comparator.comparingDouble(ChangeAttribution::getEffect).reversed();
            ordered.sort(worstFirst);
            result.add(new FloorBreach(breach.getGoalId(), breach.getRow(), ordered));
        }
        return result;
    }

    /**
     * What the change does to the broken number by itself: the projection minus the projection without it, in
     * points of a score or in exercises of a count. Nothing when it does not move it.
     */
    private static ChangeAttribution effect(ProjectedChange change, FloorBreach breach,
            Map<String, AuditNode> projectedIndex, Map<String, AuditNode> withoutIndex) {
        ComparisonRow row = breach.getRow();
        if (row == null || row.getNodeTarget() == null || row.getSubject() == null) {
            return null;
        }
        String key = ReportTree.key(row.getNodeTarget(), row.getNodeId());
        ReportTree.Value whole = ReportTree.value(projectedIndex.get(key), row.getSubject(), row.getFamily());
        ReportTree.Value without = ReportTree.value(withoutIndex.get(key), row.getSubject(), row.getFamily());
        if (whole == null || without == null || whole.value() == null || without.value() == null) {
            return null;
        }
        GoalUnit unit = row.getUnit() != null ? row.getUnit() : GoalUnit.POINTS;
        double effect = unit == GoalUnit.POINTS
                ? (whole.value() - without.value()) * 100.0
                : whole.value() - without.value();
        if (Math.abs(effect) < EPSILON) {
            return null;
        }
        return new ChangeAttribution(change.getProposalId(), change.getNodeId(), effect, unit);
    }
}
