package com.learney.contentaudit.revisiondomain.candidatecriteriaengine;

import com.learney.contentaudit.revisiondomain.candidatecriteria.CandidateAssessment;
import com.learney.contentaudit.revisiondomain.candidatecriteria.CandidateLengthMeasurement;
import com.learney.contentaudit.revisiondomain.candidatecriteria.CandidateRanking;
import com.learney.contentaudit.revisiondomain.candidatecriteria.CorrectionCriterion;
import com.learney.contentaudit.revisiondomain.candidatecriteria.CriterionVerdict;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import javax.annotation.processing.Generated;

/**
 * F-QICOR-R013: "mejor" is a fixed order, not an impression -- eligibility
 * first (a candidate that does not comply with its instruction or is not a
 * real change over the original does not compete at all), then how many
 * criteria of the catalog it satisfies, then -- only to break a tie on that
 * count -- the criterion of highest precedence among the ones that differ
 * (resolvability, faithful translation, level vocabulary, distinctness,
 * scoped edit, in that order: the order the decision ranks by how much each
 * failure harms the student), and only when everything else ties does the
 * length decide, last and never adding to the count (F-QICOR-R011). A final
 * tie keeps whichever candidate was seen first -- {@link #better} is a
 * strict comparison, so an equal challenger never dethrones the incumbent.
 *
 * <p>{@link #rankKey} packs that whole order into a single string so it can
 * travel to {@code tally.sh} (F-QICOR-J001's {@code quiz-instruction-corrector}
 * graph) and be compared there with a plain lexicographic {@code >}: eligible
 * flag, then the satisfied-criteria count as one digit (the catalog never
 * exceeds nine), then one bit per precedence criterion (most significant bit
 * first, 1 = satisfied), then the in-range bit. Every segment is fixed-width,
 * so string comparison and the order this class implements always agree.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
class DefaultCandidateRanking implements CandidateRanking {

    // F-QICOR-R013's own table, highest precedence (most damaging to the student) first.
    private static final List<CorrectionCriterion> PRECEDENCE = List.of(
            CorrectionCriterion.SOLVABLE_SAME_KIND,
            CorrectionCriterion.FAITHFUL_TRANSLATION,
            CorrectionCriterion.LEVEL_VOCABULARY,
            CorrectionCriterion.DISTINCTNESS,
            CorrectionCriterion.SCOPED_EDIT);

    @Override
    public String rankKey(CandidateAssessment assessment) {
        StringBuilder key = new StringBuilder();

        // Eligibility dominates everything else: a candidate that does not compete never
        // outranks one that does, however many criteria it happens to satisfy.
        key.append(assessment.isEligible() ? '1' : '0');

        // Cantidad de criterios cumplidos, antes que la precedencia (R013: "por que cuenta
        // primero la cantidad y despues la precedencia").
        int satisfied = Math.max(0, assessment.getSatisfiedCriteria());
        key.append((char) ('0' + Math.min(satisfied, 9)));

        // A criterion not evaluable counts as not met for ranking purposes (R013 (f)).
        Set<CorrectionCriterion> unmet = new HashSet<>();
        List<CriterionVerdict> unmetCriteria = assessment.getUnmetCriteria();
        if (unmetCriteria != null) {
            for (CriterionVerdict verdict : unmetCriteria) {
                unmet.add(verdict.getCriterion());
            }
        }
        for (CorrectionCriterion criterion : PRECEDENCE) {
            key.append(unmet.contains(criterion) ? '0' : '1');
        }

        // Length decides only once nothing else does (F-QICOR-R011): last bit, never summed
        // into satisfied/precedence above.
        CandidateLengthMeasurement length = assessment.getLengthMeasurement();
        boolean inRange = length != null && length.isInRange();
        key.append(inRange ? '1' : '0');

        return key.toString();
    }

    @Override
    public boolean better(String incumbentRankKey, String challengerRankKey) {
        String incumbent = incumbentRankKey != null ? incumbentRankKey : "";
        String challenger = challengerRankKey != null ? challengerRankKey : "";
        // Strict: an equal challenger never dethrones the incumbent, so the result is the
        // same whether one attempt or three produced the candidates being compared (R013).
        return challenger.compareTo(incumbent) > 0;
    }

    @Override
    public List<CorrectionCriterion> precedence() {
        return PRECEDENCE;
    }
}
