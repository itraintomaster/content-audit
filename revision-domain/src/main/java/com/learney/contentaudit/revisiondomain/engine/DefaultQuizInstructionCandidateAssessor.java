    // as unavailable (CandidateAssessmentUnavailableException) instead of ever fabricating
    // a verdict: a plan that does not exist, a task that is not in the plan, an analysis
    // that can no longer be loaded, a context that cannot be resolved, an original that is
    // not in the course, and -- the one case with no equivalent in DefaultRevisionEngine,
    // because the reviser is only ever invoked for its own DiagnosisKind -- a task that the
