    private List<String> signalledFragmentsOf(List<InstructionViolation> violations) {
        List<String> fragments = new ArrayList<>();
        if (violations == null) {
            return fragments;
        }
        for (InstructionViolation violation : violations) {
            if (violation.getEvidence() != null && !violation.getEvidence().isBlank()) {
                fragments.add(violation.getEvidence());
            }
        }
        return fragments;
    }

    // F-QICOR-R015: reproduces steps 1-3 of DefaultRevisionEngine.revise() (load the plan,
    // find the task, resolve its correction context, locate the original in the course)
    // over the SAME ports, then delegates into assess(...) above -- never assembling a
