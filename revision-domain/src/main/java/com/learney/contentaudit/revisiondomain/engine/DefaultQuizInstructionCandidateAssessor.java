    @Override
    public CandidateAssessment assessTask(String planId, String taskId, Path coursePath, String candidateQuizSentence, String candidateTranslation) {
        RefinementPlan plan = refinementPlanStore.load(planId)
                .orElseThrow(() -> new CandidateAssessmentUnavailableException(taskId,
                        "no existe ningun plan con id '" + planId + "'"));

        RefinementTask task = plan.getTasks() != null
                ? plan.getTasks().stream().filter(t -> taskId.equals(t.getId())).findFirst().orElse(null)
                : null;
        if (task == null) {
            throw new CandidateAssessmentUnavailableException(taskId,
                    "la tarea no esta entre las tareas del plan '" + planId + "'");
        }

        AuditReport report = auditReportStore.load(plan.getSourceAuditId())
                .orElseThrow(() -> new CandidateAssessmentUnavailableException(taskId,
                        "no se pudo cargar el analisis '" + plan.getSourceAuditId()
                                + "' del que salio el plan"));

        Optional<CorrectionContext> resolvedContext = contextResolver.resolve(report, task);
        if (resolvedContext.isEmpty()) {
            throw new CandidateAssessmentUnavailableException(taskId,
                    "el contexto de correccion de la tarea no se pudo resolver");
        }
        if (!(resolvedContext.get() instanceof QuizInstructionCorrectionContext qic)) {
            // The resolver dispatches by DiagnosisKind and hands back a context of the kind
            // the task was actually opened for -- never empty. Carrying on with a context
            // built for another diagnosis (e.g. SENTENCE_LENGTH) instead of reporting the
            // consultation unavailable is exactly the risk this branch exists to close.
            throw new CandidateAssessmentUnavailableException(taskId,
                    "la tarea consultada no es de incumplimiento de consigna de ejercicio");
        }
        // The resolver only ever sees the AuditReport's content (which carries no id of its
        // own) and always leaves sourceAuditId/planId null -- see QuizInstructionContextResolver's
        // own javadoc. DefaultRevisionEngine stamps both right after resolving for exactly this
        // reason; this is that same resolution step reproduced here, so a freshly-resolved
        // context is never handed to assess(...) with a null sourceAuditId (which the
        // distinctness criterion needs to compare against the same analysis, F-QICOR-R004
        // criterio 3) -- planId travels with it for symmetry, though nothing in
        // CandidateAssessmentInput reads it today.
        qic.setSourceAuditId(plan.getSourceAuditId());
        qic.setPlanId(planId);

        CourseEntity course = courseRepository.load(coursePath);
        CourseElementSnapshot original = elementLocator
                .snapshot(course, task.getNodeTarget(), task.getNodeId())
                .orElseThrow(() -> new CandidateAssessmentUnavailableException(taskId,
                        "el ejercicio de la tarea no se encontro en el curso"));

        return assess(qic, original, candidateQuizSentence, candidateTranslation);
    }

