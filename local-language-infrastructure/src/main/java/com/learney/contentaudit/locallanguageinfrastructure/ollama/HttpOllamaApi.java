    private Tags askTags() {
        try {
            HttpRequest request = HttpRequest.newBuilder(URI.create(baseUrl() + "/api/tags"))
                    .timeout(PROBE_TIMEOUT)
                    .GET()
                    .build();
            HttpResponse<String> response = client().send(request, HttpResponse.BodyHandlers.ofString(
                    StandardCharsets.UTF_8));
            if (response.statusCode() != 200) {
                return Tags.failed("respondió " + response.statusCode());
            }
            Map<String, String> digests = new LinkedHashMap<>();
            for (JsonNode model : JSON.readTree(response.body()).path("models")) {
                String digest = model.path("digest").asText("");
                for (String name : List.of(model.path("name").asText(""), model.path("model").asText(""))) {
                    if (!name.isEmpty() && !digest.isEmpty()) {
                        digests.putIfAbsent(name, digest);
                    }
                }
            }
            return new Tags(digests, null);
        } catch (IOException e) {
            return Tags.failed(describe(e));
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            return Tags.failed("el sondeo se interrumpió");
        } catch (RuntimeException e) {
            return Tags.failed(describe(e));
        }
    }

