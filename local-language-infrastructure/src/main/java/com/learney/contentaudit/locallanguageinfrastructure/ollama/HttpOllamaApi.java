    /** Decided on the address as written: no name is ever resolved, which would already be the network. */
    static boolean isThisMachine(String host) {
        if (host == null) {
            return false;
        }
        String h = host.toLowerCase(Locale.ROOT);
        if (h.startsWith("[") && h.endsWith("]")) {
            h = h.substring(1, h.length() - 1);
        }
        return h.equals("localhost") || h.endsWith(".localhost") || h.equals("::1") || h.equals("0:0:0:0:0:0:0:1")
                || h.matches("127\\.\\d{1,3}\\.\\d{1,3}\\.\\d{1,3}");
    }

