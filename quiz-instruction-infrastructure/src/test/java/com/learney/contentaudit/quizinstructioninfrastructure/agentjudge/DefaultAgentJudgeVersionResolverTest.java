    public void shouldDeriveANewVersionWhenTheAgentDefinitionTheModelOrTheProviderOfAJudgeChangesAndTheSameVersionOtherwiseSoAChangedJudgeTakesTheExamAgain(
            @TempDir Path agentsDir) throws IOException {
        Path prompt = writeDefinition(agentsDir, "translation-sense-from-english",
                "Leé el inglés y decí si la traducción dice lo mismo.");
        writeDefinition(agentsDir, "translation-sense-from-translation",
                "Leé la traducción y decí si el inglés dice lo mismo.");
        DefaultAgentJudgeVersionResolver resolver = new DefaultAgentJudgeVersionResolver(locatorOver(agentsDir));
        AgentJudgeConfig config = new AgentJudgeConfig(
                "claude-cli", null, null, "claude-sonnet-4-5", 0.0, 120, "medium");

        String version = resolver.resolve(FROM_ENGLISH, config, CLAUDE_CLI).orElseThrow();

        // The same judge: same definition, model and provider, whatever else is retouched.
        assertEquals(version, resolver.resolve(FROM_ENGLISH, config, CLAUDE_CLI).orElseThrow(),
                "asking twice gives the same version");
        assertEquals(version, resolver.resolve(
                        new AgentJudgeSpec("translation-sense-from-english", "translationSenseVerdict", "otro nombre"),
                        new AgentJudgeConfig("claude-cli", "http://localhost:9999/v1", "otra-clave",
                                "claude-sonnet-4-5", 0.7, 30, "medium"),
                        new LlmProviderResolved("claude-cli", LlmProviderClass.LOCAL_SESSION)).orElseThrow(),
                "its display name, address, credential, temperature and timeout are not its way of asking");

        AgentJudgeConfig anotherModel =
                new AgentJudgeConfig("claude-cli", null, null, "claude-opus-4-1", 0.0, 120, "medium");
        AgentJudgeConfig anotherReasoning =
                new AgentJudgeConfig("claude-cli", null, null, "claude-sonnet-4-5", 0.0, 120, "high");
        LlmProviderResolved anotherProvider =
                new LlmProviderResolved("openai", LlmProviderClass.REMOTE_SERVICE);
        assertEquals(version, resolver.resolve(FROM_ENGLISH, anotherModel, CLAUDE_CLI).orElseThrow());
        assertEquals(version, resolver.resolve(FROM_ENGLISH, anotherReasoning, CLAUDE_CLI).orElseThrow());
        assertEquals(version, resolver.resolve(FROM_ENGLISH, config, anotherProvider).orElseThrow());
        assertNotEquals(
                resolver.legacyRuntimeCoupledVersion(FROM_ENGLISH, config, CLAUDE_CLI).orElseThrow(),
                resolver.legacyRuntimeCoupledVersion(FROM_ENGLISH, anotherReasoning, CLAUDE_CLI).orElseThrow(),
                "the schema migration alias stays exact to its old runtime");
        assertNotEquals(version, resolver.resolve(new AgentJudgeSpec("translation-sense-from-translation",
                        "translationSenseVerdict", "juez de traducción y sentido, desde la traducción"),
                        config, CLAUDE_CLI).orElseThrow(),
                "another agent definition is another judge");

        Files.writeString(prompt, "Leé el inglés y decí si la traducción dice lo mismo, sin comparar con ningún original.");
        String edited = resolver.resolve(FROM_ENGLISH, config, CLAUDE_CLI).orElseThrow();
        assertNotEquals(version, edited, "editing its definition makes a new version that takes the exam again");
        assertEquals(edited, resolver.resolve(FROM_ENGLISH, config, CLAUDE_CLI).orElseThrow(),
                "and that new version is stable while nothing else changes");
    }

