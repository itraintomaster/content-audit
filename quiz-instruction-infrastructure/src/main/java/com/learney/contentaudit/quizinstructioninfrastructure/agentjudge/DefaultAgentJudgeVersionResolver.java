/**
 * F-JEXAM-R001: the version of a new judge is its way of asking -- every file of its located agent
 * definition --, its model and its provider, exactly as the quiz-instruction judge derives its own
 * (same digest), with the agent named by the spec. A changed judge is a new version and takes the
 * exam again; retouching the address, the credential, the temperature or the timeout is not.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
class DefaultAgentJudgeVersionResolver implements AgentJudgeVersionResolver {
    private final AgentDefinitionLocator agentDefinitionLocator;

    public DefaultAgentJudgeVersionResolver(AgentDefinitionLocator agentDefinitionLocator) {
        this.agentDefinitionLocator = agentDefinitionLocator;
    }

    @Override
    public Optional<String> resolve(AgentJudgeSpec spec, AgentJudgeConfig config,
            LlmProviderResolved provider) {
        String agentName = spec != null ? spec.getEvaluatorId() : null;
        if (agentName == null || agentName.isBlank()) {
            return Optional.empty();
        }
        String modelName = config != null ? config.getModelName() : null;
        String providerName = provider != null ? provider.getProviderName() : null;

        // The same locator the runner loads the graph with, so the directory digested here and the
        // one that runs can never diverge.
        AgentDefinitionLocation location = agentDefinitionLocator.locate(agentName);
        if (location instanceof AgentDefinitionFound found && found.getDirectory() != null) {
            return digest(agentName, modelName, providerName, found.getDirectory());
        }

        // F-JEXAM-R003 / F-QINST-R010 inv. 3: without a definition there is nothing to derive from,
        // and no placeholder that looks like a version: the runtime declares the judge not
        // available instead of stamping a fake provenance on new verdicts.
        return Optional.empty();
    }

    private static Optional<String> digest(String agentName, String modelName, String providerName,
            Path agentDir) {
        try {
            MessageDigest sha256 = MessageDigest.getInstance("SHA-256");
            sha256.update("agent:".getBytes(StandardCharsets.UTF_8));
            sha256.update(agentName.getBytes(StandardCharsets.UTF_8));
            sha256.update((byte) '\n');
            sha256.update("model:".getBytes(StandardCharsets.UTF_8));
            if (modelName != null) {
                sha256.update(modelName.getBytes(StandardCharsets.UTF_8));
            }
            sha256.update((byte) '\n');
            sha256.update("provider:".getBytes(StandardCharsets.UTF_8));
            if (providerName != null) {
                sha256.update(providerName.getBytes(StandardCharsets.UTF_8));
            }
            sha256.update((byte) '\n');

            for (Path file : sortedFilesUnder(agentDir)) {
                sha256.update(agentDir.relativize(file).toString().getBytes(StandardCharsets.UTF_8));
                sha256.update(Files.readAllBytes(file));
            }

            return Optional.of(HexFormat.of().formatHex(sha256.digest()));
        } catch (NoSuchAlgorithmException | IOException e) {
            // A definition that cannot be read cannot be digested: no version rather than one that
            // does not describe the judge that would run.
            return Optional.empty();
        }
    }

    private static List<Path> sortedFilesUnder(Path agentDir) throws IOException {
        try (Stream<Path> files = Files.walk(agentDir)) {
            return files.filter(Files::isRegularFile)
                    .sorted(Comparator.comparing(f -> agentDir.relativize(f).toString()))
                    .collect(Collectors.toList());
        }
    }
}
