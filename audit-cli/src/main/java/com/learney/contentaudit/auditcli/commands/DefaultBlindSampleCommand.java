    /** The four answers, without minding case: A, B, iguales, ambos -- and their names. */
    static PairAnswer parse(String answer) {
        if (answer == null) {
            return null;
        }
        return switch (answer.trim().toUpperCase(Locale.ROOT)) {
            case "A", "A_BETTER" -> PairAnswer.A_BETTER;
            case "B", "B_BETTER" -> PairAnswer.B_BETTER;
            case "EQUAL", "IGUALES", "IGUAL" -> PairAnswer.EQUAL;
            case "BOTH_WRONG", "AMBOS" -> PairAnswer.BOTH_WRONG;
            default -> null;
        };
    }

    private static String side(String name, StudentSide side) {
        StringBuilder text = new StringBuilder();
        QuizStudentView view = side != null ? side.getView() : null;
        if (view == null) {
            return text.append("  ").append(name).append(" · (sin vista)\n").toString();
        }
        text.append("  ").append(name).append(" · ").append(view.getStatement());
        if (view.getTranslation() != null && !view.getTranslation().isBlank()) {
            text.append(' ').append(view.getTranslation());
        }
        text.append('\n');
        if (view.getInstructions() != null && !view.getInstructions().isBlank()) {
            text.append("      consigna: ").append(view.getInstructions()).append('\n');
        }
        if (view.getOptions() != null && !view.getOptions().isEmpty()) {
            text.append("      opciones: ").append(String.join(" · ",
                    view.getOptions().stream().map(StudentOptionView::getLabel).toList())).append('\n');
        }
        if (view.getMiniTheory() != null && !view.getMiniTheory().isBlank()) {
            text.append("      miniteoría: ").append(view.getMiniTheory()).append('\n');
        }
        if (side.getAnswered() != null) {
            text.append("      respondido: ").append(side.getAnswered()).append('\n');
        }
        return text.toString();
    }

    static String result(BlindSampleResult result) {
        StringBuilder text = new StringBuilder();
        text.append(result.getSampleId()).append(" closed: ").append(result.getAnswered())
                .append(" pairs answered by ").append(result.getResponsible()).append('\n');
        text.append("  better or equal: ").append(estimate(result.getBetterOrEqual())).append('\n');
        text.append("  worse: ").append(estimate(result.getWorse())).append('\n');
        text.append("  both wrong: ").append(estimate(result.getBothWrong())).append('\n');
        text.append(result.isMeetsGoal() ? "Meets its goal." : "Does not meet its goal: "
                + String.join("; ", result.getUnmetParts() != null ? result.getUnmetParts() : List.of())).append('\n');
        if (result.getAgreement() != null) {
            text.append("Agreement with ").append(result.getAgreement().getOther()).append(": ")
                    .append(result.getAgreement().getAgreeing()).append(" of ")
                    .append(result.getAgreement().getCommonPairs()).append(" pairs alike, kappa ")
                    .append(decimal(result.getAgreement().getKappa(), "0.00")).append('\n');
        }
        if (result.getCumulative() != null) {
            text.append("Since the baseline: ").append(result.getCumulative().getSamples()).append(" samples, ")
                    .append(result.getCumulative().getPairs()).append(" pairs, ")
                    .append(result.getCumulative().getWorse()).append(" worse, bound ")
                    .append(percent(result.getCumulative().getWorseUpperBound()))
                    .append(result.getCumulative().isBelowGoal() ? " (below the goal)" : " (not yet below the goal)")
                    .append('\n');
        }
        if (result.getRevealedPairs() != null) {
            for (BlindPair pair : result.getRevealedPairs()) {
                text.append("  pair ").append(pair.getIndex()).append(": the after is ").append(pair.getAfterSide())
                        .append(" · ").append(pair.getProposalId()).append(" · ").append(pair.getNodeId()).append('\n');
            }
        }
        return text.toString().stripTrailing();
    }

