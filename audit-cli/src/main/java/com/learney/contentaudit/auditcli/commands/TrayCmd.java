    private TrayResponse response(String itemId, String answer, Integer pairIndex, String changeId, String fixFile,
            String note) throws IOException {
        String upper = answer.toUpperCase(Locale.ROOT);
        if (pairIndex != null || itemId.startsWith("ciega-")) {
            PairAnswer pair = PAIR_ANSWERS.get(upper);
            if (pair == null || pairIndex == null) {
                throw new IllegalArgumentException("un par de la muestra ciega se contesta con --pair N y A, B, iguales o"
                        + " ambos");
            }
            return new TrayResponse(itemId, TrayAnswer.BLIND_PAIR, pairIndex, pair, null, null, note, JOSE);
        }
        TrayAnswer kind;
        try {
            kind = TrayAnswer.valueOf(upper.replace('-', '_'));
        } catch (IllegalArgumentException e) {
            throw new IllegalArgumentException("'" + answer + "' no es una respuesta de la bandeja");
        }
        PanelCandidate fix = null;
        if (kind == TrayAnswer.WRITE_FIX) {
            if (fixFile == null || fixFile.isBlank()) {
                throw new IllegalArgumentException("WRITE_FIX necesita --fix <archivo> con el arreglo");
            }
            fix = fix(itemId, Path.of(fixFile));
        }
        return new TrayResponse(itemId, kind, null, null, changeId, fix, note, JOSE);
    }

    /** José's fix: course notation, translation, and optionally its quiz-local mini theory, one per nonblank line. */
    private PanelCandidate fix(String itemId, Path file) throws IOException {
        List<String> lines = new ArrayList<>();
        for (String line : Files.readAllLines(file, StandardCharsets.UTF_8)) {
            if (!line.isBlank()) {
                lines.add(line.strip());
            }
        }
        if (lines.isEmpty()) {
            throw new IllegalArgumentException("el archivo " + file + " no trae el arreglo");
        }
        String quizId = TrayBookView.quizOf(trayService.view(), itemId);
        FormEntity form = quizSentenceConverter.parse(lines.get(0));
        QuizTemplateEntity quiz = new QuizTemplateEntity();
        quiz.setId(quizId);
        quiz.setForm(form);
        quiz.setSentences(new ArrayList<>(quizSentenceConverter.toPlainSentences(form)));
        if (lines.size() > 1) {
            quiz.setTranslation(lines.get(1));
        }
        if (lines.size() > 2) {
            quiz.setMiniTheory(lines.get(2));
        }
        return new PanelCandidate(PanelCandidateKind.WHOLE_EXERCISE, quiz, null, null, "arreglo de José");
    }

    /** The tray as José reads it. */
    private static String text(Tray tray) {
        StringBuilder out = new StringBuilder();
        out.append("Bandeja de la tanda ").append(tray.getBatchId()).append(tray.isPublishable() ? " · se puede publicar"
                : " · todavía no se puede publicar").append('\n');
        for (String blocker : list(tray.getBlockers())) {
            out.append("  falta: ").append(blocker).append('\n');
        }
        int n = 1;
        for (TrayItem item : list(tray.getItems())) {
            out.append(n++).append(". [").append(item.getKind()).append("] ").append(item.getItemId());
            if (item.getSeverity() != null) {
                out.append(" · ").append(item.getSeverity());
            }
            out.append('\n');
            if (item.getQuestion() != null) {
                out.append("   ").append(item.getQuestion()).append('\n');
            }
            view(out, "antes", item.getBefore());
            view(out, "después", item.getAfter());
            for (Finding finding : list(item.getFindings())) {
                out.append("   hallazgo: ").append(finding.getAnalyzer()).append(" · ").append(finding.getRule());
                if (finding.getEvidence() != null && finding.getEvidence().getExamined() != null) {
                    for (EvidencePart part : finding.getEvidence().getExamined()) {
                        out.append("\n     ").append(part.getLabel()).append(": ").append(part.getText());
                    }
                }
                out.append('\n');
            }
            for (String reason : list(item.getReasons())) {
                out.append("   · ").append(reason).append('\n');
            }
            for (TraySamplePair pair : list(item.getSamplePairs())) {
                out.append("   ").append(pair.getChangeId()).append('\n');
                view(out, "  antes", pair.getBefore());
                view(out, "  después", pair.getAfter());
            }
            for (BlindPairView pair : list(item.getBlindPairs())) {
                out.append("   par ").append(pair.getIndex()).append('\n');
                side(out, "A", pair.getSideA());
                side(out, "B", pair.getSideB());
            }
            if (item.getRerecord() != null) {
                out.append("   regrabar ").append(item.getRerecord().getAudioKey()).append(" con «")
                        .append(String.join(" / ", list(item.getRerecord().getNewTexts()))).append("»\n");
            }
            if (!list(item.getAnswers()).isEmpty()) {
                out.append("   respuestas: ").append(String.join(", ", list(item.getAnswers()).stream()
                        .map(a -> a == TrayAnswer.BLIND_PAIR ? "A | B | iguales | ambos (--pair N)" : a.name())
                        .toList())).append('\n');
            }
        }
        return out.toString();
    }

    /**
     * An exercise as the student sees it (F-BANDEJA-R001): the sentence and its translation, and under them the
     * instructions, the options, the answers each gap takes and the mini theory -- what a rule or the panel changes is
     * often not the sentence, and José decides on the whole exercise.
     */
    private static void view(StringBuilder out, String label, QuizStudentView view) {
        if (view == null) {
            return;
        }
        out.append("   ").append(label).append(": ").append(view.getStatement());
        if (view.getTranslation() != null && !view.getTranslation().isBlank()) {
            out.append(" · ").append(view.getTranslation());
        }
        out.append('\n');
        details(out, "   " + " ".repeat(label.length() + 2), view, true);
    }

    /**
     * A side of a pair of the blind sample, laid out as {@code sample show} lays it: what the student sees and the
     * sentence answered, without the answers each gap takes, so the sample stays blind to which side is the new one.
     */
    private static void side(StringBuilder out, String name, StudentSide side) {
        QuizStudentView view = side != null ? side.getView() : null;
        if (view == null) {
            out.append("     ").append(name).append(" · (sin vista)\n");
            return;
        }
        out.append("     ").append(name).append(" · ").append(view.getStatement());
        if (view.getTranslation() != null && !view.getTranslation().isBlank()) {
            out.append(" · ").append(view.getTranslation());
        }
        out.append('\n');
        details(out, "         ", view, false);
        if (side.getAnswered() != null && !side.getAnswered().isBlank()) {
            out.append("         respondido: ").append(side.getAnswered()).append('\n');
        }
    }

    private static void details(StringBuilder out, String indent, QuizStudentView view, boolean withAnswers) {
        if (view.getInstructions() != null && !view.getInstructions().isBlank()) {
            out.append(indent).append("consigna: ").append(view.getInstructions()).append('\n');
        }
        if (view.getOptions() != null && !view.getOptions().isEmpty()) {
            out.append(indent).append("opciones: ").append(String.join(" · ", view.getOptions().stream()
                    .map(StudentOptionView::getLabel).toList())).append('\n');
        }
        if (withAnswers) {
            for (StudentGapView gap : list(view.getGaps())) {
                if (gap != null && gap.getAcceptedAnswers() != null && !gap.getAcceptedAnswers().isEmpty()) {
                    out.append(indent).append("hueco ").append(gap.getIndex() + 1).append(": ")
                            .append(String.join(" | ", gap.getAcceptedAnswers())).append('\n');
                }
            }
        }
        if (view.getMiniTheory() != null && !view.getMiniTheory().isBlank()) {
            out.append(indent).append("miniteoría: ").append(view.getMiniTheory()).append('\n');
        }
    }

    private static <T> List<T> list(List<T> values) {
        return values != null ? values : List.of();
    }

    /** What the command reads of a tray. */
    private static final class TrayBookView {
        private TrayBookView() {
        }

        static int size(Tray tray) {
            return tray != null && tray.getItems() != null ? tray.getItems().size() : 0;
        }

        static String quizOf(Tray tray, String itemId) {
            for (TrayItem item : list(tray.getItems())) {
                if (itemId.equals(item.getItemId()) && item.getQuizId() != null) {
                    return item.getQuizId();
                }
            }
            throw new IllegalArgumentException("la bandeja no tiene un ejercicio «" + itemId + "»");
        }
    }
