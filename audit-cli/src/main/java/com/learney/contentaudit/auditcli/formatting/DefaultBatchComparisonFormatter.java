    private static String verdict(BatchComparison comparison) {
        if (comparison.getVerdict().getKind() == null) {
            return "—";
        }
        return switch (comparison.getVerdict().getKind()) {
            case PASSES -> "PASA";
            case FAILS -> "NO PASA";
            case BLIND_SAMPLE_MISSING -> "FALTA LA MUESTRA CIEGA";
            case UNDECIDABLE -> "NO SE PUEDE DECIDIR";
        };
    }

    /** F-METAS-R006: with which goals it evaluated, and what changed since they were sealed. */
    private static String goals(BatchComparison comparison) {
        if (comparison.getGoalsSealedAt() == null) {
            return "Metas nunca fijadas: fijalas con 'set-goals' antes de la tanda.";
        }
        List<GoalChange> changes = list(comparison.getGoalChanges());
        if (changes.isEmpty()) {
            return "Metas fijadas el " + comparison.getGoalsSealedAt() + ", sin cambios.";
        }
        List<String> parts = new ArrayList<>();
        for (GoalChange change : changes) {
            parts.add(change.getGoalId() + " " + change.getBefore() + " → " + change.getAfter());
        }
        return "metas cambiadas desde que se fijaron: " + String.join("; ", parts);
    }

    /** The rows of the course and the levels, and those of a topic or a knowledge that change or do not hold. */
    private static boolean shown(ComparisonRow row) {
        if (row.getNodeTarget() == AuditTarget.COURSE || row.getNodeTarget() == AuditTarget.MILESTONE) {
            return true;
        }
        boolean changes = row.getChange() != null && round(row.getChange()).signum() != 0;
        boolean holds = (row.getFloor() == null || row.getFloor().getStatus() == GoalStatus.MET)
                && (row.getProgress() == null || row.getProgress().getStatus() == GoalStatus.MET);
        return changes || !holds;
    }

    /** «A1 · vocabulario: cambio de medida: 96,54 → 96,02 · 96,02 → 96,02 (0,0 puntos) · piso …: cumple». */
    static String row(ComparisonRow row) {
        if (row == null) {
            return "—";
        }
        StringBuilder text = new StringBuilder();
        text.append(row.getLabel()).append(" · ").append(row.getSubject()).append(": ");
        RowValue before = row.getRemeasuredBaseline() != null ? row.getRemeasuredBaseline() : row.getBaseline();
        if (row.getRemeasuredBaseline() != null && row.getBaseline() != null) {
            text.append("cambio de medida: ").append(value(row.getBaseline(), row.getUnit())).append(" → ")
                    .append(value(row.getRemeasuredBaseline(), row.getUnit())).append(" · ");
        }
        text.append(value(before, row.getUnit())).append(" → ").append(value(row.getProjected(), row.getUnit()));
        if (row.getChange() != null) {
            text.append(" (").append(change(row.getChange(), row.getUnit())).append(')');
        }
        if (row.getFloor() != null) {
            text.append(" · piso ").append(goal(row.getFloor()));
        }
        if (row.getProgress() != null) {
            text.append(" · avance ").append(goal(row.getProgress()));
        }
        return text.toString();
    }

    private static String goal(RowGoalStatus goal) {
        return number(goal.getThreshold()) + " " + unitWord(goal.getUnit()) + " " + referenceWords(goal) + ": "
                + statusWord(goal.getStatus());
    }

    private static String referenceWords(RowGoalStatus goal) {
        if (goal.getReference() == null) {
            return "";
        }
        return switch (goal.getReference()) {
            case BASELINE -> "contra la línea base";
            case BATCH_START -> "contra el inicio de la tanda";
            case ABSOLUTE -> "como valor";
        };
    }

    private static String statusWord(GoalStatus status) {
        if (status == null) {
            return "—";
        }
        return switch (status) {
            case MET -> "cumple";
            case NOT_MET -> "no cumple";
            case UNDECIDABLE -> "no se puede decidir";
        };
    }

    private static String unitWord(GoalUnit unit) {
        if (unit == null) {
            return "";
        }
        return switch (unit) {
            case POINTS -> "puntos";
            case EXERCISES -> "ejercicios";
            case PERCENT -> "%";
        };
    }

    /** A score as points of 100 -- «73,92» --; a count with its share -- «3 (75,0 %)». */
    static String value(RowValue value, GoalUnit unit) {
        if (value == null || value.getValue() == null) {
            return "—";
        }
        if (unit == GoalUnit.POINTS) {
            return number(value.getValue() * 100);
        }
        StringBuilder text = new StringBuilder();
        text.append(Math.round(value.getValue()));
        if (value.getShare() != null) {
            text.append(" (").append(new DecimalFormat("0.0", symbols()).format(value.getShare() * 100)).append(" %)");
        }
        if (value.getNotEvaluated() > 0) {
            text.append(", ").append(value.getNotEvaluated()).append(" sin evaluar");
        }
        return text.toString();
    }

    /** «−0,5 puntos», «+0,3 puntos», «0,0 puntos»; «−2 ejercicios», «+1 ejercicio», «0 ejercicios». */
    static String change(double change, GoalUnit unit) {
        if (unit == GoalUnit.EXERCISES) {
            long exercises = Math.round(change);
            String word = Math.abs(exercises) == 1 ? " ejercicio" : " ejercicios";
            return (exercises < 0 ? MINUS + Math.abs(exercises) : exercises > 0 ? "+" + exercises : "0") + word;
        }
        BigDecimal rounded = round(change);
        if (rounded.signum() == 0) {
            return "0,0 puntos";
        }
        String number = number(rounded.abs().doubleValue());
        return (rounded.signum() < 0 ? MINUS : "+") + number + " puntos";
    }

    /** A number with a decimal comma: 73,92; 67,0; 0,5. */
    static String number(double value) {
        return new DecimalFormat("0.0#", symbols()).format(round(value).doubleValue());
    }

    private static BigDecimal round(double value) {
        return BigDecimal.valueOf(value).setScale(2, RoundingMode.HALF_UP);
    }

    private static DecimalFormatSymbols symbols() {
        return DecimalFormatSymbols.getInstance(Locale.forLanguageTag("es-AR"));
    }

    /**
     * Why a change returns: «lemma-absence · palabra de otro nivel: grandmother es A2», «… · palabra fuera del
     * catálogo: selfie», or the analyzer with its observation.
     */
    static String reason(Finding finding) {
        String word = part(finding, "Palabra");
        String marker = finding.getIdentity() != null ? finding.getIdentity().getMarker() : null;
        if (word == null && marker != null) {
            int bar = marker.indexOf('|');
            word = bar > 0 ? marker.substring(0, bar) : marker;
        }
        String level = part(finding, "Nivel de la palabra");
        if (word != null && ("out-of-catalog-word".equals(finding.getRule()) || "fuera del EVP".equals(level))) {
            return finding.getAnalyzer() + " · palabra fuera del catálogo: " + word;
        }
        if (word != null && level != null) {
            return finding.getAnalyzer() + " · palabra de otro nivel: " + word + " es " + level;
        }
        String observation = finding.getEvidence() != null ? finding.getEvidence().getObservation() : null;
        return finding.getAnalyzer() + " · " + (observation != null ? observation : finding.getRule());
    }

    private static String part(Finding finding, String label) {
        if (finding.getEvidence() == null || finding.getEvidence().getExamined() == null) {
            return null;
        }
        for (EvidencePart part : finding.getEvidence().getExamined()) {
            if (part != null && label.equals(part.getLabel()) && part.getText() != null && !part.getText().isBlank()) {
                return part.getText().trim();
            }
        }
        return null;
    }

    private static String orDash(String value) {
        return value != null && !value.isBlank() ? value : "—";
    }

    private static <T> List<T> list(List<T> list) {
        return list != null ? list : List.of();
    }
