package com.learney.contentaudit.auditcli.commands;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.learney.contentaudit.auditcli.LexisCommand;
import com.learney.contentaudit.auditdomain.CefrLevel;
import com.learney.contentaudit.auditdomain.NlpToken;
import com.learney.contentaudit.auditdomain.NlpTokenizer;
import com.learney.contentaudit.auditdomain.lexicalflags.SentenceLexicalEvaluator;
import com.learney.contentaudit.auditdomain.lexicalflags.SentenceLexicalFlags;
import com.learney.contentaudit.coursedomain.FormEntity;
import com.learney.contentaudit.coursedomain.SentenceMode;
import com.learney.contentaudit.coursedomain.quizsentence.QuizSentenceConverter;
import java.util.List;
import java.util.concurrent.Callable;
import javax.annotation.processing.Generated;
import picocli.CommandLine.Command;
import picocli.CommandLine.Option;

/**
 * Consulta lexica de solo lectura (FEAT-CLEX): dada una quizSentence DSL y un Nivel CEFR,
 * devuelve las palabras que el analisis de mal-ubicacion del audit flaggearia para esa
 * oracion — mal ubicadas para el nivel (F-CLEX-R003) y fuera de catalogo penalizantes
 * (F-CLEX-R004) — reutilizando EXACTAMENTE el mismo pipeline lexico del audit
 * (F-CLEX-R006): {@code parse(dsl) -> toPlainSentences(canonical, mode) ->
 * NlpTokenizer.analyzeTokens(canonical) -> SentenceLexicalEvaluator.evaluate}.
 *
 * <p>Es el analogo lexico de {@link TokensCmd}, pero es un puerto gobernado
 * ({@link LexisCommand}, sentinel.yaml) porque el journey F-CLEX-J001 y sus reglas
 * necesitan trazabilidad de tests, a diferencia del helper de conteo de tokens.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
@Command(
        name = "lexis",
        description = "Query the lexical misplacement flags of a quizSentence DSL for a CEFR level, "
                + "reusing the audit's lemma-absence pipeline.",
        mixinStandardHelpOptions = true,
        footer = {
                "",
                "Examples:",
                "  content-audit lexis -q \"He ____ [sips] (sip) a lot of tea.\" -l A1",
                "  content-audit lexis -q \"You should watch the DVD. ____ [Watch the DVD.]\" -m REWRITE -l A1",
        }
)
final class LexisCmd implements LexisCommand, Callable<Integer> {
    private final QuizSentenceConverter quizSentenceConverter;

    private final NlpTokenizer nlpTokenizer;

    private final SentenceLexicalEvaluator sentenceLexicalEvaluator;

    @Option(names = {"--quiz-sentence", "-q"}, required = true,
            description = "The quizSentence DSL to analyze (e.g. \"He ____ [sips] (sip) a lot of tea.\").")
    private String quizSentence;

    @Option(names = {"--mode", "-m"},
            description = "Sentence mode: FILL (default) or REWRITE. Mirrors the knowledge's sentenceMode.")
    private String mode;

    @Option(names = {"--level", "-l"}, required = true,
            description = "CEFR level of the sentence (A1/A2/B1/B2/C1/C2).")
    private String level;

    public LexisCmd(QuizSentenceConverter quizSentenceConverter, NlpTokenizer nlpTokenizer,
            SentenceLexicalEvaluator sentenceLexicalEvaluator) {
        this.quizSentenceConverter = quizSentenceConverter;
        this.nlpTokenizer = nlpTokenizer;
        this.sentenceLexicalEvaluator = sentenceLexicalEvaluator;
    }

    @Override
    public Integer queryLexis(String quizSentence, String mode, String level) {
        // R007: el nivel es obligatorio — sin un nivel valido no hay contra que resolver
        // la mal-ubicacion. Se valida primero porque es la comprobacion mas barata.
        CefrLevel sentenceLevel;
        try {
            sentenceLevel = CefrLevel.valueOf(
                    level == null ? "" : level.trim().toUpperCase(java.util.Locale.ROOT));
        } catch (IllegalArgumentException e) {
            System.err.println("Error: Nivel CEFR invalido: '" + level
                    + "' (se esperaba A1/A2/B1/B2/C1/C2).");
            return 2;
        }

        SentenceMode sentenceMode = SentenceMode.FILL;
        if (mode != null && !mode.isBlank()) {
            try {
                sentenceMode = SentenceMode.valueOf(mode.trim().toUpperCase(java.util.Locale.ROOT));
            } catch (IllegalArgumentException e) {
                System.err.println("Error: modo invalido '" + mode + "' (se esperaba FILL o REWRITE).");
                return 2;
            }
        }

        // R002/R007: la quizSentence debe respetar la DSL de FEAT-QSENT; un DSL invalido se
        // rechaza con un mensaje claro, distinguible de una respuesta exitosa con lista vacia.
        FormEntity form;
        try {
            form = quizSentenceConverter.parse(quizSentence);
        } catch (RuntimeException e) {
            System.err.println("Error: quizSentence invalida: no respeta la DSL ("
                    + e.getMessage() + ").");
            return 2;
        }

        List<String> sentences;
        try {
            sentences = quizSentenceConverter.toPlainSentences(form, sentenceMode);
        } catch (RuntimeException e) {
            System.err.println("Error: quizSentence invalida: no respeta la DSL ("
                    + e.getMessage() + ").");
            return 2;
        }

        // R002: paridad estricta con la frase canonica por modo (F-SMODE-R003/R004) — en
        // FILL la oracion completa con el hueco relleno, en REWRITE solo la oracion respuesta.
        // Ambas son el indice 0 de toPlainSentences, la misma convencion que el audit usa
        // (CourseToAuditableMapper) y que TokensCmd ya reutiliza.
        String canonical = (sentences == null || sentences.isEmpty()) ? "" : sentences.get(0);

        // R006: mismo tokenizador que el audit.
        List<NlpToken> tokens = nlpTokenizer.analyzeTokens(canonical);

        // R006: mismo pipeline lexico completo del audit, via el evaluator compartido.
        SentenceLexicalFlags flags = sentenceLexicalEvaluator.evaluate(tokens, sentenceLevel);

        try {
            System.out.println(new ObjectMapper().writeValueAsString(flags));
        } catch (com.fasterxml.jackson.core.JsonProcessingException e) {
            System.err.println("Error: could not serialize lexical flags: " + e.getMessage());
            return 2;
        }
        return 0;
    }

    @Override
    public Integer call() {
        return queryLexis(quizSentence, mode, level);
    }
}
