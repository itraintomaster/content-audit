package com.learney.contentaudit.auditcli.commands;
import java.util.concurrent.Callable;

import com.learney.contentaudit.auditcli.ReviseInstructionsCommand;
import com.learney.contentaudit.auditcli.formatting.QuizInstructionCorrectionRunFormatter;
import com.learney.contentaudit.refinerdomain.RefinementPlanStore;
import com.learney.contentaudit.revisiondomain.QuizInstructionCorrectionRunner;
import com.learney.contentaudit.revisiondomain.quizinstruction.QuizInstructionCorrectionRunReport;
import com.learney.contentaudit.revisiondomain.quizinstruction.QuizInstructionCorrectionRunRequest;
import java.nio.file.Path;
import javax.annotation.processing.Generated;
import picocli.CommandLine.Command;
import picocli.CommandLine.Option;

/**
 * F-QICOR-R008 (journey J002): drives one bounded batch run of QUIZ_INSTRUCTION
 * corrections through {@link QuizInstructionCorrectionRunner} and renders its
 * report, naming the four declared outcomes separately (proposed / not
 * corrected / diagnosis stale / not attempted) rather than a single count.
 *
 * <p>Registered as the {@code revise-instructions} subcommand in {@code Main.java}
 * (ARCH-QICOR-004 added {@code externalImplements: [java.util.concurrent.Callable<Integer>]}
 * to this component). Deliberately its own verb, not a flag on {@code revise}:
 * correcting consigna is always an explicit operator action, never something
 * {@code analyze} or {@code revise task &lt;id&gt;} triggers on its own.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
@Command(
        name = "revise-instructions",
        description = "Run a bounded batch of QUIZ_INSTRUCTION corrections over a plan (F-QICOR-R008).%n%n"
                + "Usage: content-audit revise-instructions --plan <plan-id> [--max N] [--course-path <path>]%n%n"
                + "Each run attempts at most --max tasks (default from config, R008); tasks left over the "
                + "cap are declared, not silently dropped, and remain available for the next run.",
        mixinStandardHelpOptions = true,
        footer = {
                "",
                "Examples:",
                "  # Correct up to the configured default number of tasks",
                "  content-audit revise-instructions --plan plan-abc-123",
                "",
                "  # Cap this run at 5 tasks",
                "  content-audit revise-instructions --plan plan-abc-123 --max 5",
        }
)
final class ReviseInstructionsCmd implements ReviseInstructionsCommand, Callable<Integer> {
    private final QuizInstructionCorrectionRunner correctionRunner;

    private final RefinementPlanStore refinementPlanStore;

    private final QuizInstructionCorrectionRunFormatter runFormatter;

    @Option(names = {"--plan"}, required = true, description = "Plan id to correct.")
    private String planId;

    @Option(names = {"--max"},
            description = "Maximum number of QUIZ_INSTRUCTION tasks to attempt this run (R008). "
                    + "If omitted, falls back to the configured default.")
    private Integer maxCorrections;

    @Option(names = {"-c", "--course-path"},
            description = "Path to the course directory. Defaults to CONTENT_AUDIT_CONTENT_FOLDER env var.")
    private String coursePath;

    public ReviseInstructionsCmd(QuizInstructionCorrectionRunner correctionRunner,
            RefinementPlanStore refinementPlanStore,
            QuizInstructionCorrectionRunFormatter runFormatter) {
        this.correctionRunner = correctionRunner;
        this.refinementPlanStore = refinementPlanStore;
        this.runFormatter = runFormatter;
    }

    @Override
    public Integer call() {
        return reviseInstructions(planId, maxCorrections, coursePath);
    }

    @Override
    public Integer reviseInstructions(String planId, Integer maxCorrections, String coursePath) {
        if (planId == null || planId.isBlank()) {
            System.err.println("Error: plan id is required");
            return 1;
        }

        if (refinementPlanStore.load(planId).isEmpty()) {
            System.err.println("Error: plan not found: " + planId);
            return 1;
        }

        String resolvedCoursePath = CoursePathResolver.resolve(coursePath);
        if (resolvedCoursePath == null) {
            System.err.println("Error: missing course path. Provide it as --course-path or "
                    + "set CONTENT_AUDIT_CONTENT_FOLDER.");
            return 1;
        }

        QuizInstructionCorrectionRunRequest request = new QuizInstructionCorrectionRunRequest(
                planId, Path.of(resolvedCoursePath), maxCorrections);

        QuizInstructionCorrectionRunReport report;
        try {
            report = correctionRunner.run(request);
        } catch (RuntimeException e) {
            System.err.println("Error running the quiz-instruction correction batch: "
                    + e.getMessage());
            return 1;
        }

        System.out.println(runFormatter.format(report));
        return 0;
    }

}
