/**
 * {@code set-baseline} (F-PROYU-R006): fixes as the baseline an analysis of the history -- never a saved projection,
 * which the history does not list -- in its own record, so neither the active pair nor the sealed goals move.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
final class DefaultSetBaselineCommand implements SetBaselineCommand {
    private final BaselineStore baselineStore;

    private final AuditReportStore auditReportStore;

    public DefaultSetBaselineCommand(BaselineStore baselineStore,
            AuditReportStore auditReportStore) {
        this.baselineStore = baselineStore;
        this.auditReportStore = auditReportStore;
    }

    @Override
    public Integer setBaseline(String auditId) {
        if (auditId == null || auditId.isBlank()) {
            System.err.println("Error: the id of an analysis of the history is required.");
            return 1;
        }
        String id = auditId.trim();
        if (!inHistory(id)) {
            System.err.println("Cannot fix '" + id + "' as the baseline: it is not an analysis in the history.");
            return 1;
        }
        baselineStore.write(new Baseline(id, Instant.now()));
        System.out.println("Baseline fixed: " + id);
        return 0;
    }

    @Override
    public Integer showBaseline(String format) {
        Optional<Baseline> baseline = baselineStore.read();
        if (CommandJson.isJson(format)) {
            Map<String, Object> json = new LinkedHashMap<>();
            json.put("auditId", baseline.map(Baseline::getAuditId).orElse(null));
            json.put("fixedAt", baseline.map(Baseline::getFixedAt).orElse(null));
            System.out.println(CommandJson.write(json));
            return 0;
        }
        if (baseline.isEmpty()) {
            System.out.println("No baseline fixed. Fix one with 'set-baseline <id>'.");
            return 0;
        }
        System.out.println("Baseline: " + baseline.get().getAuditId() + " (fixed at " + baseline.get().getFixedAt()
                + ")");
        return 0;
    }

    private boolean inHistory(String auditId) {
        List<AuditReportSummary> analyses = auditReportStore.list();
        if (analyses == null) {
            return false;
        }
        for (AuditReportSummary summary : analyses) {
            if (summary != null && auditId.equals(summary.getId())) {
                return true;
            }
        }
        return false;
    }
}
