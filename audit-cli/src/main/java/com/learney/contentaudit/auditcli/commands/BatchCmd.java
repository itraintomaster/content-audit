        out.append("Ejercicios: ").append(estimate.getQuizzes()).append(", en ").append(estimate.getTopics())
                .append(" temas; el tema más pesado tiene ").append(estimate.getHeaviestTopicQuizzes())
                .append(" ejercicios.\n");
