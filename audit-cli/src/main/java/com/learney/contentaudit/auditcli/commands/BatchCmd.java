    @Override
    public Integer openBatch(String level, Integer topicsAtOnce, Integer queriesAtOnce,
            List<String> convertToMultipleChoice) {
        CefrLevel cefr = level(level);
        if (cefr == null) {
            System.err.println("Error: batch open <nivel>: A1, A2, B1, B2, C1 o C2.");
            return 2;
        }
        if (topicsAtOnce != null && topicsAtOnce < 1 || queriesAtOnce != null && queriesAtOnce < 1) {
            System.err.println("Error: --topics-at-once y --queries-at-once van con un número, 1 o más.");
            return 2;
        }
        CorrectionBatch batch;
        try {
            batch = batchService.open(new BatchOpenRequest(cefr, topicsAtOnce, queriesAtOnce,
                    convertToMultipleChoice != null ? new ArrayList<>(convertToMultipleChoice) : new ArrayList<>()));
        } catch (BatchAlreadyOpenException | IllegalStateException e) {
            System.err.println("Error: " + e.getMessage());
            return 1;
        } catch (IllegalArgumentException e) {
            System.err.println("Error: " + e.getMessage());
            return 2;
        }
        BatchSettings settings = batch.getSettings();
        StringBuilder out = new StringBuilder();
        out.append("Tanda ").append(batch.getId()).append(" abierta en ").append(batch.getLevel()).append(", sobre el")
                .append(" análisis ").append(batch.getStartAuditId()).append(" (plan ").append(batch.getPlanId())
                .append("). Línea base: ").append(batch.getBaselineAuditId()).append(".\n");
        if (settings != null) {
            out.append("A la vez: ").append(settings.getTopicsAtOnce()).append(" temas y ")
                    .append(settings.getQueriesAtOnce()).append(" consultas; hasta ").append(settings.getMaxAttempts())
                    .append(" intentos por ejercicio.\n");
        }
        List<String> tasks = list(batch.getTaskIds());
        out.append("Tareas (").append(tasks.size()).append(")").append(tasks.isEmpty() ? ".\n" : ":\n");
        for (String task : tasks) {
            out.append("  ").append(task).append('\n');
        }
        List<String> notTaken = list(batch.getNotTakenTaskIds());
        if (!notTaken.isEmpty()) {
            out.append("No entran (").append(notTaken.size()).append("), con una propuesta pendiente fuera de la tanda o")
                    .append(" un audio por regrabar: ").append(String.join(", ", notTaken)).append('\n');
        }
        for (ConversionOrder order : list(batch.getConversionOrders())) {
            out.append("Encargo de José: el tema ").append(order.getKnowledgeId()).append(" pasa a opción múltiple con ")
                    .append(order.getOptionCount()).append(" opciones.\n");
        }
        List<AudioRerecordRequest> pending = list(batch.getPendingRerecords());
        if (!pending.isEmpty()) {
            out.append("Audios que siguen por regrabar (").append(pending.size()).append("):\n");
            for (AudioRerecordRequest request : pending) {
                out.append("  ").append(rerecord(request)).append('\n');
            }
        }
        List<NotComparedCount> unevaluated = list(batch.getUnevaluated());
        if (!unevaluated.isEmpty()) {
            List<String> counts = new ArrayList<>();
            for (NotComparedCount count : unevaluated) {
                counts.add(count.getAnalyzer() + " " + count.getQuizzes());
            }
            out.append("Sin evaluar al abrir: ").append(String.join(", ", counts)).append(".\n");
        }
        out.append("Siguiente: content-audit batch estimate, y content-audit batch run.");
        System.out.println(out);
        return 0;
    }

