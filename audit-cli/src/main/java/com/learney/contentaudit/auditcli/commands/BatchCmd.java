    /** The outcomes with tasks, adding up to the tasks, and José's orders apart. */
    private static String summary(BatchReport report) {
        StringBuilder out = new StringBuilder();
        out.append("Tareas: ").append(report.getTotalTasks()).append('\n');
        for (OutcomeCount count : list(report.getOutcomes())) {
            if (count.getTasks() > 0) {
                out.append("  ").append(spanish(count.getKind())).append(": ").append(count.getTasks()).append('\n');
            }
        }
        if (report.getConversionDone() > 0 || report.getConversionNoWinner() > 0) {
            out.append("Encargos de José: ").append(report.getConversionDone()).append(" ejercicios hechos y ")
                    .append(report.getConversionNoWinner()).append(" sin ganador.\n");
        }
        return out.toString();
    }

    private static int count(BatchReport report, BatchTaskOutcomeKind kind) {
        for (OutcomeCount count : list(report.getOutcomes())) {
            if (count.getKind() == kind) {
                return count.getTasks();
            }
        }
        return 0;
    }

