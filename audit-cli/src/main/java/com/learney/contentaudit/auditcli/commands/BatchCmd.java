    /** The outcomes with tasks, adding up to the tasks, and José's orders apart. */
    private static String summary(BatchReport report) {
        StringBuilder out = new StringBuilder();
        out.append("Tareas: ").append(report.getTotalTasks()).append('\n');
        for (OutcomeCount count : list(report.getOutcomes())) {
            if (count.getTasks() > 0) {
                out.append("  ").append(spanish(count.getKind())).append(": ").append(count.getTasks()).append('\n');
            }
        }
        if (report.getConversionDone() > 0 || report.getConversionNoWinner() > 0) {
            out.append("Encargos de José: ").append(report.getConversionDone()).append(" ejercicios hechos y ")
                    .append(report.getConversionNoWinner()).append(" sin ganador.\n");
        }
        return out.toString();
    }

    private static int count(BatchReport report, BatchTaskOutcomeKind kind) {
        for (OutcomeCount count : list(report.getOutcomes())) {
            if (count.getKind() == kind) {
                return count.getTasks();
            }
        }
        return 0;
    }

    private static final Map<BatchTaskOutcomeKind, String> SPANISH = Map.ofEntries(
            Map.entry(BatchTaskOutcomeKind.PENDING, "pendientes"),
            Map.entry(BatchTaskOutcomeKind.RESOLVED_BY_RULE, "resueltas por regla"),
            Map.entry(BatchTaskOutcomeKind.RESOLVED_BY_PANEL, "resueltas por la mesa"),
            Map.entry(BatchTaskOutcomeKind.NO_LONGER_HOLDS, "ya no se sostienen"),
            Map.entry(BatchTaskOutcomeKind.COVERED, "cubiertas"),
            Map.entry(BatchTaskOutcomeKind.NO_WINNER, "sin ganador"),
            Map.entry(BatchTaskOutcomeKind.TIE, "en desempate"),
            Map.entry(BatchTaskOutcomeKind.RETURNED_WITHOUT_ATTEMPTS, "devueltas sin intentos"),
            Map.entry(BatchTaskOutcomeKind.NO_DECLARED_SCOPE, "sin alcance declarado"),
            Map.entry(BatchTaskOutcomeKind.PENDING_RERECORDING, "pendientes de regrabar"),
            Map.entry(BatchTaskOutcomeKind.NOT_ATTEMPTED, "sin intentar"));

    private static String spanish(BatchTaskOutcomeKind kind) {
        return SPANISH.getOrDefault(kind, String.valueOf(kind));
    }

    private static String resolution(BatchTaskCount count) {
        if (count.getResolution() == null) {
            return "sin resolución";
        }
        return switch (count.getResolution()) {
            case RULE -> "regla";
            case PANEL -> "mesa";
            case RANK_ONLY -> "sólo ordena";
        };
    }

    private static String hours(double hours) {
        return String.format(Locale.ROOT, "%.2f", hours).replace('.', ',');
    }

    private static String rerecord(AudioRerecordRequest request) {
        String key = request.getAudioKey() != null && !request.getAudioKey().isBlank() ? request.getAudioKey()
                : "(sin clave)";
        return key + " · " + request.getQuizId() + " · «" + String.join(" / ", list(request.getNewTexts())) + "»";
    }

    private static CefrLevel level(String level) {
        if (level == null || level.isBlank()) {
            return null;
        }
        try {
            return CefrLevel.valueOf(level.trim().toUpperCase(Locale.ROOT));
        } catch (IllegalArgumentException e) {
            return null;
        }
    }

    private static <T> List<T> list(List<T> values) {
        return values != null ? values : List.of();
    }
