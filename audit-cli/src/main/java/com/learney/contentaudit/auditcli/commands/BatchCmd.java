    @Override
    public Integer runBatch(Integer queryCap) {
        if (queryCap != null && queryCap < 0) {
            System.err.println("Error: --cap va con un número de consultas, 0 o más.");
            return 2;
        }
        BatchReport report;
        try {
            report = batchService.run(new BatchRunRequest(queryCap));
        } catch (NoOpenBatchException e) {
            System.err.println("Error: " + e.getMessage());
            return 1;
        }
        StringBuilder out = new StringBuilder();
        if (queryCap == null) {
            out.append("Sin tope de consultas: corrieron sólo las reglas, que no consultan ningún modelo; ")
                    .append(count(report, BatchTaskOutcomeKind.NOT_ATTEMPTED))
                    .append(" tareas de la mesa quedaron sin intentar. Para abrir la mesa: content-audit batch run")
                    .append(" --cap N.\n");
        } else {
            out.append("Corrida con tope de ").append(queryCap).append(" consultas.\n");
        }
        out.append(summary(report));
        if (report.getStatus() == BatchStatus.INTERRUPTED) {
            String reason = report.getInterruptionReason();
            out.append("La corrida se interrumpió antes de completar el trabajo");
            if (reason != null && !reason.isBlank()) {
                out.append(": ").append(reason.strip());
            }
            out.append(". Lo decidido quedó guardado; corregí la causa y volvé a ejecutar batch run.");
            System.err.println(out);
            return 1;
        }
        out.append("Siguiente: content-audit batch close.");
        System.out.println(out);
        return 0;
    }

    @Override
    public Integer closeBatch(Map<String, Integer> judgeBudgets, Integer queryCap) {
        String refused = refusedTope(judgeBudgets, queryCap);
        if (refused != null) {
            System.err.println("Error: " + refused);
            return 2;
        }
        BatchClosing closing;
        try {
            closing = batchService.close(new BatchCloseRequest(
                    judgeBudgets != null ? judgeBudgets : new LinkedHashMap<>(), queryCap));
        } catch (NoOpenBatchException e) {
            System.err.println("Error: " + e.getMessage());
            return 1;
        } catch (IllegalArgumentException e) {
            // F-CJUEZ-R003 inv. 4: a name that is not a judge of the batch, said by the service before it closes anything
            System.err.println("Error: " + e.getMessage());
            return 2;
        }
        BatchGateVerdict gate = closing != null ? closing.getGate() : null;
        if (gate == null) {
            System.err.println("Error: la tanda se cerró sin veredicto de la compuerta.");
            return 1;
        }
        CorrectionBatch batch = batchService.current().orElse(null);
        // F-PUBPROD-R005: con «no se puede decidir» —o con un piso sin decidir— el cierre no se lee como «pasa»: lo
        // dice y sale con 1, aunque la compuerta no haya encontrado nada roto. «no se puede decidir» se dice sólo del
        // veredicto que no se puede decidir; los pisos sin decidir de otro veredicto se cuentan aparte (VerdictWording).
        BatchVerdict verdict = closing.getComparison() != null ? closing.getComparison().getVerdict() : null;
        int undecided = VerdictWording.undecidedFloors(verdict);
        boolean undecidable = verdict != null && verdict.getKind() == VerdictKind.UNDECIDABLE;
        StringBuilder out = new StringBuilder();
        out.append(undecidable ? "No se puede decidir si la tanda empeora el curso"
                + (undecided > 0 ? ": " + VerdictWording.floors(undecided) : "")
                : (gate.isPasses() ? "La compuerta de «no empeorar» pasa" : "La compuerta de «no empeorar» no pasa")
                        + VerdictWording.floorsAfter(gate.isPasses(), undecided))
                .append(" (").append(closing.getRounds()).append(closing.getRounds() == 1 ? " vuelta" : " vueltas")
                .append(").\n");
        for (String why : list(gate.getReasons())) {
            out.append("  ").append(why).append('\n');
        }
        if (!list(closing.getReturnedChangeIds()).isEmpty()) {
            out.append("Volvieron a la mesa: ").append(String.join(", ", closing.getReturnedChangeIds())).append(".\n");
        }
        for (ReturnedChange back : list(gate.getReturned())) {
            out.append("  vuelve ").append(back.getProposalId()).append(": ").append(back.getReason()).append('\n');
        }
        for (String listed : list(gate.getListedExceptions())) {
            out.append("  aparte: ").append(listed).append('\n');
        }
        if (closing.getComparison() != null && closing.getComparison().getVerdict() != null) {
            String detail = closing.getComparison().getVerdict().getDetail();
            out.append("Veredicto de la comparación: ").append(VerdictWording.plain(verdict))
                    .append(detail != null && !detail.isBlank() ? " — " + detail : "").append('\n');
        }
        out.append(judgesBlock(closing.getJudges()));
        if (batch != null && batch.getBlindSampleId() != null) {
            out.append("Muestra ciega: ").append(batch.getBlindSampleId()).append(" (content-audit sample show ")
                    .append(batch.getBlindSampleId()).append(").\n");
        }
        out.append("Siguiente: content-audit tray show.");
        System.out.println(out);
        return gate.isPasses() && !undecidable && undecided == 0 ? 0 : 1;
    }

    @Override
    public Integer dropFromBatch(String changeId, String ruleId, String reason) {
        boolean change = changeId != null && !changeId.isBlank();
        boolean rule = ruleId != null && !ruleId.isBlank();
        if (change == rule) {
            System.err.println("Error: batch drop --change <id> o --rule <regla>, una de las dos.");
            return 2;
        }
        Set<String> droppedBefore = new HashSet<>();
        for (BatchChange each : batchService.current().map(CorrectionBatch::getChanges).orElse(List.of())) {
            if (each != null && each.getDroppedReason() != null) {
                droppedBefore.add(each.getChangeId());
            }
        }
        BatchAdjustment adjustment = new BatchAdjustment(change ? BatchAdjustmentKind.DROP_CHANGE
                : BatchAdjustmentKind.DROP_RULE, null, new ArrayList<>(), change ? changeId : null, rule ? ruleId : null,
                null, null, reason, "José", Instant.now());
        CorrectionBatch batch;
        try {
            batch = batchService.adjust(adjustment);
        } catch (NoOpenBatchException | IllegalArgumentException e) {
            System.err.println("Error: " + e.getMessage());
            return 1;
        }
        List<BatchChange> dropped = new ArrayList<>();
        for (BatchChange each : list(batch.getChanges())) {
            if (each != null && each.getDroppedReason() != null && !droppedBefore.contains(each.getChangeId())) {
                dropped.add(each);
            }
        }
        StringBuilder out = new StringBuilder();
        if (change) {
            out.append("Salió el cambio ").append(changeId).append(".\n");
        } else {
            long ofTheRule = dropped.stream().filter(c -> Objects.equals(c.getRuleId(), ruleId)).count();
            out.append("Salieron los ").append(ofTheRule).append(ofTheRule == 1 ? " cambio" : " cambios")
                    .append(" de la regla ").append(ruleId).append(".\n");
        }
        for (BatchChange each : dropped) {
            boolean named = change ? each.getChangeId().equals(changeId) : Objects.equals(each.getRuleId(), ruleId);
            out.append("  ").append(each.getChangeId()).append(": ").append(each.getDroppedReason())
                    .append(named ? "" : " (sale encadenado)").append('\n');
        }
        out.append(list(batch.getClosings()).isEmpty() ? "Sus tareas vuelven a pendiente."
                : "Sus tareas vuelven a pendiente, y la tanda se volvió a comparar contra la compuerta.");
        System.out.println(out);
        return 0;
    }

    @Override
    public Integer reportBatch(String batchId, String format) {
        BatchReport report;
        try {
            report = batchService.report(batchId);
        } catch (NoOpenBatchException e) {
            System.err.println("Error: " + e.getMessage());
            return 1;
        }
        if (CommandJson.isJson(format)) {
            System.out.println(CommandJson.write(report));
            return 0;
        }
        StringBuilder out = new StringBuilder();
        out.append("Tanda ").append(report.getBatchId()).append(" · ").append(report.getLevel()).append(" · ")
                .append(report.getStatus()).append('\n');
        out.append(summary(report));
        List<AnalyzerLevelErrors> errors = list(report.getErrorsByAnalyzer());
        if (!errors.isEmpty()) {
            out.append("Ejercicios con error, antes → después:\n");
            for (AnalyzerLevelErrors error : errors) {
                out.append("  ").append(error.getAnalyzer()).append(" en ").append(error.getLevel()).append(": ")
                        .append(error.getBefore()).append(" → ").append(error.getAfter()).append('\n');
            }
        }
        List<AudioRerecordRequest> rerecords = list(report.getRerecords());
        out.append("Audios para regrabar (").append(rerecords.size()).append(")").append(rerecords.isEmpty() ? ".\n" : ":\n");
        for (AudioRerecordRequest request : rerecords) {
            out.append("  ").append(rerecord(request)).append('\n');
        }
        if (report.getQueries() != null) {
            out.append("Consultas: ").append(report.getQueries().getProposer()).append(" del proponente y ")
                    .append(report.getQueries().getJudges()).append(" de los jueces; ").append(hours(report.getHours()))
                    .append(" horas.\n");
        }
        out.append(judgesBlock(report.getJudges()));
        List<BatchAdjustment> decisions = list(report.getJoseDecisions());
        if (!decisions.isEmpty()) {
            out.append("Decisiones de José (").append(decisions.size()).append("):\n");
            for (BatchAdjustment decision : decisions) {
                String what = decision.getChangeId() != null ? decision.getChangeId()
                        : decision.getRuleId() != null ? decision.getRuleId() : decision.getQuizId();
                out.append("  ").append(decision.getKind()).append(what != null ? " " + what : "")
                        .append(decision.getReason() != null ? ": " + decision.getReason() : "").append('\n');
            }
        }
        System.out.print(out);
        return 0;
    }

    @Override
    public Integer call() {
        if (action == null) {
            System.err.println("Error: batch necesita open, estimate, run, close, drop o report. Ver content-audit batch"
                    + " --help.");
            return 2;
        }
        try {
            return dispatch();
        } catch (IllegalStateException e) {
            System.err.println("Error: " + e.getMessage());
            return 1;
        }
    }

    private Integer dispatch() {
        return switch (action) {
            case "open" -> openBatch(target, topicsAtOnce, queriesAtOnce, convertToMultipleChoice);
            case "estimate" -> estimateBatch();
            case "run" -> runBatch(queryCap);
            case "close" -> closeBatch(judgeBudgets, queryCap);
            case "drop" -> dropFromBatch(changeId, ruleId, reason);
            case "report" -> reportBatch(target, format);
            case "review" -> reviewBatch();
            default -> {
                System.err.println("Error: batch no conoce '" + action + "'. Usá open, estimate, run, close, drop o"
                        + " report o review.");
                yield 2;
            }
        };
    }

    private Integer reviewBatch() {
        try {
            var review = decisionJson == null ? batchService.review(target)
                    : batchService.review(CommandJson.read(decisionJson, BatchReviewDecision.class));
            System.out.println(CommandJson.writeCompact(review));
            return 0;
        } catch (IllegalArgumentException | NoOpenBatchException e) {
            System.err.println("Error: " + e.getMessage());
            return 2;
        }
    }

