    @Override
    public Integer call() throws Exception {
        if (action == null) {
            System.err.println("Error: exam needs run, record or status. See content-audit exam --help.");
            return 2;
        }
        return switch (action) {
            case "run" -> takeExam(target, casesFile, photoCourse, budget, concurrency, verdictsOut);
            case "record" -> recordExam(target);
            case "status" -> CommandJson.isJson(formatName) ? showExamsJson(target) : showExams(target);
            case "cutover" -> cutover(apply);
            default -> {
                System.err.println("Error: unknown exam action '" + action + "'. Use run, record, status or cutover.");
                yield 2;
            }
        };
    }

    @Override
    public Integer takeExam(String judgeName, String casesFile, String photoCourse, Integer budget,
            Integer concurrency, String verdictsOut) {
        if (isBlank(judgeName) || isBlank(casesFile) || isBlank(photoCourse) || isBlank(verdictsOut)) {
            System.err.println("Error: exam run <judge> --cases <file> --course <photo> --out <verdicts> "
                    + "[--budget N] [--concurrency N]");
            return 2;
        }
        if (budget != null && budget < 0) {
            System.err.println("Error: --budget needs a number of consultations, 0 or more");
            return 2;
        }
        if (concurrency != null && concurrency < 1) {
            System.err.println("Error: --concurrency needs a number of consultations at a time, 1 or more");
            return 2;
        }
        Path output = Path.of(verdictsOut);
        if (Files.exists(output)) {
            System.err.println("Error: the verdicts file already exists and will not be overwritten: " + verdictsOut);
            return 2;
        }
        if (metricsOut != null && Files.exists(metricsOut)) {
            System.err.println("Error: the metrics file already exists and will not be overwritten: " + metricsOut);
            return 2;
        }
        Set<String> caseIds;
        try {
            caseIds = readCases(Path.of(casesFile));
        } catch (IOException | IllegalArgumentException e) {
            System.err.println("Error: the exam file " + casesFile + " cannot be read: " + e.getMessage());
            return 2;
        }

        JudgeExamTaken taken;
        Map<String, JsonNode> caseMetadata;
        ExamProvenance provenance = provenanceByJudge.getOrDefault(judgeName, ExamProvenance.NONE);
        try {
            caseMetadata = readCaseMetadata(Path.of(casesFile));
            JudgeExamRequest request = new JudgeExamRequest(judgeName, Path.of(photoCourse), caseIds,
                    budget != null ? budget : 0, concurrency, provenance.providerName(),
                    provenance.modelName(), provenance.reasoningEffort());
            bindRegressions(request, caseMetadata);
            taken = examService.take(request);
        } catch (IOException | IllegalArgumentException e) {
            System.err.println("Error: " + e.getMessage());
            return 1;
        }

        try {
            writeVerdicts(output, taken.getVerdicts(), taken.getRuntimeIdentity(), caseMetadata);
            if (metricsOut != null) {
                int queries = taken.getCoverage() == null || taken.getCoverage().getEvaluators() == null ? 0 : taken.getCoverage().getEvaluators().stream()
                        .filter(e -> e != null && e.getCoverage() != null)
                        .mapToInt(e -> e.getCoverage().getEvaluatedInRun() + e.getCoverage().getFailed()).sum();
                var metrics = new LinkedHashMap<String, Object>();
                metrics.put("queriesUsed", queries);
                metrics.put("judgeVersion", taken.getJudgeVersion());
                metrics.put("runtime", taken.getRuntimeIdentity());
                metrics.put("examFingerprint", taken.getExamFingerprint());
                metrics.put("regressionSuiteFingerprint", taken.getRegressionSuiteFingerprint());
                metrics.put("regressionCaseIds", taken.getRegressionCaseIds());
                metrics.put("regressionMismatchedCaseIds", taken.getRegressionMismatchedCaseIds());
                Files.writeString(metricsOut, CommandJson.writeCompact(metrics), java.nio.file.StandardOpenOption.CREATE_NEW);
            }
        } catch (IOException e) {
            System.err.println("Error: the verdicts cannot be written to " + verdictsOut + ": " + e.getMessage());
            return 1;
        }
        printSummary(taken, budget == null);
        return 0;
    }

    @Override
    public Integer recordExam(String resultFile) {
        if (isBlank(resultFile)) {
            System.err.println("Error: exam record <file with the measured result>");
            return 2;
        }
        JudgeExamRecord measured;
        try {
            measured = readMeasured(Path.of(resultFile));
        } catch (IOException | IllegalArgumentException e) {
            System.err.println("Error: the measured result " + resultFile + " cannot be read: " + e.getMessage());
            return 2;
        }
        try {
            JudgeExamStanding standing = examService.record(measured);
            System.out.println("Registrado: " + measured.getJudgeName() + " versión " + measured.getJudgeVersion()
                    + " · " + runtimeLabel(standing.getRuntimeIdentity())
                    + " → " + spanish(standing.getStatus())
                    + (standing.isConsultsOnCourse()
                            ? ". Puede consultar sobre el curso cuando se le pida tope."
                            : ". No consulta sobre el curso: " + standing.getReason()));
            return 0;
        } catch (JudgeExamNotTakenException e) {
            System.err.println("Error: " + e.getMessage() + ". Corré antes exam run con todos los ejercicios del archivo.");
            return 1;
        } catch (IllegalArgumentException e) {
            System.err.println("Error: " + e.getMessage());
            return 2;
        }
    }

    @Override
    public Integer showExams(String judgeName) {
        if (isBlank(judgeName)) {
            System.err.println("Error: exam status <judge>");
            return 2;
        }
        var current=currentStandings.get().get(judgeName);
        boolean promoted=current!=null && current.getStatus()==JudgeExamStatus.PROMOTED;
        if(promoted)System.out.println(judgeName+": PROMOVIDO POR EL OPERADOR · "+runtimeLabel(current.getRuntimeIdentity())
                +" · versión "+current.getJudgeVersion()+". "+current.getReason());
        List<JudgeExamRecord> history = examService.history(judgeName);
        if (history.isEmpty()) {
            System.out.println(promoted ? "Examen fijo: sin medición registrada; la promoción del operador habilita esta versión."
                    : judgeName + ": ninguna versión rindió el examen fijo todavía.");
            return 0;
        }
        System.out.println("Exámenes de " + judgeName + ":");
        for (JudgeExamRecord record : history) {
            StringBuilder line = new StringBuilder();
            line.append(record.getRecordedAt() != null ? record.getRecordedAt().toString() : "(sin fecha)")
                    .append("  ").append(record.getJudgeVersion())
                    .append("  ").append(provenanceLabel(record))
                    .append("  ").append(spanish(record.getStatus()));
            if (!isBlank(record.getPhoto())) {
                line.append("  foto ").append(record.getPhoto());
            }
            line.append("  juzgados ").append(record.getCasesJudged());
            if (record.getCasesNotJudged() > 0) {
                line.append(", sin juzgar ").append(record.getCasesNotJudged());
            }
            if (record.getStatus() == JudgeExamStatus.TAKEN) {
                line.append(", pendiente de medición");
            }
            if (record.getStatus() == JudgeExamStatus.APPROVED || record.getStatus() == JudgeExamStatus.FAILED) {
                line.append(record.isGoalMet() ? ", alcanzó la meta" : ", no alcanzó la meta");
                if (record.getMeasuredBy() != null) {
                    line.append(", medido por ").append(record.getMeasuredBy());
                }
                if (record.getGroups() != null && !record.getGroups().isEmpty()) {
                    line.append(", grupos ");
                    for (int i = 0; i < record.getGroups().size(); i++) {
                        JudgeExamGroupResult group = record.getGroups().get(i);
                        if (i > 0) {
                            line.append("; ");
                        }
                        line.append(group.getGroup()).append(' ')
                                .append(group.getAsExpected()).append('/').append(group.getCases())
                                .append(" como se esperaba");
                    }
                }
                if (record.getMismatchedCaseIds() != null && !record.getMismatchedCaseIds().isEmpty()) {
                    line.append(", no coincidieron ").append(record.getMismatchedCaseIds());
                }
            }
            System.out.println(line);
        }
        JudgeExamStanding standing = currentStandings.get().get(judgeName);
        if (standing != null) {
            // F-ALDIA-R002 inv. 3: why an exam of the earlier version counts for this one.
            for (EvaluatorVersionEquivalence equivalence : standing.getVersionEquivalences()) {
                System.out.println(equivalenceLine(equivalence));
            }
            // F-ALDIA-R003: with which motors the version of today is enabled.
            for (JudgeEnablement enablement : standing.getEnabledWith()) {
                System.out.println("Habilitada con " + runtimeLabel(enablement.runtimeIdentity()) + ": "
                        + (enablement.status() == JudgeExamStatus.PROMOTED ? "promovida" : "aprobó")
                        + (enablement.since() != null ? " el " + enablement.since() : "") + ".");
            }
        }
        return 0;
    }

    /**
     * F-ALDIA-R002: without {@code --apply}, what the cut-over would write, or what it wrote; with it,
     * writes it, once. It never consults a judge.
     */
    Integer cutover(boolean apply) {
        if (versionCutover == null) {
            System.err.println("Error: exam cutover no está disponible en esta instalación.");
            return 2;
        }
        List<EvaluatorVersionEquivalence> recorded = versionCutover.recorded();
        if (!recorded.isEmpty()) {
            if (apply) {
                System.err.println("Error: la equivalencia ya se anotó; es una sola vez (F-ALDIA-R002 inv. 4).");
            }
            System.out.println("La equivalencia ya está anotada:");
            recorded.forEach(equivalence -> System.out.println(equivalenceLine(equivalence)));
            return apply ? 1 : 0;
        }
        if (!apply) {
            List<EvaluatorVersionEquivalence> preview = versionCutover.preview();
            if (preview.isEmpty()) {
                System.out.println("Ningún juez cambia de versión al dejar de contar sus pruebas: no hay nada que anotar.");
                return 0;
            }
            System.out.println("Esto se anotaría, una sola vez y sin consultar a ningún juez (no se escribió nada):");
            preview.forEach(equivalence -> System.out.println(equivalenceLine(equivalence)));
            System.out.println("Para anotarlo: content-audit exam cutover --apply");
            return 0;
        }
        try {
            List<EvaluatorVersionEquivalence> written = versionCutover.apply();
            System.out.println("Anotado, " + written.size() + (written.size() == 1 ? " juez:" : " jueces:"));
            written.forEach(equivalence -> System.out.println(equivalenceLine(equivalence)));
            System.out.println("Queda en la carpeta de los agentes: versionalo junto con las definiciones corregidas.");
            return 0;
        } catch (IllegalStateException e) {
            System.err.println("Error: " + e.getMessage());
            return 1;
        }
    }

    private static String equivalenceLine(EvaluatorVersionEquivalence equivalence) {
        return "  " + equivalence.getEvaluatorId() + ": la versión " + equivalence.getEarlierVersion()
                + " es la misma que " + equivalence.getCurrentVersion() + ", anotado "
                + equivalence.getRecordedAt() + ". " + (equivalence.getReason() != null ? equivalence.getReason() : "");
    }

    /**
     * F-JEXAM-R015: the same history as {@code exam status}, as JSON for the dashboard. With a judge,
     * that judge; without one, every analyzer of the catalog that has records or takes the exam, in
     * the order of the catalog. Each judge brings its versions -- one per version and runtime, in the
     * order they first took it -- with their standing, which is their last record, and every record.
     * It only reads the registry: it never consults a judge nor writes.
     */
    Integer showExamsJson(String judgeName) {
        Map<String, List<JudgeExamRecord>> histories = new LinkedHashMap<>();
        if (!isBlank(judgeName)) {
            histories.put(judgeName.trim(), examService.history(judgeName.trim()));
        } else {
            for (String name : analyzerNames.get()) {
                List<JudgeExamRecord> history = examService.history(name);
                if (!history.isEmpty() || provenanceByJudge.containsKey(name)) {
                    histories.put(name, history);
                }
            }
        }
        ObjectNode root = MAPPER.createObjectNode();
        ArrayNode judges = root.putArray("judges");
        Map<String, JudgeExamStanding> current = currentStandings.get();
        Map<String, EvaluationRuntimeIdentity> closing = closingRuntimes.get();
        histories.forEach((name, history) -> {
            ObjectNode judge = judges.addObject();
            judge.put("judge", name);
            JudgeExamStanding standing = current.get(name);
            if (standing != null) {
                ObjectNode active = judge.putObject("current");
                active.put("judgeVersion", standing.getJudgeVersion());
                active.put("status", standing.getStatus().name());
                active.put("consultsOnCourse", standing.isConsultsOnCourse());
                active.put("reason", standing.getReason());
                EvaluationRuntimeIdentity runtime = standing.getRuntimeIdentity();
                active.put("providerName", runtime.isExplicit() ? runtime.getProviderName() : null);
                active.put("modelName", runtime.isExplicit() ? runtime.getModelName() : null);
                active.put("reasoningEffort", runtime.isExplicit() ? runtime.getReasoningEffort() : null);
                active.put("provenance", runtimeLabel(runtime));
                ArrayNode equivalences = active.putArray("versionEquivalences");
                for (EvaluatorVersionEquivalence equivalence : standing.getVersionEquivalences()) {
                    ObjectNode line = equivalences.addObject();
                    line.put("agent", equivalence.getEvaluatorId());
                    line.put("earlierVersion", equivalence.getEarlierVersion());
                    line.put("currentVersion", equivalence.getCurrentVersion());
                    line.put("recordedAt", equivalence.getRecordedAt() != null
                            ? equivalence.getRecordedAt().toString() : null);
                    line.put("reason", equivalence.getReason());
                }
                // F-JEXAM-R015 / F-ALDIA-R003: the motors with which this version is enabled.
                ArrayNode enabled = active.putArray("enabledWith");
                for (JudgeEnablement enablement : standing.getEnabledWith()) {
                    EvaluationRuntimeIdentity motor = enablement.runtimeIdentity();
                    ObjectNode line = enabled.addObject();
                    line.put("providerName", motor.getProviderName());
                    line.put("modelName", motor.getModelName());
                    line.put("reasoningEffort", motor.getReasoningEffort());
                    line.put("provenance", runtimeLabel(motor));
                    line.put("status", enablement.status() != null ? enablement.status().name() : null);
                    line.put("since", enablement.since() != null ? enablement.since().toString() : null);
                }
                // F-CMOTOR-R006: the runtime the closing would consult it with; null blocks the closing.
                EvaluationRuntimeIdentity closesWith = closing.get(name);
                if (closesWith != null && closesWith.isExplicit()) {
                    ObjectNode motor = active.putObject("closesWith");
                    motor.put("providerName", closesWith.getProviderName());
                    motor.put("modelName", closesWith.getModelName());
                    motor.put("reasoningEffort", closesWith.getReasoningEffort());
                    motor.put("provenance", runtimeLabel(closesWith));
                    motor.put("otherRuntime", !closesWith.equals(standing.getRuntimeIdentity()));
                } else {
                    active.putNull("closesWith");
                }
            }
            ArrayNode versions = judge.putArray("versions");
            for (List<JudgeExamRecord> records : byVersionAndRuntime(history)) {
                versions.add(versionJson(records));
            }
        });
        System.out.println(CommandJson.write(root));
        return 0;
    }

    /** The records of each version and runtime, in the order that version first appears. */
    private static List<List<JudgeExamRecord>> byVersionAndRuntime(List<JudgeExamRecord> history) {
        Map<List<Object>, List<JudgeExamRecord>> groups = new LinkedHashMap<>();
        for (JudgeExamRecord record : history) {
            groups.computeIfAbsent(List.of(String.valueOf(record.getJudgeVersion()), record.getRuntimeIdentity()),
                    key -> new ArrayList<>()).add(record);
        }
        return new ArrayList<>(groups.values());
    }

    private static ObjectNode versionJson(List<JudgeExamRecord> records) {
        JudgeExamRecord standing = records.get(records.size() - 1);
        ObjectNode version = MAPPER.createObjectNode();
        version.put("judgeVersion", standing.getJudgeVersion());
        version.put("provenance", provenanceLabel(standing));
        version.put("providerName", standing.getProviderName());
        version.put("modelName", standing.getModelName());
        version.put("reasoningEffort", standing.getReasoningEffort());
        version.put("status", standing.getStatus() != null ? standing.getStatus().name() : null);
        ArrayNode list = version.putArray("records");
        for (JudgeExamRecord record : records) {
            ObjectNode line = list.addObject();
            line.put("status", record.getStatus() != null ? record.getStatus().name() : null);
            line.put("recordedAt", record.getRecordedAt() != null ? record.getRecordedAt().toString() : null);
            line.put("casesJudged", record.getCasesJudged());
            line.put("casesNotJudged", record.getCasesNotJudged());
            ArrayNode groups = line.putArray("groups");
            if (record.getGroups() != null) {
                for (JudgeExamGroupResult group : record.getGroups()) {
                    groups.addObject()
                            .put("group", group.getGroup())
                            .put("cases", group.getCases())
                            .put("asExpected", group.getAsExpected())
                            .put("notAsExpected", group.getNotAsExpected());
                }
            }
            ArrayNode mismatched = line.putArray("mismatchedCaseIds");
            if (record.getMismatchedCaseIds() != null) {
                record.getMismatchedCaseIds().forEach(mismatched::add);
            }
            line.put("goalMet", record.isGoalMet());
            line.put("photo", record.getPhoto());
            line.put("measuredBy", record.getMeasuredBy());
            line.put("examFingerprint", record.getExamFingerprint());
            line.put("regressionSuiteFingerprint", record.getRegressionSuiteFingerprint());
            line.set("regressionCaseIds", MAPPER.valueToTree(record.getRegressionCaseIds()));
            line.set("regressionMismatchedCaseIds", MAPPER.valueToTree(record.getRegressionMismatchedCaseIds()));
        }
        return version;
    }

