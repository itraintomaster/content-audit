    /** {@code [{"ejercicio": "<id>"}, …]}: the ids in the order of the file, each once. */
    private static Set<String> readCases(Path file) throws IOException {
        JsonNode root = MAPPER.readTree(Files.readString(file, StandardCharsets.UTF_8));
        if (root == null || !root.isArray()) {
            throw new IllegalArgumentException("it is not a list of {\"ejercicio\": \"<id>\"}");
        }
        Set<String> ids = new LinkedHashSet<>();
        for (JsonNode entry : root) {
            JsonNode id = entry.isTextual() ? entry : entry.get("ejercicio");
            if (id == null || !id.isTextual() || id.asText().isBlank()) {
                throw new IllegalArgumentException("an entry without its \"ejercicio\": " + entry);
            }
            ids.add(id.asText().trim());
        }
        return ids;
    }

    private static Map<String, JsonNode> readCaseMetadata(Path file) throws IOException {
        Map<String, JsonNode> metadata = new LinkedHashMap<>();
        for (JsonNode entry : MAPPER.readTree(file.toFile())) {
            if (entry.isObject()) metadata.put(entry.path("ejercicio").asText(), entry);
        }
        return metadata;
    }

    private static void bindRegressions(JudgeExamRequest request, Map<String, JsonNode> metadata) {
        Map<String, String> quizIds = new LinkedHashMap<>();
        String fingerprint = null;
        Set<String> examFingerprints = new LinkedHashSet<>();
        for (Map.Entry<String, JsonNode> entry : metadata.entrySet()) {
            String examFingerprint = text(entry.getValue(), "examFingerprint");
            if (examFingerprint != null) examFingerprints.add(examFingerprint);
            String id = text(entry.getValue(), "regressionCaseId");
            if (id == null) continue;
            String next = text(entry.getValue(), "regressionSuiteFingerprint");
            if (next == null || fingerprint != null && !fingerprint.equals(next))
                throw new IllegalArgumentException("Los casos permanentes deben pertenecer a una misma edición del examen.");
            fingerprint = next;
            if (quizIds.putIfAbsent(id, entry.getKey()) != null)
                throw new IllegalArgumentException("Caso permanente repetido: " + id);
        }
        request.setRegressionSuiteFingerprint(fingerprint);
        if (examFingerprints.size() > 1) throw new IllegalArgumentException("El pedido mezcla ediciones de examen distintas.");
        request.setExamFingerprint(examFingerprints.isEmpty() ? null : examFingerprints.iterator().next());
        request.setRegressionCaseIds(new ArrayList<>(quizIds.keySet()));
        request.setRegressionQuizIds(quizIds);
    }

    /** One JSON line per exercise; source references stay outside judge input. */
    private static void writeVerdicts(Path file, List<JudgeExamVerdict> verdicts,
            EvaluationRuntimeIdentity runtimeIdentity, Map<String, JsonNode> metadata) throws IOException {
        EvaluationRuntimeIdentity runtime = runtimeIdentity != null
                ? runtimeIdentity
                : EvaluationRuntimeIdentity.legacyUnknown();
        StringBuilder lines = new StringBuilder();
        for (JudgeExamVerdict verdict : verdicts) {
            ObjectNode line = MAPPER.createObjectNode();
            line.put("ejercicio", verdict.getCaseId());
            line.put("juez", verdict.getJudgeName());
            line.put("proveedor", runtime.isExplicit() ? runtime.getProviderName() : null);
            line.put("modelo", runtime.isExplicit() ? runtime.getModelName() : null);
            line.put("esfuerzo", runtime.isExplicit() ? runtime.getReasoningEffort() : null);
            line.put("version", verdict.getJudgeVersion());
            line.put("resultado", verdict.getOutcome() != null ? verdict.getOutcome().name() : null);
            line.put("gravedad", verdict.getWorstSeverity() != null ? verdict.getWorstSeverity().name() : null);
            ArrayNode rules = line.putArray("reglas");
            if (verdict.getRules() != null) {
                verdict.getRules().forEach(rules::add);
            }
            line.put("detalle", verdict.getDetail());
            JsonNode source = metadata.get(verdict.getCaseId());
            if (source != null && source.hasNonNull("regressionCaseId")) {
                for (String key : List.of("regressionCaseId", "regressionSuiteFingerprint", "examFingerprint", "problemId",
                        "problemTitle", "problemCaseId", "sourceQuizId")) {
                    if (source.has(key)) line.set(key, source.get(key));
                }
            }
            lines.append(MAPPER.writeValueAsString(line)).append('\n');
        }
        if (file.getParent() != null) {
            Files.createDirectories(file.getParent());
        }
        Files.writeString(file, lines.toString(), StandardCharsets.UTF_8, StandardOpenOption.CREATE_NEW,
                StandardOpenOption.WRITE);
    }

    /**
     * What was measured outside: {"juez", "version", "estado": "APROBADO"|"REPROBADO", "grupos": [{"grupo",
     * "casos", "comoSeEspera", "noComoSeEspera"}], "noDieronLoEsperado": [...], "alcanzoLaMeta", "foto",
     * "medidoPor"}.
     */
    private static JudgeExamRecord readMeasured(Path file) throws IOException {
        JsonNode root = MAPPER.readTree(Files.readString(file, StandardCharsets.UTF_8));
        if (root == null || !root.isObject()) {
            throw new IllegalArgumentException("it is not an object with juez, version and estado");
        }
        String judge = text(root, "juez");
        String version = text(root, "version");
        String state = text(root, "estado");
        if (isBlank(judge) || isBlank(version) || isBlank(state)) {
            throw new IllegalArgumentException("it needs juez, version and estado");
        }
        JudgeExamStatus status = switch (state.trim().toUpperCase(Locale.ROOT)) {
            case "APROBADO" -> JudgeExamStatus.APPROVED;
            case "REPROBADO" -> JudgeExamStatus.FAILED;
            default -> throw new IllegalArgumentException("estado is APROBADO or REPROBADO, not " + state);
        };
        List<JudgeExamGroupResult> groups = new ArrayList<>();
        int cases = 0;
        for (JsonNode group : root.path("grupos")) {
            JudgeExamGroupResult result = new JudgeExamGroupResult(text(group, "grupo"), group.path("casos").asInt(),
                    group.path("comoSeEspera").asInt(), group.path("noComoSeEspera").asInt());
            cases += result.getCases();
            groups.add(result);
        }
        List<String> mismatched = new ArrayList<>();
        for (JsonNode id : root.path("noDieronLoEsperado")) {
            mismatched.add(id.asText());
        }
        JudgeExamRecord measured = new JudgeExamRecord(judge.trim(), version.trim(), status, cases, 0,
                groups, mismatched, root.path("alcanzoLaMeta").asBoolean(false), text(root, "foto"),
                text(root, "medidoPor"), null);
        measured.setRegressionSuiteFingerprint(text(root, "regressionSuiteFingerprint"));
        measured.setExamFingerprint(text(root, "examFingerprint"));
        List<String> regressionIds = new ArrayList<>();
        root.path("regressionCaseIds").forEach(id -> regressionIds.add(id.asText()));
        measured.setRegressionCaseIds(regressionIds);
        String provider = firstText(root, "proveedor", "providerName");
        String model = firstText(root, "modelo", "modelName");
        String effort = firstText(root, "esfuerzo", "reasoningEffort");
        int provenanceParts = (isBlank(provider) ? 0 : 1) + (isBlank(model) ? 0 : 1)
                + (isBlank(effort) ? 0 : 1);
        if (provenanceParts != 0 && provenanceParts != 3) {
            throw new IllegalArgumentException(
                    "la identidad medida debe declarar proveedor, modelo y esfuerzo juntos");
        }
        if (provenanceParts == 3) {
            measured.setRuntimeIdentity(EvaluationRuntimeIdentity.explicit(provider, model, effort));
        }
        return measured;
    }

    private static void printSummary(JudgeExamTaken taken, boolean rehearsal) {
        int judged = 0;
        for (JudgeExamVerdict verdict : taken.getVerdicts()) {
            if (verdict.getOutcome() != JudgeExamOutcome.NOT_JUDGED) {
                judged++;
            }
        }
        int total = taken.getVerdicts().size();
        System.out.println("Identidad examinada: " + runtimeLabel(taken.getRuntimeIdentity())
                + " · versión " + (taken.getJudgeVersion() != null ? taken.getJudgeVersion() : "sin versión") + ".");
        System.out.println("Cobertura del examen: " + total
                + " ejercicios, " + judged + " con veredicto, " + (total - judged) + " sin veredicto.");
        if (rehearsal) {
            System.out.println("Ensayo sin --budget: no se consultó al juez; se reusó lo que esa versión ya juzgó.");
        }
        JudgeCostEstimate cost = taken.getCoverage() != null ? taken.getCoverage().getCost() : null;
        if (cost != null && cost.getPendingConsultations() > 0) {
            System.out.println(String.format(Locale.ROOT,
                    "Faltan %d consultas: %.1f h de a una, %.1f h con %d a la vez (%.0f por hora, %s).",
                    cost.getPendingConsultations(), cost.getHoursOneAtATime(), cost.getHoursConcurrent(),
                    cost.getMaxConcurrentEvaluations(), cost.getRatePerHour(),
                    cost.isRateMeasured() ? "ritmo medido" : "ritmo por omisión"));
        }
        String reason = taken.getCoverage() != null ? taken.getCoverage().getUnavailableReason() : null;
        if (reason != null) {
            System.out.println("El juez dejó de consultar: " + reason);
        }
        System.out.println("Estado del examen: " + (taken.isRecordedAsTaken()
                ? "RENDIDO completo; ya se puede registrar su resultado con exam record."
                : "INCOMPLETO; su resultado todavía no se puede registrar."));
    }

    private static String spanish(JudgeExamStatus status) {
        if (status == null) {
            return "SIN ESTADO";
        }
        return switch (status) {
            case PROMOTED -> "PROMOVIDO POR EL OPERADOR";
            case APPROVED -> "APROBADO";
            case FAILED -> "REPROBADO";
            case TAKEN -> "RENDIDO";
            case NOT_TAKEN -> "SIN EXAMEN";
            case NO_VERSION -> "SIN VERSIÓN";
        };
    }

    private static String provenanceLabel(JudgeExamRecord record) {
        EvaluationRuntimeIdentity runtime = record.getRuntimeIdentity();
        if (runtime.isExplicit()) {
            return runtimeLabel(runtime);
        }
        // Historical lines may name only provider/model. They remain visible for comparison, but
        // the "legacy incompleta" label makes clear that they cannot enable an explicit runtime.
        if (!isBlank(record.getProviderName()) || !isBlank(record.getModelName())
                || !isBlank(record.getReasoningEffort())) {
            String provider = !isBlank(record.getProviderName()) ? record.getProviderName() : "proveedor desconocido";
            String model = !isBlank(record.getModelName()) ? record.getModelName() : "modelo desconocido";
            String effort = !isBlank(record.getReasoningEffort())
                    ? " (esfuerzo " + record.getReasoningEffort() + ")"
                    : "";
            return provider + "/" + model + effort + " (procedencia legacy incompleta)";
        }
        return runtimeLabel(runtime);
    }

