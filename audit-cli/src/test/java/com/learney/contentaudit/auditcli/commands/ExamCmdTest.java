    /** A service that answers every exercise and records what it was asked. */
    private static final class RecordingService implements JudgeExamService {
        final List<JudgeExamRequest> taken = new ArrayList<>();
        final List<JudgeExamRecord> recorded = new ArrayList<>();

        @Override
        public JudgeExamTaken take(JudgeExamRequest request) {
            taken.add(request);
            List<JudgeExamVerdict> verdicts = new ArrayList<>();
            for (String id : request.getCaseIds()) {
                if (id.equals(ABSENT)) {
                    verdicts.add(new JudgeExamVerdict(id, request.getJudgeName(), "v-consigna",
                            JudgeExamOutcome.NOT_JUDGED, null, List.of(), "el ejercicio no está en la foto del curso"));
                } else if (id.endsWith("24f7")) {
                    verdicts.add(new JudgeExamVerdict(id, request.getJudgeName(), "v-consigna", JudgeExamOutcome.FAILS,
                            FindingSeverity.HIGH, List.of("instruction-breach"),
                            "instruction-breach: la consigna pide algo que el ejercicio no pide"));
                } else {
                    verdicts.add(new JudgeExamVerdict(id, request.getJudgeName(), "v-consigna",
                            JudgeExamOutcome.PASSES, null, List.of(), ""));
                }
            }
            return new JudgeExamTaken(request.getJudgeName(), "v-consigna", verdicts, null, false,
                    request.getRuntimeIdentity());
        }

        @Override
        public JudgeExamStanding record(JudgeExamRecord measured) {
            recorded.add(measured);
            return new JudgeExamStanding(measured.getJudgeName(), measured.getJudgeVersion(), measured.getStatus(),
                    measured.getStatus() == JudgeExamStatus.APPROVED, null);
        }

        @Override
        public List<JudgeExamRecord> history(String judgeName) {
            return List.of();
        }
    }

    record Captured(int exit, String out, String err) {
    }

    private static Captured run(Object command, String... args) {
        PrintStream out = System.out;
        PrintStream err = System.err;
        ByteArrayOutputStream outBytes = new ByteArrayOutputStream();
        ByteArrayOutputStream errBytes = new ByteArrayOutputStream();
        System.setOut(new PrintStream(outBytes, true, StandardCharsets.UTF_8));
        System.setErr(new PrintStream(errBytes, true, StandardCharsets.UTF_8));
        try {
            int exit = new CommandLine(command).execute(args);
            return new Captured(exit, outBytes.toString(StandardCharsets.UTF_8), errBytes.toString(StandardCharsets.UTF_8));
        } finally {
            System.setOut(out);
            System.setErr(err);
        }
    }
