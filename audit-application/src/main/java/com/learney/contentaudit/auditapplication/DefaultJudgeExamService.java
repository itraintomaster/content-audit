/**
 * F-JEXAM-R001 and R002: a judge takes the fixed exam through the very same path as analyze -- the
 * runner over the frozen photo of the course, with only the analyzer that hosts the judge and an
 * EXAM policy whose declared set is the exercises of the file -- so the exam is read exactly as the
 * course is read, by construction. The report of the exam is never stored, and the exam's sessions
 * write only in the exam space of the ledger, so analyze gives the same before and after.
 *
 * <p>The gold standard of the exam is outside: the file brings only exercises, the service leaves a
 * verdict per exercise and records {@code TAKEN} for the version once every exercise of the file got
 * one; the result measured outside is accepted only for a version that took it.
 */
