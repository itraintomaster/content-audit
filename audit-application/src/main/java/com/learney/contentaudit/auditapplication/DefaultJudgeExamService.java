    private final AuditRunner auditRunner;

    private final AnalyzerCatalog analyzerCatalog;

    private final JudgeExamVerdictExporter exporter;

    private final JudgeExamRegistry examRegistry;

    private final JudgeRuntime runtime;

    public DefaultJudgeExamService(AuditRunner auditRunner, AnalyzerCatalog analyzerCatalog,
            JudgeExamVerdictExporter exporter, JudgeExamRegistry examRegistry,
            JudgeRuntime runtime) {
        this.auditRunner = auditRunner;
        this.analyzerCatalog = analyzerCatalog;
        this.exporter = exporter;
        this.examRegistry = examRegistry;
        this.runtime = runtime;
    }

    @Override
    public JudgeExamTaken take(JudgeExamRequest request) {
        String judgeName = request.getJudgeName();
        AnalyzerDescriptor card = analyzerCatalog.find(judgeName)
                .orElseThrow(() -> new UnknownAnalyzerException(judgeName));
        Set<String> caseIds = request.getCaseIds() != null
                ? new LinkedHashSet<>(request.getCaseIds())
                : new LinkedHashSet<>();

        // Budget 0 is a rehearsal (F-JEXAM-R010): it reuses what that version judged and says how
        // much is missing, without paying.
        EvaluationRunPolicy policy = new EvaluationRunPolicy(Math.max(0, request.getMaxNewEvaluations()), false, null,
                caseIds, EvaluationRunPurpose.EXAM, request.getMaxConcurrentEvaluations());
        AuditReport report = auditRunner.runAudit(request.getPhotoCourse(),
                new AuditRunRequest(Set.of(judgeName), null, Map.of(judgeName, policy)));

        JudgeCoverageDiagnosis coverage = coverageOf(report, judgeName).orElse(null);
        String judgeVersion = coverage != null && coverage.getStanding() != null
                ? coverage.getStanding().getJudgeVersion()
                : examinedVersionOf(report, judgeName);
        List<JudgeExamVerdict> verdicts = exporter.export(report, card, caseIds, coverage);

        int judged = 0;
        for (JudgeExamVerdict verdict : verdicts) {
            if (verdict.getOutcome() != JudgeExamOutcome.NOT_JUDGED) {
                judged++;
            }
        }
        boolean tookItAll = judgeVersion != null && !caseIds.isEmpty() && judged == caseIds.size();
        if (tookItAll && examRegistry.latest(judgeName, judgeVersion).isEmpty()) {
            // The condition for accepting a measured result: nobody can approve a version that did
            // not judge every exercise of the file. A version already recorded keeps its standing.
            examRegistry.record(new JudgeExamRecord(judgeName, judgeVersion, JudgeExamStatus.TAKEN, judged, 0,
                    List.of(), List.of(), false, photoOf(request), null, Instant.now()));
        }
        return new JudgeExamTaken(judgeName, judgeVersion, verdicts, coverage, tookItAll);
    }

    /**
     * F-JEXAM-R001 inv. 1: the result measured outside is kept for that version -- and becomes its
     * standing -- only when that version took the whole exam.
     */
    @Override
    public JudgeExamStanding record(JudgeExamRecord measured) {
        if (measured == null || measured.getJudgeName() == null || measured.getJudgeVersion() == null) {
            throw new IllegalArgumentException("A measured exam result needs its judge and its version");
        }
        if (measured.getStatus() != JudgeExamStatus.APPROVED && measured.getStatus() != JudgeExamStatus.FAILED) {
            throw new IllegalArgumentException("A measured exam result is APPROVED or FAILED, not "
                    + measured.getStatus());
        }
        String judgeName = measured.getJudgeName();
        String judgeVersion = measured.getJudgeVersion();
        boolean took = false;
        for (JudgeExamRecord earlier : examRegistry.history(judgeName)) {
            if (judgeVersion.equals(earlier.getJudgeVersion()) && earlier.getStatus() == JudgeExamStatus.TAKEN) {
                took = true;
                break;
            }
        }
        if (!took) {
            throw new JudgeExamNotTakenException(judgeName, judgeVersion);
        }
        examRegistry.record(new JudgeExamRecord(judgeName, judgeVersion, measured.getStatus(),
                measured.getCasesJudged(), measured.getCasesNotJudged(),
                measured.getGroups() != null ? new ArrayList<>(measured.getGroups()) : List.of(),
                measured.getMismatchedCaseIds() != null ? new ArrayList<>(measured.getMismatchedCaseIds()) : List.of(),
                measured.isGoalMet(), measured.getPhoto(), measured.getMeasuredBy(),
                measured.getRecordedAt() != null ? measured.getRecordedAt() : Instant.now()));
        return runtime.standing(judgeName, judgeVersion);
    }

    @Override
    public List<JudgeExamRecord> history(String judgeName) {
        return examRegistry.history(judgeName);
    }

    private static Optional<JudgeCoverageDiagnosis> coverageOf(AuditReport report, String judgeName) {
        if (report == null || report.getRoot() == null
                || !(report.getRoot().getDiagnoses() instanceof CourseDiagnoses diagnoses)
                || diagnoses.getJudgeCoverages() == null) {
            return Optional.empty();
        }
        for (JudgeCoverageDiagnosis coverage : diagnoses.getJudgeCoverages()) {
            if (coverage != null && judgeName.equals(coverage.getJudgeName())) {
                return Optional.of(coverage);
            }
        }
        return Optional.empty();
    }

    /**
     * Hook B-11: an analyzer with a local tool that does not consult through the judges' runtime --
     * grammar, with LanguageTool -- has no coverage; the version it took the exam with is the
     * examined version of its run's row («LanguageTool 6.8 · filtro-…»).
     */
    private static String examinedVersionOf(AuditReport report, String analyzerName) {
        if (report == null || report.getRoot() == null
                || !(report.getRoot().getDiagnoses() instanceof CourseDiagnoses diagnoses)
                || diagnoses.getLocalToolRuns() == null) {
            return null;
        }
        for (com.learney.contentaudit.auditdomain.localtools.LocalToolRunDiagnosis run : diagnoses.getLocalToolRuns()) {
            if (run != null && analyzerName.equals(run.getAnalyzer())) {
                return run.getExaminedVersion();
            }
        }
        return null;
    }

    private static String photoOf(JudgeExamRequest request) {
        return request.getPhotoCourse() != null ? request.getPhotoCourse().toString() : null;
    }
