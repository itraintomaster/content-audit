    private static Optional<JudgeCoverageDiagnosis> coverageOf(AuditReport report, String judgeName) {
        if (report == null || report.getRoot() == null
                || !(report.getRoot().getDiagnoses() instanceof CourseDiagnoses diagnoses)
                || diagnoses.getJudgeCoverages() == null) {
            return Optional.empty();
        }
        for (JudgeCoverageDiagnosis coverage : diagnoses.getJudgeCoverages()) {
            if (coverage != null && judgeName.equals(coverage.getJudgeName())) {
                return Optional.of(coverage);
            }
        }
        return Optional.empty();
    }

    /**
     * Hook B-11: an analyzer with a local tool that does not consult through the judges' runtime --
     * grammar, with LanguageTool -- has no coverage; the version it took the exam with is the
     * examined version of its run's row («LanguageTool 6.8 · filtro-…»).
     */
    private static String examinedVersionOf(AuditReport report, String analyzerName) {
        if (report == null || report.getRoot() == null
                || !(report.getRoot().getDiagnoses() instanceof CourseDiagnoses diagnoses)
                || diagnoses.getLocalToolRuns() == null) {
            return null;
        }
        for (com.learney.contentaudit.auditdomain.localtools.LocalToolRunDiagnosis run : diagnoses.getLocalToolRuns()) {
            if (run != null && analyzerName.equals(run.getAnalyzer())) {
                return run.getExaminedVersion();
            }
        }
        return null;
    }

    private static boolean samePreparation(JudgeExamRecord earlier, JudgeExamRequest request, int judged) {
        return java.util.Objects.equals(earlier.getExamFingerprint(), request.getExamFingerprint())
                && java.util.Objects.equals(earlier.getPhoto(), photoOf(request))
                && earlier.getCasesJudged() == judged && earlier.getCasesNotJudged() == 0;
    }

    private static boolean sameMeasurement(JudgeExamRecord taken, JudgeExamRecord measured, boolean permanentSuite) {
        // Count and manifest matching happen before runtime selection: two preparations of the
        // same version and motor must never consume one another's TAKEN evidence.
        boolean bound = permanentSuite || taken.getExamFingerprint() != null || measured.getExamFingerprint() != null;
        return taken.getCasesJudged() == measured.getCasesJudged()
                && taken.getCasesNotJudged() == measured.getCasesNotJudged()
                && java.util.Objects.equals(taken.getExamFingerprint(), measured.getExamFingerprint())
                && (!bound || measured.getPhoto() == null || java.util.Objects.equals(taken.getPhoto(), measured.getPhoto()));
    }

    private static String photoOf(JudgeExamRequest request) {
        return request.getPhotoCourse() != null ? request.getPhotoCourse().toString() : null;
    }

    /**
     * Selects the TAKEN record by exact runtime when the measured file names it. Historical files
     * without provenance remain accepted only when a single runtime took that process-version;
     * once Claude and Codex coexist, omitting runtime is ambiguous and therefore rejected.
     */
    private static JudgeExamRecord selectTakenIdentity(JudgeExamRecord measured,
            List<JudgeExamRecord> candidates) {
        Map<EvaluationRuntimeIdentity, JudgeExamRecord> byRuntime = new java.util.LinkedHashMap<>();
        for (JudgeExamRecord candidate : candidates) {
            byRuntime.put(candidate.getRuntimeIdentity(), candidate);
        }
        EvaluationRuntimeIdentity requested = measured.getRuntimeIdentity();
        if (requested.isExplicit()) {
            JudgeExamRecord selected = byRuntime.get(requested);
            if (selected == null && !byRuntime.isEmpty()) {
                throw new IllegalArgumentException("El runtime declarado por el resultado medido de '"
                        + measured.getJudgeName() + "' versión " + measured.getJudgeVersion()
                        + " no coincide con ninguno de los que rindieron el examen");
            }
            return selected;
        }

        if (byRuntime.size() > 1) {
            throw new IllegalArgumentException("El resultado medido de '" + measured.getJudgeName()
                    + "' versión " + measured.getJudgeVersion()
                    + " debe declarar proveedor, modelo y esfuerzo: más de un runtime rindió esa versión");
        }
        return byRuntime.values().stream().findFirst().orElse(null);
    }
