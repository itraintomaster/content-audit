/**
 * F-HALL-R005: get analyzers, config analyzer and stats analyzer read the catalog, so a name
 * appears here if and only if analyze accepts it -- the judges included.
 */
@Generated(
        value = "com.sentinel.SentinelEngine",
        comments = "Generated by Sentinel"
)
public class DefaultAnalyzerRegistry implements AnalyzerRegistry {
    private final AnalyzerCatalog analyzerCatalog;

    public DefaultAnalyzerRegistry(AnalyzerCatalog analyzerCatalog) {
        this.analyzerCatalog = analyzerCatalog;
    }

    @Override
    public List<AnalyzerDescriptor> listAnalyzers() {
        return analyzerCatalog.list();
    }

    /**
     * Empty only when the catalog does not have the name; an analyzer without configuration
     * answers with an empty map, which config analyzer shows as "(no configuration)".
     */
    @Override
    public Optional<Map<String, Object>> getAnalyzerConfig(String analyzerName) {
        if (analyzerCatalog.find(analyzerName).isEmpty()) {
            return Optional.empty();
        }
        Optional<SelfDescribingConfig> config = analyzerCatalog.provider(analyzerName)
                .flatMap(AnalyzerProvider::config);
        return Optional.of(config.map(SelfDescribingConfig::describe).orElse(Map.of()));
    }
}
